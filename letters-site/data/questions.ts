/**
 * Вопрос дня. Один на двоих, ответы открываются только когда
 * ответили оба — иначе второй подстроится под первого.
 *
 * Вопрос выбирается по дате, а не случайно: у обоих должен быть
 * один и тот же вопрос, и он не должен меняться при перезагрузке.
 */

export const QUESTIONS = [
  "Что ты во мне заметила первым — не внешне, а вообще?",
  "Какой день из этого месяца ты бы прожила ещё раз?",
  "О чём ты думаешь перед сном чаще всего?",
  "Что тебя больше всего успокаивает?",
  "Какую свою черту ты не любишь, а я, кажется, люблю?",
  "Что бы ты сделала, если бы завтра был выходной у нас обоих?",
  "Какая песня сейчас звучит у тебя в голове?",
  "Что тебе говорили в детстве, а ты до сих пор помнишь?",
  "Чего ты боишься сильнее всего в отношениях?",
  "Какое место в Уфе ты считаешь своим?",
  "Что тебя рассмешило за последнюю неделю?",
  "О чём ты жалеешь, что не сказала вовремя?",
  "Каким ты меня представляешь через пять лет?",
  "Что для тебя значит «дома»?",
  "Какой запах возвращает тебя в детство?",
  "Что ты откладываешь, хотя очень хочешь сделать?",
  "Когда ты в последний раз чувствовала себя по-настоящему спокойно?",
  "Что тебе во мне непонятно?",
  "Какую привычку ты бы хотела завести вдвоём?",
  "Что ты никогда никому не рассказывала?",
  "За что ты себя уважаешь?",
  "Каким было утро, которое ты помнишь лучше всех?",
  "Что бы ты изменила в том, как мы общаемся?",
  "Что тебе нужно, когда тебе плохо, — слова или тишина?",
  "О чём ты мечтала в шестнадцать?",
  "Что ты хочешь, чтобы я знал, но не спрашивал?",
  "Какой подарок тебе запомнился больше всего?",
  "Что бы ты сказала себе год назад?",
  "Чему ты научилась за этот месяц врозь?",
  "Что для тебя самое трудное в ожидании?",
];

/** Один и тот же вопрос у обоих в один и тот же день. */
export function questionFor(day: string): string {
  // Сумма символов даты — дешёвый и устойчивый способ разложить
  // вопросы по дням без случайности
  let sum = 0;
  for (let i = 0; i < day.length; i++) sum += day.charCodeAt(i) * (i + 1);
  return QUESTIONS[sum % QUESTIONS.length];
}
