"""Потолок на размер запроса — до того, как тело попадёт в память.

Зачем (аудит 2026-08-08, волна 148). Проверка размера у нас была, но срабатывала ПОСЛЕ приёма:
файл на 25 МБ честно получал «слишком большой» — уже будучи целиком прочитанным и раскодированным.
А для обычных запросов потолка не было вовсе.

Проба на живом сервере: десять параллельных запросов по 20 МБ на форму входа (аккаунт не нужен)
подняли память процесса с 319 МБ до 997 МБ и задержали обычный `/health` почти на две секунды.

Хуже того, ответ 422 «заполните поля» возвращает присланное тело ОБРАТНО — по копии на каждое
незаполненное поле. У формы входа два обязательных поля, значит ответ выходил ровно вдвое
больше запроса: человек без аккаунта отправлял 40 МБ и получал 80 МБ трафика в ответ.

Сегодня на проде это прикрыто настройкой nginx (1 МБ по умолчанию), но в задачах стоит поднять
её до 12 МБ ради загрузки фото. В день, когда это сделают, дыра станет 12 → 24 МБ за запрос,
и со стороны приложения её ничто не остановит. Защита должна жить в самом приложении: оно
не может полагаться на то, что перед ним всегда стоит правильно настроенный сервер.
"""
from __future__ import annotations

from fastapi import Request
from fastapi.responses import JSONResponse
from starlette.middleware.base import BaseHTTPMiddleware

from .config import settings
from .logs import log

# Сколько «сверху» к лимиту файла разрешаем на служебные поля и на разбухание base64.
# Base64 увеличивает размер примерно на треть, поэтому берём полуторный запас: честная
# загрузка максимального фото должна проходить, а не упираться в потолок.
_UPLOAD_OVERHEAD = 1.6

# Обычному запросу столько не нужно никогда: это форма входа, заявка, сообщение в чат.
# Отдельно от загрузок, чтобы дорогой потолок действовал только там, где он осмыслен.
PLAIN_BODY_LIMIT = 256 * 1024


def _limit_for(path: str) -> int:
    """Сколько байт разрешено этому пути. Загрузкам — по настройке файлов, остальным — мало."""
    if any(marker in path for marker in ("/upload", "/voice", "/photo", "/evidence")):
        return int(settings.max_upload_bytes * _UPLOAD_OVERHEAD)
    return PLAIN_BODY_LIMIT


class BodySizeLimitMiddleware(BaseHTTPMiddleware):
    """Отсекает слишком большой запрос по заявленному размеру, не читая тело.

    Проверяем `Content-Length` — заголовок, который клиент присылает ДО тела. Врать в нём
    бессмысленно: если заявлено мало, а прислано много, сервер оборвёт чтение сам.

    Запрос без заголовка (chunked) не блокируем: так шлют законные клиенты, а тело всё равно
    ограничено потолком загрузки внутри обработчика. Здесь закрывается главный случай —
    заявленный гигантский объём, который сегодня принимался целиком.
    """

    async def dispatch(self, request: Request, call_next):
        raw = request.headers.get("content-length")
        if raw:
            try:
                size = int(raw)
            except ValueError:
                size = 0
            limit = _limit_for(request.url.path)
            if size > limit:
                log.warning("[BODY] запрос отбит по размеру: %s байт при потолке %s на %s",
                            size, limit, request.url.path)
                return JSONResponse(
                    status_code=413,
                    content={"detail": {
                        "ru": "Слишком большой запрос. Попробуй отправить меньше за раз.",
                        "ba": "Һорау артыҡ ҙур. Бер юлы әҙерәк ебәреп ҡара.",
                    }},
                )
        return await call_next(request)
