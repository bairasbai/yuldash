"""Подписи к причинам отмены брони — на двух языках.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Пассажиру, у которого отменили бронь, уходил ГОЛЫЙ МАРШРУТ:
«Бронь отменена · Уфа → Сибай», и всё. Человек, который рассчитывал уехать, оставался без
двух вещей сразу — без причины и без понимания, что делать дальше (аудит сценариев 30.08).

Коды причин живут в `safety_logic.CANCEL_REASONS` и приходят от клиента; здесь только
подписи к ним. Держим рядом, чтобы список кодов и список подписей не разъехались: код без
подписи просто не добавит в пуш ничего лишнего, а не покажет человеку служебное слово.
"""
from typing import Optional

# Код → (русская фраза, башкирская). Пустая пара = причину в текст не добавляем:
# «other» и «не указана» ничего человеку не объясняют, а строку удлиняют.
REASON_TEXT = {
    "plans_changed": ("Планы изменились.", "Пландар үҙгәрҙе."),
    "found_other": ("Нашлась другая машина.", "Башҡа машина табылды."),
    "driver_no_response": ("Водитель не выходил на связь.", "Водитель бәйләнешкә сыҡманы."),
    "price": ("Не сошлись в цене.", "Хаҡ буйынса килешмәнек."),
    "driver_late": ("Водитель опаздывал.", "Водитель һуңланы."),
    "passenger_late": ("Пассажир опаздывал.", "Юлаусы һуңланы."),
    "emergency": ("Срочные обстоятельства.", "Ашығыс хәлдәр."),
    "safety": ("Причина — безопасность.", "Сәбәбе — именлек."),
    "not_going": ("Поездка не состоится.", "Сәфәр булмай."),
    "no_show": ("Пассажир не вышел.", "Юлаусы сыҡманы."),
    "other": ("", ""),
}


def cancel_reason_text(code: Optional[str]) -> tuple:
    """Код причины → человеческая фраза (ru, ba). Неизвестный код — пустая пара."""
    return REASON_TEXT.get((code or "").strip(), ("", ""))
