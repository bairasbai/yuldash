"""Наблюдаемость Юлдаша: инициализация Sentry.

Правило: без `SENTRY_DSN` — полный no-op. Ничего не импортируется тяжёлого,
ничего не шлётся наружу, приложение работает ровно как раньше. DSN — секрет,
только из env (`.env`/переменные окружения), в git не попадает.

Отдельный модуль (не в main.py), чтобы инициализацию можно было позвать и из
gunicorn-воркеров, и из тестов, и чтобы отсутствие пакета `sentry-sdk` не роняло
импорт приложения (мягкий фолбэк).
"""
import re
from urllib.parse import urlsplit

from .config import settings
from .logs import log

_sentry_ready = False

# ------------------------------ вычистка личных данных ------------------------------
# `send_default_pii=False` запрещает Sentry прикладывать куки, IP и заголовок Authorization —
# но НЕ тело запроса (его выключаем отдельно, см. init_sentry) и не спасает, если телефон
# попал ВНУТРЬ текста ошибки, в адрес запроса или в хлебную крошку. Пример:
# HTTPException(422, f"Номер {phone} занят") улетит в облако вместе с номером.
# Поэтому чистим на выходе — последний рубеж перед отправкой наружу (§8 CLAUDE.md).
#
# Чистим осознанно грубо: лучше затереть лишнее в тексте ошибки, чем отправить чужой телефон.
# Разработчику для отладки нужен вид сбоя и стек, а не персональные данные из него.

# --- телефон: что стоит между цифрами (задача #31, 17.10.2026) ---
# Раньше разделителем считались только пробел, дефис, точка и скобки. А номер из контактов
# приходит с неразрывными пробелами, автозамена делает из дефиса тире, кто-то пишет через
# слэш, запятую или переносит строку — и «8–917–765–43–21» уходил в ленту заявок целиком.
#
# «Сильные» разделители — до трёх подряд («8 – 917», «+7 (917) »): любой пробел (`\s` —
# в т.ч. U+00A0, U+202F, U+2009, перевод строки, табуляция), невидимые знаки (мягкий перенос
# U+00AD, нулевой ширины U+200B–U+200D, U+2060, U+FEFF), дефис и все тире и минусы
# (U+2010–U+2015, U+2212, U+FE58, U+FE63, U+FF0D), точка, скобки.
_PH_STRONG = r"[\s\u00ad\u200b-\u200d\u2060\ufeff\-\u2010-\u2015\u2212\ufe58\ufe63\uff0d.()]"
# «Слабые» — слэш, запятая, подчёркивание: только поодиночке, вплотную к цифрам
# («8/917/765/43/21», «917,765,43,21»). «, » с пробелом — это перечисление: «цены 800, 1 200,
# 1 500», параметры SQL «(8, 900, 1000, 15, 2)», списки в логах. Через него номер не тянем.
# Двоеточие разделителем не считаем вовсе — так время «15:07:18» не собирается в номер.
_PH_WEAK = r"[/,_]"
# IPv4 номером не бывает, а старая мойка путала: «85.239.152.155» — это восьмёрка и десять
# цифр через точку, «92.168.200.10» — девятка и девять. Октет — число 0..255, поэтому номер,
# записанный через точки («917.123.45.67»), под это не попадает: 917 не октет.
_IP_OCTET = r"(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)"
_IPV4 = rf"{_IP_OCTET}(?:\.{_IP_OCTET}){{3}}(?!\.?\d)"
# Следующая цифра номера: перед ней может стоять разделитель, но за разделителем не может
# начинаться IP — иначе «попытка 9, 85.239.152.155» собралась бы в «номер».
_PH_NEXT = rf"(?:(?:{_PH_STRONG}{{1,3}}|{_PH_WEAK})(?!{_IPV4}))?\d"
_HEX = "[0-9a-fA-F]"
_PHONE = re.compile(
    # Целиком пропускаем (не трогаем) то, внутри чего номер только мерещится: IP-адрес, UUID
    # и длинный hex-идентификатор (event_id и trace_id Sentry, client_id аналитики). В них бывает
    # «8» и десять цифр подряд — старая мойка портила так примерно каждый сотый UUID, а событие
    # с испорченным event_id Sentry выбрасывает.
    rf"(?P<keep>(?<!\d)(?<!\d\.){_IPV4}"
    rf"|(?<![0-9A-Za-z]){_HEX}{{8}}(?:-{_HEX}{{4}}){{3}}-{_HEX}{{12}}(?![0-9A-Za-z])"
    rf"|(?<![0-9A-Za-z])(?={_HEX}*[a-fA-F]){_HEX}{{16,}}(?![0-9A-Za-z]))"
    # +7 / 7 / 8 и ещё десять цифр, между ними — разделители выше. Буква цепочку рвёт.
    rf"|(?<!\d)(?:\+?7|8)(?:{_PH_NEXT}){{10}}(?!\d)"
    # Мобильный без кода страны: «звони 917 123-45-67», «9171234567». Так пишут в свободном
    # поле чаще всего (приёмка PR168, 17.10). Ровно десять цифр с девятки: «цена 900», «подъезд 9»
    # и годы не трогает. Буква или цифра вплотную — значит, это кусок идентификатора или токена,
    # а не номер: не режем. Скобку перед кодом забираем вместе с номером: «(917) 123…».
    rf"|(?<![\w+])\(?9(?:{_PH_NEXT}){{9}}(?!\w)"
    # Городской Башкортостана без восьмёрки: «347 264-18-90» (Уфа), «(34786) 2-64-18» (район),
    # «(3473) 24-56-78». Коды республики все начинаются с 347, всего цифр — десять. Узко
    # нарочно: «34» и восемь цифр ловили бы и цены «34 500, 12 300», а «347…» — уже нет.
    rf"|(?<![\w+])\(?347(?:{_PH_NEXT}){{7}}(?!\w)"
)


def _phone_or_keep(m: "re.Match[str]") -> str:
    return m.group(0) if m.group("keep") else "<телефон>"


_SCRUB = (
    # HMAC refresh и rotation_id — 64 hex-символа. В ошибках/locals имена бывают
    # raw и child_raw, поэтому маскируем само значение. До телефона: его шаблон
    # может иначе разрезать секрет на части и оставить остальное открытым.
    (re.compile(r"(?<![0-9a-fA-F])[0-9a-fA-F]{64}(?![0-9a-fA-F])"), "<токен>"),
    # Токены и координаты — ДО телефонов (приёмка PR169, 17.10): телефонный шаблон находил
    # «номер» внутри длинной дробной части («52.9123456789, 58.66…» → «52.<телефон>, 58.66…»)
    # или куска токена, и правило координат/токена после него уже не узнавало целое.
    # JWT: три base64-куска через точку. Токен = доступ к аккаунту.
    # Начинаем только с начала куска (слева не буква, не цифра, не «_», не «-»), а не с любой
    # границы слова: иначе на «a-a-a-…» шаблон пробовал старт у каждой буквы и каждый раз
    # пробегал строку до конца — время росло как квадрат длины (100 КБ — 36 с, приёмка #178).
    # Совпадение с начала куска покрывает всё, что находилось раньше: тот же токен целиком.
    (re.compile(r"(?<![A-Za-z0-9_-])[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b"),
     "<токен>"),
    # Live-ссылка близкому (/t/{token}): токен в ПУТИ — это и есть ключ к живым координатам
    # поездки. Access-лог его маскирует, алерт админу тоже (middleware.py), а Sentry
    # прикладывает полный адрес запроса САМ — и `send_default_pii=False` тут не помогает,
    # потому что URL не считается персональными данными (аудит 2026-08-08). Маскируем здесь.
    (re.compile(r"/t/[A-Za-z0-9_-]{16,}"), "/t/***"),
    # Токен Telegram-бота в адресе: https://api.telegram.org/bot<id>:<токен>/sendMessage. С ним
    # любой пишет от имени Юлдаша всем, кто запускал бота. Sentry записывает исходящие запросы
    # сервера сам — с полным адресом (приёмка #178, P2); в логе httpx токен маскирует фильтр
    # в logs.py, а здесь общий рубеж для всего остального: крошки, трейсы, текст ошибок.
    (re.compile(r"/bot\d+:[A-Za-z0-9_-]+"), "/bot<скрыто>"),
    # координаты в query-строке: /rides?lat=54.05&lng=58.31 — это местоположение человека
    (re.compile(r"\b(lat|lng|lon|latitude|longitude)=-?\d+\.\d+", re.IGNORECASE), r"\1=<коорд>"),
    # ГОЛЫЕ координаты: «52.9321, 58.6612». Правило выше ловит их только в виде lat=…&lng=…,
    # а человек и наши же экраны пишут их просто числами — и они долетали до базы аналитики
    # целиком (аудит 2026-08-08, волна 136). Точка на карте в Баймаке — это чей-то дом.
    #
    # Требуем дробную часть у обоих чисел: «мест 3, 5» или «цена 300, 400» не тронем,
    # а настоящие координаты всегда с точкой.
    (re.compile(r"(?<![\d.])-?\d{1,3}\.\d{3,}\s*,\s*-?\d{1,3}\.\d{3,}(?![\d.])"), "<коорд>"),
    # телефон в любом написании: +7/8, мобильный без кода, городской 347 — см. `_PHONE` выше
    (_PHONE, _phone_or_keep),
    # почта: попадает и в логи, и в аналитику («написал на марат@example.com»). Личное —
    # маскируем везде одинаково (аудит 2026-08-12, волна 45). `\w`, а не только латиница:
    # имя до собаки бывает кириллицей, и именно так его пишет человек в свободном поле.
    # Длины — по стандарту почты: имя до 64 знаков, домен до 253. Без потолка длинное слово
    # без «@» (base64 в логе, 100 КБ «xxxx…») разбиралось десятки секунд: шаблон пробовал старт
    # у каждой буквы и каждый раз бежал до конца слова (приёмка #178). С потолком — линейно.
    (re.compile(r"[\w.%+-]{1,64}@[\w.-]{1,253}\.[A-Za-z]{2,63}", re.UNICODE), "<почта>"),
    # Секреты в параметрах. api_id — ключ sms.ru, msg — текст СМС (в нём код входа), apikey —
    # ключ геокодера Яндекса, chat_id и text — адресат и текст сообщения Telegram (SOS с
    # координатами). Всё это лежит в строке исходящего запроса (приёмка #178, P2).
    (re.compile(r"\b(token|access_token|refresh_token|code|otp|password|secret|api_key|apikey|api_id"
                r"|key|msg|text|chat_id)=[^&\s\"']+",
                re.IGNORECASE), r"\1=<скрыто>"),
    # Адрес с номером дома или квартиры: «ул. Ленина 1, кв. 5», «дом 7». Город и улицу
    # оставляем — по ним человека не найти; номер дома и квартиры находят.
    (re.compile(r"\b(?:ул|улица|пер|переулок|пр-т|проспект)\.?\s+[А-ЯЁ][\w-]*\s*,?\s*\d+[а-яА-Я]?\b",
                re.UNICODE), "<адрес>"),
    (re.compile(r"\b(?:кв|квартира|д|дом|стр|корп)\.?\s*\d+[а-яА-Я]?\b", re.UNICODE), "<адрес>"),
    # Госномер машины (А123ВС102). В приложении он на месте и нужен — пассажир сверяет
    # машину перед посадкой. А в аналитике и логах это просто опознавательный знак человека:
    # по номеру в деревне находят двор. Формат узкий, ложных срабатываний почти нет.
    (re.compile(r"\b[АВЕКМНОРСТУХABEKMHOPCTYX]\d{3}[АВЕКМНОРСТУХABEKMHOPCTYX]{2}\d{2,3}\b",
                re.UNICODE | re.IGNORECASE), "<номер авто>"),
    # Ник в мессенджере: по нему человека находят так же, как по телефону.
    (re.compile(r"(?<![\w@])@[A-Za-z][A-Za-z0-9_]{3,}\b"), "<ник>"),
)
_SCRUB_MAX_DEPTH = 12


def scrub_text(s: str) -> str:
    for rx, repl in _SCRUB:
        s = rx.sub(repl, s)
    return s


def scrub_exc(exc: BaseException) -> str:
    """Текст исключения со стеком, очищенный от персональных данных — для ЛОКАЛЬНОГО лога.

    Скруб писался для Sentry, но ровно та же беда есть в логе своего сервера: SQLAlchemy
    вкладывает в текст `IntegrityError` параметры запроса, а там телефон человека:

        (IntegrityError) UNIQUE constraint failed: user.phone
        [parameters: ('+79991234567', 'Айгуль Хабибуллина', 'Баймак')]

    Логи читает не только разработчик: они лежат на диске, попадают в выгрузки и в чужие руки
    при разборе инцидента. §8 CLAUDE.md и 152-ФЗ говорят прямо — чувствительное не логируем
    (аудит 2026-08-08, волна 14). Стек оставляем целиком: для отладки нужен именно он.
    """
    import traceback
    text = "".join(traceback.format_exception(type(exc), exc, exc.__traceback__))
    return scrub_text(text)


def _scrub(value, depth: int = 0):
    """Рекурсивно вычистить строки в событии. Глубина ограничена: событие Sentry —
    чужая структура, зацикливаться на ней наблюдаемость права не имеет."""
    if depth > _SCRUB_MAX_DEPTH:
        return value
    if isinstance(value, str):
        return scrub_text(value)
    if isinstance(value, dict):
        return {k: _scrub(v, depth + 1) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        out = [_scrub(v, depth + 1) for v in value]
        return type(value)(out) if isinstance(value, tuple) else out
    return value


# Тело запроса и куки из события выбрасываем целиком, а не моем: в теле — имя, код из СМС,
# координаты числом, комментарий с адресом; мойка ловит не всё (имя и число она не узнает).
# Разбору сбоя хватает адреса, метода, заголовков и стека. Тела выключены и в init_sentry —
# здесь второй замок на случай, если обновлённый SDK начнёт прикладывать их по-новому.
_REQUEST_DROP = ("data", "cookies")


def before_send(event, hint):   # noqa: ARG001 — hint нужен по контракту Sentry
    """Последний рубеж перед отправкой. Любая ошибка чистки → событие НЕ отправляем:
    лучше потерять отчёт о сбое, чем отправить наружу чужой телефон."""
    try:
        cleaned = _scrub(event)   # новая копия: исходное событие не трогаем
        request = cleaned.get("request")
        if isinstance(request, dict):
            for key in _REQUEST_DROP:
                request.pop(key, None)
        return cleaned
    except Exception:  # noqa: BLE001
        return None


# Хлебные крошки — записи «что сервер делал перед сбоем», Sentry копит их сам и прикладывает
# к событию. Крошка исходящего HTTP (httpx, http.client — категория «httplib») несёт полный
# адрес и строку запроса: токен бота Telegram в пути, ключ sms.ru и код из СМС в параметрах
# (приёмка #178, P2). Мойка поймала бы известные ключи, но новый сервис принесёт новые — поэтому
# от такой крошки оставляем только то, что нужно для разбора: схему и хост, метод и код ответа.
_HTTP_CRUMB_KEEP = ("http.method", "http.response.status_code")


def _http_crumb(crumb: dict) -> dict:
    data = crumb.get("data") or {}
    parts = urlsplit(str(data.get("url") or ""))
    host = parts.hostname or ""            # без «логин:пароль@»
    if ":" in host:
        host = f"[{host}]"                 # IPv6
    if parts.port:
        host = f"{host}:{parts.port}"
    safe = {"url": f"{parts.scheme}://{host}"} if parts.scheme and host else {}
    safe.update({k: data[k] for k in _HTTP_CRUMB_KEEP if data.get(k) is not None})
    out = {k: crumb[k] for k in ("type", "category", "level", "timestamp") if k in crumb}
    out["data"] = safe                     # путь, запрос, фрагмент и текст крошки — не берём
    return out


def before_breadcrumb(crumb, hint):   # noqa: ARG001 — hint нужен по контракту Sentry
    """Крошка перед тем, как лечь в память SDK. HTTP — урезаем до схемы, хоста, метода и
    кода ответа; любую другую (строки лога, запросы к Redis и базе) — через общую мойку.
    Любая ошибка → крошку выбрасываем: лучше потерять след, чем отдать наружу ключ."""
    try:
        if crumb.get("type") == "http" or crumb.get("category") == "httplib":
            return _http_crumb(crumb)
        return _scrub(crumb)
    except Exception:  # noqa: BLE001
        return None


def init_sentry() -> bool:
    """Поднять Sentry, если задан DSN. Возвращает True, если реально включили.

    Идемпотентна: повторный вызов не пересоздаёт клиента. Любая ошибка инициализации
    (нет пакета, кривой DSN) — тихо логируется и НЕ роняет приложение."""
    global _sentry_ready
    if _sentry_ready:
        return True
    dsn = (settings.sentry_dsn or "").strip()
    if not dsn:
        return False  # no-op: DSN не задан
    try:
        import sentry_sdk
        integrations = []
        try:
            # Фоновые корутины (WS pub/sub, задачи) — их исключения иначе не попадают в Sentry.
            from sentry_sdk.integrations.asyncio import AsyncioIntegration
            integrations.append(AsyncioIntegration())
        except Exception:  # noqa: BLE001 — интеграция опциональна, не роняем init
            pass
        sentry_sdk.init(
            dsn=dsn,
            environment=settings.env,
            traces_sample_rate=settings.sentry_traces_sample_rate,
            integrations=integrations,
            # Не тащим куки, IP и заголовок Authorization (152-ФЗ). Тела запроса этот флаг
            # НЕ выключает: проверено на sentry_sdk 2.72 (задача #42) — FastAPI-интеграция
            # кладёт JSON-тело в событие при любом send_default_pii, предел ей задаёт только
            # max_request_body_size (по умолчанию «medium» = до 10 КБ). См. starlette.py,
            # StarletteRequestExtractor.extract_request_info, и _wsgi_common.request_body_within_bounds.
            send_default_pii=False,
            # Поэтому тело запрещаем отдельно: там имя, код из СМС, координаты, комментарий.
            max_request_body_size="never",
            # Локальные переменные кадра стека — та же дыра: в обработчике лежит уже разобранное
            # тело (`body=RequestIn(name=…, comment=…)`) и пользователь из базы. Для разбора
            # сбоя хватает стека и текста ошибки — так и написано в шапке мойки выше.
            include_local_variables=False,
            # Второй рубеж: before_send выбрасывает тело и куки, если они всё же пришли, и чистит
            # то, что просочилось в текст ошибки или в адрес.
            before_send=before_send,
            before_send_transaction=before_send,   # у трейсов в имени лежит URL
            # Крошки исходящих запросов — без пути и строки запроса, остальные — через мойку.
            before_breadcrumb=before_breadcrumb,
        )
        _sentry_ready = True
        log.info(f"[SENTRY] инициализирован (env={settings.env})")
        return True
    except Exception as e:  # noqa: BLE001 — наблюдаемость не должна ронять прод
        log.warning(f"[SENTRY] init skipped: {type(e).__name__}: {e}")
        return False


def sentry_enabled() -> bool:
    return _sentry_ready


def capture(exc: BaseException) -> None:
    """Отправить исключение в Sentry, если он включён (иначе тихий no-op). Безопасно —
    сама наблюдаемость не должна ронять код (фоновые задачи, обработчик 500, WS-циклы)."""
    if not _sentry_ready:
        return
    try:
        import sentry_sdk
        sentry_sdk.capture_exception(exc)
    except Exception:  # noqa: BLE001
        pass
