def _phone_key(phone: str) -> str:
    """Нормализованный ключ телефона для сравнения. +79990001122, 89990001122 и 9990001122 →
    один ключ 79990001122.

    Раньше ключом были ПОСЛЕДНИЕ 10 цифр, и код страны в сравнение не входил вовсе. По этому
    ключу выдаётся роль администратора (`_maybe_promote_admin`), а номер в аккаунт попадает из
    Telegram — то есть настоящий, но ЛЮБОЙ страны. Иностранный номер, у которого последние
    десять цифр совпадают с номером Александра, получал админку при обычном входе
    (аудит 2026-08-08). Теперь код страны — часть ключа, и совпадают только российские записи
    одного и того же номера, ради которых правило и делалось.
    """
    digits = "".join(ch for ch in phone if ch.isdigit())
    if len(digits) == 11 and digits[0] in ("7", "8"):
        return "7" + digits[1:]      # 8XXXXXXXXXX == +7XXXXXXXXXX — один российский номер
    if len(digits) == 10:
        return "7" + digits          # запись без кода страны (в .env удобно писать так)
    return digits                    # чужая страна / короткий номер — сравниваем как есть


