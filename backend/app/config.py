    def validate_production(self) -> None:
        """Запрещаем запускать прод с небезопасными значениями по умолчанию."""
        # V10: fail-safe — совсем нераспознанный ENV (опечатка «production1», мусор) не должен
        # молча уводить в dev-режим и снимать прод-гварды. Требуем явный известный ENV.
        if self.env.strip().lower() not in ("dev", "development", "prod", "production", "test"):
            raise RuntimeError(f"ENV нераспознан: {self.env!r} — задай dev или prod")
        if not self.is_prod:
            return
        problems: list[str] = []
        # Ловим не только точный дефолт, но и любой заведомо-dev секрет (напр. фолбэк из
        # docker-compose `dev-secret-...-1234` — он длиннее 16 и раньше проскакивал гвард).
        weak_secret = (
            self.jwt_secret == DEFAULT_JWT_SECRET
            or self.jwt_secret.startswith("dev-secret")
            or len(self.jwt_secret) < 16
        )
        if weak_secret:
            problems.append("JWT_SECRET должен быть задан, длинным (>=16) и не dev-дефолтом")
        # SMS — НЕобязателен: основной вход через мессенджеры (Telegram и т.п.).
        # SMS заморожен (sms_provider=mock) — это допустимо в проде. Оживить: SMS_PROVIDER=smsru + ключ.
        if self.sms_provider == "smsru" and not self.sms_ru_api_id:
            problems.append("SMS_RU_API_ID обязателен при SMS_PROVIDER=smsru")
        if self.sms_provider == "smsdar" and not (self.smsdar_id and self.smsdar_password and self.smsdar_sender):
            problems.append("SMSDAR_ID, SMSDAR_PASSWORD и SMSDAR_SENDER обязательны при SMS_PROVIDER=smsdar")
        # Telegram-бот включён, но вебхук без секрета → любой шлёт фейковые апдейты и выпускает себе код входа.
        if self.telegram_bot_token and not self.telegram_webhook_secret:
            problems.append("TELEGRAM_WEBHOOK_SECRET обязателен при заданном TELEGRAM_BOT_TOKEN")
        if self.cors_origins.strip() == "*":
            problems.append("CORS_ORIGINS не должен быть '*' в проде")
        # seed_demo в проде насыпает фейковых водителей (+7000000000X) как реальные аккаунты в пустую БД.
        if self.seed_demo:
            problems.append("SEED_DEMO должен быть выключен в проде (фейковые водители в реальной БД)")
        # mock-платежи в проде = «оплата» без денег. Включён реальный приём → ключи/реквизиты обязательны.
        if self.payments_provider == "yookassa" and not (self.yookassa_shop_id and self.yookassa_secret_key):
            problems.append("YOOKASSA_SHOP_ID и YOOKASSA_SECRET_KEY обязательны при PAYMENTS_PROVIDER=yookassa")
        if self.payments_provider == "sbp_manual" and not self.sbp_phone:
            problems.append("SBP_PHONE обязателен при PAYMENTS_PROVIDER=sbp_manual")
        # Платёжный номер СБП раздаётся в ответе оплаты ВСЕМ вошедшим, а автоадмин выдаётся
        # по номеру из ADMIN_PHONES → совпадение = раскрытый номер становится ключом к роли admin.
        if self.payments_provider == "sbp_manual" and self.sbp_phone:
            admin_keys = {_phone_key(p) for p in self.admin_phones.split(",") if p.strip()}
            if _phone_key(self.sbp_phone) in admin_keys:
                problems.append("SBP_PHONE не должен совпадать с ADMIN_PHONES (раскрытый платёжный номер = ключ к админке)")
        # Выплаты включены в проде без ключей выплат ЮKassa = «нажали вывод, а денег нет».
        if self.payouts_enabled and not (self.yookassa_payout_agent_id and self.yookassa_payout_secret_key):
            problems.append("YOOKASSA_PAYOUT_AGENT_ID и YOOKASSA_PAYOUT_SECRET_KEY обязательны при PAYOUTS_ENABLED=true")
        # Авто-одобрять водителей без OCR нельзя — это пустит непроверенных. Нужен ключ Vision.
        if self.driver_autoapprove_enabled and not self.yandex_vision_key:
            problems.append("YANDEX_VISION_KEY обязателен при DRIVER_AUTOAPPROVE_ENABLED (нельзя авто-одобрять без OCR)")
        # S3 включён явно, но без бакета/ключей — медиа некуда писать. Требуем полный набор.
        if (self.storage_backend or "").strip().lower() == "s3" and not (
            self.s3_bucket and self.s3_access_key and self.s3_secret_key
        ):
            problems.append("S3_BUCKET, S3_ACCESS_KEY и S3_SECRET_KEY обязательны при STORAGE_BACKEND=s3")
        # Такси без Redis — самый коварный вид «работает»: сервис поднимается, экраны открываются,
        # но presence живёт ТОЛЬКО в Redis GEO. Без него nearby_drivers() возвращает [], и каждый
        # заказ мгновенно уходит в «рядом никого» — неотличимо от «в городе нет водителей».
        # Разбор №2 (2026-08-03): включить TAXI_ENABLED без REDIS_URL = запустить мёртвое такси
        # и неделю искать, почему не едут. Падаем на старте, а не в первом заказе.
        if self.taxi_enabled and not self.redis_url.strip():
            problems.append("REDIS_URL обязателен при TAXI_ENABLED=true (без него presence пуст и заказы уходят в «рядом никого»)")
        # Форс-апдейт без ссылки в стор: экран «Обнови приложение» появится, а кнопка никуда
        # не поведёт — человек заперт в приложении, которым нельзя пользоваться.
        if self.min_app_version_code > 0 and not self.update_url:
            problems.append("APP_STORE_URL или APP_DOWNLOAD_URL обязателен при MIN_APP_VERSION_CODE>0 (иначе кнопка «Обновить» ведёт в никуда)")
        # «Последняя версия» ниже «минимальной» — конфиг, который сам себе противоречит: человека
        # блокируют как устаревшего и одновременно зовут обновиться до версии, которую тоже
        # заблокируют. Такое проще запретить на старте, чем ловить по жалобам.
        if 0 < self.latest_app_version_code < self.min_app_version_code:
            problems.append("LATEST_APP_VERSION_CODE меньше MIN_APP_VERSION_CODE — обновление зовёт на версию, которая уже не поддерживается")
        if self.database_url.startswith("sqlite"):
            problems.append("DATABASE_URL не должен быть sqlite в проде")
        media_base = self.media_base_url.lower()
        if media_base.startswith("http://") or "localhost" in media_base or "127.0.0.1" in media_base:
            problems.append("MEDIA_BASE_URL должен быть публичным HTTPS URL в проде")
        if problems:
            raise RuntimeError("Небезопасная прод-конфигурация: " + "; ".join(problems))

    def launch_warnings(self) -> list[str]:
        """Мешает ВЫПУСКУ, но не работе — поэтому предупреждение, а не падение.

        Отличие от `validate_production()`: там вещи, из-за которых сервис работает неправильно
        или небезопасно (падаем сразу). Здесь — вещи, из-за которых приложение отклонит стор или
        пользователи застрянут на старой версии. Сервис при этом честно работает, и валить его
        было бы вредно. Разбор №2 (2026-08-03): всё это тихо стояло в дефолтах и всплыло бы
        только отказом модерации.
        """
        warn: list[str] = []
        if not (self.review_phone.strip() and self.review_code.strip()):
            warn.append("REVIEW_PHONE/REVIEW_CODE пусты — ревьюер Google Play / RuStore не сможет войти, сборку отклонят")
        if self.min_app_version_code <= 0:
            warn.append("MIN_APP_VERSION_CODE=0 — принудительное обновление выключено, ломающий релиз будет некому раскатить")
        if self.is_prod and not self.firebase_credentials.strip():
            warn.append("FIREBASE_CREDENTIALS пуст — push не отправляются, водители не увидят заказы на погашенном экране")
        if self.is_prod and not self.sentry_dsn.strip():
            warn.append("SENTRY_DSN пуст — падения у людей останутся невидимыми")
        # Публичные документы на yulbash.ru/terms прямо обещают: «Комиссия с поездок не берётся,
        # расчёты производятся напрямую между пользователями». Пока денежные флаги выключены —
        # это правда. Включили хоть один, не переписав документы, — сервис публично обещает одно,
        # а делает другое. На это ссылаются при споре и при проверке, поэтому предупреждаем громко.
        money_on = [n for n, v in (("PARCEL_FEE_ENABLED", self.parcel_fee_enabled),
                                   ("PAYOUTS_ENABLED", self.payouts_enabled),
                                   ("TIPS_MONEY_ENABLED", self.tips_money_enabled)) if v]
        if money_on:
            warn.append(
                "Включены денежные функции (" + ", ".join(money_on) + "), а публичная оферта на "
                "yulbash.ru/terms обещает «комиссия не берётся» — обновите web/components/legal-content.ts "
                "и решите вопрос со статусом (физлицу брать комиссию нельзя)"
            )
        # Комиссия такси и доставки живёт НЕ за денежным флагом, а за самим включением такси:
        # после каждого завершённого заказа водителю заводится долг (debt.py::accrue_for_order).
        # Проверка сайта 2026-08-05 нашла, что в четырёх местах лендинга и в самой оферте
        # написано «0 ₽ комиссия сервиса» / «Комиссия с поездок не берётся». Пока такси
        # выключено — это правда (за попутки комиссии действительно нет). Включили с ненулевым
        # процентом — сервис публично обещает одно, а делает другое. На оферту ссылаются
        # при споре и при проверке, поэтому предупреждаем в момент включения, а не потом.
        fee_on = [
            f"такси {self.service_fee_percent}%" if self.taxi_enabled and self.service_fee_percent > 0 else "",
            f"доставка {self.courier_service_fee_percent}%"
            if self.courier_enabled and self.courier_service_fee_percent > 0 else "",
            # Попутка держится отдельной ставкой и по решению Александра равна нулю (волна 154).
            # Стережём её здесь же: подняли — предупреждение назовёт попутку поимённо, потому что
            # именно про неё сайт обещает «0 ₽» громче всего, и именно она приводит людей.
            f"попутка {self.ride_service_fee_percent}%" if self.ride_service_fee_percent > 0 else "",
        ]
        fee_on = [f for f in fee_on if f]
        if fee_on:
            warn.append(
                "Комиссия с водителей включена (" + ", ".join(fee_on) + "), а сайт и оферта обещают "
                "«0 ₽ комиссия сервиса» — либо обновите тексты (web/components/lang.tsx, "
                "StructuredData.tsx, legal-content.ts), либо поставьте процент в 0. "
                "Список мест — docs/tasks.md, раздел проверки сайта"
            )
        return warn


