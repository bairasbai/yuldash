"""Что в цене заказа — компенсация водителю, а не заработок платформы. ОДНА точка правды.

Зачем отдельный модуль. Одну и ту же сумму спрашивают три места, и все три считают деньги:

  1. `instant_service.order_compensation_rub` — строка в чеке «с этого комиссия не берётся»;
  2. `debt.order_commission_kop` — база, с которой комиссия РЕАЛЬНО берётся;
  3. `promo_ride.price_kop` — база, от которой считается потолок скидки по промокоду.

Пока список компенсаций был переписан в каждом из них своими руками, он и разъехался:
зимняя дорога попала в чек, но не попала в две другие. Водителю писали «с компенсации
100 ₽ комиссия не берётся» и брали с неё 15 ₽. Приложение врало ему в документе — хуже,
чем просто ошиблось.

Поэтому список живёт здесь, в модуле без единого импорта из проекта: его может позвать
кто угодно, не рискуя кругом импортов. Добавил новую компенсацию — добавь поле СЮДА,
и все три места узнают об этом одновременно. Сторож — `test_compensation_single_source.py`.
"""

# Поля заказа, которые не являются заработком платформы. Только копейки (int *_kop).
COMPENSATION_FIELDS = (
    "pickup_fee_kop",     # дорога водителя к пассажиру (бензин, который он сожжёт)
    "options_fee_kop",    # детское кресло, животное, большой багаж (его вещи и его труд)
    "weather_fee_kop",    # зимняя дорога: расчищенная колея, риск и износ
)


def compensation_kop(order) -> int:
    """Сумма всех компенсаций водителю по заказу, копейки. None-заказ → 0."""
    if order is None:
        return 0
    return sum(int(getattr(order, f, 0) or 0) for f in COMPENSATION_FIELDS)


def compensation_rub(order) -> int:
    """То же в рублях (вниз, целыми) — деньги в UI и в базах комиссии считаем в ₽."""
    return compensation_kop(order) // 100
