"""Потолки на поток однотипных действий одного человека (анти-флуд).

Чем это отличается от лимитера в middleware. Тот считает запросы с одного IP и защищает
СЕРВЕР от перегрузки: 300 запросов в минуту — потолок, который обычный клиент не достанет.
Здесь защищаем ЛЮДЕЙ, и потолки принципиально ниже: 300 сообщений в минуту сервер даже не
заметит, а человек на другом конце получит 300 пушей подряд среди ночи.

Что было до этого модуля (проверено на живом сервере 2026-08-06): один пользователь подряд
опубликовал 80 поездок, создал 80 заявок, отправил 300 сообщений в один чат и завёл
60 посылок — ни одного отказа. В приложении «между своими» на небольшой район это значит:
  • лента поездок и заявок забита одним человеком, реальных объявлений не видно;
  • каждая заявка будит пушем водителей, которые караулят это направление;
  • каждое сообщение — пуш собеседнику: травля кнопкой «отправить», а не словами.

Потолки намеренно щедрые: настоящий водитель не публикует тридцать поездок разом, а живая
переписка — это единицы сообщений в минуту, не тридцать. Упереться в такой потолок можно
только специально.

Ответ всегда 429 с человеческим текстом на двух языках: «слишком много» — это не обвинение,
а «остынь и продолжи позже».
"""
from __future__ import annotations

from datetime import timedelta

from sqlmodel import Session, select

from .errors import herr
from .timeutil import utcnow


def guard_open_items(session: Session, id_col, *conds, limit: int, ru: str, ba: str) -> None:
    """Потолок на число ОДНОВРЕМЕННО открытых объектов (активные поездки, заявки, посылки).

    Считаем не «сколько создал за всё время», а «сколько висит сейчас»: закрыл/отменил —
    место освободилось. Так потолок не наказывает того, кто реально много ездит годами.
    Запрос читает не больше `limit + 1` строк — на горячем пути это дёшево."""
    n = len(list(session.exec(select(id_col).where(*conds).limit(limit + 1)).all()))
    if n >= limit:
        raise herr(429, ru, ba)


def guard_burst(session: Session, id_col, created_col, *conds,
                per_minute: int, ru: str, ba: str) -> None:
    """Потолок на темп: сколько раз за последнюю минуту.

    Для сообщений важно не общее число за день (переписываться можно сколько угодно),
    а очередь пушей в минуту. `created_col` — колонка со временем создания той же таблицы."""
    edge = utcnow() - timedelta(minutes=1)
    n = len(list(session.exec(
        select(id_col).where(*conds, created_col >= edge).limit(per_minute + 1)
    ).all()))
    if n >= per_minute:
        raise herr(429, ru, ba)


