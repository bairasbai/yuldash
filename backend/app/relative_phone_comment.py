"""Телефон близкого из комментария заявки старых клиентов — сервер убирает его сам.

Экран «За близкого» в старых клиентах дописывал номер близкого человека прямо в комментарий
заявки. А комментарий заявки публичный: его видит любой вошедший (лента, карта), и он же
уходит админу в Telegram, если заявка «нужна помощь». Новые сайт и приложение так не делают
(PR #168, #172), но старые живут: сайт обновляется, только когда человек согласится на
подсказку, а Android-сборки 29.06–05.07.2026 могут стоять у людей до сих пор. Поэтому сервер
не доверяет клиенту (§8) и приводит такие комментарии в порядок ДО записи в базу.

Форматы — буква в букву, как их писали старые клиенты:
    сайт (до PR #168):         «Телефон близкого: <номер>[. <заметка>]», «Яҡындың телефоны: …»
    Android (29.06–05.07.2026): «Заказ за близкого · <номер>», «Яҡын кеше өсөн заказ · <номер>»

Номер → нейтральная метка того же языка (та, что пишут новые клиенты). Заметка после «. »
остаётся, но через общую мойку `scrub_text`; если в ней и после мойки 5+ цифр подряд (через
любые не-буквенные знаки) — это, скорее всего, ещё один номер в непривычном виде, и заметку
убираем, оставляем метку.
Заявку не отклоняем: человек хотел как лучше. Исходный текст нигде не логируем.

Разовая чистка уже записанных строк — отдельный скрипт `ops/` (PR #173), общего кода с ним
нет намеренно: он должен работать и на старом коде сервера.
"""
from __future__ import annotations

import re
from typing import Optional

from .observability import scrub_text

_LABEL_RU = "Заказ за близкого"
_LABEL_BA = "Яҡын кеше өсөн заказ"
# Начало комментария старого клиента → метка того же языка.
_LEGACY_PREFIXES = (
    ("Телефон близкого: ", _LABEL_RU),
    ("Яҡындың телефоны: ", _LABEL_BA),
    (_LABEL_RU + " · ", _LABEL_RU),
    (_LABEL_BA + " · ", _LABEL_BA),
)
_SEP = ". "   # так старый сайт склеивал номер и заметку
# Разделителем в номере считаем ЛЮБОЙ не-буквенный знак: кроме пробела и дефиса номер пишут
# через неразрывный пробел, тире, слэш, запятую, перевод строки — а общая мойка `scrub_text`
# знает только пробел, дефис, точку и скобки (находка ревью PR #173). Мойку здесь не трогаем:
# расширить её на всё приложение — отдельная задача со своей проверкой ложных срабатываний.
# Кусок из одних цифр и таких знаков — это ещё номер, набранный с «. » внутри («8. 917 …»).
_PHONE_ONLY = re.compile(r"[\d\W_]*\d[\d\W_]*")
# 5+ цифр подряд, между соседними — до трёх любых не-буквенных знаков.
_LONG_DIGIT_RUN = re.compile(r"\d(?:[\W_]{0,3}\d){4,}")


def strip_legacy_relative_phone(comment: Optional[str]) -> Optional[str]:
    """Комментарий старого клиента «за близкого» без номера; любой другой — как был."""
    if not comment:
        return comment
    for prefix, label in _LEGACY_PREFIXES:
        if comment.startswith(prefix):
            note = scrub_text(_note_after_phone(comment[len(prefix):])).strip()
            if not note or _LONG_DIGIT_RUN.search(note):
                return label
            return f"{label}{_SEP}{note}"
    return comment


def _note_after_phone(rest: str) -> str:
    """Всё, что после номера. Номер — до первого «. »; следующие за ним куски из одних цифр
    и знаков номера — тоже номер (иначе «8917864. 2053» оставил бы хвост «2053»)."""
    parts = rest.split(_SEP)
    i = 1
    while i < len(parts) and _PHONE_ONLY.fullmatch(parts[i]):
        i += 1
    return _SEP.join(parts[i:])
