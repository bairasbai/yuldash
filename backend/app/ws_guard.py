"""Сторож открытого веб-сокета: право читать проверяется по часам, а не по активности.

Зачем (аудит 2026-08-08, волна 141). Во всех четырёх живых каналах — чат брони, чат заказа
такси, чат посылки и трансляция координат — перепроверка права висела на счётчике
ОТПРАВЛЕННЫХ кадров: «каждое пятнадцатое сообщение сверяем токен». Для того, кто пишет, это
работало. Для того, кто ТОЛЬКО СЛУШАЕТ, не работало никогда: он не отправляет ничего, счётчик
стоит на нуле, перепроверка не наступает.

Проверено пробой на живой геолокации: пассажирка подключилась к поездке, вышла из аккаунта —
и продолжила получать координаты водителя. Ключ входа отозван, а открытый канал этого
не замечает.

Человеческая цена. «Выйти со всех устройств» — единственное, что человек может сделать, если
телефон украли или отобрали. Кнопка есть, она честно гасит ключи, но открытый канал слежки
продолжает передавать чужие координаты тому, у кого телефон в руках.

Здесь этого сторожа и ставим: раз в полминуты, независимо от того, шлёт человек что-нибудь
или молчит, проверяем — ключ ещё жив, и разговор ещё идёт. Нет — закрываем соединение.
"""
from __future__ import annotations

import asyncio
from typing import Callable, Optional

from sqlmodel import Session

from .db import engine
from .logs import log
from .security import authenticate_ws

# Как часто перепроверяем право на открытом канале. Полминуты — компромисс: «выйти со всех
# устройств» срабатывает практически сразу, а нагрузка остаётся копеечной (один короткий
# запрос на соединение в 30 секунд).
RECHECK_SEC = 30


async def watch_ws_access(
    websocket,
    token: Optional[str],
    still_allowed: Optional[Callable[[Session], bool]] = None,
    *,
    on_close: Optional[Callable[[], None]] = None,
    interval: Optional[float] = None,
) -> asyncio.Task:
    """Запустить фонового сторожа соединения. Возвращает задачу — её нужно отменить в `finally`.

    `still_allowed(session)` — проверка, специфичная для канала: поездка ещё активна, заказ
    не завершён, посылка в пути. Вернула False → закрываем. Не передали — проверяем только
    живость ключа входа.

    `on_close` — снять соединение с раздачи (обычно `manager.disconnect`). Это обязательно,
    и вот почему: основной цикл канала висит на ожидании входящего кадра, и закрытие сокета
    со стороны не будит его сразу. Пока он спит, соединение продолжает числиться подписчиком,
    и ретрансляция идёт человеку, у которого права уже нет. Поэтому сторож вычёркивает
    подписчика сам, не дожидаясь, пока цикл проснётся.
    """
    пауза = RECHECK_SEC if interval is None else interval

    async def сторож() -> None:
        while True:
            await asyncio.sleep(пауза)
            причина = None
            with Session(engine) as s:
                try:
                    authenticate_ws(token or "", s)
                except Exception:  # noqa: BLE001 — ключ отозван, истёк или аккаунта больше нет
                    причина = "Token revoked"
                else:
                    if still_allowed is not None:
                        try:
                            if not still_allowed(s):
                                причина = "Access ended"
                        except Exception as e:  # noqa: BLE001 — сбой БД не рвёт живой разговор
                            log.warning("[WS-GUARD] проверка доступа не удалась: %s", e)
            if причина is None:
                continue
            if on_close is not None:
                try:
                    on_close()          # вычёркиваем из раздачи СРАЗУ (см. док-строку)
                except Exception:  # noqa: BLE001
                    pass
            try:
                await websocket.close(code=1008, reason=причина)
            except Exception:  # noqa: BLE001 — соединение и так могло умереть
                pass
            return

    return asyncio.create_task(сторож())
