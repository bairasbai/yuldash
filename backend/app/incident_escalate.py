"""⚖️ Разбор жалобы не может зависеть от того, ответит ли обвинённый (волна 175).

Как устроен спор: человек жалуется, обвинённому уходит приглашение объясниться, дело ждёт
его версию (`awaiting_response`), и только потом попадает к человеку-разбирающему.

Право на защиту — правильная и сознательная часть протокола: односторонний разбор в райцентре,
где все знают друг друга, ломает жизнь быстрее, чем сама жалоба. Но у ожидания не было конца.

Проба: женщина пожаловалась на водителя, тот просто не отвечает — через месяц дело всё ещё
висит в «ждём объяснения». Никакой робот его не двигает, админ в очереди разбора его не видит,
«Надёжность» водителя не меняется. Молчание оказалось лучшей стратегией для того, на кого
пожаловались, а заявительница ждёт разбора, которого не будет.

Теперь у ожидания есть срок. Дело, где обвинённый молчит дольше `RESPONSE_DAYS`, само уходит
к человеку — с пометкой, что версия второй стороны не поступила. Право на защиту при этом
не отнимается: ответить можно и на разборе (`under_review` открыт для объяснений), просто
теперь молчание больше не останавливает дело.

Живёт рядом с зимним протоколом и эскалацией непринятого SOS, в общем ночном роботе
(`taxi_worker.run_once`): то, от чего зависит справедливость, не должно зависеть от того,
открыл ли кто-то экран.
"""
from __future__ import annotations

import logging
from datetime import timedelta

from sqlmodel import Session, select

from .models import Incident
from .timeutil import utcnow

log = logging.getLogger("yuldash")

#: Сколько ждём версию обвинённого. Три дня — человек успевает увидеть уведомление, подумать
#: и написать спокойно, даже если он в дороге или в вахте. Больше — заявитель начинает думать,
#: что его жалобу просто выбросили.
RESPONSE_DAYS = 3


def escalate_silent_incidents(session: Session, dry_run: bool = False) -> list:
    """Дела, где обвинённый молчит дольше срока, отправить на разбор человеком.

    Возврат: id дел, которых коснулись (для лога и тестов).
    """
    порог = utcnow() - timedelta(days=RESPONSE_DAYS)
    молчащие = session.exec(
        select(Incident).where(
            Incident.status == "awaiting_response",
            Incident.created_at <= порог,
        )
    ).all()
    тронутые = []
    for inc in молчащие:
        тронутые.append(inc.id)
        if dry_run:
            continue
        inc.status = "under_review"
        session.add(inc)
        session.commit()
        # Обе стороны должны понимать, что происходит: заявитель — что его услышали,
        # обвинённый — что молчание не закрыло вопрос и высказаться ещё можно.
        try:
            from .services import push_notification
            push_notification(
                session, inc.reporter_id, "safety",
                "Разбор начался", "Тикшереү башланды",
                "Вторая сторона не ответила за три дня — дело ушло на разбор к человеку.",
                "Икенсе яҡ өс көн эсендә яуап бирмәне — эш кеше ҡарауына китте.",
                ref_kind="incident", ref_id=inc.id,
            )
            push_notification(
                session, inc.respondent_id, "safety",
                "Дело ушло на разбор", "Эш ҡарауға китте",
                "Твоя версия не поступила за три дня. Разбор начался, но объясниться "
                "ещё можно — это учтут.",
                "Һинең версияң өс көн эсендә килмәне. Тикшереү башланды, әммә аңлатырға "
                "әле мөмкин — быны иҫәпкә алалар.",
                ref_kind="incident", ref_id=inc.id,
            )
        except Exception as e:  # noqa: BLE001 — уведомление вторично, дело уже двинулось
            log.warning(f"[incident_escalate] push failed inc={inc.id}: {e}")
    if тронутые:
        log.info(f"[incident_escalate] на разбор ушло дел: {len(тронутые)}")
    return тронутые
