"""«В поездке что-то сменилось» — будит живой канал координат раньше, чем подойдёт перепроверка по часам.

Зачем. Пока поездка не началась, канал `/ws/trip/{id}/location` точку никому не пересылает
(`visibility.trip_is_live`) и спрашивает базу «пора ли уже?». Раньше — на КАЖДЫЙ кадр: экран
поездки открывают заранее, кадры идут раз в 5–10 секунд, и у каждого открытого экрана это два
запроса к базе в каждый такт, часами, ради ответа «ещё нет». Теперь «ещё нет» запоминается на
`location.PRE_TRIP_RECHECK_SEC` (30 с).

Цена такой экономии — «Выехал». Водитель нажал кнопку, пассажир получил пуш и открыл карту, а
точка машины появилась бы только на следующей перепроверке. Чтобы мгновенность не пропала, ручка
«Выехал / Подъезжаю» после commit зовёт `poke(booking_id)`, а канал, прежде чем пропустить кадр
«по запомненному», спрашивает `poked_since`: толкали ли с момента последней проверки.

Воркеров несколько (`--workers 2`, gunicorn), а водитель и пассажир сидят на разных. Поэтому
толчок пишется и в память процесса, и в Redis (если он есть): так его видит любой воркер.
Без Redis толчок виден только своему процессу, остальные узнают самое позднее на перепроверке.

Главное свойство, ради которого это безопасно для приватности: толчок только ПРИБЛИЖАЕТ
перепроверку. Решение «показывать ли точку» по-прежнему принимает база (`trip_is_live`), а не
сам толчок. Потерянный или опоздавший толчок = задержка до 30 с, но никогда не показ раньше
времени. Поэтому и сбои Redis здесь молча глотаются.
"""
from __future__ import annotations

import time

# Сколько толчок живёт в Redis. Он нужен каналу, пока тот не перепроверит базу сам (≤ 30 с),
# так что двух минут с большим запасом.
_TTL_SEC = 120
# Чтобы словарь процесса не рос бесконечно: дойдя до этого размера, выбрасываем протухшие.
_PRUNE_AT = 2000

_local: dict[int, float] = {}


def _key(booking_id: int) -> str:
    return f"tripwake:{booking_id}"


def _redis():
    # Тот же клиент, что у presence и live-позиции (в тестах — подмена на fakeredis).
    from .instant_service import _redis as shared_redis
    return shared_redis()


def poke(booking_id: int) -> None:
    """Сообщить каналу: состояние поездки сменилось. Звать ПОСЛЕ commit. Никогда не бросает."""
    now = time.time()
    if len(_local) >= _PRUNE_AT:
        for k, t in list(_local.items()):
            if now - t > _TTL_SEC:
                _local.pop(k, None)
    _local[booking_id] = now
    try:
        r = _redis()
        if r is not None:
            r.set(_key(booking_id), repr(now), ex=_TTL_SEC)
    except Exception:  # noqa: BLE001 — Redis здесь лишь ускоритель, решает база
        pass


def poked_since(booking_id: int, since: float) -> bool:
    """Толкали ли эту бронь с момента `since` (стенные часы, `time.time()`).

    `>=`, а не `>`: на грубых часах (Windows) толчок и проверка могут попасть в один тик.
    Лишняя перепроверка стоит один запрос, пропущенная — задержки «Выехал».
    """
    t = _local.get(booking_id)
    if t is not None and t >= since:
        return True
    try:
        r = _redis()
        if r is not None:
            v = r.get(_key(booking_id))
            return v is not None and float(v) >= since
    except Exception:  # noqa: BLE001
        pass
    return False
