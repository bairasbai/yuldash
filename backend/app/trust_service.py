def record_login_consents(session: Session, user_id: int) -> None:
    """Согласия, которые человек даёт САМИМ ФАКТОМ входа (разбор №2, 2026-08-03).

    На экране входа написано «Входя, ты подтверждаешь, что тебе есть 18 лет, и принимаешь
    оферту и политику» — но раньше это оставалось надписью: в базе следа не было, и на запрос
    «покажите согласие такого-то» ответить было нечем. Реестр `Consent` существовал, а писался
    только вручную из настроек — то есть у 99 % пользователей был пуст.

    Пишем три факта с датой: оферта, политика, совершеннолетие. Идемпотентно — время ПЕРВОГО
    согласия не перезаписываем, это и есть доказательство. Отдельной галочки не добавляем
    сознательно: лишний тап на входе стоит дороже, чем даёт, а юридически значим факт
    ознакомления с текстом, который на экране виден рядом с кнопкой.
    """
    for kind in ("offer", "privacy", "age18"):
        try:
            record_consent(session, user_id, kind)
        except Exception:  # noqa: BLE001
            # Вход важнее записи. Сбой на этом шаге отдал бы 500 уже ПОСЛЕ того, как одноразовый
            # код сожжён, — человеку пришлось бы заказывать новый SMS и гадать, что случилось.
            # То же правило, что у журнала отказов: побочная запись не ломает главное действие.
            session.rollback()


INSIDER_LEVEL = 3   # «свой» — дарованный уровень при активации инвайта
MIN_INVITER_LEVEL = 2  # приглашать в круг может только проверенный (L2+)


def base_level(user: User) -> int:
    """Уровень, вычисляемый из данных профиля (без учёта дарованного статуса «свой»)."""
    lvl = 0                                                # L0: телефон (есть у любого авторизованного)
    if (user.name or "").strip() and (user.avatar_url or "").strip():
        lvl = max(lvl, 1)                                  # L1: имя + фото
    if user.verified:
        lvl = max(lvl, 2)                                  # L2: документы проверены (модерация)
    return lvl


def get_trust_row(session: Session, user_id: int) -> Optional[Trust]:
    return session.exec(select(Trust).where(Trust.user_id == user_id)).first()


def trust_level(session: Session, user: Optional[User]) -> int:
    """Итоговый уровень доверия пользователя (0..3). Аноним (None) → 0.

    Дарованный статус «свой» ЗАМОРАЖИВАЕТСЯ на время паузы «Справедливости» (§2). Круг своих —
    это про доверие, а пауза и есть заявление, что доверие сейчас под вопросом: пока идёт
    разбор, закрытые поездки человек не видит и в круг никого не приводит. Наказание кончилось —
    статус возвращается сам, отбирать его навсегда мы не хотим (аудит 2026-08-12, волна 56).

    Базовый уровень (имя, фото, проверенные документы) не трогаем: он про заполненность
    профиля, а не про доверие круга, и обнулять его наказанием было бы враньём о фактах.
    """
    if user is None:
        return 0
    granted = 0
    row = get_trust_row(session, user.id)
    if row:
        granted = row.level
    if granted > 0:
        from .safety_logic import account_paused   # локальный импорт: safety_logic тянет services
        if account_paused(session, user.id):
            granted = 0
    return max(base_level(user), granted)


def can_invite(session: Session, user: User) -> bool:
    """Может ли человек звать в круг «своих».

    Одно место на оба входа — выпуск кода и его активация новичком. Проверка была только
    на уровне («L2+»), и её обходил тот, кому статус ДАРОВАН: разжалованный участник оставался
    L3 сам и продолжал плодить новых «своих» — проверено запросом, цепочка росла от человека,
    которому платформа уже не доверяет (аудит 2026-08-12, волна 56).

    Код, выпущенный ДО наказания, тоже перестаёт работать: иначе достаточно раздать коды
    заранее. Поэтому проверяем не только выпуск, но и момент активации.

    Паузу спрашиваем ОТДЕЛЬНО, а не через уровень: у водителя базовый уровень L2 берётся
    из проверенных документов, и одного заморозенного «своего» мало — проверенный документами
    нарушитель продолжал бы звать людей в круг, пока идёт разбор.
    """
    from .safety_logic import account_paused   # локальный импорт: safety_logic тянет services
    if account_paused(session, user.id):
        return False
    return trust_level(session, user) >= MIN_INVITER_LEVEL


