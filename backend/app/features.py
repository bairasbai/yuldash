"""Выключатели направлений — запуск волнами (решение Александра, 13.10.2026).

Волна 1 — только попутки: поиск, бронь, поездка, оценка, вход, «поделиться поездкой
с близким», админка. Такси, курьеры, посылки, реклама и купоны бизнеса написаны, но
включаются по одному — когда готовы документы (закон о такси, маркировка рекламы, касса,
договоры курьеров). Включение — переменной окружения и перезапуском сервера, приложение
при этом обновлять не нужно.

Здесь две вещи:
  • `features_state()` — что включено сейчас. Отдаётся публичной ручкой GET /config/features,
    по ней приложение и сайт решают, показывать вход в направление или «Скоро в Юлдаше».
    Только флаги: ни личных данных, ни городов, ни цен.
  • `guard_*()` — серверный замок на НОВЫХ дверях направления. Экран кнопку не покажет, но
    сервер обязан отказать сам: старая версия приложения и прямой запрос экраном не являются.

Такси и курьер свои замки уже имеют (app/taxi.py, routers/courier.py) — здесь только их
флаги в общей сводке, чтобы клиенту хватало одного запроса.

Попутки не выключаются никогда: это сердце Юлдаша, флага у них нет намеренно.
"""
from __future__ import annotations

from .config import settings
from .errors import herr

# Тексты отказа — оба языка (башкирский — черновик, финал за Александром, docs/tasks.md).
# Тон тот же, что у такси: не «запрещено», а «скоро, а пока — попутка».
MSG_PARCELS_OFF = (
    "Посылки в Юлдаше скоро запустятся! А пока поезжай попуткой 🚗",
    "Юлдашта бандеролдәр тиҙҙән асыла! Ә әлегә юлдаш булып бар 🚗",
)
MSG_ADS_OFF = (
    "Реклама в Юлдаше скоро откроется 📣",
    "Юлдашта реклама тиҙҙән асыла 📣",
)
MSG_BUSINESS_OFF = (
    "«Скидки по пути» скоро откроются. А пока поезжай попуткой 🚗",
    "«Юл буйынса ташламалар» тиҙҙән асыла. Ә әлегә юлдаш булып бар 🚗",
)


def features_state() -> dict:
    """Что включено прямо сейчас. Ключи постоянные — на них завязаны клиенты.

    `rides` всегда True: попутки не выключаются. Остальные — ровно флаги из настроек,
    без городов (такси по городам уточняет /instant/availability)."""
    return {
        "rides": True,
        "taxi": bool(settings.taxi_enabled),
        "courier": bool(settings.courier_enabled),
        "parcels": bool(settings.parcels_enabled),
        "ads": bool(settings.ads_enabled),
        "business": bool(settings.business_enabled),
    }


def guard_parcels() -> None:
    """Посылки «по пути» выключены → новая посылка, лента «возьму» и приём — «скоро»."""
    if not settings.parcels_enabled:
        raise herr(403, *MSG_PARCELS_OFF)


def guard_ads() -> None:
    """Реклама выключена → новое объявление, отправка на модерацию, оплата, продление — «скоро»."""
    if not settings.ads_enabled:
        raise herr(403, *MSG_ADS_OFF)


def guard_business() -> None:
    """«Скидки по пути» выключены → регистрация бизнеса, подписка, новый купон, взять купон — «скоро»."""
    if not settings.business_enabled:
        raise herr(403, *MSG_BUSINESS_OFF)
