def test_ручная_правка_админа_не_ложится_в_промо(client, user_factory):
    """Обратная сторона и корень проблемы: `adj` — кухонный ящик, а не «промо».

    Админ доплатил человеку руками (извинился за сбой, вернул за отменённую поездку) —
    это не рекламный бюджет. Строка промо не должна расти от такого никогда.
    """
    админ = user_factory("СверкаАдмин5", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель5", role=UserRole.driver)

    было = _сверка(client, админ)
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=водитель["id"], kind=LedgerKind.adj, amount_kop=20000,
                          ext_id="", note="Извинение за сбой, доплата вручную"))
        s.commit()
    стало = _сверка(client, админ)

    assert стало["promo_comp_kop"] == было["promo_comp_kop"], (
        f"ручная доплата админа 200 ₽ легла в «расход на промо-кампании»: строка растёт "
        "от всего, что попало в кошелёк с плюсом"
    )


def test_отрицательная_правка_не_ломает_отчёт(client, user_factory):
    """Обратная сторона: `adj` бывает и со знаком минус — отчёт не должен его учитывать
    как расход на промо (это возврат денег платформе, а не выплата)."""
    админ = user_factory("СверкаАдмин6", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель6", role=UserRole.driver)

    было = _сверка(client, админ)
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=водитель["id"], kind=LedgerKind.adj, amount_kop=-20000,
                          ext_id="", note="Сняли ошибочно начисленное"))
        s.commit()
    стало = _сверка(client, админ)

    assert стало["promo_comp_kop"] == было["promo_comp_kop"]
    assert стало["platform_net_kop"] == было["platform_net_kop"]


# ---------------------------------------------------------------------------
# Разбор мутаций: проба следила за строкой промо и почти не следила за остальными.
#
# Три мутации прошли мимо: ручные доплаты админа исчезали из отчёта совсем, в «возврат»
# попадали минусовые правки, и ключ проверялся подстрокой вместо начала строки.
# ---------------------------------------------------------------------------
def _отдал_платформа(о: dict) -> int:
    """Сколько платформа отдала за период — по всем трём строкам расхода."""
    return о["promo_comp_kop"] + о["refund_kop"] + о["adj_other_kop"]


def test_ручная_доплата_видна_хотя_бы_где_то(client, user_factory):
    """Договор: убрать доплату из «промо» — не значит убрать её из отчёта.

    Это настоящие деньги платформы. Если они не попадают ни в одну строку, отчёт показывает
    доход выше настоящего и молчит о том, куда делась разница, — ровно та беда, ради которой
    волна 153 и заводила строку расхода.
    """
    админ = user_factory("СверкаАдмин7", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель7", role=UserRole.driver)

    было = _сверка(client, админ)
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=водитель["id"], kind=LedgerKind.adj, amount_kop=20000,
                          ext_id="", note="Извинение за сбой, доплата вручную"))
        s.commit()
    стало = _сверка(client, админ)

    assert _отдал_платформа(стало) - _отдал_платформа(было) == 20000, (
        "ручная доплата 200 ₽ не попала НИ В ОДНУ строку расхода: деньги ушли, а отчёт "
        "об этом молчит"
    )
    assert стало["platform_net_kop"] - было["platform_net_kop"] == -20000, (
        "итог платформы не уменьшился на отданные деньги"
    )


def test_минусовая_правка_с_ключом_возврата_не_уменьшает_расход(client, user_factory):
    """Договор: строка расхода считает то, что ОТДАЛИ, а не сальдо.

    Если админ отменит ошибочный возврат минусовой правкой с тем же ключом, строка «возвращено»
    не должна уменьшиться задним числом: за период платформа эти деньги отдавала, и отчёт
    о периоде обязан это показать. Сальдо видно по балансу, а не по строке расхода.
    """
    админ = user_factory("СверкаАдмин8", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель8", role=UserRole.driver)

    было = _сверка(client, админ)
    _возврат(водитель["id"], 5000, parcel_id=777008)
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=водитель["id"], kind=LedgerKind.adj, amount_kop=-5000,
                          ext_id="refund:parcel:777008:отмена", note="Отмена ошибочного возврата"))
        s.commit()
    стало = _сверка(client, админ)

    assert стало["refund_kop"] - было["refund_kop"] == 5000, (
        f"строка «возвращено» изменилась на {(стало['refund_kop'] - было['refund_kop']) / 100:.0f} ₽ "
        "вместо 50 ₽: минусовая правка вычлась из расхода, и отчёт за период стал неверным"
    )


def test_ключ_читаем_с_начала_а_не_подстрокой(client, user_factory):
    """Договор: `ext_id` — именованный ключ, и читать его надо с начала.

    Ключи растут: сегодня `promo:` и `refund:order:`, завтра появится новый вид доплаты.
    Если сравнивать подстрокой, любой будущий ключ, в названии которого просто встретилось
    слово, молча уедет в чужую строку — и отчёт начнёт врать без единой правки в этом коде.
    """
    админ = user_factory("СверкаАдмин9", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель9", role=UserRole.driver)

    было = _сверка(client, админ)
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=водитель["id"], kind=LedgerKind.adj, amount_kop=7000,
                          ext_id="bonus-promo:42", note="Бонус за пятьдесят поездок"))
        s.commit()
    стало = _сверка(client, админ)

    assert стало["promo_comp_kop"] == было["promo_comp_kop"], (
        "ключ `bonus-promo:42` уехал в расход на промо-кампании: сравнение идёт подстрокой, "
        "и любой будущий ключ со словом «promo» внутри будет считаться маркетингом"
    )
    assert стало["adj_other_kop"] - было["adj_other_kop"] == 7000, (
        "незнакомый ключ не попал в «прочие доплаты» — деньги пропали из отчёта"
    )
