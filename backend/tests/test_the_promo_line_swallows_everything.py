"""Строка «расход на промо» в денежном отчёте считает всё подряд (волна 217).

Волна 153 завела в сверке `/admin/ledger/reconcile` отдельную строку `promo_comp_kop`
с прямым доводом: «единственный денежный отчёт показывал доход и молчал про расход:
кампания „300 ₽ каждому“ выглядела по нему бесплатной, хотя каждую скидку оплачиваем мы».
Отсюда же считается итог: `platform_net_kop = fee_kop − promo_comp_kop`.

Считается эта строка **по знаку**, а не по смыслу:

    promo_comp_kop = sum(a for a in adj_rows if a > 0)

`adj` — это «ручная корректировка (+/−)», кухонный ящик кошелька. Туда падает всё, что
не начисление, не комиссия и не выплата. Значит в «расход на промо-кампании» с самого начала
попадала любая ручная доплата админа.

**Волна 215 сделала это регулярным.** Возврат уже уплаченной комиссии за поездку, по которой
человеку не заплатили, кладётся в кошелёк записью `adj` с плюсом — и попадает в строку промо.

Что это значит для Александра. Он читает отчёт, чтобы решить: окупается ли кампания. Месяц
с обычным числом споров «пассажир не заплатил» покажет ему раздутый расход на промо — и он
свернёт кампанию, которая на самом деле работает. Или наоборот, увидев рост «расхода
на промо», пойдёт искать причину в маркетинге, а причина в мошенничестве пассажиров.

Возврат — тоже расход платформы, и прятать его не надо. Но это **другой** расход: у промо
он про маркетинг, у возврата — про потери от неплатежей. Их надо видеть порознь, иначе
ни одно из двух решений не принять.

Отдельно важно: у обеих записей есть точный признак — `ext_id` (`promo:{id}` против
`refund:order:{id}`). Различать по знаку, когда есть ключ, — и есть корень.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

from app import debt as debt_mod
from app.db import engine
from app.ledger import post_promo_compensation
from app.models import LedgerEntry, LedgerKind, UserRole

from test_ledger import _make_done_order


@pytest.fixture(autouse=True)
def _тихо(monkeypatch):
    monkeypatch.setattr("app.services.send_push", lambda *a, **k: None)


def _промо(водитель_id: int, пассажир_id: int, сумма_коп: int) -> None:
    """Компенсация промо-скидки — так, как её кладёт живой код (нужен настоящий заказ)."""
    oid = _make_done_order(водитель_id, пассажир_id, price_rub=500)
    with Session(engine) as s:
        запись = post_promo_compensation(s, водитель_id, order_id=oid, amount_kop=сумма_коп)
    # Компенсация идемпотентна по `ext_id`. Если ключ уже занят (например, чужой тест засеял
    # `promo:{этот id}` руками), функция молча вернёт ЧУЖУЮ запись, а тест станет слепым:
    # прирост окажется нулевым, и он покраснеет по неверной причине.
    assert запись is not None and запись.amount_kop == сумма_коп, (
        f"компенсация не создалась: ключ promo:{oid} уже занят — тест слеп"
    )


def _возврат(водитель_id: int, сумма_коп: int, parcel_id: int) -> None:
    """Возврат комиссии за доставку — как его кладёт волна 215 (заказа такси тут нет)."""
    with Session(engine) as s:
        debt_mod.refund_commission_to_wallet(s, водитель_id, сумма_коп, parcel_id=parcel_id)
        s.commit()


def _сверка(client, админ) -> dict:
    ответ = client.get("/admin/ledger/reconcile", headers=админ["auth"], params={"days": 366})
    assert ответ.status_code == 200, ответ.text
    return ответ.json()


def test_возврат_комиссии_не_считается_расходом_на_промо(client, user_factory):
    """Главное: по этому числу Александр решает судьбу рекламной кампании."""
    админ = user_factory("СверкаАдмин", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель", role=UserRole.driver)

    было = _сверка(client, админ)

    пассажир = user_factory("СверкаПассажир")
    _промо(водитель["id"], пассажир["id"], 30000)      # 300 ₽ компенсации промо-скидки
    _возврат(водитель["id"], 5000, parcel_id=777002)   # 50 ₽ возврата комиссии

    стало = _сверка(client, админ)
    прирост = стало["promo_comp_kop"] - было["promo_comp_kop"]

    assert прирост == 30000, (
        f"в «расход на промо» попало {прирост / 100:.0f} ₽ вместо 300 ₽: туда затесался "
        "возврат комиссии за поездку, по которой пассажир не заплатил. По этому числу "
        "решают, окупается ли кампания, — и решат неверно"
    )


def test_возврат_виден_отдельной_строкой(client, user_factory):
    """Прятать возврат нельзя: это настоящие деньги платформы, просто расход другого рода.

    Промо — про маркетинг, возврат — про потери от неплатежей. Оба нужны, но порознь.
    """
    админ = user_factory("СверкаАдмин2", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель2", role=UserRole.driver)

    было = _сверка(client, админ)
    _возврат(водитель["id"], 5000, parcel_id=777003)
    стало = _сверка(client, админ)

    assert "refund_kop" in стало, (
        "возврат комиссии нигде в отчёте не виден: платформа отдала деньги, а отчёт молчит"
    )
    assert стало["refund_kop"] - было.get("refund_kop", 0) == 5000


def test_итог_платформы_учитывает_оба_расхода(client, user_factory):
    """Итоговая строка обязана вычесть ОБА расхода, а не один из них.

    Если возврат просто убрать из промо и никуда не добавить, «доход платформы» вырастет
    на ровно те деньги, которые платформа отдала.
    """
    админ = user_factory("СверкаАдмин3", role=UserRole.admin)
    водитель = user_factory("СверкаВодитель3", role=UserRole.driver)

    было = _сверка(client, админ)
    пассажир = user_factory("СверкаПассажир3")
    _промо(водитель["id"], пассажир["id"], 10000)
    _возврат(водитель["id"], 5000, parcel_id=777005)
    стало = _сверка(client, админ)

    assert стало["platform_net_kop"] - было["platform_net_kop"] == -15000, (
        f"итог платформы изменился на "
        f"{(стало['platform_net_kop'] - было['platform_net_kop']) / 100:.0f} ₽ вместо −150 ₽: "
        "платформа отдала 100 ₽ по промо и 50 ₽ возвратом, а в итоге это не отражено"
    )


