"""Сборка не должна мочь больше, чем ей нужно, а ключи — попадать в git.

Четвёртый заход не в код приложения: проверяется то, чем код собирается и подписывается.

**Права токена сборки.** У прогона CI не было блока `permissions`, а GitHub в этом случае
выдаёт права по умолчанию — у старых репозиториев это «чтение и запись». То есть любой шаг
сборки мог писать в репозиторий, ставить теги и публиковать релизы (аудит 2026-08-08,
волна 132).

Сборке Юлдаша ничего этого не нужно: она гоняет тесты и собирает APK. Но в ней используются
чужие действия (`setup-python`, `setup-java`, `setup-android`, `upload-artifact`), и если
однажды взломают хотя бы одно — а в мире это случалось не раз, — оно получит ровно те права,
которые мы дали. Теперь это «прочитать код».

**Ключ подписи приложения.** Проверено отдельно и оказалось в порядке: `yuldash.jks`
и `keystore.properties` лежат в рабочей папке, но в git не попадали никогда — ни в индексе,
ни в истории. Оба в `.gitignore`.

Это важнее, чем кажется: ключом подписывается приложение в Google Play. Утёкший ключ означает,
что чужой человек может выпустить «обновление Юлдаша», и телефоны примут его как наше — сменить
ключ у опубликованного приложения нельзя. Поэтому здесь стоит сторож: если кто-нибудь однажды
уберёт строку из `.gitignore` или добавит ключ принудительно, тест покраснеет.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
CI = ROOT / ".github" / "workflows" / "ci.yml"


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout


def test_у_сборки_только_право_читать_код():
    """Главное: взломанное чужое действие не должно получить право писать в репозиторий."""
    src = CI.read_text(encoding="utf-8")

    assert "permissions:" in src, (
        "у прогона сборки нет блока permissions — GitHub выдаст права по умолчанию, "
        "а это может быть «чтение и запись» на весь репозиторий"
    )
    блок = src[src.index("permissions:"):]
    блок = блок[: блок.index("\n\n") if "\n\n" in блок else 200]
    assert "contents: read" in блок, f"права шире, чем нужно сборке: {блок.strip()[:120]}"
    for опасное in ("write-all", "contents: write", "packages: write", "id-token: write"):
        assert опасное not in блок, f"сборке дано право «{опасное}», которое ей не нужно"


def test_сборка_запускается_не_из_чужих_форков_с_секретами():
    """`pull_request_target` даёт чужому коду доступ к секретам репозитория."""
    src = CI.read_text(encoding="utf-8")

    assert "pull_request_target" not in src, (
        "используется pull_request_target: код из чужого форка выполнится с нашими секретами"
    )


def test_ключ_подписи_приложения_не_в_git():
    """Утёкший ключ = чужой человек выпускает «обновление Юлдаша», и телефоны его примут."""
    отслеживаемые = _git("ls-files")
    подозрительные = [
        ln for ln in отслеживаемые.splitlines()
        if ln.endswith((".jks", ".keystore")) or ln.endswith("keystore.properties")
    ]

    assert not подозрительные, (
        f"ключ подписи приложения отслеживается в git: {подозрительные}. Сменить ключ "
        "у опубликованного в Google Play приложения НЕЛЬЗЯ — только выпускать новое"
    )


@pytest.mark.parametrize("путь", ["android/yuldash.jks", "android/keystore.properties"])
def test_ключ_подписи_не_попадал_в_историю(путь: str):
    """В git история вечна: один раз закоммитил — лежит навсегда, даже если потом удалил."""
    история = _git("log", "--all", "--oneline", "--", путь).strip()

    assert not история, (
        f"{путь} есть в истории git: {история.splitlines()[:2]}. Файл придётся считать "
        "скомпрометированным и выпускать новый ключ"
    )


@pytest.mark.parametrize("путь", ["android/yuldash.jks", "android/keystore.properties"])
def test_ключ_подписи_под_защитой_gitignore(путь: str):
    """Обратная сторона: файл должен быть закрыт ДО того, как кто-то наберёт `git add .`."""
    файл = ROOT / путь
    if not файл.exists():
        pytest.skip(f"{путь} нет в этой рабочей копии — проверять нечего")

    проверка = subprocess.run(["git", "check-ignore", "-v", путь],
                              cwd=ROOT, capture_output=True, text=True)

    assert проверка.returncode == 0, (
        f"{путь} НЕ игнорируется git: одна команда `git add .` — и ключ подписи уедет "
        "в репозиторий навсегда"
    )
