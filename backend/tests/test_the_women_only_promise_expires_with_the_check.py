"""Отметка «только женщины» переживала проверку, на которой держалась (волна 219).

Поставить поездке отметку «только женщины» может лишь подтверждённая женщина за рулём —
это закрыли волной 168. Тем же правилом живёт и фильтр в ленте: он каждый раз перепроверяет
`gender_verified` и не показывает поездку, если подтверждения больше нет.

А сама отметка лежит в базе поездки и никем не перечитывается. Подтверждение сгорает
в двух случаях, и оба обычные: модератор отклонил документы (`set_driver_docs_verdict`)
или человек переписал пол в профиле (`set_user_gender`). Поездка при этом остаётся
активной — отклонённые документы не снимают водителя с линии, это бейдж доверия,
а не допуск.

Что видит человек. Женщина листает ОБЩУЮ ленту Баймак → Сибай, без фильтров, и видит
карточку с надписью «Только женщины». Она выбирает её именно из-за надписи. Фильтр
такую поездку уже спрятал — но лента без фильтра, ссылка из чата и открытый экран
фильтр обходят. Обещание на карточке осталось, проверка под ним сгорела.

Правило одно на весь проект и живёт в `safety_logic`: отметка ДЕЙСТВУЕТ, только пока
за рулём подтверждённая женщина. Витрина поездки спрашивает у него же, у кого спрашивают
бейдж «женщина за рулём» и фильтр ленты.
"""
from __future__ import annotations

from datetime import timedelta

from sqlmodel import Session, select

from app.db import engine
from app.models import DriverProfile, Ride, User, UserRole
from app.timeutil import utcnow


def _подтверждённая_женщина(client, user_factory, метка: str):
    """Женщина за рулём, чей пол модератор сверил с фото прав."""
    водитель = user_factory(метка, role=UserRole.driver)
    админ = user_factory(f"{метка}Модератор", role=UserRole.admin)
    client.post("/driver/gender", headers=водитель["auth"], json={"gender": "female"})
    ответ = client.post(f"/admin/drivers/{водитель['id']}/moderate", headers=админ["auth"],
                        json={"approve": True, "gender_verified": True})
    assert ответ.json()["gender_verified"] is True, "подготовка: подтверждение не включилось"
    return водитель, админ


def _опубликовать_женскую(client, водитель):
    ответ = client.post("/rides", headers=водитель["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "depart_at": (utcnow() + timedelta(days=1)).replace(microsecond=0).isoformat(),
        "seats_total": 3, "price": 300, "comment": "по трассе",
        "women_only": True,
    })
    assert ответ.status_code == 200, f"подготовка: поездка не опубликовалась — {ответ.text[:200]}"
    return ответ.json()["id"]


def _карточка_в_ленте(client, ride_id: int):
    """Ровно то, что видит пассажирка в ОБЩЕЙ ленте — без фильтра «только женщины»."""
    лента = client.get("/rides", params={"from_city": "Баймак"}).json()
    свои = [r for r in лента if r["id"] == ride_id]
    return свои[0] if свои else None


def test_отклонили_документы_отметка_перестаёт_обещать(client, user_factory):
    """Главное: обещание не переживает проверку, на которой держалось."""
    водитель, админ = _подтверждённая_женщина(client, user_factory, "ЖенщинаЗаРулём")
    ride_id = _опубликовать_женскую(client, водитель)

    # Модератор пересмотрел документы и отклонил: подтверждение пола сгорает вместе с ними —
    # подтверждали его по этим самым правам.
    client.post(f"/admin/drivers/{водитель['id']}/moderate", headers=админ["auth"],
                json={"approve": False})
    with Session(engine) as s:
        профиль = s.exec(select(DriverProfile).where(
            DriverProfile.user_id == водитель["id"])).first()
        assert профиль.gender_verified is False, "подготовка: подтверждение не сгорело"
        assert s.get(Ride, ride_id).status == "active", "подготовка: поездка снялась сама"

    карточка = _карточка_в_ленте(client, ride_id)

    assert карточка is not None, "поездка исчезла из общей ленты — проба смотрит не туда"
    assert карточка["women_only"] is False, (
        "карточка в ленте по-прежнему обещает «только женщины», хотя подтверждения "
        "за рулём больше нет: женщина выберет поездку именно из-за этой надписи"
    )


def test_водитель_переписал_пол_отметка_перестаёт_обещать(client, user_factory):
    """Вторая дверь того же правила: подтверждение гасит и правка пола в профиле."""
    водитель, _ = _подтверждённая_женщина(client, user_factory, "ПередумалаЗаРулём")
