def test_обычная_поездка_проверенной_женщины_ничего_не_обещает(client, user_factory):
    """Договор: правило состоит из ДВУХ половин, и вторую тоже надо проверять.

    Мутация «правило забыло про саму отметку» (осталось только подтверждение) прошла все
    тесты насквозь. А означала она вот что: любая поездка подтверждённой женщины начинает
    показываться как «только женщины» — включая обычные, которые она публиковала для всех.
    Мужчина, увидев такую карточку, решит, что ему туда нельзя; женщина решит, что ей
    обещали женский салон, хотя водитель ничего такого не обещала.
    """
    водитель, _ = _подтверждённая_женщина(client, user_factory, "ОбычнаяПоездка")
    ответ = client.post("/rides", headers=водитель["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "depart_at": (utcnow() + timedelta(days=1)).replace(microsecond=0).isoformat(),
        "seats_total": 3, "price": 300, "comment": "по трассе",
        "women_only": False,
    })
    assert ответ.status_code == 200, f"подготовка: {ответ.text[:200]}"

    карточка = _карточка_в_ленте(client, ответ.json()["id"])

    assert карточка is not None and карточка["women_only"] is False, (
        "обычная поездка подтверждённой женщины показана как «только женщины» — "
        "водитель такого не обещала"
    )
    assert карточка["driver_is_woman"] is True, (
        "бейдж «женщина за рулём» пропал — он от отметки не зависит"
    )


def test_поездка_без_водителя_не_обещает_и_не_падает(client, user_factory):
    """Договор: правило вызывают на поездке, у которой водителя уже нет.

    Витрина берёт водителя из батча (`users.get(ride.driver_id)`), и там бывает `None` —
    аккаунт удалён (152-ФЗ, `/me/delete`). Обёртка `_women_only_in_force` проверяет это
    отдельной строкой; мутация, снявшая проверку, прошла все тесты. Она и правда
    равносильна: правило читает водителя только через `is_verified_female_driver`, а тот
    берёт оба поля через `getattr` с запасным значением, и на `None` возвращает False.

    Допущение чужое (что `gender_of` и `getattr` останутся терпимыми к `None`), поэтому
    закрепляем его тестом — а не убираем строку. Такую же строку держит соседний
    `_is_verified_female_driver`, и расходиться им нельзя.
    """
    from app.services import ride_out_with

    водитель, _ = _подтверждённая_женщина(client, user_factory, "ИсчезнувшийВодитель")
    ride_id = _опубликовать_женскую(client, водитель)

    with Session(engine) as s:
        поездка = s.get(Ride, ride_id)
        # ровно то, что отдаёт батч, когда строки водителя больше нет
        витрина = ride_out_with(поездка, users={}, profiles={}, rating_agg={}, trips_agg={})

    assert витрина.women_only is False, (
        "поездка без водителя обещает «только женщины» — проверять это обещание не у кого"
    )
    assert витрина.driver_is_woman is False, "бейдж «женщина за рулём» без водителя"


def test_бронь_мужчины_пока_остаётся_закрытой(client, user_factory):
    """Договор о ТЕКУЩЕМ поведении, а не о правильном: вопрос вынесен Александру.

    Обещание с карточки погасло, а бронь по-прежнему читает отметку прямо из базы —
    там это правило ВОДИТЕЛЯ («беру только женщин»), её выбор о своём салоне, и проверка
    документов к нему отношения не имеет. Значит мужчина упирается в отказ, которого
    на карточке уже не написано.

    Менять это молча нельзя — оба взгляда разумны (см. `docs/tasks.md`, волна 219).
    Тест держит поведение на месте, чтобы оно не уехало само, и краснеет, когда кто-то
    решит вопрос за Александра.
    """
    водитель, админ = _подтверждённая_женщина(client, user_factory, "ЗакрытаяБронь")
    ride_id = _опубликовать_женскую(client, водитель)
    client.post(f"/admin/drivers/{водитель['id']}/moderate", headers=админ["auth"],
                json={"approve": False})
    пассажир = user_factory("Пассажир", gender="male")

    ответ = client.post("/bookings", headers=пассажир["auth"],
                        json={"ride_id": ride_id, "seats": 1})

    assert ответ.status_code == 403, (
        f"поведение брони изменилось (ответ {ответ.status_code}) — это развилка продукта, "
        "её решает Александр: см. docs/tasks.md, волна 219"
    )
