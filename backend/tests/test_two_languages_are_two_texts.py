# -*- coding: utf-8 -*-
"""Два языка — это два ОТДЕЛЬНЫХ текста, а не одна строка через « · ».

Аудит 2026-08-12, волна 37. Правило записано в `docs/lessons.md` ещё в волне 20, и в записях
Центра уведомлений оно соблюдается: там честные `title_ru`/`title_ba`. А пуши БЕЗ записи —
«осталось 15 минут смены», «рядом никого», «тебе сказали рәхмәт», «совет от Юлдаша» — писались
одной строкой: «Рядом никого · Яҡында водитель юҡ».

Как это выглядит для человека с башкирским интерфейсом: приходит уведомление, где сначала
чужой язык, а свой — через точку в середине. Не «непереведено», а «мусор в сообщении».

Сторож ищет склейку по простому признаку: в одном строковом литерале есть разделитель « · »
И башкирские буквы (ә ҙ ҡ ң ө ҫ ү һ). У обычного русского текста таких букв нет, у чисто
башкирского нет русского хвоста — красным становится ровно склейка.
"""
import re
from pathlib import Path

APP = Path("app")

# Башкирские буквы, которых нет в русском алфавите.
BASHKIR_ONLY = set("әҙҡңөҫүһӘҘҠҢӨҪҮҺ")
SEPARATOR = " · "

# Места, где « · » рядом с башкирским текстом — НЕ склейка языков, а разделитель внутри
# одного текста. Причина обязательна: список должен оставаться коротким и осознанным.
ALLOWED = {
    # Публичная страница слежения открывается ЧУЖИМ браузером, и языка смотрящего мы не знаем:
    # ссылку прислали сообщением, никакого профиля у него нет. Там оба языка рядом — это
    # осознанное решение, а не забытая склейка.
    ("share.py", "живая поездка · тере сәфәр"): "публичная страница: язык смотрящего неизвестен",
    ("share.py", "Юлдаш — живая поездка · тере сәфәр"): "то же самое, заголовок вкладки",
}


def _string_literals(path: Path):
    """Строковые литералы файла (грубо, но достаточно: нам нужны тексты сообщений)."""
    src = path.read_text(encoding="utf-8")
    return re.findall(r'"([^"\n]{8,})"', src) + re.findall(r"'([^'\n]{8,})'", src)


def _looks_glued(literal: str) -> bool:
    """Склейка — это РУССКАЯ фраза, затем « · », затем башкирская.

    Важно не путать её с двумя другими, законными случаями, иначе сторож завалит прогон
    на здоровом коде и его выключат:
      • продолжение башкирского текста, которое само начинается с « · » (второй аргумент
        уже разделён по языкам, разделитель просто попал в начало строки);
      • разделитель ВНУТРИ одного текста: «{route} · курьер оҙаҡ бәйләнешкә сыҡманы» —
        слева подстановка маршрута, а не русская фраза.
    """
    head, _, tail = literal.partition(SEPARATOR)
    russian_words = len(re.findall(r"[А-Яа-яЁё]", head)) >= 3
    head_is_bashkir = bool(set(head) & BASHKIR_ONLY)
    tail_is_bashkir = bool(set(tail) & BASHKIR_ONLY)
    return russian_words and not head_is_bashkir and tail_is_bashkir


def _glued(path: Path):
    out = []
    for literal in _string_literals(path):
        if SEPARATOR not in literal or not _looks_glued(literal):
            continue
        if (path.name, literal[:40]) in ALLOWED:
            continue
        out.append(literal)
    return out


def test_в_текстах_сервера_нет_склейки_двух_языков():
    offenders = {}
    for path in sorted(APP.rglob("*.py")):
        glued = _glued(path)
        if glued:
            offenders[str(path)] = glued

    assert offenders == {}, (
        "здесь два языка склеены в одну строку через « · » — человек с башкирским интерфейсом "
        f"получит сообщение с мусором: {offenders}. Разведи на два текста: для уведомлений "
        "с записью — push_notification(title_ru, title_ba, body_ru, body_ba), для мгновенных "
        "пушей — services.push_bilingual(...)."
    )


def test_сторож_видит_саму_склейку():
    """Проверка проверки: искусственная склейка обязана распознаваться."""
    fake = "Рядом никого · Яҡында водитель юҡ"
    assert SEPARATOR in fake and (set(fake) & BASHKIR_ONLY)


def test_обычный_русский_текст_с_точкой_не_считается_склейкой():
    """Разделитель внутри одного языка — нормальная типографика, ложных тревог быть не должно."""
    fake = "Баймак → Сибай · чистыми 450 ₽"
    assert not (set(fake) & BASHKIR_ONLY)
