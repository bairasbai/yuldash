# -*- coding: utf-8 -*-
"""Ночной рейс без связи обнуляется полуночью (волна 211).

Восьмичасовой лимит смены чинили дважды, и обе починки правильные — но они не встретились
на одном шве.

* **Волна 54** отвязала смену от календарных суток: если между работой не было настоящего
  отдыха, вчерашний хвост тянется в сегодняшний счётчик. Иначе водитель работал 7:48
  до полуночи, в 00:01 получал новые восемь часов и был за рулём шестнадцать подряд.
* **Волна 171** заменила прибор измерения: «сегодня» — это БОЛЬШЕЕ из двух измерений,
  сколько человек был на линии по сигналам присутствия и сколько фактически вёз людей
  по самим заказам. Потому что у сигнала присутствия стоит потолок, и час на трассе
  без сотовой сети засчитывался как одна минута.

Хвост через полночь остался на СТАРОМ приборе — он тянет только `seconds_online`:

    return int(prev.seconds_online or 0)      # присутствие, и только оно

Отсюда дыра ровно того размера, который волна 171 закрывала внутри дня. Водитель везёт
пассажира с 21:00 до полуночи по трассе Сибай–Акъяр, где сети нет. Заказ в базе есть
и говорит «три часа за рулём». Сигналов присутствия почти не было — потолок записал минуты.
В 00:01 хвост подтягивает эти минуты вместо трёх часов, и человек получает почти полные
новые восемь. За рулём он будет одиннадцать, а сервис насчитает восемь.

Это тот же ночной рейс между сёлами, ради которого волна 171 и писалась. Просто он выехал
на час раньше и пересёк полночь.
"""
from __future__ import annotations

from datetime import datetime, time, timedelta

import pytest
from sqlmodel import Session, select

from app import workday as wd_mod
from app.config import settings
from app.db import engine
from app.models import InstantOrder, InstantOrderStatus, TaxiWorkDay, UserRole


def _utc(местное: datetime) -> datetime:
    """Местное время (Уфа) → наивный UTC, как хранится в базе."""
    return местное - timedelta(hours=settings.local_tz_offset_hours)


@pytest.fixture
def таксист(client, user_factory, request):
    """Свой водитель на каждый тест: база общая, чужие рейсы копились бы между ними."""
    return user_factory(f"НочнойРейс{abs(hash(request.node.name)) % 100000}",
                        role=UserRole.driver)


def _вечерний_рейс(водитель_id: int, пассажир_id: int, с_местного: datetime,
                   по_местное: datetime) -> None:
    """Заказ, который человек вёз по трассе без связи."""
    with Session(engine) as s:
        s.add(InstantOrder(
            passenger_id=пассажир_id, driver_id=водитель_id, status=InstantOrderStatus.done,
            price_estimate=900, price_final=900,
            accepted_at=_utc(с_местного), onboard_at=_utc(с_местного),
            done_at=_utc(по_местное),
            from_lat=52.72, from_lng=58.66, to_lat=51.94, to_lng=58.15))
        s.commit()


def _вчерашний_день(session: Session, водитель_id: int, минут_присутствия: float,
                    последний_пинг_местный: datetime) -> None:
    """Вчерашняя строка смены: сеть молчала, поэтому присутствия почти нет."""
    session.add(TaxiWorkDay(
        driver_id=водитель_id, day=последний_пинг_местный.date(),
        seconds_online=int(минут_присутствия * 60),
        limit_reached_at=None,
        last_heartbeat_at=_utc(последний_пинг_местный)))
    session.commit()


def test_ночной_рейс_без_связи_переживает_полночь(client, таксист, user_factory):
    """Главное: три часа за рулём до полуночи должны остаться в счётчике после неё.

    Сеть молчала — присутствие насчитало четыре минуты. Заказ в базе говорит про три часа.
    Хвост обязан взять большее, ровно как это делает счёт внутри дня.
    """
    пассажир = user_factory("ПассажирНочнойРейс")
    вечер_начало = datetime(2026, 8, 11, 21, 0)
    вечер_конец = datetime(2026, 8, 12, 0, 0)

    _вечерний_рейс(таксист["id"], пассажир["id"], вечер_начало, вечер_конец)
    with Session(engine) as s:
        _вчерашний_день(s, таксист["id"], минут_присутствия=4,
                        последний_пинг_местный=вечер_конец - timedelta(minutes=1))

        сейчас = _utc(datetime(2026, 8, 12, 0, 30))
        день = wd_mod._get_or_create_today(s, таксист["id"], сейчас)
        засчитано = wd_mod.shift_seconds(s, таксист["id"], день, сейчас)

    assert засчитано >= 2 * 3600, (
        f"три часа ночной трассы до полуночи засчитаны как {засчитано // 60} минут: "
        "в 00:01 человек получает почти полные новые восемь часов и будет за рулём "
        "одиннадцать. Ровно тот рейс между сёлами, ради которого лимит и заводили"
    )


def test_и_доставка_ночью_тоже_переживает_полночь(client, таксист, user_factory):
    """Вторая половина того же правила: посылка — такая же работа за рулём.

    Волна 194 уравняла режимы внутри дня. Если хвост через полночь чинить только для такси,
    та же дыра останется у курьера — а он ездит по тем же трассам и в те же часы.
    """
    from app.models import ParcelDelivery

    отправитель = user_factory("ОтправительНочью")
    вечер_начало = datetime(2026, 8, 11, 21, 0)
    вечер_конец = datetime(2026, 8, 12, 0, 0)

    with Session(engine) as s:
        s.add(ParcelDelivery(
            sender_id=отправитель["id"], courier_id=таксист["id"], status="delivered",
            from_city="Сибай", to_city="Акъяр", price=600,
            accepted_at=_utc(вечер_начало), delivered_at=_utc(вечер_конец)))
        s.commit()
        _вчерашний_день(s, таксист["id"], минут_присутствия=4,
                        последний_пинг_местный=вечер_конец - timedelta(minutes=1))

        сейчас = _utc(datetime(2026, 8, 12, 0, 30))
        день = wd_mod._get_or_create_today(s, таксист["id"], сейчас)
        засчитано = wd_mod.shift_seconds(s, таксист["id"], день, сейчас)

    assert засчитано >= 2 * 3600, (
        f"три часа ночной доставки до полуночи засчитаны как {засчитано // 60} минут: "
        "курьер на той же трассе получает новые восемь часов"
    )


def test_после_настоящего_отдыха_счётчик_всё_равно_с_нуля(client, таксист, user_factory):
    """Обратная сторона: выспался — начинаешь заново, что бы ни было в заказах.

    Без этого «починкой» сошёл бы вечный счётчик, который никогда не обнуляется, и водитель
    после выходного упирался бы в лимит на первом же заказе.
    """
    пассажир = user_factory("ПассажирОтдохнувший")
    вечер_начало = datetime(2026, 8, 11, 21, 0)
    вечер_конец = datetime(2026, 8, 12, 0, 0)

    _вечерний_рейс(таксист["id"], пассажир["id"], вечер_начало, вечер_конец)
    with Session(engine) as s:
        _вчерашний_день(s, таксист["id"], минут_присутствия=4,
                        последний_пинг_местный=вечер_конец - timedelta(minutes=1))

        # Проспал положенный отдых и вышел на линию только вечером следующего дня.
        сейчас = _utc(datetime(2026, 8, 12, 18, 0))
        день = wd_mod._get_or_create_today(s, таксист["id"], сейчас)
        засчитано = wd_mod.shift_seconds(s, таксист["id"], день, сейчас)

    assert засчитано < 600, (
        f"после полноценного отдыха счётчик показывает {засчитано // 60} минут вчерашней "
        "работы: человек упрётся в лимит на первом же заказе выспавшимся"
    )


def test_хвост_не_считает_один_час_дважды(client, таксист, user_factory):
    """Обратная сторона: два прибора меряют одно время — берём большее, не сумму.

    Иначе водитель, у которого и связь была, и заказы шли, получит вдвое больший хвост
    и уйдёт отдыхать вдвое раньше срока.
    """
    пассажир = user_factory("ПассажирСоСвязью")
    вечер_начало = datetime(2026, 8, 11, 21, 0)
    вечер_конец = datetime(2026, 8, 12, 0, 0)

    _вечерний_рейс(таксист["id"], пассажир["id"], вечер_начало, вечер_конец)
    with Session(engine) as s:
        # Связь была: присутствие насчитало те же три часа, что и заказ.
        _вчерашний_день(s, таксист["id"], минут_присутствия=180,
                        последний_пинг_местный=вечер_конец - timedelta(minutes=1))

        сейчас = _utc(datetime(2026, 8, 12, 0, 30))
        день = wd_mod._get_or_create_today(s, таксист["id"], сейчас)
        засчитано = wd_mod.shift_seconds(s, таксист["id"], день, сейчас)

    assert засчитано < 4 * 3600, (
        f"три часа работы засчитаны как {засчитано // 3600} часов: приборы сложили вместо "
        "того, чтобы взять большее, и человека отправят отдыхать вдвое раньше"
    )
