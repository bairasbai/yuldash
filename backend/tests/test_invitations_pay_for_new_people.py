"""Двое обменивались кодами и получали по два бонуса каждый (волна 165).

Программа приглашений платит за нового человека в сервисе: привёл друга — получи бесплатное
поднятие поездки (по прайсу 50 ₽). Свой собственный код себе ввести было нельзя — это очевидная
дыра, и её закрыли сразу.

А вот «ты ввёл мой код — я введу твой» проверки не имело. Проба: двое соседей обменялись
кодами и получили **по два бонуса каждый** — один как приглашённый, второй как пригласивший.
Новых людей в Юлдаше при этом не прибавилось ни одного, а платформа раздала четыре бесплатных
поднятия, то есть 200 ₽ за пустое место. И это не хитрость одиночки: обменяться кодами
в сельском чате — первое, что приходит в голову, когда видишь «пригласи друга».

Теперь код человека, который уже ввёл твой, ввести нельзя. Обычная цепочка приглашений
(А привёл Б, Б привёл В) не затронута — там каждый раз приходит новый человек.
"""
from __future__ import annotations

from sqlmodel import Session

from app.db import engine
from app.models import User


def _код(client, человек) -> str:
    return client.get("/referral/me", headers=человек["auth"]).json()["code"]


def _бонусы(user_id: int) -> tuple[int, int]:
    with Session(engine) as s:
        u = s.get(User, user_id)
        return u.referral_credits, int(u.referral_bonus_lifetime or 0)


def test_обменяться_кодами_нельзя(client, user_factory):
    """Главное: за обмен кодами между своими платформа не платит."""
    первый = user_factory("СоседПервый")
    второй = user_factory("СоседВторой")
    assert client.post("/referral/redeem", headers=второй["auth"],
                       json={"code": _код(client, первый)}).status_code == 200

    обратно = client.post("/referral/redeem", headers=первый["auth"],
                          json={"code": _код(client, второй)})

    assert обратно.status_code == 400, (
        f"двое обменялись кодами (ответ {обратно.status_code}) и получили по два бонуса каждый: "
        "новых людей не прибавилось, а бесплатные поднятия платформа раздала"
    )
    assert "ba" in обратно.text, "отказ не на двух языках"
    кредиты_первого, _ = _бонусы(первый["id"])
    assert кредиты_первого == 1, (
        f"пригласивший получил {кредиты_первого} бонуса вместо одного"
    )


def test_свой_код_себе_по_прежнему_нельзя(client, user_factory):
    """Обратная сторона: старая защита не должна была сломаться."""
    человек = user_factory("СамСебеДруг")

    ответ = client.post("/referral/redeem", headers=человек["auth"],
                        json={"code": _код(client, человек)})

    assert ответ.status_code == 400, "человек пригласил сам себя"


def test_обычная_цепочка_приглашений_работает(client, user_factory):
    """Обратная сторона и смысл программы: за каждого нового человека бонус положен."""
    первый = user_factory("ЦепочкаПервый")
    второй = user_factory("ЦепочкаВторой")
    третий = user_factory("ЦепочкаТретий")

    assert client.post("/referral/redeem", headers=второй["auth"],
                       json={"code": _код(client, первый)}).status_code == 200
    assert client.post("/referral/redeem", headers=третий["auth"],
                       json={"code": _код(client, второй)}).status_code == 200

    кредиты_первого, _ = _бонусы(первый["id"])
    кредиты_второго, _ = _бонусы(второй["id"])
    assert кредиты_первого == 1, "первый привёл человека и не получил бонус"
    assert кредиты_второго == 2, (
        f"второй пришёл по приглашению и сам привёл друга — ему положено два бонуса, "
        f"а у него {кредиты_второго}"
    )


def test_код_одного_человека_работает_для_разных_друзей(client, user_factory):
    """Обратная сторона: один код на всех — так программа и задумана."""
    хозяин = user_factory("ХозяинКода")
    друг1 = user_factory("ДругОдин")
    друг2 = user_factory("ДругДва")
    код = _код(client, хозяин)

    assert client.post("/referral/redeem", headers=друг1["auth"],
                       json={"code": код}).status_code == 200
    assert client.post("/referral/redeem", headers=друг2["auth"],
                       json={"code": код}).status_code == 200

    кредиты, _ = _бонусы(хозяин["id"])
    assert кредиты == 2, f"привёл двоих, а бонусов {кредиты}"
