# -*- coding: utf-8 -*-
"""Жалоба «опасное вождение» закрывает такси — и оставляет открытой платную доставку (волна 214).

Пассажир жалуется на **опасное вождение** или **угрозу безопасности**. Это тяжёлая категория:
сервис не ждёт накопления жалоб, а немедленно снимает человека с такси **до разбора живым
админом** и пишет в Telegram дежурному. Самое быстрое решение во всём приложении — именно
потому, что речь про руль и чужую жизнь.

Пауза живёт в `DriverProfile.taxi_paused_until`, сторожит её `guard_taxi_quality`, и зовут
её из одного места — водительского гейта такси. До курьерской двери она не доходит: у курьера
своя пауза (`CourierProfile.paused_until`), и ставит её только его собственная лестница
качества — по оценкам за доставки, которые он вёз. `app/quality.py` про `CourierProfile`
не знает вообще.

**Итог.** Вечером на человека пожаловались за опасное вождение, сервис закрыл ему такси
и позвал админа. Он открывает вкладку доставки и в ту же минуту берёт платный рейс
Акъяр — Сибай. Тот же руль, та же трасса, тот же разбор, которого ещё не было.

**Попутку трогать нельзя, и это не оговорка.** «Попутка мягче такси» — записанный принцип,
и текст паузы прямо обещает человеку «Попутка работает как обычно». Попутка — это сосед,
который и так едет в Сибай. Курьерская доставка — платная работа, тот же профессиональный
режим, что и такси; проект уже трижды решал этот вопрос одинаково (усталость — волна 194,
срок документов — 29.08, готовность к рейсу — волна 213), и довод каждый раз был один:
руль не спрашивает, человек в машине или коробка.

Поэтому проба проверяет обе стороны сразу: платная доставка обязана закрыться, попутка
обязана остаться открытой.
"""
