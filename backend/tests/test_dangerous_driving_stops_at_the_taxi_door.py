def _курьер_на_линии(client, user_factory, имя="ОпасныйКурьер"):
    админ = user_factory(name=f"Админ{имя}", role=UserRole.admin)
    c = user_factory(name=имя, role=UserRole.driver)
    aid = client.post("/courier/apply", headers=c["auth"],
                      json={"transport": "car",
                            "selfie_url": upload_doc(client, c["auth"])}).json()["id"]
    assert client.post(f"/admin/courier-applications/{aid}/approve",
                       headers=админ["auth"]).status_code == 200
    assert client.post("/courier/online", headers=c["auth"],
                       json={"zone": "region"}).status_code == 200
    # Профиль водителя: пауза такси живёт именно в нём, без него вешать её не на что.
    assert client.post("/driver/online", headers=c["auth"],
                       json={"online": True}).status_code == 200
    return c


def _заказ(client, отправитель):
    r = client.post("/courier/orders", headers=отправитель["auth"], json={
        "from_city": "Акъяр", "to_city": "Сибай",
        "from_lat": 51.90, "from_lng": 58.20, "to_lat": 52.71, "to_lng": 58.66,
        "size": "small", "description": "Лекарство",
        "receiver_name": "Гөлнара", "receiver_phone": "+79990001177",
        "rules_accepted": True, "delivery_type": "courier", "urgency": "bypath",
    })
    assert r.status_code == 200, r.text
    return r.json()["id"]


def _пожаловались_на_опасное_вождение(водитель_id: int) -> None:
    """Пауза ровно та, которую ставит тяжёлая жалоба: «до разбора у живого человека»."""
    with Session(engine) as s:
        prof = quality.pause_taxi(s, водитель_id, hours=None,
                                  reason=quality.PAUSE_REASON_REVIEW)
        assert prof is not None and prof.taxi_paused_until > utcnow(), (
            "тест слеп: пауза такси не поставилась"
        )


def test_под_разбором_за_опасное_вождение_курьер_берёт_платный_рейс(client, user_factory):
    """Главное: сервис уже решил, что этому человеку сегодня за руль нельзя."""
    курьер = _курьер_на_линии(client, user_factory)
    отправитель = user_factory(name="ОпасныйОтпр")
    pid = _заказ(client, отправитель)

    _пожаловались_на_опасное_вождение(курьер["id"])

    взял = client.post(f"/parcels/{pid}/accept", headers=курьер["auth"])

    assert взял.status_code == 403, (
        f"человек под разбором за опасное вождение взял платный рейс (ответ {взял.status_code}). "
        "Сервис в ту же минуту снял его с такси и позвал живого админа — а вкладка доставки "
        "осталась открытой: тот же руль, та же трасса Акъяр — Сибай, тот же неразобранный "
        "случай"
    )


def test_попутку_под_разбором_по_прежнему_можно(client, user_factory):
    """Обратная сторона, и она такая же важная: попутку закрывать НЕЛЬЗЯ.

    «Попутка мягче такси» — записанный принцип, и текст паузы прямо обещает человеку
    «Попутка работает как обычно». Сосед, который и так едет в Сибай, — не профессиональный
    рейс. Если починка заденет попутку, она сломает обещание, данное человеку в лицо.
    """
    водитель = _курьер_на_линии(client, user_factory, имя="ОпасныйПопутчик")
    _пожаловались_на_опасное_вождение(водитель["id"])

    ride_id = _ride(client, водитель, comment="под разбором, но еду по своим делам")

    assert ride_id, "попутка перестала публиковаться на паузе такси — сломано обещание"


def test_доставка_по_пути_под_разбором_остаётся(client, user_factory):
    """Обратная сторона: «по пути» — это попутка с коробкой, а не платный рейс.

    Там по замыслу не стоит ни один водительский гейт: человек едет в Сибай и заодно
    завозит соседу пакет. Починка не должна перепутать её с курьерским заказом.
    """
    водитель = _курьер_на_линии(client, user_factory, имя="ОпасныйПопутный")
    отправитель = user_factory(name="ОпасныйОтпрПоПути")
    r = client.post("/parcels", headers=отправитель["auth"], json={
        "from_city": "Акъяр", "to_city": "Сибай",
        "size": "small", "description": "пакет соседу",
        "receiver_name": "Гөлнара", "receiver_phone": "+79990001178",
        "rules_accepted": True,
    })
    assert r.status_code == 200, r.text
    pid = r.json()["id"]

    _пожаловались_на_опасное_вождение(водитель["id"])

    взял = client.post(f"/parcels/{pid}/accept", headers=водитель["auth"])

    assert взял.status_code == 200, (
        f"«по пути» закрыли вместе с платной доставкой ({взял.text}): это попутка с коробкой, "
        "и водительских гейтов там нет по замыслу"
    )


