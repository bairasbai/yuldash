# ---------------------------------------------------------------------------
# Разбор мутаций: проба покрывала одну дверь из двух и ни одной границы.
#
# Три мутации прошли мимо: снять гейт с выхода на курьерскую линию, заставить его
# срабатывать на ЛЮБУЮ паузу такси и заставить его игнорировать срок. Каждая — настоящая
# поломка, и каждую пропускала сама проба. Тесты ниже закрывают все три.
# ---------------------------------------------------------------------------
def test_под_разбором_на_курьерскую_линию_не_выходим(client, user_factory):
    """Вторая дверь: человеку честнее узнать сразу, а не после вечера ожидания.

    Соседняя курьерская пауза стоит на обеих дверях — и на выходе на линию, и на приёме.
    Если разбор закрывает только приём, человек весь вечер висит «на линии», получает
    рассылку о заказах и упирается в отказ на каждом.
    """
    курьер = _курьер_на_линии(client, user_factory, имя="ОпасныйНаЛинии")

    _пожаловались_на_опасное_вождение(курьер["id"])

    снова = client.post("/courier/online", headers=курьер["auth"], json={"zone": "region"})

    assert снова.status_code == 403, (
        f"человек под разбором за опасное вождение спокойно вышел на курьерскую линию "
        f"(ответ {снова.status_code}) и ждёт заказов, которых ему всё равно не дадут"
    )


def test_накопленные_жалобы_к_таксисту_курьера_не_трогают(client, user_factory):
    """Договор, ради которого гейт смотрит именно на ПРИЧИНУ паузы.

    Пауза по накопленным жалобам (`reports`) — это про качество ТАКСИ-сервиса: нахамил,
    грязная машина, опоздал. У курьера своя лестница по своим оценкам за доставки — так
    решила волна 186, и решила по делу: лестница отнимает у человека работу, а работа
    у него может быть другая.

    Если гейт начнёт срабатывать на любую паузу такси, накопленные жалобы к таксисту
    молча отнимут человеку курьерский заработок — ровно то, что волна 186 разбирала
    и запретила.
    """
    курьер = _курьер_на_линии(client, user_factory, имя="ЖалобыТаксиста")
    отправитель = user_factory(name="ЖалобыОтпр")
    pid = _заказ(client, отправитель)

    with Session(engine) as s:
        quality.pause_taxi(s, курьер["id"], hours=72,
                           reason=quality.PAUSE_REASON_REPORTS)

    взял = client.post(f"/parcels/{pid}/accept", headers=курьер["auth"])

    assert взял.status_code == 200, (
        f"накопленные жалобы к ТАКСИСТУ отняли человеку курьерскую работу ({взял.text}). "
        "У курьера своя лестница по своим оценкам — так решила волна 186"
    )


def test_разбор_кончился_человек_снова_работает(client, user_factory):
    """Обратная сторона: пауза «до разбора» — не навсегда.

    Админ разобрал и снял паузу — платная работа обязана открыться в ту же минуту. Иначе
    «до разбора» превращается в пожизненное, и человек теряет заработок за то, в чём его
    уже оправдали.
    """
    курьер = _курьер_на_линии(client, user_factory, имя="РазборКончился")
    отправитель = user_factory(name="РазборОтпр")
    pid = _заказ(client, отправитель)

    _пожаловались_на_опасное_вождение(курьер["id"])
    assert client.post(f"/parcels/{pid}/accept",
                       headers=курьер["auth"]).status_code == 403      # пока идёт — нельзя

    with Session(engine) as s:
        quality.unpause_taxi(s, курьер["id"])

    взял = client.post(f"/parcels/{pid}/accept", headers=курьер["auth"])

    assert взял.status_code == 200, (
        f"админ разобрал жалобу и снял паузу, а платная работа так и не открылась "
        f"({взял.text}): «до разбора» стало пожизненным"
    )


def test_срок_паузы_вышел_сам_и_работа_открылась(client, user_factory):
    """Обратная сторона: пауза кончается по сроку, а не только по кнопке админа.

    Предыдущий тест снимает паузу целиком (`unpause_taxi` обнуляет поле), и на нём мутация
    «гейт не смотрит на срок» оставалась зелёной: поля-то нет. Здесь поле на месте, а срок
    прошёл — так бывает, когда до разбора не дошли руки и пауза истекла сама.
    """
    from app.models import DriverProfile

    курьер = _курьер_на_линии(client, user_factory, имя="СрокВышел")
    отправитель = user_factory(name="СрокОтпр")
    pid = _заказ(client, отправитель)

    _пожаловались_на_опасное_вождение(курьер["id"])
    with Session(engine) as s:
        prof = s.exec(select(DriverProfile).where(
            DriverProfile.user_id == курьер["id"])).first()
        prof.taxi_paused_until = utcnow() - timedelta(hours=1)     # вчерашний срок, причина та же
        s.add(prof)
        s.commit()

    взял = client.post(f"/parcels/{pid}/accept", headers=курьер["auth"])

    assert взял.status_code == 200, (
        f"срок паузы вышел час назад, а человека всё ещё не пускают работать ({взял.text}): "
        "«до разбора» стало пожизненным"
    )
