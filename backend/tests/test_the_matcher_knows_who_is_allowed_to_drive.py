def test_допущенному_водителю_заказы_шлём(заказ_и_водитель, monkeypatch):
    """Обратная сторона: у кого всё в порядке — работает как раньше.

    Без этого теста «починка» могла бы просто перестать предлагать заказы всем подряд,
    и подбор молча опустел бы.
    """
    monkeypatch.setattr(settings, "pretrip_check_required", True)
    водитель, заказ = заказ_и_водитель("ВсёВПорядке",
                                       osago_until=local_date(utcnow()) + timedelta(days=30))
    with Session(engine) as s:
        pretrip_mod.confirm(s, водитель, health_ok=True, car_ok=True, no_alcohol=True)

    assert _кому_шлём(водитель, заказ) == [водитель], (
        "допущенный водитель на линии перестал получать заказы — подбор опустел"
    )


