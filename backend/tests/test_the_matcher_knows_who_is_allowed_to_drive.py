def test_без_разрешения_в_реестре_заказы_не_шлём(заказ_и_водитель, monkeypatch):
    """Договор: государственный реестр — последнее слово (580-ФЗ).

    Мутация «допуск не смотрит на реестр ФГИС» прошла все тесты насквозь. А это ровно тот
    случай, ради которого реестр и спрашивают: наше одобрение говорит «мы его проверили»,
    разрешение в реестре — «государство разрешило ему возить людей». Второе мы не выдаём
    и отменить не можем, поэтому оно и стоит последним.
    """
    monkeypatch.setattr(settings, "fgis_check_enabled", True)
    monkeypatch.setattr(settings, "fgis_api_token", "тест")
    водитель, заказ = заказ_и_водитель(
        "БезРазрешения",
        fgis_checked_at=utcnow() - timedelta(hours=1),   # реестр отвечал только что
        fgis_permit_ok=False,                            # и ответил «разрешения нет»
    )

    assert _кому_шлём(водитель, заказ) == [], (
        "подбор предложил заказ водителю, которому государство возить людей не разрешало"
    )


def test_молчание_реестра_заказы_не_рубит(заказ_и_водитель, monkeypatch):
    """Обратная сторона: «реестр не ответил» и «разрешения нет» — разные вещи.

    Молчание чужого сервера это НАША проблема. Снимать человека с линии из-за собственного
    таймаута нечестно — и он даже не поймёт, за что.
    """
    monkeypatch.setattr(settings, "fgis_check_enabled", True)
    monkeypatch.setattr(settings, "fgis_api_token", "тест")
    водитель, заказ = заказ_и_водитель("РеестрМолчит")   # fgis_checked_at пуст — ответа не было

    assert _кому_шлём(водитель, заказ) == [водитель], (
        "водителя сняли с подбора из-за того, что реестр нам не ответил"
    )


def test_кто_не_показал_машину_больше_недели_заказы_не_получает(заказ_и_водитель, monkeypatch):
    """Договор: фотоконтроль — последняя ступень мягкой лестницы.

    Мутации «допуск не смотрит на фотоконтроль» и «пакетный фотоконтроль всегда пуст» прошли
    все тесты насквозь — у пакетной проверки не было ни одного теста вовсе. Первую неделю
    просрочки человек только получает напоминания; сюда доходит тот, кто не показал машину
    больше недели, и на линию его уже не пускают. Подбор обязан знать то же самое.
    """
    monkeypatch.setattr(settings, "car_photo_taxi_enabled", True)
    водитель, заказ = заказ_и_водитель("НеПоказалМашину")
    with Session(engine) as s:
        s.add(CarPhotoCheck(
            user_id=водитель, mode=cp_mod.TAXI, kind=cp_mod.PERIODIC,
            status=cp_mod.WAITING,
            due_at=utcnow() - timedelta(days=int(settings.car_photo_soft_days) + 1),
        ))
        s.commit()

    assert _кому_шлём(водитель, заказ) == [], (
        "подбор предложил заказ водителю, который больше недели не показывает машину: "
        "пассажир садится в машину, которую никто не видел"
    )


