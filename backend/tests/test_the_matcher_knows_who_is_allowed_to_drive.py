"""Подбор такси не знал про ДОПУСК к работе — только про наказания (волна 221).

Волна 60 донесла до подбора все четыре наказания водителя: паузу «Справедливости», паузу
качества, отдых (§8) и долг по комиссии. Логика та же, что на выходе на линию, — и это
правильно: водитель мог быть на линии УЖЕ, когда наказание наступило.

Но на той же двери (`routers/instant._guard_taxi_driver`) стоят ещё две проверки, и подбор
о них не знает:

  * **допуск к такси** (`taxi.is_approved_taxi_driver`, 580-ФЗ) — одобренная заявка
    с ДЕЙСТВУЮЩИМИ документами: ОСАГО, разрешение, диагностическая карта, машина не из
    стоп-списка, разрешение есть в реестре, фото машины не просрочено;
  * **предрейсовый осмотр** (`pretrip.guard_pretrip`, 580-ФЗ) — подтверждение готовности
    НА СЕГОДНЯ.

Обе истекают САМИ, по календарю, посреди смены. Водитель вышел на линию в 22:00, всё было
в порядке; в полночь по башкирскому времени ОСАГО кончилось, а осмотр «на сегодня» стал
вчерашним. Присутствие на линии живёт своим сроком — водитель остался `online`.

Что происходило дальше. Подбор продолжал слать ему заказы. В уведомлении об оффере едет
АДРЕС ПОДАЧИ пассажира — то есть адрес уходил человеку, которому мы сами запретили работать.
Принять он не мог: `accept` идёт через тот же гейт и отвечает 403. Оффер сгорал по таймауту,
подбор шёл к следующему. Ночью в райцентре следующего может не быть — женщина на трассе
ждала машину, которую система раз за разом предлагала тому, кто по закону уже не таксист.

Подбор проверяет то же самое и той же функцией — иначе гейт и фильтр разъедутся, а такие
пары разъезжаются всегда (урок волны 60).
"""
