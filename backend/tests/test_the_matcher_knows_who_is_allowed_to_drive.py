ORIG = (54.7388, 55.9721)
DEST = (54.7500, 55.9800)


@pytest.fixture
def заказ_и_водитель(user_factory):
    """Пассажир с заказом и допущенный водитель на линии — исходная точка всех историй."""
    пассажир = user_factory("ДопускПассажир", role=UserRole.passenger)

    def make(имя: str, **поля_заявки):
        with Session(engine) as s:
            u = User(phone=f"w221-{имя}", name=имя, telegram_id=f"w221{имя}",
                     verified=True, role=UserRole.driver)
            s.add(u)
            s.commit()
            s.refresh(u)
            заявка = TaxiApplication(
                user_id=u.id, inn="123456789012", permit_number="Т-1",
                birth_date=date(1990, 1, 1), license_since_year=2010,
                status=TaxiApplicationStatus.approved,
            )
            for k, v in поля_заявки.items():
                setattr(заявка, k, v)
            s.add(заявка)
            s.add(DriverProfile(user_id=u.id, online=True, car_classes_available="economy",
                                car_make="Lada", car_model="Granta"))
            s.commit()
            o = InstantOrder(passenger_id=пассажир["id"], status=S.searching,
                             from_lat=ORIG[0], from_lng=ORIG[1], to_lat=DEST[0], to_lng=DEST[1],
                             from_text="Сибай, ул. Ленина 1", to_text="Уфа",
                             category="standard", created_at=utcnow() - timedelta(hours=1))
            s.add(o)
            s.commit()
            s.refresh(o)
            return u.id, o.id

    return make


def _кому_шлём(driver_id: int, order_id: int) -> list:
    with Session(engine) as s:
        return isv.eligible(s, [driver_id], s.get(InstantOrder, order_id))


def test_водителю_с_просроченным_осаго_заказы_не_шлём(заказ_и_водитель):
    """Главное: ОСАГО кончилось ночью, а он всё ещё на линии.

    При аварии выплаты не получил бы никто — ни пассажир, ни водитель. Ночь как раз то время,
    когда цена ошибки самая высокая (волна 80).
    """
    водитель, заказ = заказ_и_водитель("Осаго",
                                       osago_until=local_date(utcnow()) - timedelta(days=1))

    assert _кому_шлём(водитель, заказ) == [], (
        "подбор предложил заказ водителю с просроченным ОСАГО: адрес подачи пассажирки ушёл "
        "человеку, которому мы сами запретили возить, а принять заказ он всё равно не сможет"
    )


def test_водителю_с_машиной_из_стоп_списка_заказы_не_шлём(заказ_и_водитель):
    """Вторая дверь допуска: «Ока» и «копейка» такси не возят ни при каком уходе.

    Стоп-список ввели 30.08 — на выходе на линию проверка появилась, до подбора не дошла.
    """
    водитель, заказ = заказ_и_водитель("СтопСписок")
    with Session(engine) as s:
        профиль = s.exec(select(DriverProfile).where(
            DriverProfile.user_id == водитель)).first()
        профиль.car_make, профиль.car_model = "ВАЗ", "1111 Ока"
        s.add(профиль)
        s.commit()

    assert _кому_шлём(водитель, заказ) == [], (
        "подбор предложил заказ на машине из стоп-списка — пассажир платит за поездку "
        "и вправе рассчитывать на машину, в которой безопасно"
    )


def test_без_предрейсового_осмотра_заказы_не_шлём(заказ_и_водитель, monkeypatch):
    """Третья дверь: осмотр подтверждают НА СЕГОДНЯ, и в полночь он становится вчерашним."""
