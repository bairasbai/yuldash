"""Отметку «только женщины» мог поставить кто угодно, назвавшись женщиной (волна 168).

Пол в профиле человек указывает сам. Это поле никто не сверяет — и правильно, оно нужно
для мелочей вроде обращения. Но на нём же держалась отметка «только женщины» у поездки.

Проба: мужчина ставит себе в профиле «женщина», публикует поездку с этой отметкой — и она
попадает в фильтр «только женщины». А этот фильтр открывают ровно те, кому небезопасно ехать
с незнакомым мужчиной: женщина видит обещание, выбирает такую поездку и садится в машину
к тому, от кого пряталась.

Самое обидное — подтверждение модератора (`gender_verified`) в проекте есть и уже требуется
у бейджа «женщина за рулём» и при подборе машины в такси. У самой отметки его не спрашивали.
В фильтре ленты оно тоже стояло — но только на одной половине условия: «поездки, где водитель
подтверждённая женщина» проверялись, а «поездки с отметкой» проходили насквозь. Рядом даже
был комментарий, объясняющий, почему без подтверждения нельзя.

Теперь и отметка, и фильтр требуют одного: за рулём женщина, и это кто-то проверил.
Самодекларации хватает на что угодно, кроме обещания безопасности незнакомому человеку.
"""
from __future__ import annotations

from datetime import timedelta

from sqlmodel import Session, select

from app.db import engine
from app.models import DriverProfile, Ride, User, UserRole
from app.timeutil import utcnow


def _водитель(user_factory, метка: str, пол: str, подтверждена: bool):
    человек = user_factory(метка, role=UserRole.driver)
    with Session(engine) as s:
        u = s.get(User, человек["id"])
        u.gender = пол
        s.add(u)
        профиль = s.exec(select(DriverProfile).where(
            DriverProfile.user_id == человек["id"])).first()
        if профиль is None:
            профиль = DriverProfile(user_id=человек["id"])
        профиль.gender_verified = подтверждена
        s.add(профиль)
        s.commit()
    return человек


def _опубликовать(client, водитель, женская: bool):
    return client.post("/rides", headers=водитель["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "depart_at": (utcnow() + timedelta(days=1)).replace(microsecond=0).isoformat(),
        "seats_total": 3, "price": 300, "comment": "по трассе",
        "women_only": женская,
    })


def test_мужчина_не_ставит_отметку_только_женщины(client, user_factory):
    """Главное: обещание безопасности нельзя выдать себе самому."""
    самозванец = _водитель(user_factory, "Самозванец", пол="female", подтверждена=False)

    ответ = _опубликовать(client, самозванец, женская=True)

    assert ответ.status_code == 403, (
        f"поездка «только женщины» опубликована без единой проверки (ответ {ответ.status_code}): "
        "женщина выберет её именно из-за отметки и сядет в машину к незнакомому мужчине"
    )
    assert "ba" in ответ.text, "отказ не на двух языках"


def test_неподтверждённой_женщине_объясняют_что_делать(client, user_factory):
    """Она ничего плохого не сделала — документы просто ещё не проверены."""
    водитель = _водитель(user_factory, "ЖенщинаБезПроверки", пол="female", подтверждена=False)

    ответ = _опубликовать(client, водитель, женская=True)

    текст = ответ.json()["detail"]["ru"].lower()
    assert "провер" in текст, (
        f"человеку отказали, не сказав, что делать дальше: {текст}"
    )


def test_подтверждённая_женщина_отметку_ставит(client, user_factory):
    """Обратная сторона: ради этих поездок фильтр и существует."""
    водитель = _водитель(user_factory, "ЖенщинаСПроверкой", пол="female", подтверждена=True)

    ответ = _опубликовать(client, водитель, женская=True)

    assert ответ.status_code == 200, (
        f"подтверждённая женщина не может отметить свою поездку: {ответ.text[:200]}"
    )
    with Session(engine) as s:
        assert s.get(Ride, ответ.json()["id"]).women_only is True


def test_обычную_поездку_публикуют_все(client, user_factory):
    """Обратная сторона: проверка касается только отметки, а не поездок вообще."""
    водитель = _водитель(user_factory, "ОбычныйВодитель", пол="male", подтверждена=False)

    ответ = _опубликовать(client, водитель, женская=False)

    assert ответ.status_code == 200, f"обычная публикация сломалась: {ответ.text[:200]}"


def test_женский_фильтр_не_показывает_непроверенного(client, user_factory):
    """Даже если отметка уже стоит в базе — фильтр обязан её перепроверить.

    Отметки могли проставиться раньше, до этого правила, или через другую дверь. Фильтр —
    последняя линия: он показывает только то, что кто-то действительно сверил.
    """
    самозванец = _водитель(user_factory, "СамозванецВЛенте", пол="female", подтверждена=False)
    ответ = _опубликовать(client, самозванец, женская=False)
    ride_id = ответ.json()["id"]
    with Session(engine) as s:                    # отметка проставлена в обход двери
        r = s.get(Ride, ride_id)
        r.women_only = True
        s.add(r)
        s.commit()

    лента = client.get("/rides?women_only=true").json()

    assert ride_id not in [r["id"] for r in лента], (
        "в фильтре «только женщины» показана поездка водителя, которого никто не сверял: "
        "фильтр открывают те, кому небезопасно ехать с незнакомым мужчиной"
    )


def test_женский_фильтр_показывает_проверенную(client, user_factory):
    """Обратная сторона: иначе фильтр всегда пустой и бесполезный."""
    водитель = _водитель(user_factory, "ЖенщинаВЛенте", пол="female", подтверждена=True)
    ride_id = _опубликовать(client, водитель, женская=True).json()["id"]

    лента = client.get("/rides?women_only=true").json()

    assert ride_id in [r["id"] for r in лента], (
        "поездка подтверждённой женщины не видна в женском фильтре — показывать нечего, "
        "и фильтр теряет смысл"
    )


def test_поездка_проверенной_женщины_видна_и_без_отметки(client, user_factory):
    """Обратная сторона: женщина за рулём — сама по себе то, что ищут в этом фильтре."""
    водитель = _водитель(user_factory, "ЖенщинаБезОтметки", пол="female", подтверждена=True)
    ride_id = _опубликовать(client, водитель, женская=False).json()["id"]

    лента = client.get("/rides?women_only=true").json()

    assert ride_id in [r["id"] for r in лента], (
        "поездка подтверждённой женщины пропала из фильтра только потому, что она "
        "не поставила отметку"
    )
