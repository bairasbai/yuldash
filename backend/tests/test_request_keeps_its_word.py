"""Заявка не должна менять условия под уже откликнувшимся водителем.

Две истории про одну заявку «ищу машину».

**Первая — про подмену.** Марат откликнулся на «Баймак → Сибай, завтра в 8, одно место»
и назвал 400 ₽. Пассажир тихо переписал заявку на «Баймак → Магнитогорск, через час,
четыре места» и нажал «Принять». Марат оказывался связан сделкой, которой не называл:
другой город, другое время, вчетверо больше людей. Откажется — получит удар по «Надёжности»
за позднюю отмену.

У поездки такая планка стоит давно: с живыми бронями нельзя менять время, число мест
и поднимать цену. У заявки её не было вовсе (аудит 2026-08-08, волна 118) — проверено
пробой: правка после отклика проходила с ответом 200.

**Вторая — про молчание.** На заявку откликнулись четверо. Пассажир уехал с первым (или
отменил заявку) — и остальные не узнавали об этом никогда. Их отклики висели «предложено»,
люди держали утро свободным и решали, что их игнорируют.

Теперь обе двери — принятие и отмена — гасят чужие отклики ОДНОЙ функцией и пишут водителям.
"""
from __future__ import annotations

import pytest

import app.services as svc
from app.models import UserRole


@pytest.fixture
def пуши(monkeypatch):
    поймано: list[tuple[int, str]] = []
    monkeypatch.setattr(svc, "send_push", lambda s, uid, t, b, data=None: поймано.append((uid, t)))
    return поймано


@pytest.fixture
def заявка_с_откликами(client, user_factory):
    """Пассажир ищет машину, откликнулись двое водителей."""
    pax = user_factory("СловоПассажир")
    марат = user_factory("СловоМарат", role=UserRole.driver)
    ильдар = user_factory("СловоИльдар", role=UserRole.driver)
    rid = client.post("/requests", headers=pax["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "depart_at": "2030-11-01T08:00:00", "seats": 1, "max_price": 400,
    }).json()["id"]
    o1 = client.post(f"/requests/{rid}/respond", headers=марат["auth"], json={"price": 400}).json()
    o2 = client.post(f"/requests/{rid}/respond", headers=ильдар["auth"], json={"price": 450}).json()
    return pax, марат, ильдар, rid, o1["id"], o2["id"]


def _правка(client, pax, rid, **поля):
    тело = {"from_city": None, "to_city": None, "desired_at": None,
            "seats": None, "max_price": None, "comment": None}
    тело.update(поля)
    return client.post(f"/requests/{rid}/edit", headers=pax["auth"], json=тело)


def test_маршрут_под_откликом_не_переписать(client, заявка_с_откликами):
    pax, *_, rid, _, _ = заявка_с_откликами

    r = _правка(client, pax, rid, from_city="Баймак", to_city="Магнитогорск")

    assert r.status_code == 409, (
        "маршрут переписали под откликнувшимся водителем: он назвал цену за одну дорогу, "
        "а поедет по другой"
    )
    assert "откликнулись" in str(r.json()), r.json()


def test_число_мест_под_откликом_не_переписать(client, заявка_с_откликами):
    pax, *_, rid, _, _ = заявка_с_откликами

    r = _правка(client, pax, rid, seats=4)

    assert r.status_code == 409, "вместо одного пассажира в машине оказались четверо"


def test_цену_вверх_под_откликом_не_поднять(client, заявка_с_откликами):
    """Вниз — можно (это подарок водителю), вверх — нет: он торговался за другую сумму."""
    pax, *_, rid, _, _ = заявка_с_откликами

    вверх = _правка(client, pax, rid, max_price=900)
    вниз = _правка(client, pax, rid, max_price=300)

    assert вверх.status_code == 409, "потолок цены подняли после торга"
    assert вниз.status_code == 200, f"снизить цену запретили, хотя это никого не подводит: {вниз.text}"


def test_комментарий_поправить_можно(client, заявка_с_откликами):
    """Обратная сторона: опечатку в комментарии человек должен исправлять свободно."""
    pax, *_, rid, _, _ = заявка_с_откликами

    r = _правка(client, pax, rid, comment="буду у школы")

    assert r.status_code == 200, f"безобидную правку запретили: {r.text}"


def test_заявка_без_откликов_правится_свободно(client, user_factory):
    """Пока никто не откликнулся, менять можно всё — обещания ещё нет."""
    pax = user_factory("СловоСвободный")
    rid = client.post("/requests", headers=pax["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "depart_at": "2030-11-01T08:00:00", "seats": 1, "max_price": 400,
    }).json()["id"]

    r = _правка(client, pax, rid, to_city="Магнитогорск", seats=3)

    assert r.status_code == 200, f"правка до откликов запрещена: {r.text}"


def test_кому_не_повезло_узнаёт_об_этом(client, заявка_с_откликами, пуши):
    """Пассажир уехал с первым — второй не должен держать утро свободным впустую."""
    pax, _, ильдар, rid, o1, o2 = заявка_с_откликами
    пуши.clear()

    assert client.post(f"/responses/{o1}/accept", headers=pax["auth"]).status_code == 200

    адресаты = [uid for uid, _ in пуши]
    assert ильдар["id"] in адресаты, (
        f"второму водителю никто не написал: {пуши}. Его отклик так и висит «предложено», "
        "а он держит это время под пассажира, который уже уехал"
    )
    статусы = {x["id"]: x["status"] for x in client.get(f"/requests/{rid}/responses",
                                                        headers=pax["auth"]).json()}
    assert статусы[o2] != "offered", f"чужой отклик остался открытым: {статусы}"


def test_при_отмене_заявки_водителям_тоже_пишут(client, заявка_с_откликами, пуши):
    pax, марат, ильдар, rid, _, _ = заявка_с_откликами
    пуши.clear()

    assert client.post(f"/requests/{rid}/cancel", headers=pax["auth"]).status_code == 200

    адресаты = [uid for uid, _ in пуши]
    assert марат["id"] in адресаты and ильдар["id"] in адресаты, (
        f"заявку отменили молча: {пуши}. Оба водителя продолжают ждать ответа"
    )


def test_обе_двери_гасят_отклики_одной_функцией():
    """Сторож: принятие и отмена не должны разойтись — это уже случалось с другими парами.

    Пока обе зовут `close_open_responses`, водители получают одинаковый ответ откуда бы
    сделка ни закрылась; напишет кто-то свою копию — тексты и правила разъедутся.
    """
    from pathlib import Path

    src = (Path(__file__).resolve().parents[1] / "app" / "routers" / "requests.py").read_text(encoding="utf-8")
    assert src.count("close_open_responses(") >= 3, (
        "одна из дверей (принятие или отмена) перестала гасить чужие отклики — "
        "водители снова будут ждать ответа, которого не будет"
    )
