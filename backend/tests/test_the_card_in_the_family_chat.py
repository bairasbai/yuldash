# -*- coding: utf-8 -*-
"""Карточка поездки в семейном чате не должна печатать «Больница» (волна 210).

Волной 160 закрыли витрину `GET /r/{id}/preview`: она отдавала анониму `category: "hospital"`
рядом с именем водителя, датой и маршрутом. Причина была не в проверке доступа, а в том,
что обезличенная копия поездки готовилась, но использовалась только как признак «показывать
или нет» — а в витрину уходил исходный объект.

Соседняя дверь того же файла — HTML-страница `GET /r/{id}`, та самая, что уходит ссылкой
в мессенджер и разворачивается карточкой, — осталась на исходной поездке:

    if not ride or not _shareable(ride, session):     # результат выброшен
        raise herr(404, ...)
    return HTMLResponse(_render_html(_preview_dict(ride, session), lang))
                                     ^^^^ не обезличенная копия

Сегодня наружу текстом не выходит по случайности: в словаре подписей `_CATEGORY` нет ключа
`hospital`, и подпись падает в запасную «Поездка». Дыра латентная — откроется в день, когда
кто-нибудь допишет строку «Больница / Дауахана»: правку на одну строку, выглядящую как
улучшение. Тогда карточка в семейном чате начнёт печатать «БОЛЬНИЦА» рядом с именем
водителя, датой и маршрутом.

Поэтому сторожа тут два, и оба нужны:

* первый смотрит НА ВХОД в отрисовку — какую поездку дверь вообще передала рисовать.
  Он не зависит ни от словаря подписей, ни от вёрстки: пока дверь строит страницу
  по исходной поездке, он красный;
* второй показывает последствие по-человечески — дописывает недостающую подпись
  и читает готовую страницу глазами того, кому ссылку прислали.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import Ride, UserRole

from test_api import _ride


@pytest.fixture
def поездка_в_клинику(client, user_factory) -> int:
    """Опубликованная поездка с пометкой «в больницу»."""
    водитель = user_factory("КарточкаКлиника", role=UserRole.driver)
    ride_id = _ride(client, водитель, comment="в РКБ на приём")
    with Session(engine) as s:
        r = s.get(Ride, ride_id)
        r.category = "hospital"
        s.add(r)
        s.commit()
    return ride_id


def test_страница_рисуется_по_обезличенной_копии(client, поездка_в_клинику, monkeypatch):
    """Главное: дверь обязана отдавать в отрисовку копию без связки с клиникой.

    Ловим на входе в отрисовку, а не по готовому HTML: иначе тест проверяет словарь подписей
    `_CATEGORY`, а не саму дверь, и назавтра, когда подпись допишут, он останется зелёным
    ровно в тот момент, когда дыра откроется.
    """
    from app.routers import share

    отданное: list[dict] = []
    настоящая = share._render_html

    def перехват(p: dict, lang: str) -> str:
        отданное.append(p)
        return настоящая(p, lang)

    monkeypatch.setattr(share, "_render_html", перехват)

    ответ = client.get(f"/r/{поездка_в_клинику}")
    assert ответ.status_code == 200, ответ.text
    assert отданное, "страница отрисовалась мимо перехвата — тест слеп"

    assert отданное[0]["category"] != "hospital", (
        "публичная страница поездки строится по исходной поездке, а не по обезличенной копии: "
        "в отрисовку ушла связка с клиникой. Номера поездок идут подряд, так что за вечер "
        "собирается список, кто из района и когда ездит лечиться"
    )


def test_готовая_страница_не_печатает_слово_больница(client, поездка_в_клинику, monkeypatch):
    """То же самое, но глазами человека, которому прислали ссылку.

    Подпись `hospital` в словаре сейчас отсутствует — именно она и есть та единственная
    строка, которую однажды допишут «для полноты». Дописываем её здесь сами, чтобы
    проверять дверь, а не сегодняшнюю случайность.
    """
    from app.routers import share

    monkeypatch.setitem(share._CATEGORY, "hospital", ("Больница", "Дауахана"))

    страница = client.get(f"/r/{поездка_в_клинику}").text

    assert "Больница" not in страница and "Дауахана" not in страница, (
        "карточка поездки в семейном чате напечатала «Больница» рядом с именем водителя, "
        "датой и маршрутом — вход для этого не требовался"
    )


def test_обычная_поездка_на_странице_осталась(client, user_factory):
    """Обратная сторона: ссылкой делятся, чтобы её открыли — страница обязана работать.

    Без этого «починкой» сошёл бы и голый 404 на всё подряд.
    """
    водитель = user_factory("КарточкаОбычная", role=UserRole.driver)
    ride_id = _ride(client, водитель, comment="Баймак — Сибай, карточка")

    ответ = client.get(f"/r/{ride_id}")

    assert ответ.status_code == 200, ответ.text
    assert "Баймак" in ответ.text and "Сибай" in ответ.text, (
        "публичная страница перестала показывать маршрут — делиться нечем"
    )


# ---------------------------------------------------------------------------
# Разбор мутаций: подпись категории на странице не сторожил никто.
#
# Мутация «страница вообще перестала печатать категорию» (`_CATEGORY` не спрашиваем,
# всегда «Поездка») прошла мимо всего набора — 88 соседних тестов остались зелёными.
# Это не равносильная замена, а тихая поломка: курьер, который делится ссылкой
# на посылку, получил бы в чате карточку «Поездка».
#
# И для сторожей выше это важно вдвойне. Второй из них читает готовую страницу
# и молчит, когда слова «Больница» на ней нет. Если однажды подпись выкинут совсем,
# он останется зелёным по неверной причине — не потому, что дверь чинена, а потому,
# что печатать стало нечего. Первый сторож (по входу в отрисовку) от этого защищён,
# а договор ниже держит второго.
# ---------------------------------------------------------------------------
def test_подпись_категории_на_странице_настоящая(client, user_factory):
    """Договор: страница печатает подпись именно той категории, что у поездки.

    Берём «Посылку» — она в словаре подписей есть, в отличие от больничной, и её
    как раз рассылают ссылкой. Проверяем оба языка: односторонняя надпись — тоже
    поломка (правило проекта про два языка).
    """
    водитель = user_factory("КарточкаПосылка", role=UserRole.driver)
    ride_id = _ride(client, водитель, comment="посылку до Сибая", category="parcel")

    ru = client.get(f"/r/{ride_id}").text
    ba = client.get(f"/r/{ride_id}?lang=ba").text

    assert "Посылка" in ru, (
        "страница не назвала посылку посылкой — человек в чате видит просто «Поездка» "
        "и не понимает, что ему прислали"
    )
    assert "Ебәрмә" in ba, "башкирская версия страницы потеряла подпись категории"
