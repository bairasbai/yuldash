# -*- coding: utf-8 -*-
"""Ни одна таблица не растёт вечно «просто так» — либо чистится, либо решение записано.

Аудит 2026-08-12, волна 29. Ночная чистка в проекте подробная, но список того, что она НЕ
трогает, не вёл никто: из 61 таблицы 42 не упоминались в ней вообще. Часть из них — правильно
вечные (деньги, согласия, репутация), часть просто забыли (предрейсовые самопроверки водителя,
рабочие смены, журнал помеченных текстов, «недавние адреса» человека).

Отличить одно от другого было НЕЛЬЗЯ: и то и другое выглядело как молчание.

Этот сторож заставляет решать явно. Новая таблица → красный тест, пока её не отнесут либо
к чистке, либо к `cleanup.KEEP_FOREVER` с человеческой причиной. Тот же приём, что самопроверка
в тесте удаления аккаунта: она уже дважды поймала забытую таблицу раньше, чем это сделал человек.
"""
from sqlmodel import SQLModel

import app.models  # noqa: F401 — импорт наполняет metadata всеми таблицами
from app.cleanup import KEEP_FOREVER, _ALLOWED_TABLES, _rules
from app.timeutil import utcnow


def _cleaned_tables() -> set:
    """Таблицы, которые ночная чистка реально трогает (из самих правил, а не из списка рядом)."""
    return {table for _label, table, _where, _params in _rules(utcnow())}


def test_у_каждой_таблицы_есть_решение_о_сроке_хранения():
    """Либо чистим, либо записали причину, почему храним вечно. Молчания быть не должно."""
    all_tables = set(SQLModel.metadata.tables)
    decided = _cleaned_tables() | set(KEEP_FOREVER)
    forgotten = sorted(all_tables - decided)

    assert forgotten == [], (
        "у этих таблиц нет решения о сроке хранения — они просто растут: "
        f"{forgotten}. Добавь правило в cleanup._rules() ИЛИ строку в cleanup.KEEP_FOREVER "
        "с причиной, почему храним бессрочно (152-ФЗ, ст. 5 п. 7: дольше цели — нельзя)."
    )


def test_причины_вечного_хранения_написаны_по_человечески():
    """Причина — это объяснение, а не отписка «нужно». Читать её будет человек, а не машина."""
    for table, reason in KEEP_FOREVER.items():
        assert len(reason) >= 15, f"причина для {table} слишком короткая: {reason!r}"


def test_чистка_не_трогает_таблиц_вне_белого_списка():
    """SQL собирается по имени таблицы — белый список обязан покрывать все правила."""
    outside = sorted(_cleaned_tables() - set(_ALLOWED_TABLES))
    assert outside == [], f"правило чистит таблицу вне белого списка: {outside}"


def test_вечное_и_чистимое_не_пересекаются_без_объяснения():
    """Таблица в обоих списках — это нормально (чистим с большим окном), но причина обязана
    об этом говорить: иначе читатель решит, что данные хранятся вечно, и ошибётся."""
    both = sorted(set(KEEP_FOREVER) & _cleaned_tables())
    for table in both:
        reason = KEEP_FOREVER[table]
        assert "_DAYS" in reason or "окно" in reason or "чистим" in reason, (
            f"{table} и чистится, и помечена как вечная, а причина об этом молчит: {reason!r}"
        )
