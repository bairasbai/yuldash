"""Один человек без аккаунта раздувал память сервера — и получал вдвое больше, чем прислал.

Проверка размера у нас была, но срабатывала ПОСЛЕ приёма: файл на 25 МБ честно получал
«слишком большой» — уже будучи целиком прочитанным и раскодированным. А для обычных запросов
потолка не было вовсе (аудит 2026-08-08, волна 148).

Проба на живом сервере: десять параллельных запросов по 20 МБ на форму входа (аккаунт не нужен)
подняли память процесса с 319 МБ до 997 МБ и задержали обычный `/health` почти на две секунды.

Вторая половина той же беды: ответ «заполни поля» возвращал присланное тело ОБРАТНО — по копии
на каждое незаполненное поле. У формы входа два обязательных поля, значит ответ выходил ровно
вдвое больше запроса. Сервер работал усилителем чужого трафика вместо того, чтобы его гасить.

Сегодня на проде это прикрыто настройкой веб-сервера, но в задачах стоит поднять её ради
загрузки фото. В тот день дыра стала бы вдвое шире, и со стороны приложения её ничто
не остановило бы. Защита должна жить в самом приложении: оно не может полагаться на то,
что перед ним всегда стоит правильно настроенный сервер.
"""
from __future__ import annotations

import base64

import pytest

from app.bodyguard import PLAIN_BODY_LIMIT, _limit_for
from app.config import settings


def test_непомерный_запрос_отбивается_сразу(client):
    """Главное: человек без аккаунта не должен занимать память сервера гигабайтами."""
    тело = {"phone": "+79990001111", "code": "1" * (PLAIN_BODY_LIMIT + 50_000)}

    r = client.post("/auth/verify", json=тело)

    assert r.status_code == 413, (
        f"запрос на {PLAIN_BODY_LIMIT + 50_000} байт принят (ответ {r.status_code}): "
        "десяток таких параллельно поднимает память сервера втрое и подвешивает его"
    )
    assert "ru" in r.text and "ba" in r.text, f"отказ не на двух языках: {r.text[:120]}"


def test_обычный_вход_работает(client):
    """Обратная сторона: настоящая форма входа маленькая и должна проходить."""
    r = client.post("/auth/verify", json={"phone": "+79990001112", "code": "123456"})

    assert r.status_code != 413, f"обычный вход отбит по размеру: {r.text[:120]}"


def test_ответ_на_пустую_форму_не_пересказывает_тело(client):
    """Ответ не должен быть больше запроса — иначе сервер усиливает чужой трафик."""
    длинное = "я" * 20_000

    r = client.post("/auth/verify", json={"lishnee": длинное})

    assert r.status_code == 422, r.status_code
    assert длинное not in r.text, (
        f"ответ вернул присланное тело обратно ({len(r.text)} символов при запросе "
        f"{len(длинное)}): на каждое незаполненное поле шла копия данных"
    )
    assert len(r.text) < 1000, f"ответ на незаполненную форму раздут: {len(r.text)} символов"


def test_человеку_понятно_что_заполнить(client):
    """Обратная сторона: убрав пересказ данных, нельзя убрать смысл сообщения."""
    r = client.post("/auth/verify", json={"phone": "+79990001113"})

    assert r.status_code == 422
    assert "code" in r.text, (
        f"человек не понимает, какое поле незаполнено: {r.text[:150]}"
    )
    assert '"ba"' in r.text, "ответ только на одном языке"


def test_фото_по_прежнему_загружается(client, user_factory):
    """Загрузкам нужен свой потолок: обычный запрос маленький, а фото — нет."""
    человек = user_factory("РазмерФото")
    картинка = b"\x89PNG\r\n\x1a\n" + b"\x00" * 400_000       # 400 КБ, больше обычного потолка

    r = client.post("/upload/photo", headers=человек["auth"],
                    json={"photo_b64": base64.b64encode(картинка).decode(), "ext": "png"})

    assert r.status_code != 413, (
        f"фото на 400 КБ отбито по размеру ({r.text[:120]}): люди не смогут прислать документы"
    )


def test_потолок_загрузки_выше_обычного():
    """Проверяем само правило: у загрузок свой запас, у остальных — узкий."""
    обычный = _limit_for("/auth/verify")
    загрузка = _limit_for("/upload/photo")

    assert обычный == PLAIN_BODY_LIMIT, обычный
    assert загрузка > обычный, "у загрузки потолок не больше обычного — фото не пройдёт"
    assert загрузка >= settings.max_upload_bytes, (
        f"потолок запроса ({загрузка}) ниже разрешённого размера файла "
        f"({settings.max_upload_bytes}): человек не сможет прислать файл, который мы обещали принять"
    )


@pytest.mark.parametrize("путь", ["/upload/photo", "/upload/evidence", "/voice", "/upload/chat-photo"])
def test_все_двери_загрузки_знают_про_свой_потолок(путь: str):
    """Сторож: новая ручка загрузки не должна упереться в узкий обычный потолок.

    Иначе люди получат «слишком большой запрос» на обычное фото — и не поймут, почему.
    """
    assert _limit_for(путь) > PLAIN_BODY_LIMIT, (
        f"{путь} считается обычным запросом: человек не сможет прислать через него файл"
    )
