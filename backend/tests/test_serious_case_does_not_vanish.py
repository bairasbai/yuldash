"""Тяжёлый спор не должен исчезать по звонку обвинённого.

История. Гульнара подала обращение о домогательстве. Обвинённый звонит: «убери жалобу,
разойдёмся миром». Она соглашается и нажимает «Мы решили миром».

Дело закрывалось совсем — и пропадало у админа со всех вкладок (аудит 2026-08-08, волна 126).
Человек, на которого пожаловались, завтра повезёт кого-то ещё, и в Юлдаше об этом обращении
не останется ни следа, ни решения.

Давление на заявителя — обычная часть таких историй, и продукт не должен делать его рабочим
инструментом. Поэтому по тяжёлым типам (домогательство, небезопасное вождение, невыплата,
пропавшая посылка, подмена содержимого) «мир» теперь фиксирует ПОЗИЦИЮ заявителя — «претензий
не имею» — а решение по-прежнему принимает Юлдаш. Тот же принцип, что и с подтверждённой
жалобой: наказание определяет не пострадавший.

Обычные бытовые споры закрываются миром как раньше: «поспорили из-за пятидесяти рублей,
договорились» — это действительно дело двоих.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import Incident, UserRole

from test_api import _ride


@pytest.fixture
def спор(client, user_factory):
    """Пассажирка едет с водителем и подаёт обращение. Тип задаётся в тесте."""
    водитель = user_factory("СпорВодитель", role=UserRole.driver)
    гульнара = user_factory("СпорГульнара")
    ride_id = _ride(client, водитель, comment="разбор")
    bid = client.post("/bookings", headers=гульнара["auth"],
                      json={"ride_id": ride_id, "seats": 1}).json()["id"]
    client.post(f"/bookings/{bid}/confirm", headers=водитель["auth"])

    def подать(тип: str) -> int:
        r = client.post("/incidents", headers=гульнара["auth"], json={
            "booking_id": bid, "type": тип, "text": "описание",
            "respondent_id": водитель["id"],
        })
        assert r.status_code == 200, r.text
        return r.json()["id"]

    return гульнара, водитель, подать


def _статус(iid: int) -> str:
    with Session(engine) as s:
        return s.get(Incident, iid).status


def test_домогательство_не_закрывается_миром(client, спор):
    """Главное: обращение остаётся у Юлдаша, даже если заявительница передумала."""
    гульнара, _, подать = спор
    iid = подать("harassment")

    r = client.post(f"/incidents/{iid}/withdraw", headers=гульнара["auth"])

    assert r.status_code == 200, r.text
    assert _статус(iid) != "closed", (
        "обращение о домогательстве исчезло по нажатию «решили миром» — обвинённый звонит "
        "и просит убрать, а завтра он везёт кого-то ещё"
    )


def test_позиция_заявителя_записана(client, спор):
    """Мир не пропадает зря: админ должен видеть, что претензий больше нет."""
    гульнара, _, подать = спор
    iid = подать("harassment")

    client.post(f"/incidents/{iid}/withdraw", headers=гульнара["auth"])

    with Session(engine) as s:
        заметка = s.get(Incident, iid).resolution_note or ""
    assert "претензий" in заметка.lower(), f"позиция заявителя не записана: {заметка!r}"


def test_обеим_сторонам_честно_объясняют(client, спор):
    """Нельзя делать вид, что дело закрыто: человек должен понимать, чего ждать."""
    гульнара, водитель, подать = спор
    iid = подать("harassment")

    client.post(f"/incidents/{iid}/withdraw", headers=гульнара["auth"])

    for кто in (гульнара, водитель):
        тексты = str(client.get("/notifications", headers=кто["auth"]).json())
        assert "решение всё равно принимает Юлдаш" in тексты or "записали" in тексты.lower(), (
            f"человеку не сказали, что разбор продолжается: {тексты[:200]}"
        )


def test_небезопасное_вождение_тоже_остаётся(client, спор):
    """Список тяжёлых типов — общий, и он не про один только harassment."""
    гульнара, _, подать = спор
    iid = подать("unsafe")

    client.post(f"/incidents/{iid}/withdraw", headers=гульнара["auth"])

    assert _статус(iid) != "closed", "жалоба на опасную езду закрыта по просьбе водителя"


def test_бытовой_спор_закрывается_миром_как_раньше(client, спор):
    """Обратная сторона: «нагрубил, потом извинился» — это действительно дело двоих."""
    гульнара, _, подать = спор
    iid = подать("rude")

    r = client.post(f"/incidents/{iid}/withdraw", headers=гульнара["auth"])

    assert r.status_code == 200, r.text
    assert _статус(iid) == "closed", (
        "обычный спор перестал закрываться миром — теперь люди не могут разойтись по-соседски"
    )


def test_тяжёлые_типы_берутся_из_общего_списка():
    """Сторож: список тяжёлых типов один на проект, второй копии быть не должно."""
    from pathlib import Path

    src = (Path(__file__).resolve().parents[1] / "app" / "routers" / "incidents.py").read_text(encoding="utf-8")
    блок = src[src.index("def withdraw_incident"):]
    блок = блок[: блок.index("\n\n\n") if "\n\n\n" in блок else len(блок)]
    assert "SEVERE_TYPES" in блок, (
        "«мир» снова решает сам, какой спор считать тяжёлым — список должен быть один "
        "на весь проект, иначе новый тип беды доедет не до всех дверей"
    )
