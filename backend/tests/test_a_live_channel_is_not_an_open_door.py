# ------------------------------ сторож по исходникам ------------------------------
def _каналы_без_замка(текст: str, имя: str = "образец.py") -> list:
    """Каналы, где не хватает проверки личности или живого стража.

    Ищем по признакам, а не по списку путей: список устареет на первом же новом канале.

    - **личность** — `authenticate_ws`: без него в канал войдёт кто угодно;
    - **живой страж** — `watch_ws_access`: без него человек, который вышел из аккаунта
      или потерял право на поездку, остаётся в канале до закрытия приложения.
    """
    куски = re.split(r'(@router\.websocket\(\s*["\']([^"\']+)["\'])', текст)
    находки = []
    for i in range(1, len(куски), 3):
        путь = куски[i + 1]
        тело = куски[i + 2] if i + 2 < len(куски) else ""
        конец = тело.find("\n@router")
        if конец != -1:
            тело = тело[:конец]
        нет = []
        if "authenticate_ws" not in тело:
            нет.append("проверки личности")
        if "watch_ws_access" not in тело:
            нет.append("живого стража")
        if нет:
            находки.append(f"{имя}: {путь} — нет {' и '.join(нет)}")
    return находки


def test_у_каждого_живого_канала_есть_замок():
    """Главное на будущее: новый канал не появится без проверки и без стража."""
    находки = []
    for файл in sorted(КОРЕНЬ.glob("*.py")):
        находки += _каналы_без_замка(файл.read_text(encoding="utf-8"), файл.name)

    assert not находки, (
        f"{len(находки)} живых каналов без замка: {находки}. Через них идут координаты "
        "машины и переписка — незапертый канал слушают молча, и никто об этом не узнает"
    )


def test_сторож_видит_обе_ошибки_и_не_выдумывает_третью():
    """Проверка самого сторожа: слепой и придирчивый ломаются одинаково тихо."""
    голый = '''
@router.websocket("/ws/new/{thing_id}")
async def new_feed(websocket, thing_id: int):
    await websocket.accept()
    manager.register(thing_id, websocket)
'''
    без_стража = '''
@router.websocket("/ws/new/{thing_id}")
async def new_feed(websocket, thing_id: int):
    await websocket.accept()
    user_id = authenticate_ws(token, s).id
    manager.register(thing_id, websocket)
'''
    без_личности = '''
@router.websocket("/ws/new/{thing_id}")
async def new_feed(websocket, thing_id: int):
    await websocket.accept()
    страж = await watch_ws_access(websocket, token, lambda s2: True)
    manager.register(thing_id, websocket)
'''
    правильный = '''
@router.websocket("/ws/new/{thing_id}")
async def new_feed(websocket, thing_id: int):
    await websocket.accept()
    user_id = authenticate_ws(token, s).id
    страж = await watch_ws_access(websocket, token, lambda s2: True)
    manager.register(thing_id, websocket)
'''
    обычная_ручка = '''
@router.get("/rides/near")
def rides_near(user=Depends(current_user)):
    return []
'''

    assert len(_каналы_без_замка(голый)) == 1, "сторож не видит канал вообще без защиты"
    assert "живого стража" in _каналы_без_замка(без_стража)[0], (
        "сторож не заметил канал без живого стража — человек останется слушать после выхода"
    )
    assert "проверки личности" in _каналы_без_замка(без_личности)[0], (
        "сторож не заметил канал без проверки личности — туда войдёт кто угодно"
    )
    assert not _каналы_без_замка(правильный), "сторож ругается на правильный канал"
    assert not _каналы_без_замка(обычная_ручка), "сторож цепляется к обычной ручке"
