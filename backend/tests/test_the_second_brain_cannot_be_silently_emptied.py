"""Второй мозг нельзя обрезать молча.

Волна 209. Скрипт, дописывавший разбор волны в конец документа, был написан так:

    io.open(p, "w").write(io.open(p).read() + новое)

Python сначала вычисляет то, у чего вызывают метод, — то есть открывает файл НА ЗАПИСЬ
и обнуляет его, и только потом читает уже пустой файл. В `docs/audit-security-2026-08-08.md`
осталось 2 КБ вместо 400 КБ, в `docs/lessons.md` — 2 КБ вместо 450 КБ. 850 КБ разбора
и уроков исчезли, и ни один тест этого не заметил.

Заметил случайный: `test_dependencies_do_not_surprise` требует, чтобы в аудите было слово
`ecdsa`, — он и покраснел. Если бы автор той проверки выбрал другое слово или другой файл,
пропажу нашли бы через недели, когда второй мозг понадобился бы новому агенту.

Сторож считает РАЗДЕЛЫ, а не байты: документы только растут, поэтому нижняя граница
не устаревает и её не надо подкручивать. Обрезание до последнего куска оставляет
единицы разделов — это ловится сразу.
"""
from pathlib import Path

import pytest

ДОКИ = Path(__file__).resolve().parents[2] / "docs"

# файл -> сколько разделов там обязано быть. Взято с большим запасом вниз от текущего
# (примерно половина), чтобы граница не требовала правок при обычном росте документа.
МОЗГ = {
    "00-INDEX.md": 20,
    "architecture.md": 60,
    "decisions.md": 100,
    "lessons.md": 200,
    "tasks.md": 500,
    "audit-security-2026-08-08.md": 190,
    "handoff-audit-2026-08-22.md": 14,
    "design.md": 14,
}


def разделов(текст: str) -> int:
    """Сколько заголовков в документе (# / ## / ###)."""
    return sum(1 for строка in текст.splitlines()
               if строка.startswith(("# ", "## ", "### ")))


def проверить(имя: str, текст: str, минимум: int) -> None:
    было = разделов(текст)
    assert было >= минимум, (
        f"{имя}: осталось {было} разделов, а должно быть не меньше {минимум}. "
        "Похоже, файл обрезали — проверь скрипт, который в него дописывал "
        "(частая причина: открыли на запись до того, как прочитали)"
    )


@pytest.mark.parametrize("имя,минимум", sorted(МОЗГ.items()))
def test_документ_мозга_не_обрезан(имя: str, минимум: int) -> None:
    файл = ДОКИ / имя
    assert файл.exists(), f"{имя}: файла второго мозга нет вовсе"
    проверить(имя, файл.read_text(encoding="utf-8"), минимум)


def test_сторож_видит_обрезанный_файл() -> None:
    """Обратная проверка: скорми сторожу огрызок — он обязан покраснеть.

    Без неё сторож может «проходить» всегда — например, если считать заголовки
    научится неправильно и вернёт большое число на любом тексте.
    """
    огрызок = "\n---\n\n## 🌊 Волна 207 — единственный уцелевший кусок\n\nтекст\n"
    with pytest.raises(AssertionError, match="обрезали"):
        проверить("lessons.md", огрызок, МОЗГ["lessons.md"])


def test_сторож_пропускает_целый_файл() -> None:
    """И не краснеет на нормальном документе — иначе его отключат первым же коммитом."""
    целый = "\n".join(f"## Раздел {i}\n\nтекст\n" for i in range(300))
    проверить("lessons.md", целый, МОЗГ["lessons.md"])
