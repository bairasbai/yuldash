"""Расписание водителя не должно работать наводкой.

Что это за экран. Водитель может завести регулярный маршрут: «Баймак → Сибай, по понедельникам,
средам и пятницам, в 08:00», плюс комментарий — туда пишут ориентиры вроде «забираю у школы».
Полезная вещь: по ней люди и находят постоянную попутку.

В чём была беда (аудит 2026-08-08, волна 113). Отдавалось это всем и всегда, по номеру
водителя, без входа в приложение. Номера идут подряд — то есть посторонний мог пройти по ним
и собрать недельные графики передвижений жителей района. Не отдельные поездки, а сразу ответ
на вопрос «где искать этого человека по вторникам в восемь утра».

Хуже всего было с блокировкой. Гульнара закрылась от навязчивого пассажира — а он продолжал
открывать её расписание и видеть, когда и откуда она выезжает. Кнопка «заблокировать»
обещала больше, чем делала.

Что сделано. Расписание спрашивает ту же общую точку видимости, что и поездки: заблокированный
не видит, снятого с линии не рекламируем. Постороннему без входа расписание по-прежнему видно —
это витрина продукта, ради неё всё и затевалось.
"""
from __future__ import annotations

from datetime import timedelta

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import SafetyProfile, UserRole
from app.timeutil import utcnow


def _снять_с_линии(user_id: int) -> None:
    with Session(engine) as s:
        s.add(SafetyProfile(user_id=user_id, suspended_until=utcnow() + timedelta(days=1)))
        s.commit()


@pytest.fixture
def водитель_с_расписанием(client, user_factory):
    водитель = user_factory("РасписаниеГульнара", role=UserRole.driver)
    r = client.post("/driver/schedule", headers=водитель["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай", "weekdays": "1,3,5",
        "time": "08:00", "comment": "забираю у школы",
    })
    assert r.status_code == 200, r.text
    return водитель


def _расписание(client, driver_id: int, headers=None):
    r = client.get(f"/drivers/{driver_id}/schedule", headers=headers or {})
    assert r.status_code == 200, r.text
    return r.json()


def test_заблокированный_не_видит_расписание(client, водитель_с_расписанием, user_factory):
    """Главное: от кого закрылись, тот не должен знать, когда человек выезжает."""
    навязчивый = user_factory("РасписаниеНавязчивый")
    assert client.post("/blocks", headers=водитель_с_расписанием["auth"],
                       json={"blocked_user_id": навязчивый["id"]}).status_code in (200, 201)

    видит = _расписание(client, водитель_с_расписанием["id"], навязчивый["auth"])

    assert видит == [], (
        "человек, от которого закрылись, по-прежнему видит недельный график: маршрут, дни, "
        "время выезда и ориентир. Это уже не «неудобство», это наводка"
    )


def test_снятого_с_линии_не_рекламируем(client, водитель_с_расписанием):
    _снять_с_линии(водитель_с_расписанием["id"])

    assert _расписание(client, водитель_с_расписанием["id"]) == [], (
        "расписание снятого с линии всё ещё зовёт пассажиров на рейсы, которых не будет"
    )


def test_обычному_человеку_расписание_видно(client, водитель_с_расписанием, user_factory):
    """Обратная сторона: ради этого экрана всё и делалось."""
    сосед = user_factory("РасписаниеСосед")

    видит = _расписание(client, водитель_с_расписанием["id"], сосед["auth"])

    assert len(видит) == 1 and видит[0]["time"] == "08:00", видит


def test_без_входа_расписание_тоже_видно(client, водитель_с_расписанием):
    """Витрина открыта: человек смотрит попутку до того, как заведёт аккаунт."""
    assert len(_расписание(client, водитель_с_расписанием["id"])) == 1


def test_расписание_спрашивает_общую_точку():
    """Сторож: своя проверка здесь снова начнёт отставать от ленты.

    Так уже было дважды — с публичной страницей поездки (волна 112) и с этой ручкой.
    Правил «кому показывать» несколько, и они растут; пока ручка спрашивает общую точку,
    новое правило доезжает до неё само.
    """
    from pathlib import Path

    src = (Path(__file__).resolve().parents[1] / "app" / "routers" / "driver_schedule.py")
    text = src.read_text(encoding="utf-8")
    block = text[text.index('@router.get("/drivers/{driver_id}/schedule"'):]
    block = block[: block.index("\n\n\n")]
    assert "visible_schedules(" in block, (
        "расписание снова решает само, кому себя показывать. Спроси общую точку — иначе "
        "следующее правило видимости опять доедет не до всех дверей."
    )
