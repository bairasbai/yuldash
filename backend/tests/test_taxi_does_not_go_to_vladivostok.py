# -*- coding: utf-8 -*-
"""Палец соскользнул по карте — и водитель потерял работу (волна 187).

История. Человек вызывает такси, карта под пальцем прокручивается, точка назначения улетает
на другой конец страны. Он не замечает и жмёт «Заказать».

Что было дальше. Гейт такси проверял только точку ПОДАЧИ — «работает ли такси в этом
городе». Куда ехать, не смотрел никто. Заказ Баймак → Владивосток (7000 км) уходил в работу
с ценой 83 450 ₽. Проверено пробой целиком, а не рассуждением:

    водитель принял → «на месте» → «в пути» → «завершил»
    цена: 83 450 ₽
    долг водителя платформе: 2 503 ₽
    доступ к работе: 403, заблокирован за долг

То есть промах пассажира отнимал работу у водителя, который ничего не нарушил. Чтобы
вернуться на линию, ему пришлось бы заплатить платформе две с половиной тысячи за поездку,
которой не было. И заметить подмену заранее он не мог: цена в оффере выглядела просто щедрой.

Теперь у такси есть предел расстояния, и он живёт в одном месте — в расчёте цены, через
который ходят все четыре двери: оценка, заказ, предзаказ и повторный поиск воркером.
Тысяча километров — с большим запасом: Башкортостан с севера на юг ~550 км, самые дальние
живые направления (Оренбург, Челябинск, Казань, Самара) ≤700 км.
"""
import fakeredis
import pytest
from sqlmodel import Session, select

from app.config import settings
from app.db import engine
from app import instant_service as isv
from app.models import CommissionDebt, UserRole

БАЙМАК = (52.591, 58.317)
СИБАЙ = (52.716, 58.664)              # обычная поездка, ~28 км
УФА = (54.7351, 55.9587)              # дальний, но живой межгород — ~350 км по прямой
ВЛАДИВОСТОК = (43.1155, 131.8855)     # промах по карте — 7000 км


@pytest.fixture
def fake_redis():
    r = fakeredis.FakeStrictRedis(decode_responses=True)
    isv._redis_override = r
    yield r
    isv._redis_override = None


def _оценка(client, кто, куда):
    return client.post("/instant/estimate", headers=кто["auth"], json={
        "from_lat": БАЙМАК[0], "from_lng": БАЙМАК[1],
        "to_lat": куда[0], "to_lng": куда[1],
        "from_text": "Баймак", "to_text": "куда-то",
    })


def _заказ(client, кто, куда):
    return client.post("/instant/orders", headers=кто["auth"], json={
        "from_lat": БАЙМАК[0], "from_lng": БАЙМАК[1],
        "to_lat": куда[0], "to_lng": куда[1],
        "from_text": "Баймак", "to_text": "куда-то",
    })


def test_заказ_на_другой_конец_страны_не_создаётся(client, user_factory, fake_redis):
    """Главное: промах по карте не должен становиться заказом на 83 тысячи."""
    пассажир = user_factory("Пасс187Промах")

    r = _заказ(client, пассажир, ВЛАДИВОСТОК)

    assert r.status_code == 422, (
        f"заказ Баймак → Владивосток принят ({r.status_code}). Водитель примет его, «завершит» "
        "и получит долг платформе за поездку, которой не было"
    )


def test_человеку_говорят_что_делать_и_на_двух_языках(client, user_factory, fake_redis):
    """Пассажир уверен, что всё сделал правильно: он должен понять, куда смотреть."""
    пассажир = user_factory("Пасс187Текст")

    detail = _заказ(client, пассажир, ВЛАДИВОСТОК).json()["detail"]

    assert detail["ru"] and detail["ba"] and detail["ru"] != detail["ba"], (
        f"отказ не на двух языках: {detail}"
    )
    assert "карт" in detail["ru"].lower(), (
        f"не сказано, что проверить: {detail['ru']!r}. «Слишком далеко» без подсказки — тупик"
    )


def test_у_водителя_не_появляется_долг_за_чужой_промах(client, user_factory, fake_redis):
    """Главная цена дыры была не в цене, а в том, что за неё платил водитель."""
    водитель = user_factory("Води187Промах", role=UserRole.driver)
    assert client.post("/driver/online", headers=водитель["auth"],
                       json={"online": True}).status_code == 200
    client.post("/instant/presence", headers=водитель["auth"],
                json={"lat": БАЙМАК[0], "lng": БАЙМАК[1]})
    пассажир = user_factory("Пасс187Долг")

    _заказ(client, пассажир, ВЛАДИВОСТОК)

    with Session(engine) as s:
        долги = s.exec(select(CommissionDebt).where(
            CommissionDebt.driver_id == водитель["id"])).all()
    assert not долги, f"на водителе повис долг за несуществующую поездку: {долги}"
    ещё_работает = client.post("/instant/presence", headers=водитель["auth"],
                               json={"lat": БАЙМАК[0], "lng": БАЙМАК[1]})
    assert ещё_работает.status_code == 200, "водителя отключили от работы из-за чужого промаха"


def test_оценка_и_заказ_отвечают_одинаково(client, user_factory, fake_redis):
    """Правило одно на все двери: иначе цену покажут, а заказать не дадут (или наоборот)."""
    пассажир = user_factory("Пасс187Двери")

    оценка = _оценка(client, пассажир, ВЛАДИВОСТОК)
    заказ = _заказ(client, пассажир, ВЛАДИВОСТОК)

    assert оценка.status_code == заказ.status_code == 422, (
        f"двери разошлись: оценка {оценка.status_code}, заказ {заказ.status_code}"
    )


def test_предзаказ_тоже_под_правилом(client, user_factory, fake_redis):
    """Третья дверь — «заказать на завтра». Она считает цену тем же расчётом."""
    пассажир = user_factory("Пасс187Предзаказ")

    r = client.post("/instant/schedule", headers=пассажир["auth"], json={
        "from_lat": БАЙМАК[0], "from_lng": БАЙМАК[1],
        "to_lat": ВЛАДИВОСТОК[0], "to_lng": ВЛАДИВОСТОК[1],
        "from_text": "Баймак", "to_text": "куда-то",
        "scheduled_at": "2030-01-01T10:00:00",
    })

    assert r.status_code == 422, f"через предзаказ промах всё ещё проходит: {r.status_code}"


