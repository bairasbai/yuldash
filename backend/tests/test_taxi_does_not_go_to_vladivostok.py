def test_обычная_поездка_работает_как_прежде(client, user_factory, fake_redis):
    """Перестраховка не должна отнять нормальные заказы — иначе я сломал сервис."""
    пассажир = user_factory("Пасс187Обычный")

    r = _заказ(client, пассажир, СИБАЙ)

    assert r.status_code == 200, f"обычная поездка Баймак → Сибай перестала оформляться: {r.text[:200]}"


def test_дальний_межгород_по_республике_разрешён(client, user_factory, fake_redis):
    """Граница взята с запасом: Баймак → Уфа это 350 км, и это живой маршрут."""
    пассажир = user_factory("Пасс187Уфа")

    r = _оценка(client, пассажир, УФА)

    assert r.status_code == 200, (
        f"поездку через полреспублики запретили вместе с промахом: {r.text[:200]}"
    )
    assert r.json()["distance_km"] > 300, r.json()


def test_потолок_живёт_в_настройке_а_не_в_коде(client, user_factory, fake_redis, monkeypatch):
    """Число должно правиться конфигом: границы районов и планы меняются без пересборки."""
    пассажир = user_factory("Пасс187Настройка")
    monkeypatch.setattr(settings, "max_trip_km", 10.0)

    r = _оценка(client, пассажир, СИБАЙ)      # 28 км — теперь за потолком

    assert r.status_code == 422, "потолок захардкожен: настройка ни на что не влияет"
