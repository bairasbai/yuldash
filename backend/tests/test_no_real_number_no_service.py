"""Без настоящего номера в сервис не пускают — и это никто не проверял (волна 182).

Вход через Telegram не даёт номера телефона: приложение заводит человеку заглушку вида
`tg123456789` и ждёт, пока он подтвердит настоящий номер. До этого момента пользоваться
сервисом нельзя — любая ручка отвечает `phone_required`.

Правило не про удобство, а про безопасность. Юлдаш — поездки между своими: человек садится
в чужую машину или пускает чужого к себе. Аккаунт без номера — это аноним: заблокируешь —
заведёт новый за минуту, обидит кого-то — искать будет некого, а полиции нечего предъявить.
Номер и есть та единственная ниточка, которая связывает аккаунт с живым человеком.

**Как нашли.** Волна 182 ломала главные защиты по очереди и смотрела, заметит ли хоть один
тест. Четыре из пяти были прикрыты. Эту — убрал целиком, и **все 3588 тестов остались
зелёными**. То есть защита работала только потому, что её никто не трогал.

Тестовые пользователи её не задевают: у них номера вида `tg-test-7`, а заглушкой считается
`tg` строго с цифрами (`tg123`). Поэтому дыра и не всплывала — обычные тесты этот путь
просто не проходят.
"""
from __future__ import annotations

from datetime import timedelta

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import User, UserRole
from app.security import is_placeholder_phone, make_token
from app.timeutil import utcnow

_счёт = {"n": 0}


def _телеграмный_гость(имя: str = "ГостьИзТелеграма") -> dict:
    """Человек вошёл через Telegram и номер ещё не подтвердил — как в жизни."""
    _счёт["n"] += 1
    n = _счёт["n"]
    with Session(engine) as s:
        u = User(phone=f"tg99{n}0000", name=имя, telegram_id=f"tgguest{n}", verified=True)
        s.add(u)
        s.commit()
        s.refresh(u)
        assert is_placeholder_phone(u.phone), "проба не та: номер не считается заглушкой"
        ток = make_token(u.id)
        return {"id": u.id, "token": ток, "auth": {"Authorization": f"Bearer {ток}"}}


def test_без_номера_в_сервис_не_пускают(client):
    """Главное: аноним не может пользоваться сервисом, пока не подтвердит номер."""
    гость = _телеграмный_гость()

    ответ = client.get("/me", headers=гость["auth"])

    assert ответ.status_code == 403, (
        f"человек вошёл через Telegram, номер не подтвердил — и уже внутри: "
        f"{ответ.status_code}. Такого не забанишь и не найдёшь: заблокируют — "
        f"заведёт новый аккаунт за минуту"
    )
    assert "phone_required" in ответ.text, f"отказ есть, но причина непонятна: {ответ.text[:120]}"


# Лента поездок открыта и без входа — это витрина, там ничего личного. Правило про номер
# закрывает ДЕЙСТВИЯ и личные данные: свои брони, уведомления, кошелёк, публикацию поездки.
@pytest.mark.parametrize("дверь,метод,тело", [
    ("/notifications", "get", None),
    ("/bookings/mine", "get", None),
    ("/driver/debt", "get", None),
    ("/rides", "post", {"from_city": "Сибай", "to_city": "Уфа", "seats": 3,
                        "price": 700, "depart_at": "2027-01-01T10:00:00"}),
])
def test_анонима_не_пускают_ни_в_одну_дверь(client, дверь, метод, тело):
    """Дверей много, и закрыты должны быть все — иначе правило пустое."""
    гость = _телеграмный_гость()

    ответ = getattr(client, метод)(дверь, headers=гость["auth"], **({"json": тело} if тело else {}))

    assert ответ.status_code == 403, (
        f"{дверь}: аноним без номера прошёл ({ответ.status_code})"
    )


def test_подтвердил_номер_и_работает(client):
    """Обратная сторона: правило не должно запирать того, кто номер уже дал."""
    гость = _телеграмный_гость("ПодтвердилНомер")
    with Session(engine) as s:
        u = s.get(User, гость["id"])
        u.phone = f"+7999000{гость['id']:04d}"
        s.add(u)
        s.commit()

    ответ = client.get("/me", headers=гость["auth"])

    assert ответ.status_code == 200, (
        f"человек подтвердил настоящий номер, а его всё равно не пускают: {ответ.text[:150]}"
    )


def test_пустой_номер_тоже_считается_анонимом(client):
    """Заглушка бывает не только телеграмная: пустое поле — тот же аноним."""
    _счёт["n"] += 1
    with Session(engine) as s:
        u = User(phone="", name="БезНомераВовсе", telegram_id=f"empty{_счёт['n']}",
                 verified=True, role=UserRole.passenger)
        s.add(u)
        s.commit()
        s.refresh(u)
        ток = make_token(u.id)

    ответ = client.get("/me", headers={"Authorization": f"Bearer {ток}"})

    assert ответ.status_code == 403, "человек без номера вообще ходит по сервису свободно"


def test_правило_не_ломается_о_старый_токен(client):
    """Контроль: отказ именно про номер, а не про протухший вход — их легко перепутать."""
    гость = _телеграмный_гость("СвежийТокен")
    with Session(engine) as s:
        u = s.get(User, гость["id"])
        u.tokens_valid_from = utcnow() - timedelta(days=365)
        s.add(u)
        s.commit()

    ответ = client.get("/me", headers=гость["auth"])

    assert ответ.status_code == 403 and "phone_required" in ответ.text, (
        f"ожидали отказ про номер, пришло другое: {ответ.status_code} {ответ.text[:120]}"
    )
