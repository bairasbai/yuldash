"""Рассылка курьерам не должна звать того, от кого отправитель закрылся.

История. Гульнара заблокировала Ильдара — это обещание «мы больше не пересекаемся». Она
заказывает курьера Сибай → Баймак, и телефон Ильдара звенит: «Новая доставка рядом 📦».
Он открывает вкладку — пусто. Пробует взять по прямой ссылке — «Эту посылку взять нельзя».

Для него это выглядит либо как поломка приложения, либо как подсказка «кто-то тут от меня
прячется» — оба варианта плохие (аудит 2026-08-08, волна 129).

Личные данные при этом не утекали: в уведомлении только города. Но обещание кнопки
«Заблокировать» — это не только про данные, а про то, чтобы человека вообще не звали
туда, где он встретит того, от кого закрылся.

Гейты в рассылке уже стояли: отстранённый разбором, пауза по качеству, долг по комиссии,
чужая зона. Блокировки среди них не было — ровно тот же класс, что чинили в волне 61
(рассылка звала наказанных) и в волне 77 (оповещения «карауль маршрут»).
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

import app.services as svc
from app.db import engine
from app.models import CourierApplication, CourierProfile, UserRole


@pytest.fixture(autouse=True)
def курьерская_служба_включена():
    """Гейт запуска: в проде курьер пока выключен, а проверяем мы именно его рассылку."""
    from app.config import settings
    было = settings.courier_enabled
    settings.courier_enabled = True
    yield
    settings.courier_enabled = было


@pytest.fixture
def пуши(monkeypatch):
    поймано: list[int] = []
    monkeypatch.setattr(svc, "send_push", lambda s, uid, t, b, data=None: поймано.append(uid))
    return поймано


@pytest.fixture
def курьер_на_линии(client, user_factory):
    """Одобренный курьер, на линии, без долгов и пауз, зона не ограничена."""
    def создать(имя: str):
        человек = user_factory(имя, role=UserRole.driver)
        with Session(engine) as s:
            # Одобрение живёт в ЗАЯВКЕ — её и спрашивают гейт курьера и рассылка
            # (`courier.courier_not_allowed_reason`, волна 222). `status` на профиле ниже
            # оставлен как был: он тут ни на что не влияет и никем не читается.
            s.add(CourierApplication(user_id=человек["id"], status="approved",
                                     full_name="Курьер Курьеров", transport="car",
                                     rules_accepted=True))
            s.add(CourierProfile(
                user_id=человек["id"], status="approved", online=True,
                zone=None,          # зона не выбрана → курьер берёт любые заказы
                work_intercity=True, work_regions=True,
            ))
            s.commit()
        return человек
    return создать


def _заказ_курьера(client, отправитель) -> int:
    """Именно КУРЬЕРСКАЯ заявка: у «по пути» рассылки нет вовсе (там берёт попутчик)."""
    r = client.post("/courier/orders", headers=отправитель["auth"], json={
        "from_city": "Сибай", "to_city": "Баймак",
        "from_lat": 52.9, "from_lng": 58.66, "to_lat": 52.6, "to_lng": 58.3,
        "size": "small", "description": "лекарство",
        "receiver_name": "Мама", "receiver_phone": "+79990000129",
        "rules_accepted": True, "delivery_type": "courier", "urgency": "bypath",
    })
    assert r.status_code == 200, r.text
    return r.json()["id"]


def test_заблокированного_курьера_не_зовут(client, user_factory, курьер_на_линии, пуши):
    """Главное: телефон человека не должен звенеть заказом, который ему всё равно закроют."""
    гульнара = user_factory("РассылкаГульнара")
    ильдар = курьер_на_линии("РассылкаИльдар")
    assert client.post("/blocks", headers=гульнара["auth"],
                       json={"blocked_user_id": ильдар["id"]}).status_code in (200, 201)
    пуши.clear()

    _заказ_курьера(client, гульнара)

    assert ильдар["id"] not in пуши, (
        "заблокированному курьеру пришло «Новая доставка рядом»: он откроет список — пусто, "
        "попробует взять — откажут. Для него это или поломка, или намёк, что от него прячутся"
    )


def test_блокировка_действует_и_в_обратную_сторону(client, user_factory, курьер_на_линии, пуши):
    """Закрылся курьер от отправителя — его тоже не зовут."""
    отправитель = user_factory("РассылкаОтправитель")
    курьер = курьер_на_линии("РассылкаКурьер2")
    assert client.post("/blocks", headers=курьер["auth"],
                       json={"blocked_user_id": отправитель["id"]}).status_code in (200, 201)
    пуши.clear()

    _заказ_курьера(client, отправитель)

    assert курьер["id"] not in пуши, "курьер, закрывшийся от этого отправителя, всё равно позван"


def test_обычного_курьера_зовут(client, user_factory, курьер_на_линии, пуши):
    """Обратная сторона: ради этой рассылки всё и делалось.

    Бабушке срочно нужно лекарство из Сибая, три курьера едут мимо — они должны узнать.
    """
    отправитель = user_factory("РассылкаОтправитель3")
    курьер = курьер_на_линии("РассылкаКурьер3")
    пуши.clear()

    _заказ_курьера(client, отправитель)

    assert курьер["id"] in пуши, (
        f"курьер на линии не получил уведомление о новой доставке: {пуши}"
    )


def test_рассылка_считает_блокировки_один_раз():
    """Сторож: список блокировок должен считаться на всю рассылку, а не на каждого курьера.

    Это горячее место: заявка создаётся, а курьеров на линии могут быть десятки. Наказанные
    и так считаются одним запросом — блокировки обязаны считаться так же, иначе рассылка
    начнёт ходить в базу по разу на человека.
    """
    from pathlib import Path

    src = (Path(__file__).resolve().parents[1] / "app" / "routers" / "parcels.py").read_text(encoding="utf-8")
    блок = src[src.index("def _notify_couriers_new_parcel"):]
    блок = блок[: блок.index("\n\n\n") if "\n\n\n" in блок else len(блок)]
    цикл = блок[блок.index("for prof in rows"):]
    assert "blocked_user_ids(" not in цикл, (
        "список заблокировавших считается внутри цикла по курьерам — это поход в базу "
        "на каждого человека в горячем месте"
    )
    assert "blocked_user_ids(" in блок, (
        "рассылка курьерам снова зовёт заблокированных: у человека звенит телефон заказом, "
        "который ему всё равно закроют"
    )
