"""Час за рулём без связи засчитывался как одна минута (волна 171).

Восьмичасовой лимит смены — про усталость: после восьми часов человек за рулём опасен,
и сервис обязан его остановить. Считалось это время только по сигналам присутствия, которые
приложение шлёт каждые 10–15 секунд, причём у каждого сигнала стоит потолок: редкий пинг
добавляет не больше минуты.

Потолок нужен — иначе один сигнал раз в три часа записал бы три часа «работы» человеку,
который всё это время спал. Но он же терял настоящую работу там, где её больше всего.

**Проба:** водитель час вёз пассажира по трассе между сёлами, где сотовой сети нет. Пингов
не было; связь вернулась — засчиталась **одна минута вместо часа**. Восьмичасовой лимит
превращается в двенадцатичасовой ровно там, где усталость опаснее всего: ночная дорога,
встречный свет, лёд и никакой связи.

Теперь время смены — это **большее из двух измерений**: сколько человек был на линии
по сигналам и сколько фактически вёз людей по самим заказам. Именно большее, а не сумма:
два прибора меряют одно и то же время, складывать их значило бы считать час дважды. Прибор,
который увидел больше, и ближе к правде — сеть могла молчать, а руль нет.
"""
from __future__ import annotations

from datetime import timedelta

import pytest
from sqlmodel import Session, select

from app import workday as wd_mod
from app.config import settings
from app.db import engine
from app.models import InstantOrder, InstantOrderStatus as S, TaxiWorkDay, UserRole
from app.timeutil import utcnow


@pytest.fixture
def таксист(client, user_factory, request):
    """Свой водитель на каждый тест: база общая, и рейсы одного имени копились бы между ними.

    Ровно на этом файл и упал в первый раз — тот же урок, что в волне 167: что создал,
    то и убери, а лучше не пересекайся вовсе.
    """
    return user_factory(f"ТаксистСмена{abs(hash(request.node.name)) % 100000}",
                        role=UserRole.driver)


def _рейс(водитель_id: int, пассажир_id: int, с: object, по: object, статус=S.done) -> None:
    with Session(engine) as s:
        s.add(InstantOrder(passenger_id=пассажир_id, driver_id=водитель_id, status=статус,
                           price_estimate=500, price_final=500,
                           accepted_at=с, onboard_at=с, done_at=(по if статус == S.done else None),
                           from_lat=52.5, from_lng=58.3, to_lat=52.9, to_lng=58.6))
        s.commit()


def _смена(водитель_id: int) -> int:
    with Session(engine) as s:
        день = s.exec(select(TaxiWorkDay).where(
            TaxiWorkDay.driver_id == водитель_id)).first()
        if день is None:
            день = wd_mod._get_or_create_today(s, водитель_id, utcnow())
        return wd_mod.shift_seconds(s, водитель_id, день)


def test_рейс_без_связи_попадает_в_смену(client, таксист, user_factory):
    """Главное: руль крутился, даже если сеть об этом не знала."""
    пассажир = user_factory("ПассажирБезСвязи")
    начало = utcnow() - timedelta(hours=1)
    with Session(engine) as s:
        wd_mod.record_heartbeat(s, таксист["id"], начало)      # вышел на линию
        wd_mod.record_heartbeat(s, таксист["id"], utcnow())    # связь вернулась через час
    _рейс(таксист["id"], пассажир["id"], начало, utcnow())

    засчитано = _смена(таксист["id"])

    assert засчитано >= 3000, (
        f"час за рулём по трассе без связи засчитан как {засчитано} секунд: восьмичасовой "
        "лимит превращается в двенадцатичасовой там, где усталость опаснее всего"
    )


def test_идущий_рейс_тоже_считается(client, таксист, user_factory):
    """Человек в дороге прямо сейчас — время идёт, а не ждёт завершения заказа."""
    пассажир = user_factory("ПассажирВПути")
    _рейс(таксист["id"], пассажир["id"], utcnow() - timedelta(minutes=90), None,
          статус=S.onboard)

    засчитано = _смена(таксист["id"])

    assert засчитано >= 5000, (
        f"водитель полтора часа везёт человека прямо сейчас, а в смене {засчитано} секунд"
    )


def test_время_не_считается_дважды(client, таксист, user_factory):
    """Обратная сторона: два прибора меряют одно время — берём большее, а не сумму.

    Иначе водитель, у которого и связь хорошая, и заказы идут, упрётся в лимит вдвое раньше
    и потеряет полсмены заработка ни за что.
    """
    пассажир = user_factory("ПассажирСоСвязью")
    начало = utcnow() - timedelta(hours=1)
    with Session(engine) as s:                       # связь была всю дорогу: пинги каждую минуту
        for i in range(0, 61):
            wd_mod.record_heartbeat(s, таксист["id"], начало + timedelta(minutes=i))
    _рейс(таксист["id"], пассажир["id"], начало, utcnow())

    засчитано = _смена(таксист["id"])

    assert засчитано <= 4200, (
        f"час работы с хорошей связью засчитан как {засчитано} секунд — время посчитано "
        "дважды, и человек упрётся в лимит вдвое раньше"
    )


def test_лимит_наступает_после_восьми_часов_рейсов(client, таксист, user_factory):
    """Смысл всей проверки: после восьми часов за рулём человека останавливают."""
    пассажир = user_factory("ПассажирДолгий")
    начало = utcnow() - timedelta(hours=9)
    _рейс(таксист["id"], пассажир["id"], начало, начало + timedelta(hours=8, minutes=30))

    засчитано = _смена(таксист["id"])

    assert засчитано >= settings.taxi_shift_limit_hours * 3600, (
        f"после восьми с половиной часов рейсов в смене {засчитано / 3600:.1f} ч — "
        "лимит не наступит, и уставший человек поедет дальше"
    )


def test_чужие_рейсы_в_смену_не_попадают(client, таксист, user_factory):
    """Контроль: считаем только свои поездки."""
    другой = user_factory("ДругойТаксист", role=UserRole.driver)
    пассажир = user_factory("ПассажирЧужой")
    _рейс(другой["id"], пассажир["id"], utcnow() - timedelta(hours=3), utcnow())

    засчитано = _смена(таксист["id"])

    assert засчитано < 600, (
        f"водителю засчитали чужие рейсы: {засчитано} секунд на пустой смене"
    )


def test_вчерашние_рейсы_в_сегодняшнюю_смену_не_попадают(client, таксист, user_factory):
    """Контроль: день считается по местному календарю, вчерашняя работа — не сегодняшняя.

    Берём рейс, целиком уместившийся во вчерашний ДЕНЬ по Уфе. Первая версия теста считала
    «вчера» как «сутки назад», и если запускать её вечером, рейс переходил через полночь —
    четыре часа честно попадали в сегодня, а тест ругался на верный ответ.
    """
    from datetime import datetime, time as time_type
    пассажир = user_factory("ПассажирВчерашний")
    вчерашняя_полночь = (datetime.combine(wd_mod.local_day(utcnow()), time_type())
                         - wd_mod._tz() - timedelta(days=1))
    начало = вчерашняя_полночь + timedelta(hours=8)      # вчера, 8 утра по Уфе
    _рейс(таксист["id"], пассажир["id"], начало, начало + timedelta(hours=6))

    засчитано = _смена(таксист["id"])

    assert засчитано < 3600, (
        f"вчерашние шесть часов попали в сегодняшнюю смену: {засчитано} секунд"
    )
