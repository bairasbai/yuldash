def test_поиск_заранее_на_дату_через_пять_дней_находит_этот_день_и_не_находит_соседние(client, user_factory):
    """Календарь у человека местный: рейс «в 4 утра» лежит в базе вчерашним числом (UTC), но
    найтись обязан в свой день. Проверяем и ранний, и вечерний рейс, и соседние сутки."""
    водитель = user_factory("ДатаВодитель", role=UserRole.driver)
    утро = _опубликовать(client, водитель, "Мелеуз", "Октябрьский", _день(5, 4, 0), comment="затемно")["id"]
    вечер = _опубликовать(client, водитель, "Мелеуз", "Октябрьский", _день(5, 23, 30), comment="поздно")["id"]
    вчера = _опубликовать(client, водитель, "Мелеуз", "Октябрьский", _день(4, 12, 0), comment="за день до")["id"]
    завтра = _опубликовать(client, водитель, "Мелеуз", "Октябрьский", _день(6, 0, 30), comment="после полуночи")["id"]
    день = _день(5).date().isoformat()
    маршрут = {"from_city": "Мелеуз", "to_city": "Октябрьский"}

    for имя, ответ in (
        ("/rides", _ids(_ленту_листаем(client, "/rides", {**маршрут, "date": день}))),
        ("/rides/near", _ids(_near(client, **маршрут, date=день)["items"])),
    ):
        assert {утро, вечер} <= ответ, f"{имя}: на {день} не нашлись рейсы этого дня: {ответ}"
        assert not ({вчера, завтра} & ответ), f"{имя}: в дату {день} попали рейсы соседних суток"

    # Без даты — видны все четыре (дата только сужает).
    все = _ids(_ленту_листаем(client, "/rides", маршрут))
    assert {утро, вечер, вчера, завтра} <= все


