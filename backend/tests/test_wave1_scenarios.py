def test_гость_видит_ленту_без_телефона_и_точной_точки_а_бронь_без_входа_закрыта(client, user_factory):
    """Человек открыл приложение, не входя. Видит, кто куда едет, но не телефон водителя и не
    точку, где он стоит у дома. Нажал «Забронировать» — просьба войти (401), брони не появилось.

    Проверяем ВСЕ три двери ленты (общая лента, «Ближайшие», карточка) и ищем сами строки
    телефона и координат в теле ответа — в любом поле, в том числе в тех, о которых тест не знает."""
    водитель = user_factory("ГостьВодитель", role=UserRole.driver)
    телефон = _дать_телефон(водитель["id"])
    рейс = _опубликовать(
        client, водитель, "Белебей", "Кумертау", _день(5),
        pickup="Белебей, ул. Красная 12, второй подъезд", pickup_lat=54.09871, pickup_lng=54.11213,
        comment=f"Еду аккуратно, звоните {телефон}")
    rid = рейс["id"]

    лента = client.get("/rides", params={"from_city": "Белебей", "to_city": "Кумертау", "limit": 200})
    рядом = client.get("/rides/near", params={"from_city": "Белебей", "to_city": "Кумертау", "limit": 200})
    карточка = client.get(f"/rides/{rid}")
    for имя, r in (("лента", лента), ("«Ближайшие»", рядом), ("карточка", карточка)):
        assert r.status_code == 200, f"{имя}: {r.status_code} {r.text[:200]}"
        for секрет in (телефон, "54.09871", "54.11213", "ул. Красная 12"):
            assert секрет not in r.text, f"гость увидел в ответе «{имя}» личное: {секрет}"

    # Контроль: сама поездка в ленте есть (иначе «ничего не утекло» — потому что ничего нет).
    assert rid in _ids(лента.json()) and rid in _ids(рядом.json()["items"])
    assert карточка.json()["from_city"] == "Белебей" and карточка.json()["pickup"] == ""
    # Контроль: у самого водителя («Мои поездки») точка на месте — значит, прячет сервер,
    # а не данные пропали. Публичная карточка точку не отдаёт никому: она открывается только
    # по подтверждённой брони (`/bookings/{id}/details`).
    своя = next(x for x in client.get("/driver/rides", headers=водитель["auth"]).json() if x["id"] == rid)
    assert своя["pickup"].startswith("Белебей, ул. Красная") and своя["pickup_lat"] == 54.09871

    # Бронь без входа — 401, и брони не появилось.
    r = client.post("/bookings", json={"ride_id": rid, "seats": 1})
    assert r.status_code == 401, r.text
    assert client.get("/driver/bookings", headers=водитель["auth"]).json() == []
    assert client.get(f"/rides/{rid}", headers=водитель["auth"]).json()["seats_left"] == 3


