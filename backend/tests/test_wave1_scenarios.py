def test_друг_из_сибая_а_я_в_уфе_лента_находит_сибай_уфа_без_радиуса(client, user_factory):
    водитель = user_factory("СибайУфаВодитель", role=UserRole.driver)
    рейс = _опубликовать(client, водитель, "Сибай", "Уфа", _день(5, 6, 0))["id"]
    чужой = _опубликовать(client, водитель, "Учалы", "Уфа", _день(5, 6, 0))["id"]

    r = _near(client, from_cities="Сибай", to_cities="Уфа")
    assert рейс in _ids(r["items"]), "«из Сибая» не нашло поездку Сибай → Уфа"
    assert чужой not in _ids(r["items"]), "в «из Сибая» попала поездка из Учалов"

    # Я сам стою в Уфе: координаты передаю (для «сколько км до точки выезда»), радиус — нет.
    # Сибай далеко, но раз радиуса не просили — поездка не режется, а расстояние честно большое.
    r = _near(client, from_cities="Сибай", to_cities="Уфа", lat=УФА[0], lng=УФА[1])
    своя = next((x for x in r["items"] if x["id"] == рейс), None)
