    assert 250 < (своя["distance_km"] or 0) < 330, f"Уфа ↔ Сибай: {своя['distance_km']} км"
    # А вот с радиусом 50 км — «рядом» её уже нет: фильтр по городу и радиус — разные вещи.
    r = _near(client, from_cities="Сибай", to_cities="Уфа", lat=УФА[0], lng=УФА[1], radius_km=50)
    assert рейс not in _ids(r["items"])


