@pytest.mark.parametrize("откуда,куда,где_отправление,почему", [
    ("Белебей", "Кумертау", (54.100, 54.110), "город → город"),
    ("Бакалы", "Уфа", (55.176, 53.802), "райцентр → город"),
    # Аскарово — и райцентр Абзелиловского района, и тёзка-деревня в другом районе (≈230 км южнее).
    # Без уточнения района сервер берёт райцентр — его и ждёт водитель, публикующий «Аскарово → Учалы».
    ("Аскарово", "Учалы", (53.332, 58.526), "райцентр → город, есть тёзка-деревня"),
    ("1-е Иткулово", "Баймак", (52.62894, 57.96766), "настоящая деревня из справочника → город"),
])
def test_водитель_публикует_маршрут_и_сервер_знает_где_он_на_карте(
        client, user_factory, откуда, куда, где_отправление, почему):
    """Публикация проходит для любого места из справочника, а не только для Баймака и Сибая:
    у поездки появляются координаты концов — без них «рядом со мной» эту поездку не найдёт,
    и водитель из деревни жалуется «никто не видит мою поездку»."""
    водитель = user_factory(f"Публикует{откуда[:6]}", role=UserRole.driver)
    рейс = _опубликовать(client, водитель, откуда, куда, _день(5), comment=почему)
    assert рейс["status"] == "active" and рейс["seats_left"] == 3

    в_базе = _рейс_из_базы(рейс["id"])
    assert (в_базе.from_lat, в_базе.from_lng) != (None, None), f"{откуда}: у отправления нет координат"
    assert (в_базе.to_lat, в_базе.to_lng) != (None, None), f"{куда}: у назначения нет координат"
    assert abs(в_базе.from_lat - где_отправление[0]) < 0.01 and abs(в_базе.from_lng - где_отправление[1]) < 0.01, (
        f"{откуда}: отправление поставлено не туда — ({в_базе.from_lat}, {в_базе.from_lng}), "
        f"ждали {где_отправление}")
    # И лента её находит по тому же названию.
    найдено = _ids(client.get("/rides", params={"from_city": откуда, "to_city": куда, "limit": 200}).json())
    assert рейс["id"] in найдено, f"{откуда} → {куда}: опубликованная поездка не нашлась в ленте"


