    # Прошло больше окна — писать нельзя (409), читать можно.
    with Session(engine) as s:
        r = s.get(Ride, s.get(Booking, bid).ride_id)
        r.depart_at = utcnow() - timedelta(hours=settings.chat_after_trip_hours + 5)
        s.add(r)
        s.commit()
    закрыт = client.post(url, headers=водитель["auth"], json={"text": "ещё одно"})
    assert закрыт.status_code == 409 and закрыт.json()["detail"]["ru"] and закрыт.json()["detail"]["ba"], закрыт.text
    assert len(client.get(url, headers=пассажир["auth"]).json()) == 4, "после закрытия история пропала"


