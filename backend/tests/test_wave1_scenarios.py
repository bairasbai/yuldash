def test_чат_брони_до_подтверждения_после_и_после_поездки(client, user_factory):
    """Что разрешено: пока бронь живая (даже не подтверждённая) — оба пишут; посторонний — нет;
    после поездки — ещё 48 часов (забытые вещи), потом чат только для чтения, история остаётся."""
    водитель = user_factory("ЧатВодитель", role=UserRole.driver)
    пассажир = user_factory("ЧатПассажир")
    посторонний = user_factory("ЧатПосторонний")
