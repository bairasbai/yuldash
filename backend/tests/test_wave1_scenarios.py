def test_ссылка_близкого_живёт_без_входа_показывает_этапы_и_гаснет_после_отзыва(client, user_factory):
    """Путь по порядку: поделилась → мама открывает без входа («скоро начнётся») → водитель выехал
    («едет к точке посадки») → брат получил ту же ссылку по ошибке, дочь её отозвала → у брата 404,
    у мамы живёт. Участников поездки ссылка не раскрывает: ни телефонов, ни фамилии, ни точки встречи.
    (Этапы «в пути» и «завершено» — в `journeys/test_journey_path13_share_with_family.py`.)"""
    водитель = user_factory("СсылкаВодитель", role=UserRole.driver)
    пассажир = user_factory("Гульнара Фамилиева")
    тел_п, тел_в = _дать_телефон(пассажир["id"]), _дать_телефон(водитель["id"])
    рейс = _опубликовать(client, водитель, "Кумертау", "Уфа", datetime.now(TZ) + timedelta(hours=3),
                         pickup="Дом культуры, Кумертау", pickup_lat=52.7581, pickup_lng=55.7991)["id"]
    bid = _забронировать(client, пассажир, рейс).json()["id"]
    _подтвердить(client, водитель, bid)

    def поделиться(имя: str, телефон: str):
        c = client.post("/trusted-contacts", headers=пассажир["auth"],
                        json={"name": имя, "relation": имя.lower(), "phone": телефон}).json()
        s = client.post(f"/bookings/{bid}/share", headers=пассажир["auth"], json={"contact_id": c["id"]})
        assert s.status_code == 200, s.text
        return s.json()

    мама, брат = поделиться("Мама", "+79170000801"), поделиться("Брат", "+79170000802")
    assert мама["token"] != брат["token"] and len(мама["token"]) >= 16

    # Страница и данные открываются БЕЗ входа и без приложения.
    страница = client.get(f"/t/{мама['token']}")
    assert страница.status_code == 200 and "noindex" in страница.headers.get("x-robots-tag", "")
    состояние = client.get(f"/t/{мама['token']}/state.json")
    assert состояние.status_code == 200
    assert состояние.json()["status"] == "wait"
    assert состояние.json()["phase_text"] == {"ru": "Поездка скоро начнётся", "ba": "Сәфәр оҙакламай башлана"}

    # Водитель выехал (за час до выезда — раньше сервер «Выехал» не примет, P2-Г) — тот же адрес теперь
    # говорит «едет к точке посадки».
    trip_starts(bid)
    assert client.post(f"/bookings/{bid}/driver-status", headers=водитель["auth"],
                       json={"status": "departed"}).status_code == 200
    assert client.get(f"/t/{мама['token']}/state.json").json()["status"] == "to_pickup"

    # Ссылка не раскрывает людей и места.
    for что, r in (("state.json", client.get(f"/t/{мама['token']}/state.json")), ("страница", страница)):
        for секрет in ("Фамилиева", тел_п, тел_в, "+79170000801", "Дом культуры", "52.7581"):
            assert секрет not in r.text, f"по ссылке близкого ({что}) утекло: {секрет}"

    # Брат получил ссылку по ошибке — отзыв: у него «не найдено», у мамы всё работает; угадать нельзя.
    assert client.delete(f"/bookings/{bid}/share/{брат['id']}", headers=пассажир["auth"]).status_code == 200
    assert client.get(f"/t/{брат['token']}/state.json").status_code == 404
    assert client.get(f"/t/{брат['token']}").status_code == 404
    assert client.get(f"/t/{мама['token']}/state.json").status_code == 200
    assert client.get(f"/t/{мама['token'][:-2]}zz/state.json").status_code == 404
    # Отозвать чужую ссылку и делиться чужой поездкой нельзя.
    assert client.post(f"/bookings/{bid}/share", headers=водитель["auth"],
                       json={"contact_id": 1}).status_code == 403


