def _видит(client, кто, водитель_города: tuple[str, str], рейс: int) -> dict[str, bool]:
    """Где этот человек видит поездку: лента, «Ближайшие», карточка по прямой ссылке, список городов."""
    откуда, куда = водитель_города
    заголовки = кто["auth"] if кто else None
    return {
        "лента": рейс in _ids(_ленту_листаем(client, "/rides", {"from_city": откуда, "to_city": куда}, заголовки)),
        "ближайшие": рейс in _ids(_near(client, headers=заголовки, from_city=откуда, to_city=куда)["items"]),
        "карточка": client.get(f"/rides/{рейс}", headers=заголовки).status_code == 200,
        "города": откуда in {c["ru"] for c in client.get("/rides/cities", headers=заголовки).json()["from"]},
    }


