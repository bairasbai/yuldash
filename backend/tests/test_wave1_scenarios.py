def test_регулярная_поездка_создаёт_настоящие_бронируемые_рейсы_раз_в_неделю(client, user_factory):
    """«Каждый понедельник Кумертау → Уфа»: один тап — пять рейсов (этот и четыре следующих),
    ровно через неделю, и любой из них можно забронировать."""
    водитель = user_factory("СерияВодитель", role=UserRole.driver)
    первый = _опубликовать(client, водитель, "Кумертау", "Уфа", _день(5, 6, 0), recurrence="weekly",
                           comment="каждую неделю")
    серия = sorted((r for r in client.get("/driver/rides", headers=водитель["auth"]).json()
                    if r["from_city"] == "Кумертау"), key=lambda r: r["depart_at"])
    assert len(серия) == 5, f"в серии {len(серия)} рейсов вместо пяти"
    моменты = [datetime.fromisoformat(r["depart_at"]) for r in серия]
    assert all(b - a == timedelta(weeks=1) for a, b in zip(моменты, моменты[1:])), (
        f"рейсы серии не через неделю друг от друга: {моменты}")
    assert первый["id"] == серия[0]["id"]
    # Второй тап по «Опубликовать» серию не удваивает: рейсов по-прежнему пять.
    повтор = _опубликовать(client, водитель, "Кумертау", "Уфа", _день(5, 6, 0), recurrence="weekly",
                           comment="каждую неделю")
    assert повтор["id"] == первый["id"]
    assert len([r for r in client.get("/driver/rides", headers=водитель["auth"]).json()
                if r["from_city"] == "Кумертау"]) == 5, "двойной тап удвоил серию рейсов"

    пассажир = user_factory("СерияПассажир")
    r = _забронировать(client, пассажир, серия[3]["id"])
    assert r.status_code == 200, f"рейс серии нельзя забронировать: {r.text}"


