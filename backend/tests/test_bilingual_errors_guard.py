"""Сторож двуязычия серверных ошибок: их число, написанное только по-русски, не должно расти.

Главное правило Юлдаша — любая надпись на двух языках. В приложении оно соблюдается: там
есть свой сторож, который читает исходники экранов. На сервере такого сторожа не было, и
получилось вот что (замер 2026-08-06): **170 ответов двуязычных и 284 только на русском**.

Что это значит для человека. Башкироязычный пользователь видит приложение на своём языке —
ровно до первой ошибки. «Место уже занято», «Заявка не найдена», «Нельзя отменить поездку
за час до выезда» приходят по-русски. То есть язык пропадает именно там, где нужнее всего:
когда что-то пошло не так и надо понять, что делать.

Почему тест с «храповиком», а не с нулём. Перевести 284 строки разом нельзя: башкирский от
модели — черновик, его подтверждает носитель (Александр), и это отдельная работа. Поэтому
тест фиксирует ТЕКУЩЕЕ число и запрещает ему расти: новая односторонняя ошибка роняет сборку,
а перевод старых опускает планку. Так число может только уменьшаться.

Как переводить: вместо `HTTPException(404, "Заявка не найдена")` писать
`herr(404, "Заявка не найдена", "Заявка табылманы")` — `herr` уже умеет отдавать оба языка,
и приложение показывает нужный (`ApiClient.errorMessage`).
"""
from __future__ import annotations

import collections
import pathlib
import re

_ROUTERS = pathlib.Path(__file__).resolve().parents[1] / "app" / "routers"

# Ответы только на русском. Планка может только опускаться.
# Уменьшил число — уменьши и здесь: иначе сторож перестанет сторожить.
# История: 284 при заведении сторожа (2026-08-06) → 270 после перевода самых частых
# (поездка, бронь, чат — то, во что человек упирается каждый день).
RUSSIAN_ONLY_MAX = 270

# Админские ручки переводить не нужно: админ один и он русскоязычный.
_ADMIN_WORDS = ("админ", "admin")

_PLAIN_ERROR = re.compile(r'HTTPException\(\s*(4\d\d)\s*,\s*"([^"]{4,})"')


def _russian_only() -> collections.Counter:
    """Сколько ответов 4xx с текстом только на русском в каждом файле роутеров."""
    found: collections.Counter = collections.Counter()
    for path in sorted(_ROUTERS.glob("*.py")):
        src = path.read_text(encoding="utf-8")
        for m in _PLAIN_ERROR.finditer(src):
            message = m.group(2)
            if any(w in message.lower() for w in _ADMIN_WORDS):
                continue
            found[path.name] += 1
    return found


def test_число_односторонних_ошибок_не_растёт():
    """Новая ошибка только на русском роняет сборку. Это дешевле, чем чинить потом 284 штуки."""
    found = _russian_only()
    total = sum(found.values())
    worst = ", ".join(f"{name}: {n}" for name, n in found.most_common(5))
    assert total <= RUSSIAN_ONLY_MAX, (
        f"Ответов только на русском стало {total} (планка {RUSSIAN_ONLY_MAX}). "
        f"Башкироязычный человек прочитает их на чужом языке — и именно тогда, когда что-то "
        f"пошло не так. Пиши herr(код, «по-русски», «башҡортса») вместо HTTPException.\n"
        f"Больше всего: {worst}"
    )


def test_планка_не_забыта_наверху():
    """Обратная сторона храповика: перевели строки — опустите планку, иначе она перестанет
    ловить новые нарушения. Допуск 15 — чтобы тест не падал после каждой мелкой правки."""
    total = sum(_russian_only().values())
    assert total >= RUSSIAN_ONLY_MAX - 15, (
        f"Односторонних ответов осталось {total}, а планка всё ещё {RUSSIAN_ONLY_MAX}. "
        f"Опусти RUSSIAN_ONLY_MAX до {total} — иначе сторож пропустит новые нарушения."
    )


def test_разбор_вообще_работает():
    """Страховка от «зелено, потому что ничего не нашли»: если регулярка перестанет цеплять
    вызовы, оба теста выше пройдут по нулю и мы этого не заметим."""
    total = sum(_russian_only().values())
    assert total > 50, f"Нашли всего {total} ответов — разбор исходников сломался"


def test_двуязычных_ответов_много():
    """Второй конец той же страховки: herr в проекте активно используется, и если он вдруг
    перестал находиться — значит сломался разбор, а не проект."""
    count = 0
    for path in sorted(_ROUTERS.glob("*.py")):
        count += len(re.findall(r"\bherr\(", path.read_text(encoding="utf-8")))
    assert count > 100, f"Двуязычных ответов нашлось всего {count} — разбор сломался"
