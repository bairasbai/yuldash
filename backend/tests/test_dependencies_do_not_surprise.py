"""Зависимости не должны приезжать на прод сами по себе.

Второй заход не в код приложения, а в то, из чего он собран.

**Что было.** Все библиотеки были закреплены только снизу: `fastapi>=0.110`, `Pillow>=10.0`
и так далее. А деплой на сервере делает `pip install -r requirements.txt`. Значит любое
обновление могло приехать на прод само: вышла FastAPI новой мажорной версии — и она встала
на сервер в ближайший деплой, на версии, которую никто не запускал и не тестировал
(аудит 2026-08-08, волна 131).

Это не теория: мажорные версии ломают совместимость по определению, а деплой у нас делается
не в спокойный вторник, а когда что-то надо срочно поправить.

Теперь у каждой зависимости есть верхняя граница. Это не «не обновляться никогда», а
«обновляться осознанно»: поднял границу, прогнал тесты, задеплоил. Мелкие и патч-версии —
там, где живут исправления безопасности, — приезжают как раньше, сами.

**Проверка на известные уязвимости** (`pip-audit` по зависимостям проекта) даёт одну находку:
`ecdsa` — атака по времени на подпись кривой P-256. Нас она не касается: токены Юлдаша
подписываются HS256, то есть симметричным алгоритмом на секрете, а `ecdsa` приходит прицепом
как зависимость `python-jose` и в подписи не участвует. Исправленной версии не будет никогда —
авторы библиотеки считают атаки по побочным каналам вне области проекта. Менять библиотеку
JWT ради этого не стали: замена трогает вход ВСЕХ пользователей, а выигрыш нулевой.

---

**Чего этот тест не может.** Он читает `requirements.txt`, а не то, что реально стоит
на сервере. Список известных уязвимостей меняется каждый день, и офлайн-тест его не знает —
`pip-audit` надо запускать отдельно (команда записана в docs/tasks.md).
"""
from __future__ import annotations

import re
from pathlib import Path

REQ = Path(__file__).resolve().parents[1] / "requirements.txt"


def _зависимости() -> list[str]:
    строки = []
    for line in REQ.read_text(encoding="utf-8").splitlines():
        голая = line.split("#")[0].strip()
        if голая:
            строки.append(голая)
    return строки


def test_у_каждой_зависимости_есть_верхняя_граница():
    """Главное: мажорная версия не должна приезжать на прод сама."""
    без_потолка = [d for d in _зависимости() if "<" not in d]

    assert not без_потолка, (
        f"эти зависимости закреплены только снизу: {без_потолка}. Любой деплой может подтянуть "
        "их новую мажорную версию — ту, на которой проект никто не запускал"
    )


def test_нижняя_граница_тоже_на_месте():
    """Обратная сторона: без нижней границы приедет древняя версия без исправлений."""
    без_пола = [d for d in _зависимости() if ">=" not in d and "==" not in d]

    assert not без_пола, (
        f"у этих зависимостей нет нижней границы: {без_пола}. Тогда можно поставить старую "
        "версию, где известные дыры ещё не залатаны"
    )


def test_границы_не_запирают_исправления_безопасности():
    """Граница ставится по МАЖОРНОЙ версии, а не по точной.

    Если закрепить `fastapi==0.135.2`, то патч с исправлением дыры не приедет вообще, пока
    кто-нибудь не вспомнит. Нам нужно ровно обратное: патчи сами, мажорные — руками.
    """
    слишком_жёсткие = [d for d in _зависимости() if "==" in d]

    assert not слишком_жёсткие, (
        f"эти зависимости прибиты к точной версии: {слишком_жёсткие}. Патчи безопасности "
        "к ним перестанут приезжать сами"
    )


def test_установленное_укладывается_в_границы():
    """Границы должны описывать то, на чём проект реально работает, а не мешать ему."""
    from importlib.metadata import PackageNotFoundError, version

    конфликты = []
    for d in _зависимости():
        m = re.match(r"^([A-Za-z0-9_.\-]+)(\[[^\]]+\])?", d)
        if not m:
            continue
        имя = m.group(1)
        потолок = re.search(r"<\s*(\d+)", d)
        if not потолок:
            continue
        try:
            стоит = version(имя)
        except PackageNotFoundError:
            continue
        мажор = int(стоит.split(".")[0])
        if мажор >= int(потолок.group(1)):
            конфликты.append(f"{имя} {стоит} не влезает в {d}")

    assert not конфликты, (
        f"границы противоречат тому, что установлено: {конфликты}. Значит на сервере "
        "либо не поставится нужное, либо стоит версия вне проверенного диапазона"
    )


def test_решение_про_ecdsa_записано():
    """Сторож на память: единственная известная уязвимость должна остаться объяснённой.

    Иначе через полгода кто-нибудь увидит её в отчёте сканера, испугается и полезет менять
    библиотеку входа — а причина, по которой её оставили, будет забыта.
    """
    аудит = (Path(__file__).resolve().parents[2] / "docs" /
             "audit-security-2026-08-08.md").read_text(encoding="utf-8")

    assert "ecdsa" in аудит, "в журнале аудита нет объяснения про ecdsa"
    assert "HS256" in аудит, (
        "не записано, ПОЧЕМУ уязвимость ecdsa нас не касается — что токены подписываются "
        "симметричным алгоритмом, а ecdsa в подписи не участвует"
    )
