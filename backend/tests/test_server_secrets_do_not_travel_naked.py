"""Бэкап не должен уезжать в чужое облако голым, а фоновые задачи — мочь всё.

Это первая волна не про код приложения, а про то, чем настраивается сервер. Конфиги лежат
в репозитории, значит их можно и нужно проверять здесь.

**1. Дамп базы уходил в S3 как есть.** В нём весь район: имена, телефоны, адреса, координаты
поездок, переписка, ссылки на документы водителей. Один утёкший ключ облака или ошибка в правах
бакета — и вся база у постороннего, причём молча: узнать об этом мы не сможем никак
(аудит 2026-08-08, волна 130).

Теперь в облако едет только зашифрованный файл. Ключ хранится ОТДЕЛЬНО от бэкапов; если ключа
нет — в облако мы просто не идём и громко об этом пишем, а локальная копия делается как раньше.
Проверка восстановления умеет расшифровывать — иначе шифрование превратило бы бэкап в кирпич.

**2. Фоновые задачи работали без ограждения.** Пять ночных задач ходят в интернет (Яндекс,
Firebase, Telegram, ЮKassa) и разбирают чужие данные. Работали они хоть и не от root, но
без единого ограничения: могли писать куда угодно, видеть чужие домашние каталоги и общий /tmp.
Теперь у них выключено повышение прав, система только на чтение, свой /tmp и запись только
в свой каталог.

**3. Секреты лежали открыто.** Деплой ставил владельца файлам, но не права: `.env`, созданный
обычным способом, получается 644 — то есть ключи ЮKassa, Firebase, Telegram и JWT-секрет читает
любой пользователь сервера. Теперь деплой выставляет 600.

---

**Чего этот тест НЕ может.** У меня нет доступа к самому серверу: я проверяю ИСХОДНИКИ скриптов
и юнитов, а не то, что реально запущено на yulbash.ru. Если на сервере лежит старая копия
скрипта, правки из репозитория туда не приедут, пока не выполнить деплой. Проверка «на живом
сервере всё применилось» остаётся за человеком — она в docs/tasks.md.
"""
from __future__ import annotations

from pathlib import Path

import pytest

BACKEND = Path(__file__).resolve().parents[1]
OPS = BACKEND / "ops"
DEPLOY = BACKEND / "deploy"


def _текст(p: Path) -> str:
    assert p.exists(), f"пропал файл настройки сервера: {p}"
    return p.read_text(encoding="utf-8")


def test_в_облако_дамп_едет_только_зашифрованным():
    """Главное: голый дамп в чужом хранилище — это вся база района у постороннего."""
    src = _текст(OPS / "backup.sh")
    отправка = src[src.index("S3_ENV_FILE="):]

    assert "openssl enc" in отправка, (
        "дамп уходит в облако без шифрования: имена, телефоны, адреса и координаты поездок "
        "всего района лежат у стороннего провайдера открытым файлом"
    )
    assert "BACKUP_ENCRYPT_PASSPHRASE" in отправка, "нечем шифровать — не задан ключ"
    # Отправляем именно зашифрованный файл, а не исходный. Смотрим ИСТОЧНИК (первый аргумент
    # после `cp`), а не строку целиком: имя в облаке тоже содержит ENC_FILE, и проверка
    # «где-то в строке есть ENC_FILE» проходила даже когда заливали открытый дамп.
    строка_отправки = [ln for ln in отправка.splitlines() if "s3 cp" in ln]
    assert строка_отправки, "не нашёл отправку в облако"
    for ln in строка_отправки:
        источник = ln.split("s3 cp", 1)[1].strip().split()[0]
        assert "ENC_FILE" in источник, (
            f"в облако кладут незашифрованный файл: источник {источник}"
        )


def test_без_ключа_в_облако_не_ходим():
    """Лучше остаться без офсайт-копии, чем отдать базу района открытым текстом."""
    src = _текст(OPS / "backup.sh")

    assert 'if [ -z "${BACKUP_ENCRYPT_PASSPHRASE:-}" ]' in src, (
        "нет проверки на отсутствие ключа — значит при пустом ключе всё поедет как раньше"
    )
    assert "ПРОПУЩЕН" in src, "человек не узнает, почему копии в облаке нет"


def test_локальный_бэкап_делается_всегда():
    """Обратная сторона: шифрование не должно отменить сам бэкап.

    Дамп снимается ДО всей истории с облаком — значит нет ключа, нет aws-cli, нет интернета,
    а копия на сервере всё равно есть.
    """
    src = _текст(OPS / "backup.sh")
    дамп = src.index("pg_dump")
    облако = src.index("S3_ENV_FILE=")
    assert дамп < облако, "дамп снимается после отправки в облако — при сбое копии не будет вовсе"


def test_восстановление_умеет_расшифровать():
    """Шифрование без расшифровки — это не бэкап, а кирпич."""
    src = _текст(OPS / "restore-verify.sh")

    assert "openssl enc -d" in src, (
        "проверка восстановления не умеет читать зашифрованный дамп — значит проверить "
        "облачную копию нельзя, а бэкап без проверки бэкапом не является"
    )
    assert "BACKUP_ENCRYPT_PASSPHRASE" in src


@pytest.mark.parametrize("unit", sorted(p.name for p in DEPLOY.glob("*.service")))
def test_каждая_фоновая_задача_ограждена(unit: str):
    """Ночные задачи ходят в интернет и разбирают чужие данные — им нужен намордник."""
    src = _текст(DEPLOY / unit)

    assert "User=" in src and "User=root" not in src, f"{unit} работает от root"
    for правило in ("NoNewPrivileges=yes", "ProtectSystem=", "ProtectHome=yes", "PrivateTmp=yes"):
        assert правило in src, (
            f"в {unit} нет ограждения «{правило}»: если через эту задачу однажды получится "
            "выполнить чужой код, он сможет больше, чем нужно для её работы"
        )


def test_деплой_закрывает_права_на_секреты():
    """chown ставит хозяина, но не права: .env на 644 читает любой на сервере."""
    src = _текст(OPS / "deploy.sh")

    assert "chmod 600" in src, (
        "деплой не закрывает права на файлы с секретами — ключи ЮKassa, Firebase, Telegram "
        "и JWT-секрет доступны любому пользователю сервера"
    )
    assert ".env" in src.split("chmod 600")[0][-400:] or ".env" in src.split("chmod 600")[1][:200], \
        "не видно, что именно закрывается"


def test_в_репозитории_нет_настоящих_секретов():
    """Обратная сторона всей волны: пример окружения должен оставаться примером."""
    src = _текст(BACKEND / ".env.example")
    подозрительные = []
    for line in src.splitlines():
        if "=" not in line or line.strip().startswith("#"):
            continue
        имя, _, значение = line.partition("=")
        значение = значение.split("#")[0].strip()
        if not значение:
            continue
        if any(k in имя.upper() for k in ("SECRET", "KEY", "TOKEN", "PASSWORD")):
            # dev-заглушки разрешены и прямо помечены как заглушки.
            if значение.startswith(("dev-", "change", "test", "your", "<")):
                continue
            подозрительные.append(f"{имя}={значение[:12]}…")
    assert not подозрительные, (
        f"в .env.example похоже на настоящие секреты: {подозрительные}. Пример окружения "
        "лежит в git — всё, что в нём написано, считается публичным"
    )
