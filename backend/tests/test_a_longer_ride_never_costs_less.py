def test_изменение_цены_снимает_предложение_у_водителя(client, user_factory, убрать_заказы):
    """Главное: водитель не может принять заказ по цене, которой уже нет."""
    from app.models import InstantOrder, InstantOrderStatus as S

    водитель = user_factory("ОферВодитель", role=UserRole.driver)
    пассажир = user_factory("ОферПассажир")
    with Session(engine) as s:
        заказ = InstantOrder(passenger_id=пассажир["id"], status=S.searching,
                             # Далеко от Баймака: заказ в статусе «ищем машину» поднимает
                             # спрос, а соседние тесты проверяют спокойный сурж в районе.
                             from_lat=50.0000, from_lng=55.0000,
                             to_lat=50.2000, to_lng=55.2000,
                             price_estimate=300, category="comfort",
                             current_offer_driver_id=водитель["id"],
                             offer_expires_at=utcnow() + timedelta(seconds=30))
        s.add(заказ)
        s.commit()
        s.refresh(заказ)
        oid = заказ.id

    with Session(engine) as s:                    # пассажир согласился искать и в «Эконом»
        isv.add_fallback_category(s, s.get(InstantOrder, oid), "standard")

    with Session(engine) as s:
        итог = s.get(InstantOrder, oid)
    assert итог.price_estimate < 300, "цена не изменилась — проверять нечего"
    assert итог.current_offer_driver_id is None, (
        f"цена стала {итог.price_estimate} ₽, а предложение у водителя осталось: он видит "
        "на экране 300 ₽, принимает — и везёт втрое дешевле, узнав об этом после поездки"
    )
    assert итог.offer_expires_at is None, "срок старого предложения не снят"


def test_согласие_на_класс_без_удешевления_предложение_не_рвёт(client, user_factory,
                                                               убрать_заказы):
    """Обратная сторона: рассылку заново запускаем только когда цена реально изменилась.

    Лишний сброс — это потерянные секунды поиска машины, а в мороз они дороже денег.
    """
    from app.models import InstantOrder, InstantOrderStatus as S

    водитель = user_factory("ОферВодитель2", role=UserRole.driver)
    пассажир = user_factory("ОферПассажир2")
    with Session(engine) as s:
        заказ = InstantOrder(passenger_id=пассажир["id"], status=S.searching,
                             from_lat=50.0000, from_lng=55.0000,
                             to_lat=50.2000, to_lng=55.2000,
                             price_estimate=1, category="comfort",
                             current_offer_driver_id=водитель["id"],
                             offer_expires_at=utcnow() + timedelta(seconds=30))
        s.add(заказ)
        s.commit()
        s.refresh(заказ)
        oid = заказ.id

    with Session(engine) as s:                    # цена уже минимальная — дешевле не станет
        isv.add_fallback_category(s, s.get(InstantOrder, oid), "standard")

    with Session(engine) as s:
        итог = s.get(InstantOrder, oid)
    assert итог.current_offer_driver_id == водитель["id"], (
        "предложение сняли, хотя цена не менялась: поиск машины начнётся заново на пустом месте"
    )
