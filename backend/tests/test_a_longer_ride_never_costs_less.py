"""Поездка на сто метров длиннее стоила на 130 ₽ дешевле (волна 167).

У такси две тарифные зоны. Город берёт больше за километр — короткие поездки; межгород
меньше — дальние. Само по себе это правильно. Но на стыке зон получался разрыв в обратную
сторону:

* 40,0 км по городскому тарифу — **690 ₽**;
* 40,1 км по межгородскому — **560 ₽**.

Сто метров пути делали поездку дешевле на 130 ₽. Для человека это выглядит как ошибка
приложения: сосед доехал дальше и заплатил меньше, а объяснить разницу невозможно — «у нас
так тариф устроен» никого не убеждает. Водителю та же ступенька — прямой убыток: согласиться
везти на километр дальше значит потерять деньги.

Чиним не цифрами в базе (их правит Александр, и они будут меняться), а правилом: **цена
не падает при росте расстояния**. Межгородская поездка стоит минимум столько же, сколько
стоила бы поездка ровно до границы зон по городскому тарифу. Дальше межгородский тариф растёт
своим темпом, дешевле за километр, — как и задумано.

**Вторая находка того же прохода: цена уезжала из-под оффера.** Заказ «Комфорт» за 300 ₽
разослан водителю, тот смотрит на экран. Пассажир в эту секунду соглашается искать и в «Эконом»
— цена падает до 100 ₽, а предложение у водителя остаётся прежним. Он видит 300, нажимает
«Принять» и везёт за 100, узнавая об этом только после поездки. Теперь изменение цены снимает
текущее предложение: заказ уходит в рассылку заново, и водители видят настоящую сумму.

**Заодно проверено пробой и оказалось чистым:** водитель, оплативший поднятие поездки,
действительно оказывается выше в ленте; смена класса машины доплаты не создаёт (цена
фиксируется на минимальной из согласованных ещё при согласии пассажира).
"""
from __future__ import annotations

from datetime import timedelta

import pytest
from sqlmodel import Session, select

from app import instant_service as isv
from app.config import settings
from app.db import engine
from app.models import Ride, UserRole
from app.timeutil import utcnow

from test_api import _ride

СТАРТ = (52.0000, 58.0000)
ГРАДУС_КМ = 111.0


def _точка_на(км: float) -> tuple:
    """Точка строго на север от старта, чтобы получить нужную длину маршрута."""
    return (СТАРТ[0] + км / ГРАДУС_КМ, СТАРТ[1])


def _оценка(км: float) -> dict:
    with Session(engine) as s:
        return isv.estimate(s, СТАРТ, _точка_на(км), "standard")


@pytest.mark.parametrize("шаг", [1.0, 2.0, 5.0])
def test_цена_не_падает_при_росте_расстояния(client, шаг):
    """Главное: чем дальше едешь, тем не дешевле. Проверяем весь стык зон, а не одну точку."""
    граница = settings.instant_intercity_km
    длины = [граница * 0.6 + шаг * i for i in range(14)]

    цены = [(round(км, 1), _оценка(км)["price"]) for км in длины]

    падения = [(a, b) for (км_a, a), (км_b, b) in zip(цены, цены[1:]) if b < a]
    assert not падения, (
        f"на росте расстояния цена падает: {цены}. Сосед доехал дальше и заплатил меньше — "
        "объяснить это человеку невозможно, а водителю ехать дальше становится невыгодно"
    )


def test_на_стыке_зон_нет_обрыва(client):
    """Точка стыка — самое опасное место: слева город, справа межгород."""
    граница = settings.instant_intercity_km

    до = _оценка(граница - 0.5)["price"]
    после = _оценка(граница + 0.5)["price"]

    assert после >= до, (
        f"поездка за границей зоны ({граница + 0.5:g} км) стоит {после} ₽, а чуть ближе "
        f"({граница - 0.5:g} км) — {до} ₽. Километр пути сделал поездку дешевле"
    )


def test_дальняя_поездка_всё_ещё_дешевле_за_километр(client):
    """Обратная сторона: смысл межгородского тарифа не должен пропасть.

    Пол на стыке защищает от обрыва, но дальше межгород обязан оставаться выгоднее за километр —
    иначе люди перестанут ездить между сёлами, ради чего сервис и делался.
    """
    граница = settings.instant_intercity_km
    близко = _оценка(граница - 0.5)
    далеко = _оценка(граница * 2.5)

    цена_за_км_близко = близко["price"] / близко["distance_km"]
    цена_за_км_далеко = далеко["price"] / далеко["distance_km"]
    assert цена_за_км_далеко < цена_за_км_близко, (
        f"дальняя поездка стала дороже за километр ({цена_за_км_далеко:.1f} против "
        f"{цена_за_км_близко:.1f} ₽/км): межгородский тариф потерял смысл"
    )


def test_короткая_поездка_считается_по_городскому(client):
    """Обратная сторона: пол на стыке не должен трогать обычные городские поездки."""
    оценка = _оценка(3.0)

    assert оценка["zone"] == "city", f"короткая поездка ушла не в ту зону: {оценка['zone']}"
    assert оценка["price"] > 0


def test_оплаченное_поднятие_поднимает_в_ленте(client, user_factory):
    """Проверено пробой: за поднятие берут деньги и место действительно дают."""
    первый = user_factory("ЛентаОбычный", role=UserRole.driver)
    второй = user_factory("ЛентаОплатил", role=UserRole.driver)
    ранний = _ride(client, первый, comment="еду рано")
    поздний = _ride(client, второй, comment="еду позже")
    with Session(engine) as s:
        r1, r2 = s.get(Ride, ранний), s.get(Ride, поздний)
        r1.depart_at = utcnow() + timedelta(hours=2)
        r2.depart_at = utcnow() + timedelta(hours=5)
        r2.boosted_until = utcnow() + timedelta(hours=24)
        s.add(r1)
        s.add(r2)
        s.commit()

    лента = client.get("/rides").json()

    порядок = [r["id"] for r in лента if r["id"] in (ранний, поздний)]
    assert порядок[:1] == [поздний], (
        f"водитель заплатил за поднятие, а его поездка в ленте ниже: {порядок}"
    )


