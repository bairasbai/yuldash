"""Цена такси считалась не на то время и не имела верхней границы (волна 163).

**Предзаказ на ночь уходил по дневной цене.** Человек днём заказывает машину на пять утра —
на поезд, в больницу, на вахту. Сервер считал цену на момент НАЖАТИЯ, поэтому ночная надбавка
в неё не попадала. А надбавка существует ровно затем, чтобы кто-то согласился выехать в мороз
до рассвета: по дневной ставке такой заказ не берёт никто. Итог — у человека на руках
подтверждённый заказ, за который в пять утра никто не приедет, и он стоит на морозе.

Обратный случай не лучше: заказ на полдень, оформленный в час ночи, брал ночную наценку
с человека, который поедет днём.

Спрос и погода по-прежнему считаются «на сейчас» — предсказать пробки и метель на завтра нельзя,
а врать точной цифрой хуже, чем показать честную оценку по тарифу.

**Платное ожидание тикало без потолка.** Пять минут бесплатно, дальше 5 ₽ в минуту — и никакой
границы. Водитель нажимает «я на месте» и уходит по делам: за три часа набегало 875 ₽, больше
двух поездок. Пассажир при этом не может ни остановить счётчик, ни доказать, что машины у
подъезда не было. Час платного ожидания (300 ₽) — предел, за которым это уже не ожидание,
а простой: правильный ответ там не «считать дальше», а закрыть заказ и разойтись.
"""
from __future__ import annotations

from datetime import timedelta

import pytest
from sqlmodel import Session, select

from app import instant_service as isv
from app.config import settings
from app.db import engine
from app.models import Tariff
from app.timeutil import utcnow

БАЙМАК = (52.5911, 58.3178)
СИБАЙ = (52.9128, 58.6689)


@pytest.fixture
def ночной_тариф(client):
    """Ночная надбавка ×1.5 с 22:00 до 6:00 по местному времени."""
    with Session(engine) as s:
        тарифы = s.exec(select(Tariff).where(Tariff.active == True)).all()  # noqa: E712
        было = [(t.id, t.night_k, t.night_from_hour, t.night_to_hour) for t in тарифы]
        for t in тарифы:
            t.night_k = 1.5
            t.night_from_hour = 22
            t.night_to_hour = 6
            s.add(t)
        s.commit()
    yield
    with Session(engine) as s:
        for tid, nk, nf, nt in было:
            t = s.get(Tariff, tid)
            t.night_k, t.night_from_hour, t.night_to_hour = nk, nf, nt
            s.add(t)
        s.commit()


def _местный_час(час: int):
    """Момент UTC, который в Уфе (UTC+5) даёт нужный час."""
    сдвиг = timedelta(hours=settings.local_tz_offset_hours)
    местное = (utcnow() + сдвиг).replace(hour=час, minute=0, second=0, microsecond=0)
    return местное - сдвиг


def _оценка(когда=None) -> dict:
    """Цена поездки Баймак → Сибай на указанный момент (None = сейчас)."""
    with Session(engine) as s:
        return isv.estimate(s, БАЙМАК, СИБАЙ, "standard", when=когда)


def test_ночной_предзаказ_считается_по_ночной_ставке(client, ночной_тариф):
    """Главное: цену считаем на время подачи, иначе в мороз за человеком никто не поедет."""
    днём = _оценка(_местный_час(13))
    ночью = _оценка(_местный_час(4))

    assert ночью["price"] > днём["price"], (
        f"поездка в четыре утра стоит столько же, сколько в час дня ({ночью['price']} против "
        f"{днём['price']} ₽): по дневной ставке ночью никто не поедет, и человек "
        "с подтверждённым заказом останется на морозе"
    )
    assert ночью["night_k"] == 1.5, f"ночная надбавка не применилась: {ночью['night_k']}"


def test_дневной_предзаказ_ночной_наценки_не_берёт(client, ночной_тариф):
    """Обратная сторона: заказ на полдень, оформленный ночью, — это дневная поездка."""
    оценка = _оценка(_местный_час(13))

    assert оценка["night_k"] == 1.0, (
        f"с человека, который едет в час дня, взяли ночную наценку {оценка['night_k']} "
        "только потому, что он оформил заказ ночью"
    )


def test_обычный_заказ_считается_на_сейчас(client, ночной_тариф):
    """Обратная сторона: без указания времени всё работает как раньше."""
    сейчас = _оценка()
    явно = _оценка(utcnow())

    assert сейчас["price"] == явно["price"], (
        f"оценка «сейчас» разошлась с явным временем: {сейчас['price']} против {явно['price']}"
    )


def test_ожидание_упирается_в_потолок(client):
    """Главное: счётчик не может тикать вечно, пока водитель занят своими делами."""
    сумма = isv.waiting_fee_kop(utcnow() - timedelta(hours=3), utcnow())

    assert сумма == settings.wait_fee_cap_rub * 100, (
        f"за три часа насчитали {сумма / 100:g} ₽ вместо потолка {settings.wait_fee_cap_rub} ₽: "
        "нажал «я на месте», ушёл по делам — и человек должен как за две поездки"
    )


def test_короткое_ожидание_считается_как_прежде(client):
    """Обратная сторона: за десять минут простоя водителю честно причитается."""
    сумма = isv.waiting_fee_kop(utcnow() - timedelta(minutes=15), utcnow())

    ожидаемо = (15 - settings.wait_free_minutes) * settings.wait_fee_rub_per_min * 100
    assert сумма == ожидаемо, (
        f"обычное ожидание посчитано неверно: {сумма} вместо {ожидаемо} коп"
    )


def test_первые_минуты_бесплатны(client):
    """Обратная сторона: человек собирается, это нормально — за это не берут."""
    assert isv.waiting_fee_kop(utcnow() - timedelta(minutes=4), utcnow()) == 0, (
        "с человека взяли деньги за четыре минуты сборов, хотя пять минут обещаны бесплатно"
    )
