"""Волна 203: календарь считаем по человеку, а не по серверу.

База живёт в UTC, человек — в Башкортостане (UTC+5). Значит его «первое число» начинается
на пять часов раньше серверного, а «понедельник» — тоже. Проект это давно знает: есть
`timeutil.local_date`, `workday.local_day`, местные тихие часы, местный день у долга.

Но переводится не всё. Осталось три места, где календарь брали прямо у сервера:

  * «≤5 водительских бонусов в КАЛЕНДАРНЫЙ месяц» — ограда фермы приглашений. Начисление
    первого числа между полуночью и пятью утра по Уфе попадало в ПРОШЛЫЙ месяц, то есть
    в окно, где потолок уже не считается;
  * номер недели у долга по комиссии — по нему водитель сверяет, за что платит;
  * «С нами с <месяц год>» на карточке водителя — по нему решают, садиться ли в машину.

Все три — про одно: сервер считает свой календарь, а человек читает свой.
"""
from __future__ import annotations

from datetime import datetime, timedelta

from sqlmodel import Session

from app import debt as debt_mod
from app import services as svc
from app.config import settings
from app.db import engine
from app.models import ReferralBonus, User, UserRole
from app.routers import referral as ref
from app.timeutil import local_date

# Ночь на первое сентября по Уфе = 31 августа 21:00 UTC. Ровно то окно, где серверный
# календарь ещё в августе, а человек уже в сентябре.
НОЧЬ_ПЕРВОГО = datetime(2026, 8, 31, 21, 30)      # UTC → 1 сентября 02:30 по Уфе
# Ночь на понедельник по Уфе = воскресенье 21:00 UTC.
НОЧЬ_ПОНЕДЕЛЬНИКА = datetime(2026, 8, 30, 21, 30)  # UTC → 31 августа (пн) 02:30 по Уфе


def test_the_probe_itself_is_in_the_right_window():
    """Опора: выбранные моменты действительно попадают в разрыв календарей."""
    assert settings.local_tz_offset_hours == 5
    assert НОЧЬ_ПЕРВОГО.month == 8, "серверный календарь — ещё август"
    assert local_date(НОЧЬ_ПЕРВОГО).month == 9, "календарь человека — уже сентябрь"
    assert НОЧЬ_ПОНЕДЕЛЬНИКА.isocalendar()[1] != local_date(НОЧЬ_ПОНЕДЕЛЬНИКА).isocalendar()[1], (
        "выбранный момент должен попадать на разные недели у сервера и у человека"
    )


# ==================== 1. Ограда фермы: «календарный месяц» ====================
def test_monthly_bonus_cap_counts_the_humans_month(client, user_factory):
    """Потолок «≤5 бонусов в месяц» обязан считать месяц человека.

    Иначе в ночь на первое число открывается пятичасовое окно, где выданные бонусы
    попадают в прошлый месяц: ферма получает вдвое больше, чем ей положено.
    """
    хозяин = user_factory("КалендарьХозяин", role=UserRole.driver)
    with Session(engine) as s:
        # Потолок уже выбран — но все бонусы выданы в НОЧЬ на первое, то есть в сентябре
        # по календарю человека и в августе по календарю сервера.
        for i in range(ref.DRIVER_BONUS_MONTHLY_CAP):
            приглашённый = user_factory(f"КалендарьГость{i}", role=UserRole.driver)
            s.add(ReferralBonus(referrer_id=хозяин["id"], invited_user_id=приглашённый["id"],
                                kind="driver", created_at=НОЧЬ_ПЕРВОГО))
        s.commit()

        выдано = ref.granted_driver_bonuses_this_month(
            s, хозяин["id"], now=НОЧЬ_ПЕРВОГО + timedelta(minutes=10))

    assert выдано == ref.DRIVER_BONUS_MONTHLY_CAP, (
        f"в этом месяце насчитали {выдано} бонусов вместо {ref.DRIVER_BONUS_MONTHLY_CAP}: "
        "ночь на первое число сервер относит к прошлому месяцу, и потолок открывается заново"
    )


def test_last_months_bonuses_do_not_count_against_this_month(client, user_factory):
    """Защита не сломана: прошлый месяц потолок этого месяца не занимает."""
    хозяин = user_factory("КалендарьПрошлый", role=UserRole.driver)
    with Session(engine) as s:
        приглашённый = user_factory("КалендарьПрошлыйГость", role=UserRole.driver)
        s.add(ReferralBonus(referrer_id=хозяин["id"], invited_user_id=приглашённый["id"],
                            kind="driver", created_at=НОЧЬ_ПЕРВОГО - timedelta(days=10)))
        s.commit()

        выдано = ref.granted_driver_bonuses_this_month(
            s, хозяин["id"], now=НОЧЬ_ПЕРВОГО + timedelta(minutes=10))

    assert выдано == 0, f"бонус прошлого месяца засчитали в этот: {выдано}"


# ==================== 2. Номер недели у долга ====================
def test_debt_week_is_the_humans_week():
    """Водитель платит комиссию понедельными счетами. Неделя — его, а не серверная.

    Поездка в ночь на понедельник по Уфе — это уже новая неделя. У сервера в этот момент
    ещё воскресенье, и долг ложился в счёт ПРОШЛОЙ недели, которую водитель уже закрыл.
    """
    ключ = debt_mod._week_key(НОЧЬ_ПОНЕДЕЛЬНИКА)
    человеческий = local_date(НОЧЬ_ПОНЕДЕЛЬНИКА).isocalendar()

    assert ключ == f"{человеческий[0]}-W{человеческий[1]:02d}", (
        f"долг записан в неделю {ключ}, а у водителя на часах уже "
        f"{человеческий[0]}-W{человеческий[1]:02d}"
    )


def test_debt_week_is_stable_in_the_middle_of_the_day():
    """Защита не сломана: днём, когда календари совпадают, номер недели прежний."""
    полдень = datetime(2026, 9, 2, 12, 0)          # среда, разрыва нет
    assert debt_mod._week_key(полдень) == "2026-W36"


# ==================== 3. «С нами с <месяц год>» на карточке ====================
def test_member_since_uses_the_humans_month(client, user_factory):
    """Человек зарегистрировался в ночь на первое сентября — значит он «с сентября».

    Это бейдж доверия: по нему решают, садиться ли в машину. «С августа» вместо
    «с сентября» — мелочь, но она из той же семьи, что и ранний рейс из волны 79.
    """
    assert svc.member_since(НОЧЬ_ПЕРВОГО) == "2026-09", (
        f"на карточке написано «{svc.member_since(НОЧЬ_ПЕРВОГО)}», "
        "а человек зарегистрировался уже первого сентября по своим часам"
    )


def test_member_since_is_empty_without_a_date():
    """Нет даты — нет и надписи, а не «1970»."""
    assert svc.member_since(None) == ""


def test_member_since_shows_on_the_ride_card(client, user_factory):
    """Сквозная проверка: бейдж доезжает до карточки поездки и он местный."""
    водитель = user_factory("КалендарьВодитель", role=UserRole.driver)
    with Session(engine) as s:
        u = s.get(User, водитель["id"])
        u.created_at = НОЧЬ_ПЕРВОГО
        s.add(u)
        s.commit()

    from test_api import _ride
    ride_id = _ride(client, водитель)
    # Свою поездку берём ПО НОМЕРУ, а не ищем в ленте: в полном прогоне лента общая на все
    # тесты и у неё есть потолок выдачи — наша туда просто не помещается.
    ответ = client.get(f"/rides/{ride_id}", headers=водитель["auth"])

    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["driver_since"] == "2026-09", (
        f"на карточке {ответ.json()['driver_since']}"
    )


# ==================== 4. Сторож на будущее ====================
КАЛЕНДАРНЫЕ_ПРИЁМЫ = (
    (".isocalendar()", "номер недели"),
    ('.strftime("%Y-%m"', "месяц строкой"),
    ("replace(day=1", "начало месяца"),
    (".date()", "календарный день"),
)


def test_no_new_code_reads_the_calendar_off_the_server():
    """Календарь считает `timeutil` и только он.

    Так эта дыра и жила: приёмы разбросаны по файлам, каждый сам по себе выглядит
    безобидно, а вместе они дают разные ответы на вопрос «какое сегодня число».
    Сторож не даст следующему появиться незаметно — правило одно и живёт в одном месте
    (тот же приём, что у сторожа двуязычия из волны 193).
    """
    import pathlib

    корень = pathlib.Path("app")
    нарушения = []
    for файл in sorted(корень.rglob("*.py")):
        if файл.name == "timeutil.py":
            continue                     # это и есть единственное место, где можно
        текст = файл.read_text(encoding="utf-8")
        for номер, строка in enumerate(текст.splitlines(), 1):
            голая = строка.split("#")[0]
            if "local" in голая:
                continue                 # уже приведено к местному времени
            for приём, что in КАЛЕНДАРНЫЕ_ПРИЁМЫ:
                if приём in голая:
                    нарушения.append(f"{файл}:{номер} — {что}: {строка.strip()[:70]}")

    подсказка = "календарь считается мимо `timeutil` — у человека и у сервера разные сутки:"
    assert not нарушения, подсказка + chr(10) + chr(10).join(нарушения)
