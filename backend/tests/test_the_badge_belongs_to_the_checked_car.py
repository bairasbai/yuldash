"""Водитель менял машину после проверки, а бейдж «Проверен» оставался (волна 169).

Продолжение волны 168 — тот же класс, другой признак. Там обещание безопасности выдавалось
самодекларацией; здесь подтверждение было настоящим, но относилось к другому автомобилю.

Женщина ждёт машину у подъезда вечером. У неё на экране: «Lada Granta, белая, А123БВ102»
и зелёная галочка «Проверен». Она сверяет номер — это единственный способ убедиться, что
садится в ту машину. Проверка номера и есть весь смысл: у BlaBlaCar был случай, когда
приезжала другая машина с другим человеком за рулём, и сверить было нечем.

Проба: водитель проходит модерацию на «Lada Granta А123БВ102», затем открывает профиль
и вписывает «Toyota Camry Х999ХХ777». Бейдж остаётся. Модератор сверял одну машину, ездит
другая, а пассажирка видит галочку и верит ей.

Тот же приём уже применён рядом — к подтверждению пола: прислал другие права, подтверждение
гаснет, модератор сверяет заново. Здесь ровно та же логика про автомобиль. Работать это
водителю не мешает: бейдж — про доверие, а не про допуск; он отправляет документы и получает
галочку обратно.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session, select

from app.db import engine
from app.models import DriverProfile, User, UserRole

ЛАДА = {"car_make": "Lada", "car_model": "Granta", "car_color": "белая",
        "car_plate": "А123БВ102", "seats": 4}


@pytest.fixture
def проверенный_водитель(client, user_factory):
    """Водитель заполнил машину и прошёл модерацию."""
    водитель = user_factory("ПроверенныйВодитель", role=UserRole.driver)
    client.post("/driver/profile", headers=водитель["auth"], json=ЛАДА)
    with Session(engine) as s:
        u = s.get(User, водитель["id"])
        u.verified = True
        s.add(u)
        s.commit()
    return водитель


def _бейдж(user_id: int) -> bool:
    with Session(engine) as s:
        return bool(s.get(User, user_id).verified)


def test_подмена_машины_снимает_бейдж(client, проверенный_водитель):
    """Главное: галочка относится к конкретной машине, а не к человеку вообще."""
    client.post("/driver/profile", headers=проверенный_водитель["auth"], json={
        "car_make": "Toyota", "car_model": "Camry", "car_color": "чёрная",
        "car_plate": "Х999ХХ777", "seats": 4,
    })

    assert not _бейдж(проверенный_водитель["id"]), (
        "водитель прошёл проверку на «Ладе», вписал «Тойоту» — и бейдж «Проверен» остался. "
        "Пассажирка сверяет номер у подъезда, видит галочку и садится в машину, которую "
        "никто не проверял"
    )


def test_смена_одного_номера_тоже_снимает(client, проверенный_водитель):
    """Номер и есть то, по чему сверяют: «белая Гранта» у подъезда ничего не доказывает."""
    client.post("/driver/profile", headers=проверенный_водитель["auth"],
                json={**ЛАДА, "car_plate": "О777ОО102"})

    assert not _бейдж(проверенный_водитель["id"]), (
        "госномер сменился, а бейдж остался — сверять больше нечего"
    )


def test_водителю_говорят_почему_бейдж_пропал(client, проверенный_водитель):
    """Молча снятый бейдж выглядит как поломка приложения или как наказание без причины."""
    from app.models import Notification

    client.post("/driver/profile", headers=проверенный_водитель["auth"],
                json={**ЛАДА, "car_plate": "О777ОО102"})

    with Session(engine) as s:
        письма = s.exec(select(Notification).where(
            Notification.user_id == проверенный_водитель["id"])).all()
    тексты = " ".join((n.title_ru or "") + " " + (n.body_ru or "") for n in письма)
    assert "провер" in тексты.lower(), (
        f"бейдж сняли молча: {тексты[:200]}. Человек не поймёт, что случилось и что делать"
    )


def test_число_мест_бейдж_не_трогает(client, проверенный_водитель):
    """Обратная сторона: машина та же, изменилось только количество мест в объявлении."""
    client.post("/driver/profile", headers=проверенный_водитель["auth"],
                json={**ЛАДА, "seats": 3})

    assert _бейдж(проверенный_водитель["id"]), (
        "водитель поправил число мест — и потерял бейдж: машина при этом не менялась"
    )


def test_повторная_отправка_тех_же_данных_бейдж_не_трогает(client, проверенный_водитель):
    """Обратная сторона: человек открыл профиль, нажал «Сохранить», ничего не поменяв."""
    client.post("/driver/profile", headers=проверенный_водитель["auth"], json=ЛАДА)

    assert _бейдж(проверенный_водитель["id"]), (
        "сохранение без изменений сняло бейдж: так человек потеряет галочку случайно"
    )


def test_первое_заполнение_профиля_бейджа_не_касается(client, user_factory):
    """Обратная сторона: у нового водителя машины ещё не было — снимать нечего."""
    новичок = user_factory("НовичокВодитель", role=UserRole.driver)
    with Session(engine) as s:                      # редкий, но возможный порядок: сначала бейдж
        u = s.get(User, новичок["id"])
        u.verified = True
        s.add(u)
        s.commit()

    client.post("/driver/profile", headers=новичок["auth"], json=ЛАДА)

    assert _бейдж(новичок["id"]), (
        "водитель впервые вписал машину — и это сочли подменой"
    )


def test_данные_машины_сохранились(client, проверенный_водитель):
    """Контроль: снятие бейджа не должно мешать водителю обновлять профиль."""
    client.post("/driver/profile", headers=проверенный_водитель["auth"], json={
        "car_make": "Toyota", "car_model": "Camry", "car_color": "чёрная",
        "car_plate": "Х999ХХ777", "seats": 4,
    })

    with Session(engine) as s:
        профиль = s.exec(select(DriverProfile).where(
            DriverProfile.user_id == проверенный_водитель["id"])).first()
    assert профиль.car_plate == "Х999ХХ777", "новые данные машины не сохранились"
