"""Подтверждение перевода гасило и тот долг, которого админ не видел (волна 220).

Комиссия за такси — единственный доход платформы. Платят её переводом по СБП «на доверии»:
водитель жмёт «Я оплатил», долг уходит в статус «ждёт подтверждения», Александру летит
сообщение с суммой, он сверяет банк и жмёт «Подтвердить».

У ОПЛАТЫ КАРТОЙ такая же дверь уже закрыта границей по времени: `debt.mark_all_paid(up_to=…)`
гасит только долг, начисленный ДО создания платежа, и в её же описании написано, почему —
«иначе долг, накопленный в окне между «жму оплатить» и подтверждением, погасился бы бесплатно».
У ручного подтверждения (`debt.admin_confirm`) границы не было: оно гасило ВЕСЬ долг водителя,
который на момент нажатия оказался в статусе «ждёт подтверждения».

Что видит человек. Александр открывает список долгов и видит: «Ильдар — 500 ₽». Идёт
в банк, находит перевод на 500 ₽. Пока он сверял, Ильдар довозит пассажира (+300 ₽ комиссии)
и второй раз жмёт «Я оплатил», ничего не переводя. Александр возвращается к открытой
странице, где написано 500 ₽, и нажимает «Подтвердить» — гасится 800 ₽.

Заметить это он не мог: страница, на которую он смотрел, говорила 500.

Починка: подтверждение и отклонение работают с ОДНИМ заявлением — тем, которое админ видел.
Долг, заявленный позже, остаётся ждать своей очереди и своего сообщения.
"""
from __future__ import annotations

from datetime import timedelta

from sqlmodel import Session, select

from app.db import engine
from app.models import CommissionDebt, DebtStatus, UserRole
from app.timeutil import utcnow


def _долг(driver_id: int, рублей: int, *, недели_назад: int = 0) -> int:
    """Начисленная комиссия за такси, ещё не оплаченная."""
    with Session(engine) as s:
        d = CommissionDebt(
            driver_id=driver_id, amount_kop=рублей * 100, week="2026-35",
            status=DebtStatus.unpaid,
            created_at=utcnow() - timedelta(days=недели_назад * 7),
            due_at=utcnow() + timedelta(days=7),
        )
        s.add(d)
        s.commit()
        s.refresh(d)
        return d.id


def _заявить_оплату(client, водитель):
    return client.post("/driver/debt/paid", headers=водитель["auth"])


def _строка_в_админке(client, админ, driver_id: int):
    строки = client.get("/admin/debts", headers=админ["auth"]).json()
    свои = [g for g in строки if g["driver_id"] == driver_id]
    return свои[0] if свои else None


def _долг_рублей(driver_id: int) -> int:
    """Сколько водитель ещё должен платформе (не считая уже подтверждённого)."""
    with Session(engine) as s:
        rows = s.exec(select(CommissionDebt).where(
            CommissionDebt.driver_id == driver_id,
            CommissionDebt.status != DebtStatus.paid,
        )).all()
        return sum(d.amount_kop for d in rows) // 100


def test_подтверждают_ровно_ту_сумму_которую_видели(client, user_factory):
    """Главное: за один проверенный перевод гасится один заявленный долг."""
    водитель = user_factory("Ильдар", role=UserRole.driver)
    админ = user_factory("Александр", role=UserRole.admin)
    _долг(водитель["id"], 500)

    _заявить_оплату(client, водитель)                 # перевёл 500 ₽ и заявил
    строка = _строка_в_админке(client, админ, водитель["id"])
    assert строка["amount"] == 500, f"подготовка: админ видит {строка['amount']} ₽ вместо 500"
    debt_id = строка["debt_id"]

    # Пока Александр сверяет банк, Ильдар довозит пассажира и заявляет оплату второй раз —
    # ничего не переведя.
    _долг(водитель["id"], 300)
    _заявить_оплату(client, водитель)

    ответ = client.post(f"/admin/debts/{debt_id}/confirm", headers=админ["auth"])

    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["paid_kop"] == 500_00, (
        f"подтвердили {ответ.json()['paid_kop'] // 100} ₽ вместо проверенных 500 ₽"
    )
    assert _долг_рублей(водитель["id"]) == 300, (
        "долг, заявленный уже после того, как админ посмотрел на страницу, погашен бесплатно: "
        "комиссия — единственный доход платформы"
    )


def test_отклоняют_ровно_то_заявление_которое_смотрели(client, user_factory):
    """Та же граница у отказа: «деньги не пришли» относится к одному переводу, не ко всем."""
    водитель = user_factory("ИльдарОтказ", role=UserRole.driver)
    админ = user_factory("АлександрОтказ", role=UserRole.admin)
    _долг(водитель["id"], 500)
    _заявить_оплату(client, водитель)
    debt_id = _строка_в_админке(client, админ, водитель["id"])["debt_id"]

    _долг(водитель["id"], 300)
    _заявить_оплату(client, водитель)

    ответ = client.post(f"/admin/debts/{debt_id}/reject", headers=админ["auth"])

    assert ответ.status_code == 200, ответ.text
    with Session(engine) as s:
        строки = s.exec(select(CommissionDebt).where(
            CommissionDebt.driver_id == водитель["id"])).all()
        по_статусам = {d.amount_kop // 100: d.status for d in строки}
    assert по_статусам[500] == DebtStatus.unpaid, "отклонённое заявление не вернулось в долг"
    assert по_статусам[300] == DebtStatus.pending, (
        "второе заявление сбросили заодно с первым — водитель ждёт ответа, которого уже никто не даст"
    )


def test_обычный_случай_один_перевод_один_долг(client, user_factory):
    """Обратная сторона: когда водитель заявляет один раз, гасится всё заявленное."""
    водитель = user_factory("ИльдарЧестный", role=UserRole.driver)
    админ = user_factory("АлександрЧестный", role=UserRole.admin)
    _долг(водитель["id"], 300, недели_назад=2)
    _долг(водитель["id"], 200)

    _заявить_оплату(client, водитель)                 # оба долга уходят в одно заявление
    debt_id = _строка_в_админке(client, админ, водитель["id"])["debt_id"]

    ответ = client.post(f"/admin/debts/{debt_id}/confirm", headers=админ["auth"])

    assert ответ.json()["paid_kop"] == 500_00, (
        f"одно заявление на 500 ₽ погасило только {ответ.json()['paid_kop'] // 100} ₽"
    )
    assert _долг_рублей(водитель["id"]) == 0, "после подтверждения долга остаться не должно"


def test_сумма_изменилась_пока_админ_смотрел_ничего_не_гасим(client, user_factory):
    """Договор между экраном и дверью: гасим ровно то, что админ видел, или не гасим ничего.

    Изначально этот тест был написан под другую модель — я группировал список по заявлению.
    При слиянии выяснилось, что ту же дыру уже закрыли на `main`, и точнее: админка присылает
    СУММУ, которую видит на экране, а сервер сверяет её с текущей. Не сошлась — 409 и ни одна
    запись не тронута. Это сильнее группировки: оно ловит любое изменение суммы, а не только
    появление второго заявления.

    Тест переписан под эту модель и держит её главное обещание.
    """
    водитель = user_factory("ИльдарСверка", role=UserRole.driver)
    админ = user_factory("АлександрСверка", role=UserRole.admin)
    _долг(водитель["id"], 500)
    _заявить_оплату(client, водитель)
    строка = _строка_в_админке(client, админ, водитель["id"])
    видел_рублей = строка["amount"]

    # Пока Александр сверяет банк, Ильдар довозит пассажира и заявляет оплату второй раз.
    _долг(водитель["id"], 300)
    _заявить_оплату(client, водитель)

    ответ = client.post(f"/admin/debts/{строка['debt_id']}/confirm", headers=админ["auth"],
                        json={"amount_kop": строка["amount_kop"]})

    assert ответ.status_code == 409, (
        f"сумма на экране была {видел_рублей} ₽, а стала другой — подтверждать нельзя "
        f"(ответ {ответ.status_code})"
    )
    assert _долг_рублей(водитель["id"]) == 800, (
        "отказ по несошедшейся сумме тронул записи: он должен не менять НИЧЕГО"
    )
    текст = ответ.json()["detail"]["ru"].lower()
    assert "обнови" in текст, f"человеку не сказали, что делать дальше: «{текст}»"


def test_сумма_сошлась_гасим_целиком(client, user_factory):
    """Обратная сторона: сверил банк, ничего не поменялось — подтверждение проходит."""
    водитель = user_factory("ИльдарСошлось", role=UserRole.driver)
    админ = user_factory("АлександрСошлось", role=UserRole.admin)
    _долг(водитель["id"], 500)
    _заявить_оплату(client, водитель)
    строка = _строка_в_админке(client, админ, водитель["id"])

