"""Когда падает что-то внешнее, Юлдаш должен продолжать работать.

Шестой заход не в поиск дыр, а в проверку устойчивости: что произойдёт, если откажет
не наш код, а то, от чего мы зависим. Проверено прогоном, а не чтением (аудит 2026-08-08,
волна 134).

**Redis (кеш и присутствие).** Полностью мёртвый Redis — публикация поездки, лента, бронь
и профиль водителя работают как ни в чём не бывало. Кеш не имеет права ронять запрос, и он
его не роняет.

**Внешние сервисы по сети.** Проверены все места, где сервер ходит наружу: ЮKassa, SMS-шлюз,
Яндекс, Firebase, Telegram. Каждый вызов обёрнут: отказ платёжного провайдера превращается
в мягкое «Оплата временно недоступна, попробуй ещё раз» и уборку зависшей строки, а не в 500.

**Внутренняя ошибка.** Если что-то ломается у нас, человек получает `{"detail": "Внутренняя
ошибка сервера"}` — без трейсбека, без путей на диске, без имён файлов. Проверено подстановкой
исключения с текстом «пароль базы hunter2»: наружу не ушло ничего.

**Индексы и планы запросов.** Лента поездок идёт по индексу статуса, полного сканирования
таблицы нет. Из 62 таблиц без единого индекса только одна — служебный журнал дневной сводки,
который растёт медленно.

Здесь дыр не нашлось. Тесты ниже — чтобы устойчивость не потерялась при следующих правках:
такие вещи ломаются молча и всплывают в самый неудачный момент.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

import app.routers.rides as rides_mod
import app.services as svc
from app.main import app
from app.models import UserRole

from test_api import _ride

APP_DIR = Path(__file__).resolve().parents[1] / "app"


class МёртвыйRedis:
    """Ведёт себя как упавший сервер: на любое действие — ошибка соединения."""

    def __getattr__(self, _имя):
        def взрыв(*a, **k):
            raise ConnectionError("redis недоступен")
        return взрыв


@pytest.fixture
def без_redis(monkeypatch):
    monkeypatch.setattr(svc, "_cache_client", lambda: МёртвыйRedis())


def test_лента_и_бронь_работают_без_redis(client, user_factory, без_redis):
    """Главное: кеш — ускоритель, а не условие работы."""
    водитель = user_factory("СбойВодитель", role=UserRole.driver)
    пассажир = user_factory("СбойПассажир")

    ride_id = _ride(client, водитель, comment="без кеша")
    лента = client.get("/rides", headers=пассажир["auth"])
    бронь = client.post("/bookings", headers=пассажир["auth"],
                        json={"ride_id": ride_id, "seats": 1})

    assert лента.status_code == 200, f"лента упала без Redis: {лента.status_code}"
    assert isinstance(лента.json(), list), "лента вернула не список"
    # Свою поездку ищем по прямому номеру, а не в общей ленте: у выдачи есть потолок
    # (FEED_MAX), и в полном прогоне туда попадают сотни чужих поездок — как в уроке волны 92.
    своя = client.get(f"/rides/{ride_id}", headers=пассажир["auth"])
    assert своя.status_code == 200, f"поездка недоступна без кеша: {своя.status_code}"
    assert бронь.status_code == 200, f"бронь не оформить без Redis: {бронь.text[:120]}"


