def test_внутренняя_ошибка_не_показывает_внутренности(client, user_factory, monkeypatch):
    """Трейсбек наружу — это карта нашего сервера для того, кто её попросил."""
    пассажир = user_factory("СбойЛюбопытный")

    def взрыв(*a, **k):
        raise RuntimeError("секрет: /opt/yuldash/.env, пароль базы hunter2")

    monkeypatch.setattr(rides_mod, "rides_out", взрыв)
    настоящий = TestClient(app, raise_server_exceptions=False)

    r = настоящий.get("/rides", headers=пассажир["auth"])

    assert r.status_code == 500
    for утечка in ("Traceback", "hunter2", ".env", "rides.py", "app/routers"):
        assert утечка not in r.text, (
            f"наружу ушло «{утечка}»: ответ на ошибку раскрывает устройство сервера — "
            f"{r.text[:150]}"
        )


def test_каждый_поход_наружу_обёрнут():
    """Сторож: отказ чужого сервиса не должен превращаться в 500 у нашего человека.

    Ищем сетевые вызовы без `try` поблизости. Так уже было бы легко ошибиться: платежи,
    SMS и погода живут в разных файлах, и обернуть новый вызов забывается молча.
    """
    # Часть вызовов НАМЕРЕННО без try: это низкоуровневые функции, которые бросают наверх,
    # а ловит и решает вызывающий — он знает, что делать с деньгами и что сказать человеку.
    # У каждой такой записано, КТО её ловит. Появится новая без записи — тест покраснеет.
    ЛОВЯТ_ВЫШЕ = {
        "create_payment": "routers/payments.py::_start_yookassa — чистит зависший счёт, отдаёт 503",
        "create_payout": "ledger.py — пишет компенсирующую проводку, историю денег не правит",
        "fetch_payment": "routers/courier.py и routers/debt.py — оба зовут в try, при сбое "
                         "оставляют счёт в ожидании вместо ложного «оплачено»",
        "_smsdar_send": "services.py::send_text — ловит и логирует; SMS вторичны, "
                        "основную операцию их сбой не валит",
    }

    голые = []
    for путь in list(APP_DIR.glob("*.py")) + list((APP_DIR / "routers").glob("*.py")):
        строки = путь.read_text(encoding="utf-8").splitlines()
        функция = "?"
        for i, ln in enumerate(строки):
            m = re.match(r"\s*(?:async )?def (\w+)", ln)
            if m:
                функция = m.group(1)
            if not re.search(r"(httpx\.(get|post)|requests\.(get|post)|urlopen)\(", ln):
                continue
            окно = "\n".join(строки[max(0, i - 14):i + 1])
            if "try:" in окно or функция in ЛОВЯТ_ВЫШЕ:
                continue
            голые.append(f"{путь.name}:{i + 1} (в {функция})")
    assert not голые, (
        f"сетевые вызовы без защиты: {голые}. Упал чужой сервис — человек получил 500 "
        "вместо понятного «попробуй ещё раз». Либо оберни здесь, либо добавь функцию "
        "в ЛОВЯТ_ВЫШЕ с указанием, кто именно ловит"
    )


def test_оплата_переживает_отказ_провайдера():
    """У денег отдельная планка: при сбое нельзя оставлять человеку висящий счёт."""
    src = (APP_DIR / "routers" / "payments.py").read_text(encoding="utf-8")
    блок = src[src.index("def _start_yookassa"):]
    блок = блок[: блок.index("\n\n\n") if "\n\n\n" in блок else 800]

    assert "except" in блок, "сбой ЮKassa не обработан — человек получит 500"
    assert "session.delete(payment)" in блок, (
        "при сбое остаётся зависшая строка платежа без номера у провайдера: человек увидит "
        "«ожидает оплаты» по счёту, которого не существует"
    )
    assert "503" in блок, "нет мягкого ответа «попробуй ещё раз»"


def test_растущие_таблицы_имеют_индексы():
    """Без индекса лента живёт до первых тысяч поездок, а потом ложится."""
    модели = (APP_DIR / "models.py").read_text(encoding="utf-8")
    таблицы = re.findall(r"class (\w+)\(SQLModel, table=True\)", модели)
    assert len(таблицы) > 40, "модель проекта неожиданно уменьшилась — проверь тест"

    без_индексов = []
    for имя in таблицы:
        нач = модели.index(f"class {имя}(SQLModel, table=True)")
        кон = модели.find("\nclass ", нач + 10)
        блок = модели[нач: кон if кон > 0 else len(модели)]
        if "index=True" not in блок:
            без_индексов.append(имя)

    # Журнал дневной сводки растёт по строке в день — ему индекс не нужен.
    без_индексов = [t for t in без_индексов if t != "DailyDigestLog"]
    assert not без_индексов, (
        f"в этих таблицах нет ни одного индекса: {без_индексов}. Пока район маленький, это "
        "незаметно; на тысячах записей каждая выборка станет полным перебором"
    )
