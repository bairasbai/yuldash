"""Дверь заперли, а окно рядом оставили открытым.

Точную точку сбора и координаты поездки прятали с самого начала: они раскрываются только тому,
кто забронировал. А рядом лежало свободное поле, куда водитель своими руками пишет ровно то же
самое: «заберу у дома, Баймак ул. Ленина 12, звони +7 999 111-22-33».

Это поле уходило В ЛЕНТЕ и БЕЗ ВХОДА. Любой человек в интернете, не заводя аккаунта, читал
адреса и телефоны водителей всего района — списком, за один запрос (аудит 2026-08-08, волна 138).
У заявок пассажиров было мягче и всё равно плохо: вход требовался, но дальше двести заявок
с адресами и телефонами видел каждый зарегистрированный.

Защита обходилась не взломом, а самым обычным поведением: человек пишет ориентир там, где
удобно, и не знает, что читает его не только попутчик.

**Что теперь.** Свободный текст объявления и заявки чистится общей мойкой — той же, что моет
логи, Sentry и аналитику. Замазывается только личное: телефон, номер дома, координаты. Смысл
объявления цел: «еду через Сибай, заберу у автовокзала» не трогается вовсе.

**Кому по-прежнему видно всё.** Водителю — его собственный текст. Пассажиру с живой бронью —
он уже сторона сделки, ему этот ориентир и написан. Отменённая бронь права не даёт: иначе
собрать адреса района можно было бы, бронируя и сразу отменяя.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from app.models import UserRole
from app.services import public_ride_payload

from test_api import _ride

ЛИЧНОЕ = "заберу у дома, Баймак ул. Ленина 12, звони +7 999 111-22-33"
СЛЕДЫ = ("Ленина 12", "111-22-33")
APP = Path(__file__).resolve().parents[1] / "app"


@pytest.fixture
def поездка(client, user_factory):
    водитель = user_factory("ВитринаВодитель", role=UserRole.driver)
    пассажир = user_factory("ВитринаПассажир")
    посторонний = user_factory("ВитринаПосторонний")
    ride_id = _ride(client, водитель, comment=ЛИЧНОЕ)
    bid = client.post("/bookings", headers=пассажир["auth"],
                      json={"ride_id": ride_id, "seats": 1}).json()["id"]
    client.post(f"/bookings/{bid}/confirm", headers=водитель["auth"])
    return водитель, пассажир, посторонний, ride_id, bid


def _следы(текст: str) -> list[str]:
    return [с for с in СЛЕДЫ if с in текст]


@pytest.mark.parametrize("дверь", [
    "/rides",
    "/rides/near?lat=52.9&lng=58.6",
])
def test_гость_не_выкачивает_адреса_района_лентой(client, поездка, дверь):
    """Главное: без аккаунта нельзя собрать адреса и телефоны водителей списком."""
    r = client.get(дверь)

    assert r.status_code == 200, r.text
    assert not _следы(r.text), (
        f"{дверь} отдаёт гостю {_следы(r.text)}: адреса и телефоны водителей района "
        "выкачиваются одним запросом, без регистрации"
    )


def test_страница_для_шеринга_тоже_молчит(client, поездка):
    """Ссылкой на поездку делятся в общем чате села — она заведомо уходит дальше своих."""
    *_, ride_id, _ = поездка

    превью = client.get(f"/r/{ride_id}/preview")
    страница = client.get(f"/r/{ride_id}")

    assert not _следы(превью.text), f"превью для шеринга сливает {_следы(превью.text)}"
    assert not _следы(страница.text), f"страница поездки сливает {_следы(страница.text)}"


def test_посторонний_с_аккаунтом_тоже_не_видит(client, поездка):
    """Регистрация — не пропуск к чужому адресу: аккаунт заводится за минуту."""
    _, _, посторонний, ride_id, _ = поездка

    r = client.get(f"/rides/{ride_id}", headers=посторонний["auth"])

    assert r.status_code == 200
    assert not _следы(r.text), (
        f"зарегистрированный посторонний видит {_следы(r.text)} — защита стоит ровно "
        "до бесплатной регистрации"
    )


def test_свой_видит_ориентир_целиком(client, поездка):
    """Обратная сторона: замазать всем — значит сломать поездку.

    Пассажирка с бронью должна знать, где её заберут, а водитель — видеть свой текст.
    """
    водитель, пассажир, _, ride_id, _ = поездка

    у_пассажира = client.get(f"/rides/{ride_id}", headers=пассажир["auth"])
    у_водителя = client.get(f"/rides/{ride_id}", headers=водитель["auth"])
    свои_поездки = client.get("/driver/rides", headers=водитель["auth"])

    assert _следы(у_пассажира.text) == list(СЛЕДЫ), (
        "пассажирка с бронью не видит ориентир — она не найдёт машину у дома"
    )
    assert _следы(у_водителя.text) == list(СЛЕДЫ), "водитель не видит собственный текст"
    assert _следы(свои_поездки.text) == list(СЛЕДЫ), (
        "в своих поездках водитель видит объявление замазанным — решит, что текст пропал"
    )


def test_отменённая_бронь_доступа_не_даёт(client, user_factory):
    """Иначе адреса района собираются так: забронировал → прочитал → отменил → следующий."""
    водитель = user_factory("ВитринаВодитель2", role=UserRole.driver)
    хитрец = user_factory("ВитринаХитрец")
    ride_id = _ride(client, водитель, comment=ЛИЧНОЕ)
    bid = client.post("/bookings", headers=хитрец["auth"],
                      json={"ride_id": ride_id, "seats": 1}).json()["id"]
    client.post(f"/bookings/{bid}/cancel", headers=хитрец["auth"],
                json={"reason": "plans_changed"})

    r = client.get(f"/rides/{ride_id}", headers=хитрец["auth"])

    assert not _следы(r.text), (
        f"после отмены брони адрес всё ещё виден ({_следы(r.text)}): чтобы собрать адреса "
        "района, хватит бронировать и сразу отменять"
    )


def test_лента_заявок_не_раздаёт_адрес_заявителя(client, user_factory):
    """У заявок вход требовался, но дальше их видел каждый — двести адресов на экране."""
    пассажирка = user_factory("ВитринаЗаявитель")
    водитель = user_factory("ВитринаВодитель3", role=UserRole.driver)
    заявка = client.post("/requests", headers=пассажирка["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай",
        "desired_at": "2030-11-02T08:00:00", "seats": 1,
        "comment": "жду у дома, Баймак ул. Ленина 12, звони +7 999 111-22-33",
    })
    assert заявка.status_code == 200, заявка.text

    лента = client.get("/requests/feed", headers=водитель["auth"])

    assert лента.status_code == 200, лента.text
    assert not _следы(лента.text), (
        f"лента заявок отдаёт {_следы(лента.text)}: адрес и телефон женщины читает любой, "
        "кто завёл аккаунт, — ещё до того, как она выбрала водителя"
    )


def test_лента_из_кеша_чистится_так_же():
    """Вторая дверь той же витрины — и её легко не заметить.

    Лента без фильтров отдаётся из кеша, а там поездка — уже не объект, а простой словарь.
    Ветка кода другая, и на тестах она молчит: Redis в прогоне выключен, лента идёт напрямую.
    На проде всё наоборот — из кеша приходит почти каждый запрос ленты. Значит защита,
    поставленная только в одной ветке, на сервере не работала бы вовсе.
    """
    из_кеша = public_ride_payload({"id": 1, "comment": ЛИЧНОЕ})

    assert not _следы(из_кеша["comment"]), (
        f"поездка из кеша отдаёт {_следы(из_кеша['comment'])}: на сервере лента идёт именно "
        "этим путём, и защита обошлась бы сама собой"
    )


def test_водитель_после_правки_видит_свой_текст(client, поездка):
    """Обратная сторона в третьей ветке: ответы на действия самого водителя.

    Он поправил цену — и должен увидеть своё объявление целиком. Замазанный собственный текст
    читается как «приложение испортило мою запись», и водитель начнёт переписывать её заново.
    """
    водитель, _, _, ride_id, _ = поездка

    правка = client.post(f"/rides/{ride_id}/edit", headers=водитель["auth"],
                         json={"price": 250})   # с живой бронью цену можно только снижать

    assert правка.status_code == 200, правка.text
    assert _следы(правка.text) == list(СЛЕДЫ), (
        "после своей же правки водитель получил объявление с замазанным текстом — решит, "
        "что приложение испортило запись"
    )


def test_смысл_объявления_не_страдает():
    """Обратная мутация: перестраховка сломала бы саму витрину.

    Если замазывать всё подряд, объявления станут нечитаемыми и человек не поймёт, куда идти.
    """
    обычное = "Еду через Сибай, заберу у автовокзала. Багажник свободен, 2 места."
    видно = public_ride_payload({"comment": обычное})["comment"]

    assert видно == обычное, (
        f"мойка испортила обычное объявление: {видно!r}. Ориентиры «у автовокзала», «через "
        "Сибай» — это и есть польза текста, их трогать нельзя"
    )


def test_новая_дверь_со_свободным_текстом_не_проедет_молча():
    """Сторож по признаку, а не по имени: любая выдача чужого свободного текста.

    Дыра пришла не из злого умысла, а из того, что поле добавили в ответ и не подумали, кто
    его прочитает. Следующий раз будет таким же — поэтому ищем сам приём.
    """
    # Места, где полный текст отдаётся ОСОЗНАННО, с указанием кому именно.
    #
    # Ключ — ИМЯ ФУНКЦИИ, а не номер строки: строки съезжают от любой соседней правки, и такой
    # сторож поднимал бы ложную тревогу каждую неделю, пока его не отключат. Имя функции живёт
    # столько же, сколько сама дверь.
    СВОИМ = {
        "admin_request_for_phone": "админ завёл заявку за человека по телефону — текст его же",
        "respond_to_request": "отклик водителя — его собственные слова, адресованные автору заявки",
        "_response_out": "отклики на МОЮ заявку — их читает только автор заявки",
        "public_schedules": "расписание — закрыто по видимости (волна 113), посторонним не видно",
    }
    голые: list[str] = []
    for путь in sorted((APP / "routers").glob("*.py")):
        функция = "?"
        for i, ln in enumerate(путь.read_text(encoding="utf-8").splitlines(), 1):
            m = re.match(r"\s*(?:async )?def (\w+)", ln)
            if m:
                функция = m.group(1)
            if not re.search(r"comment=\w+\.comment\b", ln):
                continue
            if "scrub_text" in ln or функция in СВОИМ:
                continue
            голые.append(f"{путь.name}:{i} (в {функция})  {ln.strip()[:60]}")
    assert not голые, (
        f"свободный текст человека уходит в выдачу без чистки: {голые}. Либо прогони через "
        "общую мойку (scrub_text), либо впиши функцию в СВОИМ и объясни, кто именно это читает"
    )
