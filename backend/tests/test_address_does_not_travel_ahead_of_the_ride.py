"""Адрес человека уезжал вперёд него самого — в чужие телефоны и мимо блокировки.

Две находки одного дня, обе про одно: правило спрятать адрес применили наполовину.

**Первая: адрес подачи в предложении заказа.** Карточка такси-заказа прячет номер дома
назначения, пока водитель не согласился везти, — отказаться можно бесплатно и сколько угодно
раз, так что иначе адреса собирались бы одними отказами. А в пуше, который предлагает заказ
кандидатам, обрезали только «куда». «Откуда» уходило целиком: «ул. Ленина, 12, кв. 43,
подъезд 2» (аудит 2026-08-08, волна 143).

Женщина вызывает такси от дома ночью. Заказ предлагается водителям по очереди — её адрес
с номером квартиры и подъезда всплывает на погашенных экранах нескольких чужих телефонов
подряд, ещё до того, как кто-то согласился ехать. На стоянке рядом стоят другие люди и читают
то же самое.

Точный адрес, подъезд и комментарий водитель получает сразу после «Беру» — в карточке заказа,
где он уже сторона сделки. До этого ему хватает улицы, чтобы решить, ехать ли в тот конец.

**Вторая: расписание водителя мимо блокировки.** Волна 113 закрыла недельный график водителя
от заблокированных и отстранённых, но оставила его открытым гостю — «витрина продукта».
Навязчивому пассажиру достаточно нажать «Выйти», и он снова видит: по каким дням, во сколько
и — в свободном комментарии — у какого подъезда.

Хуже: приложение запрашивало расписание вообще БЕЗ ключа входа. То есть сервер видел не
человека, а гостя, и фильтр по блокировке не срабатывал ни разу — даже для тех, кто вошёл.

Теперь гостю остаётся только маршрут и дни недели («ездит Баймак → Сибай по будням» — этим
попутку ищут, и никого не выслеживают), а время и ориентир требуют входа.
"""
from __future__ import annotations

