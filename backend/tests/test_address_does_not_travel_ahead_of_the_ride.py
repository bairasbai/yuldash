def test_выход_из_аккаунта_не_снимает_блокировку(client, расписание):
    """Главное: «Заблокировать» должно работать и против того, кто просто вышел."""
    женщина, сталкер = расписание

    вошёл = client.get(f"/drivers/{женщина['id']}/schedule", headers=сталкер["auth"])
    вышел = client.get(f"/drivers/{женщина['id']}/schedule")

    assert вошёл.json() == [], "заблокированный видит расписание, хотя вошёл под собой"
    assert "второй подъезд" not in вышел.text, (
        f"стоит выйти из аккаунта — и ориентир снова виден: {вышел.text[:120]}. Женщина "
        "закрылась от человека, а он читает, у какого подъезда её ждать"
    )
    assert "08:00" not in вышел.text, (
        f"время выезда видно гостю: {вышел.text[:120]}. Это и есть ответ на вопрос, "
        "во сколько её подкараулить"
    )


def test_витрина_для_гостя_осталась(client, расписание):
    """Обратная сторона: по расписанию люди ищут попутку — совсем закрывать нельзя."""
    женщина, _ = расписание

    гостю = client.get(f"/drivers/{женщина['id']}/schedule")

    assert гостю.status_code == 200, гостю.text
    строки = гостю.json()
    assert строки, "гость перестал видеть расписание вовсе — сломали поиск попутки"
    assert строки[0]["from_city"] == "Баймак" and строки[0]["to_city"] == "Сибай", строки
    assert строки[0]["weekdays"] == "1,3,5", "пропали дни недели — витрина стала бесполезной"


def test_свой_человек_видит_расписание_целиком(client, расписание, user_factory):
    """Тот, кто вошёл и не заблокирован, должен видеть и время, и ориентир."""
    женщина, _ = расписание
    обычный = user_factory("ГрафикПопутчик")

    r = client.get(f"/drivers/{женщина['id']}/schedule", headers=обычный["auth"])

    строки = r.json()
    assert строки and строки[0]["time"] == "08:00", f"пропало время выезда: {строки}"
    assert "второй подъезд" in строки[0]["comment"], f"пропал ориентир водителя: {строки}"


def test_приложение_представляется_серверу():
    """Сторож: без ключа входа сервер видит гостя, и блокировка не срабатывает ни для кого.

    Дыра была именно тут: фильтр на сервере работал правильно, но приложение спрашивало
    расписание анонимно — и правило не применялось НИ РАЗУ.
    """
    src = ANDROID.read_text(encoding="utf-8")
    начало = src.index("suspend fun getPublicDriverSchedules")
    блок = src[начало: начало + 400]

    assert "auth = true" in блок, (
        "приложение снова спрашивает расписание без ключа входа: сервер увидит гостя, "
        "и «заблокировать» перестанет работать даже для вошедших"
    )
