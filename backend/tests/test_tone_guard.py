"""Сервер говорит с человеком на «ты» — тем же голосом, что и приложение.

Почему отдельный сторож. Правило тона из `CLAUDE.md` §9 держал `ToneSourceGuardTest`, но он
читает только исходники экранов. Половина надписей, которые видит человек, приходит с сервера:
ошибки брони, пуши о доставке, сообщения про оплату. Их не проверял никто — и тон разъехался.

Что нашлось при заведении сторожа (2026-08-13), 10 мест. Самое показательное — одна и та же
строка в трёх файлах:

    herr(403, "Это не ваша поездка", "Был һинең сәфәрең түгел")

Русский на «вы», а башкирский рядом уже на «ты». То есть человек получает разный тон в
зависимости от того, каким языком пользуется. Ровно ту же болезнь нашли и в приложении
(«Найдите поездку» рядом с «бронла»): значит, дело не в невнимательности одного автора,
а в отсутствии проверки.

Тест читает `app/**.py` и падает на вежливой форме внутри строкового литерала: повелительное
на «-ите» и местоимения «ваш/вам/вас/Вы».
"""
from __future__ import annotations

import pathlib
import re

_APP = pathlib.Path(__file__).resolve().parents[1] / "app"

_VERBS = [
    "Найдите", "Укажите", "Введите", "Проверьте", "Выберите", "Нажмите", "Попробуйте",
    "Свяжитесь", "Отправьте", "Подтвердите", "Заполните", "Позвоните", "Напишите",
    "Дождитесь", "Откройте", "Включите", "Выключите", "Загрузите", "Сохраните",
    "Добавьте", "Оплатите", "Закройте", "Обновите", "Расскажите", "Опишите",
    "Помните", "Сделайте", "Поставьте", "Выйдите", "Войдите", "Поищите", "Посмотрите",
    "Уточните", "Повторите", "Обратитесь", "Пришлите", "Перешлите", "Оставьте",
    "Смените", "Измените",
]
_PRONOUNS = [
    "ваш", "ваша", "ваше", "ваши", "вашу", "вашей", "вашего", "вашим", "вашими",
    "ваших", "вам", "вас", "Вы", "Ваш",
]

# Границу слова пишем кириллицей явно: в питоновском `\b` для кириллицы всё в порядке,
# но в Java он работает только по латинице — на этом уже обожглись в ToneSourceGuardTest,
# и одинаковая форма записи в обоих сторожах избавляет от соблазна «упростить».
_L = "А-Яа-яЁё"
# ПРАВИЛО, а не список. Перечисление глаголов пропустило «Используйте Telegram» на первом
# экране приложения и «Оцените поездку» в пуше — при зелёных сторожах (2026-08-13). Список
# описывает то, о чём вспомнил автор; вежливое повелительное узнаётся по окончанию «-ите»/«-йте»
# с большой буквы. Явный список оставлен — он ловит формы вроде «Свяжитесь» и «Помните».
_POLITE_IMPERATIVE = r"[А-ЯЁ][а-яё]+(?:ите|йте)"
_RE = re.compile(rf"(?<![{_L}])({_POLITE_IMPERATIVE}|{'|'.join(_VERBS + _PRONOUNS)})(?![{_L}])")

# Разрешённые места — каждое с причиной.
_ALLOWED = {
    # SMS уходит на телефон доверенного контакта — человеку, который Юлдашем НЕ пользуется
    # и получает тревожное сообщение от незнакомого сервиса. Обращаться к постороннему на «ты»
    # в такой момент — не тёплость, а фамильярность. Единственный адресат вне приложения.
    ("app/routers/safety.py", "Свяжитесь скорее"),
}


def _sources():
    return sorted(_APP.rglob("*.py"))


def _in_string_literal(line: str, pos: int) -> bool:
    """Грубо, но надёжно: нечётное число кавычек слева = мы внутри строки."""
    before = line[:pos]
    return before.count('"') % 2 == 1 or before.count("'") % 2 == 1


def test_сторож_видит_исходники():
    assert len(_sources()) > 30, "не нашёл модули сервера — сторож ничего не проверяет"


def test_сервер_говорит_на_ты():
    hits = []
    for path in _sources():
        rel = path.relative_to(_APP.parent).as_posix()
        for num, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if '"' not in line and "'" not in line:
                continue
            for m in _RE.finditer(line):
                if not _in_string_literal(line, m.start()):
                    continue
                if any(f == rel and frag in line for f, frag in _ALLOWED):
                    continue
                hits.append(f"{rel}:{num}  «{m.group(0)}»  {line.strip()[:90]}")
    assert not hits, (
        "обращение на «вы» в надписях сервера — %d шт. (тон Юлдаша — «ты», CLAUDE.md §9):\n%s"
        % (len(hits), "\n".join(hits))
    )


def test_русский_и_башкирский_в_одной_ошибке_не_спорят_о_тоне():
    """`herr(status, ru, ba)` — одна фраза на двух языках. Вежливый русский рядом с башкирским
    на «һин» означает, что человек получит разный тон в зависимости от языка."""
    ru_polite = re.compile(rf"(?<![{_L}])(ваш\w*|вам|вас|Вы)(?![{_L}])")
    ba_informal = re.compile(r"һин\w*|һиңә|-ың\b")
    hits = []
    for path in _sources():
        src = path.read_text(encoding="utf-8")
        for m in re.finditer(r'herr\(\s*\d+\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"', src):
            ru, ba = m.group(1), m.group(2)
            if ru_polite.search(ru) and ba_informal.search(ba):
                num = src[: m.start()].count("\n") + 1
                hits.append(f"{path.relative_to(_APP.parent).as_posix()}:{num}  ru=«{ru[:50]}» ba=«{ba[:50]}»")
    assert not hits, "русский на «вы», башкирский на «ты» в одной ошибке:\n" + "\n".join(hits)
