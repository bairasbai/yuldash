"""Политика конфиденциальности обещает — код должен исполнять.

Пятый заход не в код приложения: сверка юридического документа с тем, что происходит
на самом деле. Политика на сайте — это не украшение, а обещание человеку, и по нему нас
могут спросить.

**Что нашлось.** Политика прямо пишет: «Резервные копии базы данных хранятся до 14 дней
и затем перезаписываются». Локальные копии действительно чистились по сроку с самого начала.
А копии в облаке не удалялись НИКОГДА — за год там накопился бы годовой архив со всеми
телефонами, адресами и поездками района (аудит 2026-08-08, волна 133).

Это не только расхождение с документом. Каждая лишняя копия базы — ещё одно место, откуда
может утечь весь район; чем меньше копий живёт, тем меньше площадь.

Теперь облачные копии чистятся тем же сроком, что и локальные. Возраст берётся из имени файла
(его задаёт сам скрипт), а не из метки хранилища: метку легко случайно обновить перезаливкой.

---

**Мимоходом пойманная ошибка, которую не видно в коде.** Первая версия ротации была написана
с русскими именами переменных. Синтаксическая проверка (`bash -n`) их пропускает, а на сервере
скрипт упал бы: POSIX-shell не разрешает кириллицу в именах переменных. Поймано только запуском
логики на настоящих именах файлов.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BACKUP = ROOT / "backend" / "ops" / "backup.sh"
LEGAL = ROOT / "web" / "components" / "legal-content.ts"


def test_срок_в_политике_и_в_скрипте_совпадает():
    """Главное: если документ обещает 14 дней, столько и должно быть на деле."""
    политика = LEGAL.read_text(encoding="utf-8")
    обещано = re.search(r"копи[^.]{0,60}?хранятся до (\d+) дней", политика)
    assert обещано, "в политике пропало обещание про срок хранения резервных копий"

    скрипт = BACKUP.read_text(encoding="utf-8")
    по_умолчанию = re.search(r'KEEP_DAYS="\$\{KEEP_DAYS:-(\d+)\}"', скрипт)
    assert по_умолчанию, "в скрипте бэкапа пропал срок хранения"

    assert обещано.group(1) == по_умолчанию.group(1), (
        f"политика обещает {обещано.group(1)} дней, а скрипт хранит {по_умолчанию.group(1)}. "
        "Документ на сайте — это обещание человеку, а не украшение"
    )


def test_облачные_копии_тоже_чистятся():
    """Локальные чистились всегда, а в облаке дампы копились вечно."""
    скрипт = BACKUP.read_text(encoding="utf-8")

    assert "s3 rm" in скрипт, (
        "копии в облаке не удаляются никогда: за год там накопится годовой архив со всеми "
        "телефонами и поездками района, хотя политика обещает 14 дней"
    )
    assert "CUTOFF_DAY" in скрипт, "нет границы по дате — непонятно, что считать старым"


def test_ротация_не_трогает_чужие_файлы():
    """В бакете могут лежать не только наши дампы — снести чужое было бы хуже дыры."""
    скрипт = BACKUP.read_text(encoding="utf-8")
    блок = скрипт[скрипт.index("CUTOFF_DAY="):]

    assert '"${DB_NAME}"-*.sql.gz.enc' in блок, (
        "ротация не проверяет имя файла — под удаление попадёт всё, что лежит в бакете"
    )


def test_скрипт_бэкапа_запускается_в_обычном_shell():
    """Кириллица в именах переменных валит скрипт на сервере, а `bash -n` этого не видит.

    Так и случилось при первой версии этой правки: синтаксис прошёл, а выполнение упало бы
    на строке `ГРАНИЦА=...`. Поэтому здесь проверка именно на кириллические имена.
    """
    скрипт = BACKUP.read_text(encoding="utf-8")
    кириллические = re.findall(r"^\s*([А-Яа-яЁё_][А-Яа-яЁё_0-9]*)=", скрипт, re.MULTILINE)

    assert not кириллические, (
        f"переменные с русскими именами: {кириллические}. POSIX-shell такие не принимает — "
        "на сервере скрипт упадёт, хотя проверка синтаксиса пройдёт"
    )
    # Разбор самим bash-ом — только там, где он действительно есть. На Windows вызов «bash»
    # из Python уводит в WSL, которого может не быть: получилась бы ложная тревога.
    # В CI (Ubuntu) проверка отрабатывает по-настоящему.
    bash = _нужен_bash()
    проверка = subprocess.run([bash, "-n", str(BACKUP)], capture_output=True, text=True, timeout=10)
    assert проверка.returncode == 0, f"скрипт бэкапа не разбирается: {проверка.stderr[:200]}"


def _нужен_bash() -> str:
    """Пропускаем шаги, требующие настоящего shell, если его в системе нет."""
    candidates = [shutil.which("bash")]
    if os.name == "nt":
        # Windows может выбрать launcher WSL вместо установленного Git Bash.
        git_bash = Path(os.environ.get("ProgramFiles", "C:/Program Files")) / "Git/bin/bash.exe"
        if git_bash.is_file():
            candidates.insert(0, str(git_bash))
    for bash in candidates:
        if not bash:
            continue
        try:
            проба = subprocess.run([bash, "-c", "echo ok"], capture_output=True, text=True, timeout=10)
        except (OSError, subprocess.TimeoutExpired):
            continue
        if проба.returncode == 0 and "ok" in проба.stdout:
            return bash
    pytest.skip("работающий bash недоступен — проверка в CI на Ubuntu")


def test_логика_возраста_отбирает_правильные_файлы():
    """Проверка не по глазам, а прогоном: старые уходят, свежие и чужие остаются."""
    bash = _нужен_bash()
    сценарий = r'''
DB_NAME=yuldash
CUTOFF_DAY=20260802
for key in yuldash-20260710-0300.sql.gz.enc yuldash-20260801-0300.sql.gz.enc \
           yuldash-20260815-0300.sql.gz.enc postgres-other.tar yuldash-latest.sql.gz; do
  case "$key" in
    "${DB_NAME}"-*.sql.gz.enc) ;;
    *) echo "skip $key"; continue ;;
  esac
  day="${key#"${DB_NAME}"-}"; day="${day%%-*}"
  if [ -n "$day" ] && [ "$day" -lt "$CUTOFF_DAY" ] 2>/dev/null; then echo "del $key"; else echo "keep $key"; fi
done
'''
    вывод = subprocess.run([bash, "-c", сценарий], capture_output=True, text=True, timeout=10).stdout

    assert "del yuldash-20260710-0300.sql.gz.enc" in вывод, вывод
    assert "del yuldash-20260801-0300.sql.gz.enc" in вывод, вывод
    assert "keep yuldash-20260815-0300.sql.gz.enc" in вывод, "свежая копия попала под удаление"
    assert "skip postgres-other.tar" in вывод, "чужой файл в бакете попал под удаление"
    assert "skip yuldash-latest.sql.gz" in вывод, "незашифрованный старый дамп трогать не наше дело"


def test_права_человека_из_политики_описаны_в_задачах():
    """Политика обещает «получить сведения об обработке» — выгрузки своих данных в коде нет.

    Это не дыра безопасности, а недостающая возможность по закону, и решать, в каком виде
    её делать, — Александру. Здесь сторож на то, чтобы обещание не потерялось из виду.
    """
    задачи = (ROOT / "docs" / "tasks.md").read_text(encoding="utf-8")

    assert "экспорт" in задачи.lower() or "выгруз" in задачи.lower(), (
        "политика обещает человеку право получить сведения о своих данных, а в задачах "
        "об этом ничего нет — обещание потеряется"
    )
