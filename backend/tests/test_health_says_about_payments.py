"""Приложение узнаёт про онлайн-оплату ДО того, как покажет кнопку.

История. На экране завершённой поездки человеку предлагали «Оплатить онлайн — карта или СБП».
Эквайринг при этом выключен: провайдер стоит заглушкой, договора с банком нет. Кнопка была
живой, нажималась, и только тогда сервер отвечал «нельзя» — карточка исчезала до конца
сессии. То есть ровно один раз за сессию человек жал кнопку впустую.

Теперь `/health` говорит, включена ли онлайн-оплата, и приложение спрашивает это заранее.
Поле публичное намеренно: «принимаем ли мы карты» видно любому, кто нажмёт кнопку, — это
свойство сервиса, а не данные человека.
"""
from __future__ import annotations

from app.config import settings


def test_при_заглушке_платежей_говорим_off(client):
    """Провайдер `mock` — это не «работает потихоньку», это «не работает»."""
    было = settings.payments_provider
    settings.payments_provider = "mock"
    try:
        тело = client.get("/health").json()
        assert тело["payments"] == "off", тело
    finally:
        settings.payments_provider = было


def test_включённый_провайдер_называет_себя(client):
    """Когда эквайринг включат, приложение должно узнать об этом без новой версии."""
    было = settings.payments_provider
    settings.payments_provider = "yookassa"
    try:
        тело = client.get("/health").json()
        assert тело["payments"] == "yookassa", тело
    finally:
        settings.payments_provider = было


def test_поле_не_требует_входа(client):
    """Спрашивают его до входа в аккаунт — на экране, где человек ещё никто."""
    ответ = client.get("/health")
    assert ответ.status_code == 200
    assert "payments" in ответ.json()
