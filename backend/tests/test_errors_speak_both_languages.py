# -*- coding: utf-8 -*-
"""Ошибка, которую видит человек, звучит на его языке.

Аудит 2026-08-12, волна 38. Третье применение того же приёма: правило есть, помощник есть
(`errors.herr`), а посчитать, где он НЕ применён, никто не догадался. На 519 двуязычных
ошибок нашлось 58 одноязычных, и 30 из них видит обычный человек — в самых частых местах:
одиннадцать в заказе такси, «аккаунт на паузе до разбора», «поездка завершена — чат только
для чтения», «слишком много загрузок за сутки».

Для башкироязычного человека это выглядит как приложение, которое в трудную минуту переходит
на чужой язык. Именно в трудную: ошибку читают, когда что-то не получилось.

Сторож требует: 4xx с человеческим текстом — только через `herr`. Исключения — ниже,
с причиной у каждого.
"""
import re
from pathlib import Path

APP = Path("app")

# Одноязычные 4xx, которые оставлены осознанно.
ALLOWED_PATTERNS = {
    "Только для админа": "видит только Александр, а он читает по-русски",
    "Только для администратора": "то же самое, другая формулировка в старом коде",
    "status: pending|approved|rejected|all": "подсказка админскому фильтру, а не текст человеку",
    "bad secret": "машинный код для служебной ручки, человек его не видит",
    "phone_required": "машинный код: клиент по нему открывает экран ввода телефона",
    "Пустой токен": "служебная проверка регистрации устройства для пушей",
    "Недопустимый тип бонуса": "админ заводит промокампанию — текст для него",
    "У пользователя нет зафиксированного устройства": "админский инструмент бана устройств",
    "Укажи device_id или user_id": "тот же админский инструмент",
    "У оценки нет текста для модерации": "админ в очереди модерации",
    "Вина на заявителе": "админ разбирает спор — объяснение ему, почему так нельзя",
    "Слоты основателей заняты": "объявление заводит админ, текст для него",
    "status: {' | '.join(_FINAL_STATUSES)}": "подсказка админскому фильтру доставок",
    "Номер {phone} занят": "это ПРИМЕР в комментарии про чистку логов, а не живая ошибка",
}


def _monolingual_4xx():
    """(файл, строка, текст) для всех HTTPException(4xx, "текст") с человеческим текстом."""
    pattern = re.compile(r'HTTPException\(\s*4\d\d\s*,\s*[f]?"([^"]{4,})"')
    out = []
    for path in sorted(APP.rglob("*.py")):
        for i, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
            m = pattern.search(line)
            if m:
                out.append((path.name, i, m.group(1)))
    return out


def test_сторож_вообще_видит_такие_ошибки():
    """Если разбор сломается, проверка ниже позеленеет по недоразумению."""
    src = 'raise HTTPException(404, "Заказ не найден")'
    assert re.search(r'HTTPException\(\s*4\d\d\s*,\s*[f]?"([^"]{4,})"', src)


def test_человеческие_ошибки_на_двух_языках():
    forgotten = [
        f"{name}:{line} — {text[:60]}"
        for name, line, text in _monolingual_4xx()
        if not any(marker in text for marker in ALLOWED_PATTERNS)
    ]
    assert forgotten == [], (
        "эти ошибки увидит человек, а они только по-русски: " + "; ".join(forgotten) +
        ". Переведи на herr(status, ru, ba) — черновик башкирского в docs/tasks.md "
        "на проверку Александру. Если текст видит только админ или это машинный код — "
        "впиши его в ALLOWED_PATTERNS с причиной."
    )


def test_причины_исключений_написаны_для_человека():
    for marker, reason in ALLOWED_PATTERNS.items():
        assert len(reason) >= 20, f"причина для «{marker}» слишком короткая: {reason}"
