"""Пересмотр тарифа 2026-08-21: минута в городе и километр межгорода.

Зачем. Наш тариф был ниже рынка не «слегка», а там, где это бьёт по водителю. Минута в
городе стоила 3 ₽ против 7,5 ₽ у Яндекса в Уфе — человек стоял в пробке почти бесплатно,
хотя именно там уходит его время. Межгород — 9 ₽/км против 15 ₽ у Максима: дальняя поездка
занимает весь день, а платили за неё в полтора раза меньше конкурента.

Это связано с комиссией напрямую. Процент считается ОТ ЧЕКА, и при заниженном чеке водитель
в рублях получает меньше даже при более низком проценте. Поднять комиссию, не поправив тариф,
означало бы забрать у водителя дважды.

Что проверяем:
- новые цифры действительно применяются к цене поездки;
- порядок классов не сломался: Комфорт дороже Эконома и по итогу, и покомпонентно;
- ручную правку цены из админки обновление НЕ затирает (иначе решение Александра молча
  откатывалось бы при каждом рестарте сервера).
"""
import pytest
from sqlmodel import Session, select

from app import instant_service as isv
from app.db import engine
from app.models import Tariff


@pytest.fixture(autouse=True)
def _app_started(client):
    """Схему и стартовые тарифы создаёт подъём приложения — как в проде (main.py)."""
    return client


def _tariff(zone: str, category: str = "standard") -> Tariff:
    with Session(engine) as s:
        row = s.exec(
            select(Tariff).where(Tariff.zone == zone, Tariff.category == category)
        ).first()
        assert row is not None, f"нет тарифа {zone}/{category} — сид не отработал"
        return row


def _price(t: Tariff, dist_km: float, eta_min: float) -> float:
    """Та же формула, что в проде: подача + километры + минуты."""
    return t.base + t.per_km * dist_km + t.per_min * eta_min


# ------------------------------ новые цифры на месте ------------------------------
def test_city_minute_is_no_longer_almost_free():
    """Минута в городе — 5 ₽. При 3 ₽ водитель стоял в пробке почти даром."""
    assert _tariff("city").per_min == 5.0


# Живой рынок межгорода из Уфы (замер 21.08.2026, taxi24online.ru/tarify-mezhgorod/ufa):
# Сибай 12 000 ₽ / 420 км, Магнитогорск 10 000 / 350, Белорецк 8 000 / 270,
# Стерлитамак 4 000 / 140 — везде ровно 28–30 ₽/км.
MARKET_INTERCITY_RUB_PER_KM = 28.6


def test_intercity_kilometre_caught_up_with_the_market():
    """Межгород — 24 ₽/км: чуть дешевле рынка, но уже не вдвое."""
    per_km = _tariff("intercity").per_km
    assert per_km == 24.0
    assert per_km < MARKET_INTERCITY_RUB_PER_KM, "стали дороже рынка — незачем"
    assert per_km > MARKET_INTERCITY_RUB_PER_KM * 0.75, (
        "снова уехали сильно ниже рынка. Дёшево на межгороде означает не «выгодно», "
        "а «водитель не возьмёт заказ»"
    )


# ------------------------------ что это даёт в рублях ------------------------------
def test_typical_city_ride_got_dearer_but_stays_under_yandex():
    """Городская 15 км / 25 мин: было 310 ₽, стало ~370 ₽. У Яндекса в Уфе — 417 ₽.

    Смысл вилки: пассажиру по-прежнему дешевле, чем у большого агрегатора, а водителю
    при комиссии 15% остаётся больше, чем раньше при 8%.
    """
    price = _price(_tariff("city"), 15, 25)
    assert 360 <= price <= 380, f"городская поездка стоит {price} ₽ — вне ожидаемой вилки"
    assert price < 417, "стали дороже Яндекса — весь смысл «дешевле для пассажира» потерян"
    # Водителю при 15% комиссии и 4% налога остаётся больше, чем раньше при 8% и 4% с 310 ₽.
    assert price * (1 - 0.15 - 0.04) > 310 * (1 - 0.08 - 0.04)


# Уфа — Сибай: 450 км по дороге, 5 ч 44 мин по замеру самого Яндекса.
UFA_SIBAY_KM, UFA_SIBAY_MIN = 450, 344
# Расходы водителя (август 2026): АИ-92 64–65 ₽/л по Башстату, Гранта на трассе 7 л/100 км,
# износ (ТО, шины, ремонт) ≈ 3,5 ₽/км.
FUEL_RUB_PER_KM = 7.0 / 100 * 65
WEAR_RUB_PER_KM = 3.5


def test_a_long_ride_with_an_empty_return_does_not_cost_the_driver_money():
    """Главная проверка межгорода: водитель не должен платить за то, что поработал.

    Он едет 450 км с пассажиром и столько же обратно пустым — 11,5 часов и 900 км своей
    машины. При тарифе 9 ₽/км, а потом и 12, он оставался в МИНУСЕ на две тысячи рублей
    после бензина и износа. Такую поездку человек делает один раз, а потом уходит и
    рассказывает другим.

    Считаем по худшему сценарию (пустой возврат) — на нём тариф и должен сходиться.
    Нашёл обратный заказ — заработал вчетверо, но это удача, а не условие работы.
    """
    price = _price(_tariff("intercity"), UFA_SIBAY_KM, UFA_SIBAY_MIN)
    net = price * (1 - 0.15 - 0.04)                      # комиссия 15% + налог самозанятого
    costs = UFA_SIBAY_KM * 2 * (FUEL_RUB_PER_KM + WEAR_RUB_PER_KM)
    hourly = (net - costs) / (UFA_SIBAY_MIN / 60 * 2)
    assert hourly > 150, (
        f"водителю остаётся {hourly:.0f} ₽/час за рулём — это ниже любой другой работы, "
        f"на которую он может уйти завтра (чек {price:.0f} ₽, расходы {costs:.0f} ₽)"
    )


def test_a_long_ride_stays_cheaper_than_the_market():
    """При этом мы всё же дешевле: рынок берёт 12 000 ₽ за Уфа — Сибай."""
    price = _price(_tariff("intercity"), UFA_SIBAY_KM, UFA_SIBAY_MIN)
    market = MARKET_INTERCITY_RUB_PER_KM * UFA_SIBAY_KM
    assert price < market, f"дороже рынка: {price:.0f} против {market:.0f} ₽"


# ------------------------------ порядок классов не сломался ------------------------------
def test_comfort_stays_dearer_than_economy_in_every_component():
    """Минута Комфорта не может стоить дешевле минуты Эконома.

    Итоговая цена и так осталась бы выше, но пассажир видит разбивку — и «в Комфорте минута
    дешевле» читалось бы как ошибка в приложении, а не как задумка.
    """
    for zone in ("city", "intercity"):
        eco, comfort = _tariff(zone), _tariff(zone, "comfort")
        assert comfort.per_min >= eco.per_min, f"{zone}: минута Комфорта дешевле Эконома"
        assert comfort.per_km > eco.per_km, f"{zone}: километр Комфорта не дороже Эконома"
        assert _price(comfort, 15, 25) > _price(eco, 15, 25)


CLASSES = ("standard", "comfort", "minivan", "business")
# Порог разный, и это не произвол. В городе класс — половина смысла заказа: за Комфорт
# берут именно ради машины, и разница должна быть видна. На межгороде платят за километры:
# у Яндекса Уфа→Сибай Эконом → Комфорт всего +11%, Комфорт → Комфорт+ +5% (замер 21.08.2026).
# Пять часов трассы одинаковы в любом салоне. Требовать там 15% значило бы требовать лесенку
# круче рыночной — сторож, который «умнее рынка», рано или поздно заставит сломать цену.
MIN_STEP = {"city": 1.15, "intercity": 1.08}


def test_each_class_is_a_real_step_up_not_a_rounding_difference():
    """Шаг между классами должен быть заметным — и в городе, и на межгороде.

    Живой пример, ради которого сторож и написан. Подняв межгород Эконому и Комфорту и не
    тронув Минивэн с Бизнесом, я сжал шаг Комфорт → Минивэн с 34% до 11%: минивэн на дальнем
    маршруте стоил почти как комфорт. Формально порядок не нарушен — тесты «дороже предыдущего»
    остались бы зелёными. А по делу компания из пяти человек берёт минивэн (мест больше, цена
    та же), Комфорт на межгороде перестают заказывать, и водитель минивэна везёт восьмерых
    за цену четверых.

    Поэтому проверяем не «дороже», а «дороже НАСТОЛЬКО». Правишь один класс — проверь соседей.
    """
    for zone, dist, eta in (("city", 15, 25), ("intercity", 450, 344)):
        prices = [_price(_tariff(zone, c), dist, eta) for c in CLASSES]
        for i in range(1, len(prices)):
            step = prices[i] / prices[i - 1]
            assert step >= MIN_STEP[zone], (
                f"{zone}: {CLASSES[i]} дороже {CLASSES[i - 1]} всего на {(step - 1) * 100:.0f}% "
                f"({prices[i - 1]:.0f} → {prices[i]:.0f} ₽). Класс, который почти не отличается "
                f"ценой, отнимает заказы у соседнего снизу и недоплачивает своему водителю."
            )


def test_class_ladder_by_the_minute_has_no_ties():
    """Эконом < Комфорт < Минивэн < Бизнес — по минуте, без совпадений.

    Равенство здесь не безобидно: за минивэн человек платит именно за вместимость, и если
    его минута стоит как у Комфорта, разницу нечем объяснить.
    """
    minutes = [_tariff("city", c).per_min for c in ("standard", "comfort", "minivan", "business")]
    assert minutes == sorted(minutes), f"ступени сбились: {minutes}"
    assert len(set(minutes)) == len(minutes), f"два класса с одной ценой минуты: {minutes}"


# ------------------------------ чужое решение не затираем ------------------------------
def test_a_hand_set_price_survives_restart():
    """Александр поправил цену в админке — рестарт сервера не должен её откатить.

    Обновление узнаёт «нетронутую» строку по прежнему стартовому значению. Если цифра другая,
    её ставил человек, и молча вернуть свою — значит отменить его решение без спроса, да ещё
    и незаметно: сервер перезапускается сам.
    """
    with Session(engine) as s:
        row = s.exec(select(Tariff).where(
            Tariff.zone == "city", Tariff.category == "standard")).first()
        before = row.per_min
        row.per_min = 4.2                      # «рука Александра»
        s.add(row)
        s.commit()
    try:
        with Session(engine) as s:
            isv.seed_tariffs(s)                # как при старте приложения
        assert _tariff("city").per_min == 4.2, "рестарт затёр ручную правку цены"
    finally:
        with Session(engine) as s:             # вернуть как было — тест не должен пачкать базу
            row = s.exec(select(Tariff).where(
                Tariff.zone == "city", Tariff.category == "standard")).first()
            row.per_min = before
            s.add(row)
            s.commit()


def test_retariff_is_idempotent():
    """Второй запуск ничего не меняет: строки уже несут новые значения, а не старые."""
    with Session(engine) as s:
        assert isv._retariff(s) == 0, "повторный проход снова что-то правит — значит зациклится"
