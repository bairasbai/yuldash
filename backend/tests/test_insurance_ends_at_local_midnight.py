"""Страховка кончается в местную полночь, а не пятью часами позже.

История. У Рината ОСАГО действует по 14 августа. Пятнадцатого он не имеет права возить
людей — ни утром, ни ночью. Но сроки сверялись по мировому времени, которое отстаёт от
башкирского на пять часов: с полуночи до пяти утра сервер считал, что ещё четырнадцатое,
и допуск к такси оставался (аудит 2026-08-08, волна 80).

Пять часов — это ровно ночная смена, самое опасное время на трассе. Случись авария в три
часа ночи, страховки нет ни у пассажира, ни у встречной машины: полис кончился накануне,
а приложение говорило, что всё в порядке.

Тот же счёт работает и в другую сторону — не должен «сгорать» день, который у человека ещё
есть: до местной полуночи 14-го полис действителен, и снимать водителя с линии нельзя.
"""
from __future__ import annotations

from datetime import date, datetime

import app.doc_check as dc
from app.models import TaxiApplication

# Момент времени задаём в мировом; в скобках — что показывают часы в Уфе (UTC+5).
NIGHT_AFTER = datetime(2030, 8, 14, 19, 30)    # 15 августа, 00:30 местного — полис уже истёк
LAST_EVENING = datetime(2030, 8, 14, 18, 30)   # 14 августа, 23:30 местного — последний вечер
MORNING_BEFORE = datetime(2030, 8, 14, 5, 0)   # 14 августа, 10:00 местного — обычный рабочий день


def _osago(until: date) -> TaxiApplication:
    return TaxiApplication(user_id=1, osago_until=until)


def _at(monkeypatch, moment: datetime):
    monkeypatch.setattr(dc, "utcnow", lambda: moment)


def test_ночью_после_местной_полуночи_полис_просрочен(monkeypatch):
    _at(monkeypatch, NIGHT_AFTER)
    overdue = dc.overdue_docs(_osago(date(2030, 8, 14)))
    assert overdue, "в половине первого ночи водитель с истёкшим ОСАГО всё ещё допущен к такси"


def test_в_последний_вечер_полис_ещё_действует(monkeypatch):
    """Обратная сторона: нельзя отбирать у человека день, который у него есть."""
    _at(monkeypatch, LAST_EVENING)
    assert not dc.overdue_docs(_osago(date(2030, 8, 14))), \
        "водителя сняли с линии в его последний законный вечер"


def test_обычный_день_не_трогаем(monkeypatch):
    _at(monkeypatch, MORNING_BEFORE)
    assert not dc.overdue_docs(_osago(date(2030, 8, 20))), "полис со сроком в будущем посчитали истёкшим"


def test_пустой_срок_не_блокирует(monkeypatch):
    """Поля со сроками появились позже живого приложения: у кого их нет — работают как раньше."""
    _at(monkeypatch, NIGHT_AFTER)
    assert not dc.overdue_docs(TaxiApplication(user_id=1)), \
        "водитель без заполненных сроков остался без работы на ровном месте"
