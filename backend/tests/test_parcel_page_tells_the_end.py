"""Страница слежения должна говорить, чем доставка кончилась.

История. Отправитель послал коробку из Баймака в Сибай и кинул получателю ссылку слежения
в SMS. Курьер не смог вручить и привёз посылку обратно.

Получатель открывает ссылку и читает: «Ищем курьера…» — и ждёт. Коробка уже дома у отправителя
(аудит 2026-08-08, волна 124). Мало того, обе точки продолжали показываться на карте, а на такую
посылку выпускалась новая ссылка слежения — с кодом вручения внутри, хотя вручать нечего.

Причина простая и знакомая: финальных статусов у доставки ТРИ (вручена, отменена, возвращена),
а страница слежения знала два. Список финалов в проекте есть — общий, в самих посылках; сюда
он не доехал.

Первая версия починки сделала хуже наполовину: возврат стал показываться как «Посылка
доставлена ✅». Поэтому у каждого финала теперь свой текст.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import ParcelDelivery


@pytest.fixture
def посылка_со_ссылкой(client, user_factory):
    отправитель = user_factory("КоробкаОтправитель")
    pid = client.post("/parcels", headers=отправитель["auth"], json={
        "from_city": "Баймак", "to_city": "Сибай", "size": "small", "rules_accepted": True,
        "receiver_name": "Мама", "receiver_phone": "+79990000124", "price": 200,
    }).json()["id"]
    r = client.post(f"/parcels/{pid}/track-link", headers=отправитель["auth"])
    assert r.status_code == 200, r.text
    токен = r.json().get("token") or r.json().get("url", "").rsplit("/", 1)[-1]
    return отправитель, pid, токен


def _статус(pid: int, статус: str) -> None:
    with Session(engine) as s:
        p = s.get(ParcelDelivery, pid)
        p.status = статус
        s.add(p)
        s.commit()


def _страница(client, токен) -> dict:
    r = client.get(f"/t/{токен}/state.json")
    assert r.status_code == 200, r.text
    return r.json()


def test_возврат_виден_на_странице(client, посылка_со_ссылкой):
    """Главное: получатель не должен ждать коробку, которая уже уехала обратно."""
    _, pid, токен = посылка_со_ссылкой
    _статус(pid, "returned")

    страница = _страница(client, токен)

    assert страница["status"] == "finished", (
        f"страница пишет «{страница['phase_text']['ru']}» — человек будет ждать посылку, "
        "которую уже вернули отправителю"
    )
    assert "вернули" in страница["phase_text"]["ru"], страница["phase_text"]
    assert страница["car"] is None, "после конца доставки позиция курьера показываться не должна"


def test_отмена_не_называется_доставкой(client, посылка_со_ссылкой):
    """Каждый финал говорит своё: «доставлена ✅» на отменённой — такая же ложь."""
    _, pid, токен = посылка_со_ссылкой
    _статус(pid, "canceled")

    текст = _страница(client, токен)["phase_text"]["ru"]

    assert "отменена" in текст.lower(), f"отмена показана как «{текст}»"


def test_вручение_по_прежнему_радостное(client, посылка_со_ссылкой):
    """Обратная сторона: у счастливого конца свой текст, и он не должен потеряться."""
    _, pid, токен = посылка_со_ссылкой
    _статус(pid, "delivered")

    assert "доставлена" in _страница(client, токен)["phase_text"]["ru"].lower()


def test_пока_везут_страница_живая(client, посылка_со_ссылкой):
    """И главное: до финала страница должна показывать ход доставки как раньше."""
    _, pid, токен = посылка_со_ссылкой
    _статус(pid, "in_transit")

    страница = _страница(client, токен)

    assert страница["status"] != "finished", страница
    assert "пути" in страница["phase_text"]["ru"].lower(), страница["phase_text"]


def test_на_завершённую_посылку_новую_ссылку_не_выпустить(client, посылка_со_ссылкой):
    """В ссылке живёт код вручения — выпускать её, когда вручать нечего, нельзя."""
    отправитель, pid, _ = посылка_со_ссылкой
    _статус(pid, "returned")

    r = client.post(f"/parcels/{pid}/track-link", headers=отправитель["auth"])

    assert r.status_code == 409, f"на возвращённую посылку выпущена новая ссылка: {r.status_code}"


def test_финал_доставки_описан_в_одном_месте():
    """Сторож: список финальных статусов не должен снова размножиться.

    Он уже был размножен — и разошёлся: в посылках три статуса, на странице слежения два.
    Пока обе стороны берут его из общего места, четвёртый статус доедет до всех сам.
    """
    from pathlib import Path

    routers = Path(__file__).resolve().parents[1] / "app" / "routers"
    for файл in ("share.py", "family.py"):
        src = (routers / файл).read_text(encoding="utf-8")
        assert "PARCEL_FINAL_STATUSES" in src, (
            f"{файл} снова решает сам, что считать концом доставки — а статусов уже три"
        )
        assert '("delivered", "canceled")' not in src, (
            f"в {файл} остался свой короткий список финалов: возврат снова выпадет"
        )
