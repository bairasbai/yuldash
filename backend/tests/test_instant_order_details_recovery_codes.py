def test_missing_details_code_does_not_change_alternatives_error(client, user_factory):
    user = user_factory("TF05Missing")
    # A negative primary key is not generated by normal fixtures; assert the premise.
    missing = -9051705
    with Session(engine) as session:
        assert session.get(InstantOrder, missing) is None
    details = client.get(f"/instant/orders/{missing}", headers=user["auth"])
    assert details.status_code == 404, details.text
    assert details.json() == {"detail": {
        "ru": "Заказ не найден", "ba": "Заказ табылманы", "code": "instant_order_not_found",
    }}
    other = client.get(f"/instant/orders/{missing}/alternatives", headers=user["auth"])
    assert other.status_code == 404, other.text
    assert other.json() == {"detail": {"ru": "Заказ не найден", "ba": "Заказ табылманы"}}


def test_denied_details_code_has_no_order_payload_or_cross_route_change(client, user_factory, fake_redis):
    driver, passenger, oid = _accepted(client, user_factory, "TF05DriverDenied", "TF05PassengerDenied")
    outsider = user_factory("TF05Outsider")
    details = client.get(f"/instant/orders/{oid}", headers=outsider["auth"])
    assert details.status_code == 403, details.text
    assert details.json() == {"detail": {
        "ru": "Нет доступа к заказу", "ba": "Заказға рөхсәт юҡ", "code": "instant_order_access_denied",
    }}
    other = client.get(f"/instant/orders/{oid}/alternatives", headers=outsider["auth"])
    assert other.status_code == 403, other.text
    assert other.json() == {"detail": {"ru": "Нет доступа к заказу", "ba": "Заказға рөхсәт юҡ"}}
    # Real authorized GET still uses the existing serializer, with no new error fields.
    for owner, role in [(driver, "driver"), (passenger, "passenger")]:
        response = client.get(f"/instant/orders/{oid}", headers=owner["auth"])
        assert response.status_code == 200, response.text
        body = response.json()
        assert (body["id"], body["role"], body["status"]) == (oid, role, "accepted")
        with Session(engine) as session:
            order = session.get(InstantOrder, oid)
            user = session.get(User, owner["id"])
            expected = isv.order_payload(session, order, user)
            assert set(body) == set(expected)
        assert "detail" not in body and "code" not in body
