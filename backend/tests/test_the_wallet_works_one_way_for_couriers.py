def _курьер(client, user_factory, имя: str):
    """Одобренный курьер: кабинет `/courier/me` открыт только им."""
    админ = user_factory(name=f"Админ{имя}", role=UserRole.admin)
    c = user_factory(name=имя, role=UserRole.driver)
    aid = client.post("/courier/apply", headers=c["auth"],
                      json={"transport": "car",
                            "selfie_url": upload_doc(client, c["auth"])}).json()["id"]
    assert client.post(f"/admin/courier-applications/{aid}/approve",
                       headers=админ["auth"]).status_code == 200
    return c


def _доставка_с_долгом(курьер_id: int, отправитель_id: int, комиссия_коп: int) -> int:
    """Вручённая доставка с НЕоплаченной комиссией — это и есть долг курьера."""
    with Session(engine) as s:
        p = ParcelDelivery(
            sender_id=отправитель_id, courier_id=курьер_id, status="delivered",
            from_city="Акъяр", to_city="Сибай", description="коробка",
            delivery_type="courier", price=100000,
            accepted_at=utcnow(), delivered_at=utcnow(),
            commission_kop=комиссия_коп, commission_paid=False, settled=True)
        s.add(p)
        s.commit()
        s.refresh(p)
        return p.id


def _в_кошелёк(курьер_id: int, сумма_коп: int, note: str = "Возврат комиссии") -> None:
    """Деньги платформы, уже лежащие у человека, — как их кладёт волна 215."""
    with Session(engine) as s:
        s.add(LedgerEntry(driver_id=курьер_id, kind=LedgerKind.adj,
                          amount_kop=сумма_коп, ext_id=f"тест:{курьер_id}:{сумма_коп}",
                          note=note))
        s.commit()


def _к_оплате(client, курьер) -> int:
    """Число, которое человек читает в кабинете как «к оплате прямо сейчас»."""
    ответ = client.get("/courier/me", headers=курьер["auth"])
    assert ответ.status_code == 200, ответ.text
    return int(ответ.json()["statement"]["commission_owed_kop"])


def test_деньги_платформы_в_кошельке_гасят_комиссию_курьера(client, user_factory):
    """Главное: платформа держит его деньги и просит перевести полную сумму наличными.

    Долг из двух доставок — 50 ₽ и 150 ₽. В кошельке 50 ₽. Гасим ЦЕЛЫМИ доставками
    и по старшинству (то же правило, что у такси с волны 154: суммы на доставке
    не переписываем, у неё меняется флаг, а не цифра). Значит старая закрывается целиком,
    к оплате остаётся 150 ₽.
    """
    курьер = _курьер(client, user_factory, "РустамКошелёк")
    отправитель = user_factory("ОтправительКошелёк")
    _доставка_с_долгом(курьер["id"], отправитель["id"], 5000)       # старая: 50 ₽
    _доставка_с_долгом(курьер["id"], отправитель["id"], 15000)      # свежая: 150 ₽
    _в_кошелёк(курьер["id"], 5000)                                  # его 50 ₽ у платформы

    к_оплате = _к_оплате(client, курьер)

    assert к_оплате == 15000, (
        f"кабинет просит перевести {к_оплате / 100:.0f} ₽ комиссии, при этом 50 ₽ его "
        "собственных денег платформа держит у себя: вывести их нельзя (выплаты выключены), "
        "и долг они не гасят. Ровно та ситуация, которую волна 154 разобрала у таксиста"
    )


def test_на_одну_большую_доставку_кошелька_не_хватает_осознанно(client, user_factory):
    """Договор про границу механизма, а НЕ про починку: гасим только целыми доставками.

    В кошельке 50 ₽, а вся комиссия — одна доставка на 200 ₽. Частично её закрыть нельзя:
    это значило бы переписать сумму на доставке, а суммы мы не переписываем. Деньги ждут
    следующей доставки, которую они покроют целиком.

    Ровно так же ведёт себя такси с волны 154 — это общая граница обоих режимов, а не
    недоделка курьерского зачёта. Стоит ли разрешить частичное погашение — вопрос
    Александру, записан в `docs/tasks.md`.
    """
    курьер = _курьер(client, user_factory, "РустамОднаБольшая")
    отправитель = user_factory("ОтправительОднаБольшая")
    _доставка_с_долгом(курьер["id"], отправитель["id"], 20000)
    _в_кошелёк(курьер["id"], 5000)

    assert _к_оплате(client, курьер) == 20000, "доставку закрыли частично — сумму переписали"
    with Session(engine) as s:
        assert driver_balance(s, курьер["id"]) == 5000, "деньги списали, долг не закрыв"


