def test_таксисту_ничего_не_сломали(client, user_factory):
    """Обратная сторона: у такси этот механизм работает с волны 154 — не трогаем его.

    Проверяем именно то, что курьерский зачёт не хватает чужие долги: комиссия за такси
    закрывается своим путём, со своей блокировкой строки и своим условием в UPDATE.
    """
    from app.models import CommissionDebt, DebtStatus

    человек = _курьер(client, user_factory, "ИОбоихРежимов")
    отправитель = user_factory("ОтправительОбоих")
    _доставка_с_долгом(человек["id"], отправитель["id"], 5000)      # курьерский долг 50 ₽
    with Session(engine) as s:
        s.add(CommissionDebt(driver_id=человек["id"], order_id=None, amount_kop=7000,
                             status=DebtStatus.unpaid, week_key="2026-W35",
                             created_at=utcnow()))
        s.commit()
    _в_кошелёк(человек["id"], 5000)                                 # ровно на курьерский

    assert _к_оплате(client, человек) == 0, "курьерский долг не погасился"

    with Session(engine) as s:
        такси = s.exec(select(CommissionDebt).where(
            CommissionDebt.driver_id == человек["id"])).first()
        assert такси.status == DebtStatus.unpaid, (
            "курьерский зачёт закрыл такси-долг чужими деньгами"
        )
        assert debt_mod.taxi_owed_kop(s, человек["id"]) == 7000


