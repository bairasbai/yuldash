def test_платит_ровно_столько_сколько_осталось_после_зачёта(client, user_factory):
    """Договор: сумма платежа считается ПОСЛЕ зачёта, иначе он платит и своими, и наличными.

    Число в кабинете и сумма в платеже должны совпадать — иначе человек видит одно,
    а с него берут другое.
    """
    from app.models import Payment

    курьер = _курьер(client, user_factory, "РустамПлатёж")
    отправитель = user_factory("ОтправительПлатёж")
    _доставка_с_долгом(курьер["id"], отправитель["id"], 5000)
    _доставка_с_долгом(курьер["id"], отправитель["id"], 15000)
    _в_кошелёк(курьер["id"], 5000)

    ответ = client.post("/courier/pay-commission", headers=курьер["auth"])
    assert ответ.status_code == 200, ответ.text

    with Session(engine) as s:
        платёж = s.exec(select(Payment).where(
            Payment.user_id == курьер["id"],
            Payment.purpose == "courier_commission").order_by(Payment.id.desc())).first()
    assert платёж is not None and платёж.amount_kop == 15000, (
        f"счёт выставлен на {(платёж.amount_kop if платёж else 0) / 100:.0f} ₽ вместо 150 ₽: "
        "50 ₽ его денег платформа держит у себя и берёт с него полную сумму"
    )


