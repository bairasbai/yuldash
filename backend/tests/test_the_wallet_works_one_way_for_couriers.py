def test_списание_видно_в_кошельке_отдельной_записью(client, user_factory):
    """История денег обязана объяснять, куда делись деньги, — иначе баланс «просто упал».

    Кошелёк append-only и его читает человек. Долг закрылся его деньгами — значит в истории
    должна стоять строка на эту сумму, а не молчаливое уменьшение.
    """
    курьер = _курьер(client, user_factory, "РустамИстория")
    отправитель = user_factory("ОтправительИстория")
    _доставка_с_долгом(курьер["id"], отправитель["id"], 5000)
    _в_кошелёк(курьер["id"], 20000)

    _к_оплате(client, курьер)

    with Session(engine) as s:
        списания = [e for e in s.exec(select(LedgerEntry).where(
            LedgerEntry.driver_id == курьер["id"])).all() if e.amount_kop < 0]
    assert списания, "долг закрыт деньгами человека, а в истории кошелька об этом ни строки"
    assert sum(e.amount_kop for e in списания) == -5000, (
        f"списали {sum(-e.amount_kop for e in списания) / 100:.2f} ₽ вместо 50 ₽"
    )
    with Session(engine) as s:
        assert driver_balance(s, курьер["id"]) == 15000, "баланс после зачёта неверный"


