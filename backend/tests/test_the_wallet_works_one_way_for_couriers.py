"""Кошелёк курьера работает в одну сторону: деньги в нём есть, а долг он не гасит (волна 216).

Волна 154 разобрала эту ситуацию у таксиста и решила её прямо: «деньги платформы у водителя
и долг водителя платформе гасят друг друга — так это и должно работать, без банковских
договоров». Появился `settle_debt_from_wallet`, и с тех пор компенсация промо-скидки уходит
в счёт свежей комиссии сама.

У курьера этого нет. `settle_debt_from_wallet` ходит по `CommissionDebt`, а тот привязан
к `InstantOrder` — то есть к такси. Комиссия курьера живёт флагом на самой доставке
(`ParcelDelivery.commission_kop` + `commission_paid`), и кошелька не видит вообще.

**Раньше это ничего не значило**, потому что курьеру и класть в кошелёк было нечего:
компенсацию промо-скидки платформа кладёт за такси-заказ. **Волна 215 это изменила** —
теперь туда попадает возврат уже уплаченной комиссии за доставку, по которой курьеру
не заплатили. То есть дыру заметно расширила предыдущая волна этой же сессии, и честно
это признать: угол нашёлся не «в старом коде», а в шве между старым кодом и вчерашней
починкой.

**Что видит человек.** Рустаму не заплатили за доставку, разбор подтвердил, 50 ₽ комиссии
вернули ему в кошелёк. Через неделю кабинет пишет: «к оплате 200 ₽». Ровно те 50 ₽ его
собственных денег платформа держит у себя и просит перевести полную сумму наличными.
Вывести их он тоже не может: выплаты выключены до оформления ИП, а `payable_balance`
и так вычитает весь долг.

Проверяем обе стороны: долг обязан уменьшиться на то, что платформа уже держит, — и
у таксиста ничего не должно сломаться, там этот механизм работает с волны 154.
"""
