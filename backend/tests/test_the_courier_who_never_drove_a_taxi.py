def _полдень():
    """«Сегодня в полдень по Уфе» в UTC — момент, от которого часы назад лежат в том же дне.

    Иначе ночной прогон уводит часть отрезка во вчерашний местный день, и тест краснеет
    от часа запуска, а не от кода (урок волны 194 и 210).
    """
    местное = utcnow() + timedelta(hours=settings.local_tz_offset_hours)
    полдень = местное.replace(hour=12, minute=0, second=0, microsecond=0)
    return полдень - timedelta(hours=settings.local_tz_offset_hours)


@pytest.fixture
def курьер(client, user_factory, request):
    """Свой курьер на каждый тест: база общая, чужие доставки копились бы между ними."""
    return user_factory(f"ЧистыйКурьер{abs(hash(request.node.name)) % 100000}",
                        role=UserRole.driver)


def _доставка(курьер_id: int, отправитель_id: int, принял, вручил) -> None:
    with Session(engine) as s:
        s.add(ParcelDelivery(
            sender_id=отправитель_id, courier_id=курьер_id, status="delivered",
            from_city="Сибай", to_city="Акъяр", description="коробка",
            delivery_type="courier", accepted_at=принял, delivered_at=вручил))
        s.commit()


def _гейт_пустил(курьер_id: int, момент) -> bool:
    """Прошёл ли человек гейт отдыха. True = пустили работать дальше."""
    with Session(engine) as s:
        try:
            workday.guard_rested(s, курьер_id, момент)
            return True
        except Exception as e:                    # noqa: BLE001 — это HTTPException 403
            assert getattr(e, "status_code", None) == 403, e
            return False


# ----------------------------- дневной лимит -----------------------------
def test_одиннадцать_часов_с_коробками_и_гейт_молчит(client, курьер, user_factory):
    """Главное: человек за рулём одиннадцать часов подряд, следующую коробку брать нельзя."""
    отправитель = user_factory("ОтправительОдиннадцать")
    сейчас = _полдень()
    _доставка(курьер["id"], отправитель["id"], сейчас - timedelta(hours=11), сейчас)

    with Session(engine) as s:
        видно = workday.work_seconds_today(s, курьер["id"], сейчас)
    assert видно >= 10 * 3600, f"тест слеп: система не видит работу ({видно} сек)"

    assert not _гейт_пустил(курьер["id"], сейчас), (
        f"курьер за рулём {видно // 3600} часов подряд, а гейт отдыха его пропустил. "
        "Система эти часы ВИДИТ и всё равно даёт следующую коробку: флаг лимита ставит "
        "только такси-пинг, а на такси-линию он не выходил ни разу"
    )


def test_после_блока_курьер_отдыхает_до_утра(client, курьер, user_factory):
    """Блок должен не только наступить, но и держаться — иначе он снимется сам через минуту."""
    отправитель = user_factory("ОтправительДоУтра")
    сейчас = _полдень()
    _доставка(курьер["id"], отправитель["id"], сейчас - timedelta(hours=11), сейчас)

    assert not _гейт_пустил(курьер["id"], сейчас)          # блок поставлен
    assert not _гейт_пустил(курьер["id"], сейчас + timedelta(hours=2)), (
        "через два часа курьер снова берёт заказы: блок не пережил даже вечер"
    )


# ----------------------------- недельный лимит -----------------------------
def test_сорок_часов_за_неделю_с_коробками_тоже_считаются(client, курьер, user_factory):
    """Вторая половина: недельный потолок суммирует `seconds_online`, а у курьера он пуст.

    Раскладываем работу по дням так, чтобы дневной лимит НИ РАЗУ не сработал — по семь часов.
    Иначе тест поймал бы дневной лимит и промолчал бы про недельный.
    """
    отправитель = user_factory("ОтправительНеделя")
    сейчас = _полдень()
    for назад in range(1, 7):                     # шесть прошлых дней по 7 часов = 42 часа
        день = сейчас - timedelta(days=назад)
        _доставка(курьер["id"], отправитель["id"], день - timedelta(hours=7), день)

    with Session(engine) as s:
        за_неделю = workday.week_seconds(s, курьер["id"], сейчас)

    assert за_неделю >= workday.week_limit_sec(), (
        f"за неделю курьер наездил {за_неделю // 3600} часов вместо 42: недельный потолок "
        "суммирует только сигналы присутствия, а у того, кто возит посылки, их нет вовсе"
    )


