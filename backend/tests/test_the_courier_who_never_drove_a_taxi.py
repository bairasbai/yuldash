def test_курьер_без_единой_доставки_свободен(client, курьер):
    """Обратная сторона: человек только вышел — гейт обязан молчать и не заводить строк."""
    сейчас = _полдень()

    assert _гейт_пустил(курьер["id"], сейчас), "гейт не пустил курьера, который не работал"

    with Session(engine) as s:
        строки = s.exec(select(TaxiWorkDay).where(
            TaxiWorkDay.driver_id == курьер["id"])).all()
    assert not строки, (
        "гейт завёл строку рабочего дня человеку, который ничего не делал: такие строки "
        "потом попадут в недельный счёт и в статистику"
    )


def test_выспавшийся_курьер_снова_на_линии(client, курьер, user_factory):
    """Обратная сторона: отдых кончился — работать можно.

    Без этого «починкой» сошёл бы вечный блок, который никогда не снимается.
    """
    отправитель = user_factory("ОтправительВыспался")
    вчера = _полдень() - timedelta(days=1)
    _доставка(курьер["id"], отправитель["id"], вчера - timedelta(hours=11), вчера)

    assert not _гейт_пустил(курьер["id"], вчера)           # вчера упёрся

    завтра_утром = _полдень() + timedelta(hours=6)         # следующий день, за полдень
    assert _гейт_пустил(курьер["id"], завтра_утром), (
        "курьер выспался, наступил следующий день, а линия для него так и не открылась"
    )


# ---------------------------------------------------------------------------
# Разбор мутаций: смешанную неделю не сторожил никто.
#
# Мутация «брать максимум по ВСЕМУ окну недели, а не по дням» прошла мимо всех
# 52 тестов про смену. Это не равносильная замена: неделя, где часть дней измерена
# присутствием, а часть — фактическими рейсами, схлопывается в бо́льшую половину.
# Ровно так выглядит реальная неделя водителя, который ездит и по городу (связь есть),
# и по трассе между сёлами (связи нет).
# ---------------------------------------------------------------------------
def _день_по_присутствию(курьер_id: int, день, часов: float) -> None:
    """День, который виден только сигналам: строка есть, заказов нет."""
    with Session(engine) as s:
        s.add(TaxiWorkDay(driver_id=курьер_id, day=день, seconds_online=int(часов * 3600)))
        s.commit()


def test_смешанная_неделя_складывается_по_дням(client, курьер, user_factory):
    """Договор: каждый день недели меряется своим прибором, и потом дни СКЛАДЫВАЮТСЯ.

    Четыре дня по городу со связью (видит присутствие) плюс три дня по трассе без связи
    (видят только заказы) — это сорок два часа за неделю, а не двадцать четыре.
    """
    отправитель = user_factory("ОтправительСмешанный")
    сейчас = _полдень()

    for назад in (0, 1, 2, 3):                       # четыре дня со связью, по 6 часов
        _день_по_присутствию(курьер["id"], workday.local_day(сейчас - timedelta(days=назад)), 6)
    for назад in (4, 5, 6):                          # три дня без связи, по 6 часов
        день = сейчас - timedelta(days=назад)
        _доставка(курьер["id"], отправитель["id"], день - timedelta(hours=6), день)

    with Session(engine) as s:
        за_неделю = workday.week_seconds(s, курьер["id"], сейчас)

    assert за_неделю >= workday.week_limit_sec(), (
        f"за неделю насчитано {за_неделю // 3600} часов вместо 42: дни со связью и дни без "
        "связи схлопнулись в одну половину вместо того, чтобы сложиться"
    )
