"""Курьер, который никогда не выходил на такси-линию, не отдыхает никогда (волна 212).

Волна 194 (29.08) поставила гейт отдыха на приём курьерского заказа: «руль не спрашивает,
человек в машине или коробка». Гейт там честно стоит и честно срабатывает — но только если
флаг «смена выработана» уже поставлен.

**Ставить его некому.** Флаг `limit_reached_at` пишет один-единственный вызов —
`record_heartbeat`, а зовут его из одного места: `POST /instant/presence`. Туда пускают
только водителя с включённым «Я на линии» в ТАКСИ. Человек, который весь день возит
посылки и такси не касался, туда не заходит ни разу.

Та же дыра у недельного лимита, только глубже: он суммирует `seconds_online` по строкам
рабочего дня, а у чистого курьера этих строк вообще нет — сорок часов за неделю для него
всегда ноль.

Итог: оба лимита, дневной и недельный, для чистого курьера декоративные. Это ровно тот
диагноз, который волна 194 поставила самой себе («лимит наполовину декоративный»), — просто
вторая половина оказалась глубже, чем показалось.

Система при этом рабочее время **видит**: `work_seconds_today` считает доставки с волны 194
и возвращает верное число. Она знает, что человек за рулём одиннадцать часов, и всё равно
даёт ему следующую коробку.
"""
