def test_каждое_место_с_часами_обезврежено_в_тестах():
    """Сторож на класс: код может смотреть на часы, но прогон от этого зависеть не должен."""
    найденные: dict[str, str] = {}
    for path in sorted(APP.rglob("*.py")):
        func = "?"
        for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            m = re.match(r"\s*(?:async )?def (\w+)", line)
            if m:
                func = m.group(1)
            # `datetime(ln.year, ln.month, ln.day)` — это сборка местной полуночи из даты,
            # а не ветвление по календарю: такие места прогон не ломают.
            if re.search(r"datetime\([^)]*\.year", line):
                continue
            if re.search(r"\.hour\b|\.month\b", line):
                найденные[func] = f"{path.name}:{i}"

    забытые = {f: где for f, где in найденные.items() if f not in ЧАСОЗАВИСИМЫЕ}
    assert not забытые, (
        "здесь код смотрит на стенные часы или календарь, а как это обезврежено в тестах — "
        f"не записано: {забытые}. Либо сделай поведение управляемым (передавай момент явно "
        "или заводи флаг), либо добавь запись в ЧАСОЗАВИСИМЫЕ с причиной. Иначе однажды прогон "
        "покраснеет ночью или зимой, и никто не поймёт почему."
    )
