"""Проверки не должны зависеть от того, который час на стене.

Что случилось. 15 августа в 22:01 по Уфе прогон покраснел на семнадцати тестах про
уведомления. Код при этом не менялся ни строкой — просто наступила ночь, и включились тихие
часы волны 105: пуши перестали уходить, а тесты их ждали (аудит 2026-08-08, волна 111).

Почему это опаснее, чем кажется. Человек, увидев красный прогон, либо час ищет поломку,
которой нет, либо привыкает к красному — и однажды пропустит настоящую. Это уже случалось
в проекте дважды: с общим файлом тестовой базы (2026-08-06) и с дневной сводкой после 21:00.
Оба раза лечение было одинаковым: сделать тестовую среду независимой от внешних условий.

Теперь тихие часы в тестах выключены целиком, а тесты самой тишины включают её себе явно.
Правило простое: **что проверяем, тем и управляем**.

Ниже — проверка на живом поведении (оповещение доходит в любой час) и сторож на весь класс:
у каждого места, где код смотрит на час или месяц по стенным часам, должно быть записано,
как оно обезврежено в тестах.
"""
from __future__ import annotations

import re
from datetime import datetime
