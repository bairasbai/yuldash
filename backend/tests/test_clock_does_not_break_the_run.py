APP = Path(__file__).resolve().parents[1] / "app"
CONFTEST = Path(__file__).resolve().parent / "conftest.py"

# Моменты по Уфе (сервер живёт в UTC, Уфа = UTC+5).
ГЛУБОКАЯ_НОЧЬ = datetime(2026, 1, 14, 22, 30)   # 03:30 у человека, ещё и январь
СЕРЕДИНА_ДНЯ = datetime(2026, 6, 14, 9, 30)     # 14:30 у человека
# Ровно та минута, когда всё и сломалось: 22:01 по Уфе, первая минута тишины. Первая версия
# этого теста брала три часа ночи — и пропускала поломку самого выключателя тишины.
НАЧАЛО_ТИШИНЫ = datetime(2026, 8, 15, 17, 30)   # 22:30 у человека


@pytest.fixture
def caught(monkeypatch):
    out: list[str] = []
    monkeypatch.setattr(svc, "send_push", lambda s, uid, t, b, data=None: out.append(t))
    return out


def _notify(user_id: int):
    with Session(engine) as s:
        svc.push_notification(s, user_id, "ride", "Оцените поездку", "Баһала",
                              "текст", "текст", ref_kind="ride", ref_id=user_id)


@pytest.mark.parametrize("момент", [ГЛУБОКАЯ_НОЧЬ, НАЧАЛО_ТИШИНЫ, СЕРЕДИНА_ДНЯ],
                         ids=["три-ночи", "начало-тишины", "день"])
def test_проверки_идут_одинаково_в_любой_час(client, user_factory, caught, monkeypatch, момент):
    """Один и тот же тест обязан вести себя одинаково в три ночи и в два дня."""
    monkeypatch.setattr(svc, "utcnow", lambda: момент)
    person = user_factory(f"Часы{момент.hour}{момент.month}")

    _notify(person["id"])

    assert caught, (
        "уведомление не ушло — значит прогон снова зависит от часа на стене, и ночная сборка "
        "покраснеет сама собой"
    )


def test_тихие_часы_в_тестах_выключены():
    """Обезврежены они ровно одной строкой — её и стережём."""
    src = CONFTEST.read_text(encoding="utf-8")
    assert 'os.environ["QUIET_HOURS_TO"] = "0"' in src, (
        "в тестовой среде снова включились тихие часы: прогон после десяти вечера начнёт ронять "
        "посторонние тесты про уведомления"
    )


def test_тишину_всё_ещё_проверяют():
    """Обратная сторона: выключить ночь в тестах — не значит перестать её проверять."""
