"""Голосовое сообщение уносило с собой место записи.

У фотографий место съёмки срезается с волны 21: женщина фотографируется дома, ставит снимок
в профиль, и координаты дома внутрь файла больше не попадают. У голосовых такой чистки
не было вовсе (аудит 2026-08-08, волна 142).

Проверено пробой: файл с местом записи внутри доехал до сервера целиком и отдавался ГОСТЮ —
без всякого входа. Голосовые лежат по публичной ссылке, иначе собеседник их не послушает.

Телефоны действительно пишут туда место: в звуковом файле для этого есть отдельные поля.
То есть женщина записала голосовое из дома, отправила водителю — и адрес уехал вместе
со звуком, доступный любому, кто получил ссылку.

**Что теперь.** Голосовые чистятся в том же месте, где чистятся фото, — в единственной точке,
через которую проходят все загрузки. Поле с координатами помечается как пустое место, которое
проигрыватели пропускают: размер и структура файла не меняются, звук не трогаем.

**Где сознательно остановились.** Не разбираем и не перекодируем звук: перекодирование ради
чистки дороже и рискованнее самой задачи, а сломанное голосовое человек уже не переслушает.
Битый или незнакомый файл проходит как есть — сообщение важнее идеальной чистки.
"""
from __future__ import annotations

import base64

import pytest

from app.imagemeta import strip_audio_metadata

ЗНАК = bytes([0xA9])                       # «©» в имени поля — один байт, не буква
КООРДИНАТЫ = b"+52.5942+58.3156/"          # двор в Баймаке, формат как у телефона


def _атом(тип: bytes, тело: bytes) -> bytes:
    return (len(тело) + 8).to_bytes(4, "big") + тип + тело


def _голосовое_с_местом_записи() -> bytes:
    """Звуковой файл, внутри которого телефон записал, где человек находился."""
    поле = _атом(ЗНАК + b"xyz", b"\x00\x11\x15\xc7" + КООРДИНАТЫ)
    return _атом(b"ftyp", b"M4A " + b"\x00" * 24) + _атом(b"moov", _атом(b"udta", поле))


def test_место_записи_не_доезжает_до_сервера(client, user_factory):
    """Главное: по голосовому нельзя узнать, откуда человек его записал."""
    человек = user_factory("ГолосЖенщина")
    файл = _голосовое_с_местом_записи()
    assert КООРДИНАТЫ in файл, "проверять нечего — в исходнике нет места записи"

    r = client.post("/voice", headers=человек["auth"],
                    json={"audio_b64": base64.b64encode(файл).decode(), "ext": "m4a"})

    assert r.status_code == 200, r.text
    ссылка = r.json()["url"].replace("https://yulbash.ru", "")
    отдано = client.get(ссылка, headers=человек["auth"]).content
    assert (ЗНАК + b"xyz") not in отдано, (
        "поле с местом записи уехало вместе с голосовым: адрес дома человека лежит внутри "
        "файла, который слушает собеседник"
    )


def test_голосовое_лежит_на_виду_и_потому_это_важно(client, user_factory):
    """Почему это не мелочь: файл скачивает кто угодно по ссылке, без входа."""
    человек = user_factory("ГолосЖенщина2")
    файл = _голосовое_с_местом_записи()
    r = client.post("/voice", headers=человек["auth"],
                    json={"audio_b64": base64.b64encode(файл).decode(), "ext": "m4a"})
    ссылка = r.json()["url"].replace("https://yulbash.ru", "")

    гостю = client.get(ссылка)                       # БЕЗ входа в приложение

    assert гостю.status_code == 200, (
        "голосовое перестало открываться по ссылке — собеседник не сможет его послушать"
    )
    assert (ЗНАК + b"xyz") not in гостю.content, (
        "гость без входа скачивает файл вместе с местом записи"
    )


def test_звук_и_структура_файла_целы():
    """Обратная сторона: чистка не должна ломать сообщение.

    Сломанное голосовое человек уже не переслушает — цена ошибки здесь выше, чем у фото.
    """
    файл = _голосовое_с_местом_записи()

    чистый = strip_audio_metadata(файл, "m4a")

    assert len(чистый) == len(файл), "размер файла изменился — структура поехала"
    assert чистый[:8] == файл[:8], "испорчен заголовок файла"
    assert b"moov" in чистый and b"udta" in чистый, "снесены служебные разделы файла"
    assert b"free" in чистый, (
        "поле не помечено как пустое место: проигрыватель попытается прочитать мусор"
    )


@pytest.mark.parametrize("мусор", [
    b"",                                    # пустой
    b"\x00\x00\x00\x08ftyp",                # обрубок
    b"\xff\xfb\x90\x00" + b"\x00" * 40,     # это вообще mp3-кадр, не наш контейнер
    b"\x00\x00\xff\xffmoov" + b"\x11" * 20,  # заявленная длина не сходится с настоящей
])
def test_битый_файл_не_роняет_отправку(мусор: bytes):
    """Голосовое важнее идеальной чистки: не разобрали — пропускаем как есть, но не падаем."""
    результат = strip_audio_metadata(мусор, "m4a")

    assert результат == мусор, "чистка испортила файл, который не смогла разобрать"


def test_на_случайном_мусоре_чистка_не_падает():
    """Голосовое приходит с любого телефона, и файл может быть каким угодно.

    Исключение здесь означало бы, что человек не может отправить сообщение вообще. Гоняем
    случайные байты: важно не то, что чистка сработала, а то, что она никого не уронила.
    """
    import random

    rnd = random.Random(142)
    for _ in range(300):
        длина = rnd.randint(0, 200)
        кусок = bytes(rnd.randrange(256) for _ in range(длина))
        try:
            strip_audio_metadata(кусок, "m4a")
        except Exception as e:  # noqa: BLE001
            raise AssertionError(
                f"чистка упала на случайном файле ({type(e).__name__}: {e}) — человек "
                f"не сможет отправить голосовое: {кусок[:40]!r}"
            ) from e


def test_незнакомый_формат_не_трогаем_даже_если_похоже():
    """Обратная сторона: в чужом формате те же байты могут значить совсем другое.

    Внутри ogg-файла последовательность «loci» — обычные данные звука, а не поле с местом.
    Если применить к нему разбор нашего контейнера, он молча испортит чужой файл.
    """
    # Кусок, который наш разбор ПРИНЯЛ БЫ за поле с местом: правильная длина, знакомое имя.
    # В ogg это просто звук, и трогать его нельзя.
    данные = (16).to_bytes(4, "big") + b"loci" + "звукзву".encode()[:8]

    assert strip_audio_metadata(данные, "ogg") == данные, (
        "чужой формат разобран как наш и испорчен: человек получит битое сообщение"
    )


def test_незнакомый_формат_проходит_как_есть():
    """Волна не должна молча портить то, чего не понимает."""
    данные = b"OggS" + b"\x00" * 40

    assert strip_audio_metadata(данные, "ogg") == данные


def test_чистка_стоит_на_общем_пути_а_не_у_одной_кнопки():
    """Сторож: правило должно жить там, где проходят ВСЕ загрузки.

    У фото так и сделано с волны 21 — одна точка на аватар, чат, документы и доказательства.
    Если чистку голосовых прицепить к одной ручке, следующая загрузка звука её не унаследует,
    и дыра вернётся ровно там, где её никто не ищет.
    """
    from pathlib import Path

    src = (Path(__file__).resolve().parents[1] / "app" / "services.py").read_text(encoding="utf-8")
    начало = src.index("def _validate_upload")
    блок = src[начало: src.index("\ndef ", начало + 10)]

    assert "strip_audio_metadata" in блок, (
        "чистка голосовых стоит не в общей проверке загрузки: значит она работает только "
        "у той кнопки, где её прописали руками"
    )
    assert "strip_image_metadata" in блок, "чистка фото уехала из общей точки"
