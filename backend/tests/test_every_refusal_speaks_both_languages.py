"""Тринадцать отказов человек читал только по-русски — включая «не могу войти» (волна 173).

Правило проекта простое: каждая видимая надпись — на двух языках. Для отказов оно важнее,
чем для всего остального: человек видит их в момент, когда что-то не получилось, и должен
понять, что делать дальше.

Самое неудачное место нашлось на входе. Код не ушёл — приложение отвечало «SMS не отправлено»,
по-русски и без объяснений. Башкироязычный человек в эту минуту не может вообще ничего:
ни войти, ни понять причину, ни узнать, куда обращаться. Правило двуязычия существует ровно
для таких минут.

Рядом были «Вход через VK ещё не подключён», «Пустой токен» и ещё несколько. Все переписаны
на два языка и заодно на человеческий: не «ошибка 502», а «попробуй ещё раз через минуту» —
сбой у оператора связи проходит сам, и это стоит сказать.

**Админские отказы оставлены по-русски сознательно.** «Только для админа», «Укажи device_id»
и подобные читает один человек — Александр, и переводить их значило бы делать работу ради
галочки. Сторож отличает их двумя признаками сразу: по адресу ручки (`/admin/…`) и по самому
тексту. Одного адреса мало — проверки роли живут в общих хелперах, которые лежат выше всех
ручек файла, и ближайший декоратор для них ничего не значит.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1] / "app"
#: Код ответа числом (`401`) или именем (`status.HTTP_401_UNAUTHORIZED`). Именная форма была
#: слепым пятном: так записанные отказы сессии уходили человеку только по-русски, хотя это
#: самый частый отказ приложения — он стоит на каждом защищённом запросе (аудит leaf-2.1).
_КОД = r'(?:\d{3}|status\.HTTP_\d{3}_[A-Z_]+)'


def _отказы_на_одном_языке(текст_файла: str, имя: str = "образец.py") -> list:
    """Отказы с русским текстом вне админских ручек — то есть видимые обычному человеку.

    Ищем по ДВУМ признакам, потому что одного мало (волна 177):

    1. Русский текст прямо в вызове — `HTTPException(403, "Пройди проверку")`.
    2. Русский текст, спрятанный в константе — `HTTPException(403, TAXI_NOT_APPROVED_MSG)`,
       где рядом лежит `TAXI_NOT_APPROVED_MSG = "Пройди проверку таксиста..."`.

    Второй признак и был слепым пятном: пять отказов уехали в константы, сторож их не видел,
    а человек читал. Причём читал не по-русски: приложение, увидев одноязычный `detail`,
    показывает башкироязычному общую заглушку «Был эшкә рөхсәт юҡ» — то есть «нельзя»
    без «почему». Русскоязычному в той же ситуации объясняли, что делать.
    """
    строки = текст_файла.splitlines()
    словарь = _русские_константы(текст_файла)
    найдено = []
    for i, строка in enumerate(строки, 1):
        # Позиционная форма — `HTTPException(403, "Пройди проверку")`.
        m = re.search(r'HTTPException\(\s*' + _КОД + r'\s*,\s*["\']([^"\']{4,})', строка)
        # Именованная — `HTTPException(status_code=404, detail="Бронь не найдена")`.
        # Слепое пятно, через которое проскочили три отказа на экране оценки поездки
        # (сверка двуязычия, 2026-08-31): человек оценивал поездку и читал русский текст.
        if m is None:
            m = re.search(
                r'HTTPException\(\s*status_code\s*=\s*' + _КОД + r'\s*,\s*'
                r'detail\s*=\s*["\']([^"\']{4,})',
                строка,
            )
        текст = m.group(1) if m else None
        if текст is None:
            k = re.search(r'HTTPException\(\s*' + _КОД + r'\s*,\s*([A-Za-z_][A-Za-z0-9_.]*)\s*[,)]',
                          строка)
            if k:
                текст = словарь.get(k.group(1).split(".")[-1])
        if текст is None or not re.search(r"[А-Яа-яЁё]", текст):
            continue
        if _двуязычный_текст(текст) or _админский(строки, i, текст):
            continue
        найдено.append(f"{имя}:{i}: {текст[:50]}")
    return найдено


#: Кириллица, которой в русском нет: если она есть в строке, башкирский там тоже есть.
_БАШКИРСКИЕ_БУКВЫ = "әөүҙҫңғҡӘӨҮҘҪҢҒҠ"


def _двуязычный_текст(текст: str) -> bool:
    """Обе фразы в одной строке через разделитель — так сделан отказ забаненному устройству."""
    return any(б in текст for б in _БАШКИРСКИЕ_БУКВЫ)


def _русские_константы(текст_файла: str) -> dict:
    """`ИМЯ = "русский текст"` — модульные константы, которые потом уходят в отказ.

    Берём только имена ЗАГЛАВНЫМИ (включая `_PAYOUT_SOON`): так пишут константы, и это
    отсекает обычные переменные внутри функций, где текст уже собран по языку.
    """
    словарь = {}
    for m in re.finditer(r'^(_?[A-Z][A-Z0-9_]*)\s*=\s*(\(?(?:\s*["\'][^"\']*["\'])+\s*\)?)',
                         текст_файла, re.M):
        # Константу часто склеивают из нескольких строк — берём ВСЕ куски. Иначе башкирская
        # половина, лежащая во второй строке, не видна, и сторож ругается на честный текст.
        куски = re.findall(r'["\']([^"\']*)["\']', m.group(2))
        целиком = " ".join(к for к in куски if к).strip()
        if len(целиком) >= 4:
            словарь[m.group(1)] = целиком
    return словарь


def _админский(строки: list, номер: int, текст: str) -> bool:
    """Отказ адресован админу? Два признака, любого достаточно.

    Адрес ручки — надёжный признак, но проверки роли живут в общих хелперах (`_require_admin`),
    которые лежат ВЫШЕ всех ручек файла: для них ближайший декоратор ничего не значит.
    Поэтому вторым признаком берём сам текст: «Только для админа» адресовано одному человеку —
    Александру, и переводить это значило бы работать ради галочки.
    """
    if any(слово in текст for слово in ("админ", "Админ", "модератор")):
        return True
    for j in range(номер - 1, max(0, номер - 60), -1):
        if "@router." in строки[j - 1]:
            return "/admin/" in строки[j - 1]
    return False


def test_ни_один_отказ_человеку_не_остался_одноязычным():
    """Главное: отказ, который читает обычный человек, звучит на обоих языках."""
    находки = []
    for файл in sorted(КОРЕНЬ.rglob("*.py")):
        находки += _отказы_на_одном_языке(файл.read_text(encoding="utf-8"),
                                          str(файл.relative_to(КОРЕНЬ)))

    assert not находки, (
        f"{len(находки)} отказов человек читает только по-русски: {находки}. "
        "Каждый такой текст встречает человека в момент, когда что-то уже не получилось"
    )


def test_сторож_отличает_админскую_ручку_от_обычной():
    """Проверка самого сторожа: слепой и придирчивый ломаются одинаково тихо.

    Слепой пропустит новый одноязычный отказ, придирчивый будет требовать башкирский
    от админской консоли — и его перестанут читать.
    """
    обычная = '''
@router.post("/auth/request-code")
def request_code():
    raise HTTPException(400, "Неверный номер телефона")
'''
    админская = '''
@router.post("/admin/bans/device/{device_id}")
def ban_device():
    raise HTTPException(400, "Укажи device_id или user_id")
'''
    двуязычная = '''
@router.post("/auth/request-code")
def request_code():
    raise herr(400, "Неверный номер", "Номер дөрөҫ түгел")
'''
    английская = '''
@router.post("/internal/ping")
def ping():
    raise HTTPException(503, "service unavailable")
'''

    спрятанный_в_константе = '''
TAXI_NOT_APPROVED_MSG = "Пройди проверку таксиста, чтобы возить такси"


@router.post("/instant/zone")
def set_zone():
    raise HTTPException(403, taxi_mod.TAXI_NOT_APPROVED_MSG)
'''
    константа_двуязычная = '''
DEVICE_BANNED_MSG = ("Аккаунт заблокирован — напиши в поддержку."
                     " · Аккаунт бикләнгән — ярҙам хеҙмәтенә яҙ.")


@router.post("/instant/zone")
def set_zone():
    raise HTTPException(403, DEVICE_BANNED_MSG)
'''
    символьный_код = '''
@router.post("/auth/refresh")
def refresh():
    raise HTTPException(status.HTTP_401_UNAUTHORIZED, "Сессия завершена. Войди заново.")
'''
    просто_переменная = '''
@router.post("/instant/zone")
def set_zone():
    msg = "Пройди проверку" if ru else "Тикшереү үт"
    raise HTTPException(403, msg)
'''

    assert _отказы_на_одном_языке(обычная), "сторож не видит одноязычный отказ человеку"
    assert _отказы_на_одном_языке(спрятанный_в_константе), (
        "отказ уехал в константу — и сторож ослеп: ровно так волна 177 и случилась"
    )
    assert not _отказы_на_одном_языке(константа_двуязычная), (
        "сторож ругается на константу, где оба языка лежат в одной строке"
    )
    assert _отказы_на_одном_языке(символьный_код), (
        "код ответа записан именем status.HTTP_* — и сторож ослеп: так ушли отказы сессии"
    )
    assert not _отказы_на_одном_языке(просто_переменная), (
        "сторож принял обычную переменную за константу с русским текстом"
    )
    assert not _отказы_на_одном_языке(админская), "сторож требует башкирский от админской консоли"
    assert not _отказы_на_одном_языке(двуязычная), "сторож ругается на двуязычный отказ"
    assert not _отказы_на_одном_языке(английская), "сторож цепляется к служебной строке"


def test_отказ_входа_объясняет_что_делать(client, monkeypatch):
    """Живая проверка самого больного места: код не ушёл — что человек прочитает."""
    from app.config import settings
    from app import services

    monkeypatch.setattr(settings, "env", "prod", raising=False)
    monkeypatch.setattr(settings, "sms_provider", "smsru", raising=False)
    monkeypatch.setattr(settings, "sms_ru_api_id", "test-id", raising=False)

    def сломанный_httpx(*a, **kw):
        raise RuntimeError("сеть недоступна")

    monkeypatch.setattr(services, "send_sms", services.send_sms)   # реальная функция
    monkeypatch.setattr("httpx.get", сломанный_httpx)

    ответ = client.post("/auth/request-code", json={"phone": "+79170009999"})

    assert ответ.status_code == 502, f"неожиданный ответ: {ответ.status_code} {ответ.text[:150]}"
    detail = ответ.json()["detail"]
    assert detail.get("ru") and detail.get("ba"), (
        f"человек, который не может войти, читает отказ на одном языке: {detail}"
    )
    assert "минут" in detail["ru"], (
        f"человеку не сказали, что делать дальше: {detail['ru']}"
    )
