"""Бизнес доплачивал 990 ₽ и терял «Премиум» за собственные деньги (волна 164).

Кафе в Баймаке платит за «Премиум» — это место на первом экране витрины «Скидки по пути».
Через две недели владелец решает продлить и по ошибке (или из экономии на следующий месяц)
берёт «Базовый». Сервер продлевал срок правильно — а тариф ставил тот, что в чеке. То есть
человек платил ещё 990 ₽ и **немедленно** терял премиум-место, за которое уже заплатил
и которое ещё не кончилось.

Ровно это чинили у поднятия поездки (волна 151): доплата должна давать больше, а не меньше.
Теперь пока действует более дорогой тариф, докупка дешёвого только складывает дни; уровень
останется прежним до конца оплаченного срока.
"""
from __future__ import annotations

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import Partner, Payment, UserRole
from app.routers.coupons import PARTNER_PLANS


@pytest.fixture
def бизнес(client, user_factory):
    владелец = user_factory("КафеВладелец")
    админ = user_factory("КафеАдмин", role=UserRole.admin)
    pid = client.post("/partner", headers=владелец["auth"], json={
        "name": "Кафе Айгуль", "category": "food", "city": "Баймак",
        "address": "ул. Мира 1", "description": "Домашняя кухня",
    }).json()["id"]
    client.post(f"/admin/partners/{pid}/approve", headers=админ["auth"])
    return владелец, админ, pid


def _оплатить(client, админ, владелец, pid: int, тариф: str):
    """Бизнес оплатил тариф, админ подтвердил поступление денег."""
    with Session(engine) as s:
        pay = Payment(user_id=владелец["id"], purpose="partner_sub", partner_id=pid,
                      tier=тариф, amount_kop=PARTNER_PLANS[тариф]["amount_kop"],
                      status="pending")
        s.add(pay)
        s.commit()
        s.refresh(pay)
        payment_id = pay.id
    ответ = client.post(f"/admin/payments/{payment_id}/confirm", headers=админ["auth"])
    assert ответ.status_code == 200, ответ.text


def _подписка(pid: int):
    with Session(engine) as s:
        p = s.get(Partner, pid)
        return p.subscription_plan, p.subscription_until


def test_докупка_дешёвого_не_снимает_премиум(client, бизнес):
    """Главное: человек доплатил — значит должен получить больше, а не меньше."""
    владелец, админ, pid = бизнес
    _оплатить(client, админ, владелец, pid, "premium")

    _оплатить(client, админ, владелец, pid, "basic")

    план, _ = _подписка(pid)
    assert план == "premium", (
        f"бизнес доплатил ещё 990 ₽ и остался с тарифом «{план}»: премиум-место на витрине, "
        "за которое он уже заплатил и срок которого не кончился, снялось за его же деньги"
    )


def test_оплаченные_дни_складываются(client, бизнес):
    """Обратная сторона: докупка обязана добавить срок, иначе деньги пропали."""
    владелец, админ, pid = бизнес
    _оплатить(client, админ, владелец, pid, "premium")
    _, срок_до = _подписка(pid)

    _оплатить(client, админ, владелец, pid, "basic")

    _, срок_после = _подписка(pid)
    добавлено = (срок_после - срок_до).days
    assert добавлено >= PARTNER_PLANS["basic"]["period_days"] - 1, (
        f"докупка добавила {добавлено} дней вместо месяца ({срок_до} → {срок_после}): "
        "оплаченный остаток сгорел, деньги взяли — срок почти не двинулся"
    )


def test_переход_на_дорогой_работает_сразу(client, бизнес):
    """Обратная сторона: за повышение платят, чтобы оно случилось сегодня, а не через месяц."""
    владелец, админ, pid = бизнес
    _оплатить(client, админ, владелец, pid, "basic")

    _оплатить(client, админ, владелец, pid, "premium")

    план, _ = _подписка(pid)
    assert план == "premium", (
        f"бизнес заплатил за «Премиум», а остался на «{план}»: повышение должно работать сразу"
    )


def test_после_окончания_срока_берётся_новый_тариф(client, бизнес):
    """Обратная сторона: правило защищает оплаченный срок, а не запирает бизнес в тарифе.

    Подписка кончилась — значит защищать больше нечего, и человек начинает с того тарифа,
    который выбрал.
    """
    from app.timeutil import utcnow
    from datetime import timedelta
    владелец, админ, pid = бизнес
    _оплатить(client, админ, владелец, pid, "premium")
    with Session(engine) as s:                       # премиум-месяц закончился
        p = s.get(Partner, pid)
        p.subscription_until = utcnow() - timedelta(days=1)
        s.add(p)
        s.commit()

    _оплатить(client, админ, владелец, pid, "basic")

    план, _ = _подписка(pid)
    assert план == "basic", (
        f"срок премиума истёк, бизнес осознанно купил «Базовый» — а остался на «{план}»: "
        "теперь он платит за базовый, а числится премиумом бесплатно"
    )
