"""Второй рубеж чистки координат из фото не проверял никто (волна 183).

Телефон записывает в снимок координаты съёмки. Женщина фотографирует машину у своего дома
и ставит фото в профиль; фото профиля видит каждый, кто открыл её поездку, и скачивается
по прямой ссылке без всякого входа. Поэтому метаданные срезаются на сервере — в единственном
месте, через которое проходят все загрузки (аудит 2026-08-08, волна 21).

Рубежей два:

1. **Основной** — вырезать служебный блок целиком (в JPEG это APP1, где лежит EXIF).
   Он проверен: сломай его, и тесты краснеют.
2. **Страховочный** — если блок всё-таки уцелел (нестандартная упаковка, EXIF внутри
   другого сегмента), поменять НОМЕР тега GPS на нулевой. Читалки пропускают неизвестный
   тег, длина файла не меняется, картинка остаётся прежней.

**Второй рубеж не проверял никто.** Волна 183 убрала его целиком — все 3597 тестов остались
зелёными. Страховка, о которой знает только автор, страховкой не является: следующий человек
увидит функцию, которую «ничто не использует», и уберёт при уборке.

Здесь оба рубежа проверяются на настоящих байтах: собираем снимок с координатами Уфы
и смотрим, что после чистки их там нет.
"""
from __future__ import annotations

import struct

import pytest

from app.imagemeta import _blind_gps_pointer, strip_image_metadata

# Координаты, которые «сняла камера»: 54.7261 N, 55.9475 E — это Уфа.
ШИРОТА, ДОЛГОТА = 54, 55
ТЕГ_GPS = 0x8825


def _exif_с_координатами() -> bytes:
    """Блок EXIF, внутри которого лежит указатель на координаты съёмки."""
    tiff = b"MM\x00\x2a" + struct.pack(">I", 8)
    ifd0 = (struct.pack(">H", 1)
            + struct.pack(">HHI", ТЕГ_GPS, 4, 1) + struct.pack(">I", 26)
            + struct.pack(">I", 0))
    gps = (struct.pack(">H", 1)
           + struct.pack(">HHII", 0x0002, 5, 3, ШИРОТА)
           + struct.pack(">I", 0))
    return b"Exif\x00\x00" + tiff + ifd0 + gps


def _снимок_с_координатами() -> bytes:
    """Минимальный JPEG, как его отдаёт телефон: картинка плюс координаты."""
    exif = _exif_с_координатами()
    app1 = b"\xff\xe1" + struct.pack(">H", len(exif) + 2) + exif
    return b"\xff\xd8" + app1 + b"\xff\xdb\x00\x04\x00\x00" + b"\xff\xd9"


def test_координаты_съёмки_не_доживают_до_сервера():
    """Главное: после загрузки в фото нет ни блока EXIF, ни следов координат."""
    снимок = _снимок_с_координатами()
    assert b"Exif\x00\x00" in снимок, "проба не та: в исходнике нет метаданных"

    чистое = strip_image_metadata(снимок, "jpg")

    assert b"Exif\x00\x00" not in чистое, (
        "в фото профиля остались координаты съёмки. Женщина сняла машину у дома — "
        "и адрес уехал каждому, кто открыл её поездку"
    )


def test_страховка_ослепляет_координаты_если_блок_уцелел():
    """Второй рубеж: блок остался — номер тега координат обнулён."""
    сырое = _exif_с_координатами()
    assert struct.pack(">H", ТЕГ_GPS) in сырое, "проба не та: тега координат нет в исходнике"

    ослеплённое = _blind_gps_pointer(сырое)

    assert struct.pack(">H", ТЕГ_GPS) not in ослеплённое, (
        "основной рубеж не сработал, а страховка не ослепила указатель — координаты "
        "остались читаемыми обычной программой просмотра"
    )


def test_страховка_не_портит_картинку():
    """Обратная сторона: страховка не должна ничего ломать — фото людям ещё смотреть."""
    сырое = _exif_с_координатами()

    ослеплённое = _blind_gps_pointer(сырое)

    assert len(ослеплённое) == len(сырое), "длина файла изменилась — читалки могут споткнуться"
    assert ослеплённое[:6] == b"Exif\x00\x00", "заголовок блока испорчен"


def test_страховка_молчит_когда_метаданных_нет():
    """Обычное фото без координат проходит насквозь и не портится."""
    обычное = b"\xff\xd8\xff\xdb\x00\x04\x00\x00\xff\xd9"

    assert _blind_gps_pointer(обычное) == обычное


@pytest.mark.parametrize("формат,снимок,след", [
    ("png", (b"\x89PNG\r\n\x1a\n"
             + struct.pack(">I", 13) + b"IHDR" + b"\x00" * 13 + b"\x00\x00\x00\x00"
             + struct.pack(">I", 24) + b"tEXt" + b"GPS\x0054.7261N 55.9475E"
             + b"\x00\x00\x00\x00"
             + struct.pack(">I", 0) + b"IEND" + b"\xae\x42\x60\x82"), b"54.7261N"),
    ("webp", (b"RIFF" + struct.pack("<I", 20) + b"WEBP"
              + b"EXIF" + struct.pack("<I", 8) + b"II*\x00\x08\x00\x00\x00"), b"EXIF"),
])
def test_у_каждого_формата_чистятся_свои_метаданные(формат, снимок, след):
    """Форматов три, и человеку всё равно, в каком снял телефон."""
    чистое = strip_image_metadata(снимок, формат)

    assert след not in чистое, (
        f"{формат}: метаданные остались в файле — координаты съёмки уедут вместе с фото"
    )
