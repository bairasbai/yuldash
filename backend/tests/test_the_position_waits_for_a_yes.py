"""Координаты текли до того, как водитель согласился везти — и тест этого не видел (волна 181).

Правило приватности простое: пока сделки нет, местоположение не передаётся никуда. Пассажир
отправил заявку на место — водитель ещё не ответил. В эту минуту ни один из них не должен
видеть, где находится другой: согласия нет, а точка на карте — это дом, работа, детский сад.

В коде правило есть: канал координат закрывается, если бронь не в состоянии «подтверждена»
или «в пути». И тест на него есть — с 2026 года. **Только он ничего не проверял.**

Волна 180 показала почему: тест доказывал отказ тем, что «ничего не пришло». Канал, который
ПУСТИЛ и просто молчит, отвечает ровно так же. Проверка мутацией это подтвердила: убираем
проверку статуса брони — и весь набор тестов остаётся зелёным. Ни один из двадцати двух
тестов приватности координат не заметил, что защита исчезла.

Здесь то же правило проверяется честно: одна сторона шлёт настоящие координаты, вторая
слушает. Услышала до подтверждения — правило сломано, и это видно сразу.
"""
from __future__ import annotations

import json

import pytest
from sqlmodel import Session

from app.db import engine
from app.models import Booking, BookingStatus, UserRole

from test_api import _ride

КООРДИНАТА = {"type": "loc", "lat": 52.591, "lng": 58.317, "ts": 1}


def _услышал_координаты(client, путь: str, слушатель_токен: str, отправитель_токен: str) -> bool:
    """Дошли ли координаты от одного человека до другого.

    Проверяем по утечке, а не по молчанию: молчащий канал неотличим от закрытого.
    """
    try:
        with client.websocket_connect(путь) as слушатель:
            слушатель.send_text(json.dumps({"type": "auth", "token": слушатель_токен}))
            with client.websocket_connect(путь) as отправитель:
                отправитель.send_text(json.dumps({"type": "auth", "token": отправитель_токен}))
                отправитель.send_text(json.dumps(КООРДИНАТА))
                try:
                    услышал = слушатель.receive_text()
                except Exception:
                    return False
                return "lat" in услышал
    except Exception:
        return False


@pytest.fixture
def заявка_без_ответа(client, user_factory):
    """Пассажир попросился в машину, водитель ещё не ответил."""
    водитель = user_factory("ВодительМолчитПока", role=UserRole.driver)
    пассажир = user_factory("ПассажиркаЖдётОтвета")
    ride_id = _ride(client, водитель, seats=2)
    bid = client.post("/bookings", headers=пассажир["auth"],
                      json={"ride_id": ride_id, "seats": 1}).json()["id"]
    with Session(engine) as s:
        assert s.get(Booking, bid).status == BookingStatus.pending, "бронь должна ждать ответа"
    return {"booking": bid, "водитель": водитель, "пассажир": пассажир}


def test_до_согласия_водителя_координаты_не_текут(client, заявка_без_ответа):
    """Главное: пока водитель не сказал «да», пассажирка не видит, где он ездит."""
    д = заявка_без_ответа

    услышала = _услышал_координаты(
        client, f"/ws/trip/{д['booking']}/location",
        д["пассажир"]["token"], д["водитель"]["token"],
    )

    assert not услышала, (
        "водитель ещё не согласился везти, а его точка на карте уже уехала человеку, "
        "которого он не выбирал. Точка — это дом, работа, детский сад"
    )


def test_и_в_обратную_сторону_тоже(client, заявка_без_ответа):
    """Симметрично: водитель не видит, где живёт человек, которого он ещё не взял."""
    д = заявка_без_ответа

    услышал = _услышал_координаты(
        client, f"/ws/trip/{д['booking']}/location",
        д["водитель"]["token"], д["пассажир"]["token"],
    )

    assert not услышал, "водитель видит адрес пассажирки до того, как согласился её везти"


def test_после_согласия_координаты_идут(client, заявка_без_ответа):
    """Обратная сторона: подтвердили — связь обязана работать, иначе поездка вслепую."""
    д = заявка_без_ответа
    ответ = client.post(f"/bookings/{д['booking']}/confirm", headers=д["водитель"]["auth"])
    assert ответ.status_code == 200, ответ.text[:150]

    услышала = _услышал_координаты(
        client, f"/ws/trip/{д['booking']}/location",
        д["пассажир"]["token"], д["водитель"]["token"],
    )

    assert услышала, (
        "водитель подтвердил поездку, едет за человеком — а его машина не видна на карте. "
        "Человек стоит на улице и не знает, едут за ним или нет"
    )


def test_после_отмены_координаты_прекращаются(client, заявка_без_ответа):
    """Сделка кончилась — вместе с ней кончается и право видеть чужую точку."""
    д = заявка_без_ответа
    client.post(f"/bookings/{д['booking']}/confirm", headers=д["водитель"]["auth"])
    отмена = client.post(f"/bookings/{д['booking']}/cancel", headers=д["пассажир"]["auth"])
    assert отмена.status_code in (200, 204), отмена.text[:150]

    услышала = _услышал_координаты(
        client, f"/ws/trip/{д['booking']}/location",
        д["пассажир"]["token"], д["водитель"]["token"],
    )

    assert not услышала, "поездку отменили, а координаты водителя всё ещё идут пассажиру"


def test_чужой_человек_не_слышит_подтверждённую_поездку(client, заявка_без_ответа,
                                                       user_factory):
    """Контроль: подтверждение открывает канал участникам, а не всем подряд."""
    д = заявка_без_ответа
    client.post(f"/bookings/{д['booking']}/confirm", headers=д["водитель"]["auth"])
    посторонний = user_factory("ПостороннийНаКанале181")

    услышал = _услышал_координаты(
        client, f"/ws/trip/{д['booking']}/location",
        посторонний["token"], д["водитель"]["token"],
    )

    assert not услышал, "посторонний слушает координаты подтверждённой чужой поездки"
