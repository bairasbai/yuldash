"""Приём уведомлений можно было забрать у человека одним запросом.

Две находки роя, обе про то, кому телефон шлёт уведомления.

**Чужой приём угонялся.** Запись «этот телефон принадлежит такому-то» перепривязывалась
к любому, кто прислал ту же строку токена. Проверки, что запрос пришёл с того самого телефона,
не было (аудит 2026-08-08, волна 147).

У жертвы после этого не остаётся ни одного устройства — она перестаёт получать всё: сообщение
от попутчика, «водитель подъехал», напоминание по сигналу SOS. Тихо: приложение выглядит
рабочим, просто уведомления «почему-то не приходят». А уведомления захватчика — включая те,
что помечены как личные, — прилетают на телефон жертвы.

Законная перепривязка при этом нужна: общий телефон в семье, отец вышел — зашёл сын, и
уведомления должны идти тому, кто сейчас в приложении. Поэтому различаем по устройству:
забрать запись можно только с того самого телефона, на котором она живёт.

**«Выйти со всех устройств» не выходило.** Кнопка гасила ключи входа, но запись устройства
не трогала: сервер продолжал считать трубку принадлежащей этому человеку. Отвязка жила
в отдельной ручке, которую клиент должен позвать сам и при живой сети — то есть в момент,
когда телефон отобрали, она не срабатывает.

Деревенский сценарий проще: общий телефон, отец вышел, зашёл сын — и уведомления отца
продолжают падать на экран, который теперь смотрит сын.
"""
from __future__ import annotations

from sqlmodel import Session, select

from app.db import engine
from app.models import DeviceToken

ТОКЕН = "fcm-token-очень-длинная-случайная-строка-777"


def _устройств(user_id: int) -> list[str]:
    with Session(engine) as s:
        return [t.token for t in s.exec(
            select(DeviceToken).where(DeviceToken.user_id == user_id)).all()]


def test_чужой_приём_уведомлений_не_забрать(client, user_factory):
    """Главное: у человека нельзя отнять уведомления, зная строку его токена."""
    хозяйка = user_factory("ПушХозяйка")
    чужой = user_factory("ПушЧужой")
    client.post("/push/register", headers={**хозяйка["auth"], "X-Device-Id": "device-hers"},
                json={"token": ТОКЕН})

    захват = client.post("/push/register",
                         headers={**чужой["auth"], "X-Device-Id": "device-his"},
                         json={"token": ТОКЕН})

    assert захват.status_code == 409, (
        f"чужой забрал приём уведомлений одним запросом (ответ {захват.status_code}): "
        "жертва перестанет получать сообщения, «водитель подъехал» и напоминание по SOS"
    )
    assert _устройств(хозяйка["id"]) == [ТОКЕН], (
        f"у хозяйки не осталось устройств: {_устройств(хозяйка['id'])}"
    )
    assert _устройств(чужой["id"]) == [], "чужой получил запись, которая ему не принадлежит"


def test_на_общем_телефоне_смена_человека_работает(client, user_factory):
    """Обратная сторона: отец вышел, зашёл сын — уведомления должны идти сыну."""
    отец = user_factory("ПушОтец")
    сын = user_factory("ПушСын")
    общий = "device-family-phone"
    client.post("/push/register", headers={**отец["auth"], "X-Device-Id": общий},
                json={"token": ТОКЕН + "-family"})

    смена = client.post("/push/register", headers={**сын["auth"], "X-Device-Id": общий},
                        json={"token": ТОКЕН + "-family"})

    assert смена.status_code == 200, (
        f"на общем телефоне не удалось переключить уведомления на того, кто вошёл: {смена.text}"
    )
    assert _устройств(сын["id"]), "сын не получает уведомления на телефоне, где он вошёл"
    assert _устройств(отец["id"]) == [], "отец вышел, а уведомления ему всё ещё идут"


def test_старый_клиент_без_отметки_устройства_работает(client, user_factory):
    """Кто не обновился — не должен остаться без уведомлений вовсе."""
    человек = user_factory("ПушСтарыйКлиент")

    r = client.post("/push/register", headers=человек["auth"],
                    json={"token": ТОКЕН + "-old"})

    assert r.status_code == 200, f"старая версия приложения не смогла включить уведомления: {r.text}"
    assert _устройств(человек["id"]), "запись устройства не создалась"


def test_свой_же_человек_без_отметки_устройства_не_теряет_уведомления(client, user_factory):
    """Запись завело новое приложение, а обновление пришло без отметки телефона.

    Так бывает у веб-версии и у того, кто откатился на старую сборку. Это тот же человек
    и тот же телефон — отбивать его нельзя, иначе он молча останется без уведомлений.
    """
    человек = user_factory("ПушСмешанный")
    токен = ТОКЕН + "-mixed"
    client.post("/push/register", headers={**человек["auth"], "X-Device-Id": "device-new-app"},
                json={"token": токен})

    без_отметки = client.post("/push/register", headers=человек["auth"], json={"token": токен})

    assert без_отметки.status_code == 200, (
        f"тот же человек прислал свой же токен без отметки телефона и получил отказ "
        f"({без_отметки.status_code}): он останется без уведомлений, не понимая почему"
    )
    assert _устройств(человек["id"]) == [токен], _устройств(человек["id"])


def test_выход_из_аккаунта_отключает_уведомления(client, user_factory):
    """Телефон отобрали — «выйти со всех устройств» должно закрыть и уведомления."""
    человек = user_factory("ПушВыход")
    client.post("/push/register", headers={**человек["auth"], "X-Device-Id": "device-lost"},
                json={"token": ТОКЕН + "-lost"})
    assert _устройств(человек["id"]), "проверять нечего — устройство не зарегистрировалось"

    client.post("/auth/logout", headers=человек["auth"])

    assert _устройств(человек["id"]) == [], (
        "человек вышел со всех устройств, а его уведомления продолжают падать на телефон, "
        "который он больше не держит в руках"
    )


def test_выход_не_трогает_чужие_устройства(client, user_factory):
    """Обратная сторона: мой выход не должен отключать уведомления соседу."""
    первый = user_factory("ПушПервый")
    второй = user_factory("ПушВторой")
    client.post("/push/register", headers={**первый["auth"], "X-Device-Id": "device-1"},
                json={"token": ТОКЕН + "-1"})
    client.post("/push/register", headers={**второй["auth"], "X-Device-Id": "device-2"},
                json={"token": ТОКЕН + "-2"})

    client.post("/auth/logout", headers=первый["auth"])

    assert _устройств(второй["id"]), "выход одного человека отключил уведомления другому"


def test_свой_телефон_можно_перерегистрировать(client, user_factory):
    """Приложение шлёт токен на каждом старте — повтор со своего телефона не должен ломаться."""
    человек = user_factory("ПушПовтор")
    свой = {"X-Device-Id": "device-mine"}
    client.post("/push/register", headers={**человек["auth"], **свой},
                json={"token": ТОКЕН + "-mine"})

    ещё_раз = client.post("/push/register", headers={**человек["auth"], **свой},
                          json={"token": ТОКЕН + "-mine"})

    assert ещё_раз.status_code == 200, f"повторная регистрация своего телефона упала: {ещё_раз.text}"
    assert len(_устройств(человек["id"])) == 1, "запись задвоилась"
