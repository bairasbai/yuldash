"""Красная кнопка отвечала «слишком много запросов» из-за чужого трафика (волна 179).

В селе один адрес оператора на многих: вышка раздаёт интернет, NAT сводит десяток телефонов
в один IP. Лимит запросов считается по адресу — значит соседи по сети делят один бюджет.

Это знали. В аудите 2026-08-07 SOS вынесли в отдельный счётчик и написали в коде: «кнопка,
которая обязана сработать всегда, отказывала из-за чужих логинов». Но закрыли половину:
SOS отделили от `/auth`, а ОБЩИЙ бюджет он продолжал делить со всеми.

**Проба.** Сосед по сети тридцать раз открыл ленту уведомлений — обычная работа, не спам.
Общий лимит выбран. Женщина в машине жмёт SOS и получает **429 «Слишком много запросов.
Подожди немного»**. Логины тут ни при чём: хватило любого трафика с того же адреса.

Теперь у SOS бюджет ВМЕСТО общего, а не в дополнение к нему. Свой счётчик остался — он и
защищает от спама, просто чужой трафик в него не попадает.

Заодно 429 стал двуязычным: раньше отказ приходил русской строкой, и башкироязычный человек
видел общую заглушку по коду ответа вместо объяснения (тот же класс, что волна 177).
"""
from __future__ import annotations

import pytest

from app.config import settings

ТОЧКА = {"lat": 52.591, "lng": 58.317}


@pytest.fixture
def тесная_сеть(monkeypatch):
    """Общий бюджет маленький — как в селе, где за одним адресом много телефонов."""
    monkeypatch.setattr(settings, "rate_limit_enabled", True)
    monkeypatch.setattr(settings, "rate_limit_per_min", 20)
    monkeypatch.setattr(settings, "rate_limit_sos_per_min", 30)
    yield


def _забить_общий_бюджет(client, сосед) -> int:
    """Сосед по сети просто работает в приложении — и выбирает общий лимит."""
    отказов = 0
    for _ in range(30):
        if client.get("/notifications", headers=сосед["auth"]).status_code == 429:
            отказов += 1
    return отказов


def test_кнопка_срабатывает_когда_сеть_занята_соседями(client, user_factory, тесная_сеть):
    """Главное: чужой трафик не может закрыть красную кнопку."""
    женщина = user_factory("ЖенщинаВНочнойМашине")
    сосед = user_factory("СоседПоВышке")
    assert _забить_общий_бюджет(client, сосед) > 0, "общий лимит не выбран — проба не та"

    ответ = client.post("/sos", headers=женщина["auth"], json=ТОЧКА)

    assert ответ.status_code == 200, (
        f"человеку страшно, он жмёт SOS — и приложение отвечает «слишком много запросов»: "
        f"{ответ.text[:150]}. Сигнал не ушёл никому, а виноват сосед по сети оператора"
    )


def test_паника_жмёт_кнопку_несколько_раз(client, user_factory, тесная_сеть):
    """Человек в беде жмёт кнопку подряд — это нормально, а не спам."""
    женщина = user_factory("ЖенщинаЖмётПодряд")

    коды = [client.post("/sos", headers=женщина["auth"], json=ТОЧКА).status_code
            for _ in range(5)]

    assert all(к == 200 for к in коды), f"панические нажатия не прошли: {коды}"


def test_свой_предел_у_кнопки_остался(client, user_factory, monkeypatch):
    """Обратная сторона: бюджет ВМЕСТО общего — не значит «без бюджета вовсе»."""
    monkeypatch.setattr(settings, "rate_limit_enabled", True)
    monkeypatch.setattr(settings, "rate_limit_per_min", 500)
    monkeypatch.setattr(settings, "rate_limit_sos_per_min", 3)
    человек = user_factory("ТотКтоЖмётБезКонца")

    коды = [client.post("/sos", headers=человек["auth"], json=ТОЧКА).status_code
            for _ in range(6)]

    assert 429 in коды, (
        f"свой счётчик SOS перестал считать вовсе — кнопкой можно завалить сервер: {коды}"
    )


def test_обычные_запросы_по_прежнему_ограничены(client, user_factory, тесная_сеть):
    """Обратная сторона: чинили красную кнопку, а не отключали защиту."""
    человек = user_factory("ОбычныйПользователь179")

    коды = [client.get("/notifications", headers=человек["auth"]).status_code
            for _ in range(30)]

    assert 429 in коды, f"общий лимит перестал работать: {set(коды)}"


def test_отказ_понятен_на_двух_языках(client, user_factory, тесная_сеть):
    """Человек упёрся в лимит — он должен прочитать, что делать, на своём языке."""
    человек = user_factory("УпёрсяВЛимит179")
    отказ = None
    for _ in range(30):
        r = client.get("/notifications", headers=человек["auth"])
        if r.status_code == 429:
            отказ = r.json()
            break

    assert отказ is not None, "не дошли до отказа — проба не та"
    тело = отказ.get("detail")
    assert isinstance(тело, dict) and тело.get("ru") and тело.get("ba"), (
        f"отказ пришёл одной строкой — башкироязычный увидит заглушку: {тело}"
    )
    assert отказ.get("retry_after"), "не сказали, сколько ждать"


# ------------------------------ то же самое, но через Redis ------------------------------
# На проде счётчики живут в Redis (общие на все воркеры), в тестах по умолчанию — в памяти.
# Это две разные ветки кода, и чинить надо обе: правка в одной ничего не значит для другой.
# Здесь подставляем поддельный Redis и повторяем главную проверку — иначе на живом сервере
# красная кнопка осталась бы занятой, а тесты были бы зелёными.


@pytest.fixture
def через_redis(monkeypatch):
    import fakeredis.aioredis
    from app import middleware as mw

    поддельный = fakeredis.aioredis.FakeRedis(decode_responses=True)
    monkeypatch.setattr(mw.RateLimitMiddleware, "_get_redis", lambda self: поддельный)
    yield поддельный


def test_кнопка_срабатывает_и_когда_счётчики_в_redis(client, user_factory, тесная_сеть,
                                                    через_redis):
    """Прод считает лимиты в Redis — там кнопка тоже обязана срабатывать."""
    женщина = user_factory("ЖенщинаВНочнойМашинеRedis")
    сосед = user_factory("СоседПоВышкеRedis")
    assert _забить_общий_бюджет(client, сосед) > 0, "общий лимит не выбран — проба не та"

    ответ = client.post("/sos", headers=женщина["auth"], json=ТОЧКА)

    assert ответ.status_code == 200, (
        f"на проде (счётчики в Redis) красная кнопка занята чужим трафиком: {ответ.text[:150]}"
    )
