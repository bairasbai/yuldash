WITH coords(city, lat, lng) AS (VALUES
    ('Баймаҡ', 52.591, 58.317), ('Баймак', 52.591, 58.317), ('Сибай', 52.716, 58.664),
    ('Уфа', 54.735, 55.958), ('Темясово', 52.972, 58.160), ('Учалы', 54.304, 59.430),
    ('Магнитогорск', 53.412, 58.984), ('Ургаза', 52.850, 58.300),
    ('Зилаир', 52.230, 57.443), ('Акъяр', 51.880, 58.198)
)
UPDATE ride r SET from_lat = c.lat, from_lng = c.lng
FROM coords c WHERE r.from_city = c.city AND r.from_lat IS NULL;

