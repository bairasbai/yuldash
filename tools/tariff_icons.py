# -*- coding: utf-8 -*-
"""Готовит картинки машин: витрину тарифов (вид сбоку) и метки на карте (вид сверху).

Два набора для двух разных мест. В карточке тарифа машина отвечает на вопрос «что за мной
приедет» — там нужен вид сбоку, как в каталоге. На карте машина отвечает «где она едет» —
там нужен вид сверху, иначе метка не читается как машина, снятая с высоты.

Витрина: убирает пустые поля и ставит машины в один ряд.

ЗАЧЕМ. Codex рисует машины на канве 320×150, и вокруг каждой остаётся прозрачный воздух —
у Эконома по 58 пикселей слева и 62 справа, то есть больше трети ширины пусто. На карточке
шириной 132 точки это выглядело так, будто машину уменьшили: она честно вписывалась в кадр
вместе с полями. Плюс поля у всех разные, и машины в ряду стояли вразнобой по размеру.

ЧТО ДЕЛАЕТ. Обрезает прозрачные поля по факту, потом вписывает силуэт в общую канву
с одинаковыми правилами: доля ширины одна для всех, низ машины на одной линии. Ряд после
этого читается как ряд, а не как четыре случайные картинки.

ФОРМАТ. Сохраняем в WebP, а не в PNG. Правило проекта (`ImageWeightTest`): картинка тяжелее
60 КБ в PNG — нарушение. Юлдаш ставят там, где интернет две палки, и каждый лишний мегабайт
установки — повод бросить на половине. Подготовленная машина в PNG весит ~130 КБ, в WebP
качества 90 — около 30 КБ, и разницы не видно. Имя ресурса от смены расширения не меняется:
`R.drawable.yuldash_tariff_economy` работает и с .webp.

КОГДА ЗАПУСКАТЬ. После каждого обновления исходников (ветка Codex с иконками):

    python tools/tariff_icons.py <папка-с-исходниками>

По умолчанию источник — C:/Users/Bayra/Yuldash-icons/android/app/src/main/res/drawable-nodpi.
Результат кладётся в android/app/src/main/res/drawable-nodpi этого репозитория.
"""
from __future__ import annotations

import os
import sys

from PIL import Image

ФАЙЛЫ = (
    "yuldash_tariff_economy",
    "yuldash_tariff_comfort",
    "yuldash_tariff_business",
    "yuldash_tariff_minivan",
    "yuldash_tariff_business_night",
)

# Исходники живут В РЕПОЗИТОРИИ, а не в ветке Codex и не во временных папках.
# Причина простая: то, чего нет в git, однажды исчезнет. Оригиналы машин уже лежали только
# в буфере обмена Codex — восстановить их было неоткуда, кроме как искать по временным файлам.
ИСТОЧНИК = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "assets-src", "cars")
ИСТОЧНИК_КАРТА = os.path.join(ИСТОЧНИК, "top")
ЦЕЛЬ = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    "android", "app", "src", "main", "res", "drawable-nodpi")

# Канва витрины. Соотношение совпадает с местом под картинку в карточке тарифа
# (MobilityUi.TaxiServiceClassTile), поэтому машина заполняет кадр без полей по бокам.
#
# Выравниваем по ШИРИНЕ, а не по высоте: в ряду машины должны читаться как один парк,
# а не как случайные картинки разного масштаба. Высота получается своя у каждой — так и
# должно быть, минивэн выше седана. Низ у всех на одной линии: машины стоят на земле.
ШИРИНА, ВЫСОТА = 440, 300
ДОЛЯ_ШИРИНЫ = 0.95      # почти во всю ширину: поля съедают ощущение «дорого»
НИЗ = 0.97              # колёса чуть выше нижнего края — машина стоит, а не висит
# Пустая полоса сверху нужна не для красоты: там стоит пилюля с временем подачи, и на
# машине во всю высоту кадра она ложилась поверх капота.


def без_каймы(im: "Image.Image") -> "Image.Image":
    """Снимает белый ореол по краю вырезанной машины.

    Картинки рисуются на белом фоне, и фон убирают прозрачностью. По контуру остаётся полоса
    полупрозрачных пикселей, в которых цвет машины уже смешан с белым. На светлой карточке
    этого не видно — фон тоже белый. На тёмной такая полоса превращается в грязную светлую
    кайму, и машина выглядит вырезанной ножницами.

    Лечим арифметикой, а не размытием: раз известно, что примешан белый, его можно вычесть.
    Цвет восстанавливаем как (C - 255·(1−a)) / a, а совсем прозрачные точки (a < 20) гасим
    полностью — они всё равно ничего не показывают, кроме мусора по контуру.
    """
    im = im.convert("RGBA")
    ширина, высота = im.size
    точки = im.load()
    for y in range(высота):
        for x in range(ширина):
            r, g, b, a = точки[x, y]
            if a == 0 or a >= 250:
                continue
            if a < 20:
                точки[x, y] = (0, 0, 0, 0)
                continue
            k = a / 255.0
            чистый = tuple(
                max(0, min(255, int(round((c - 255 * (1 - k)) / k))))
                for c in (r, g, b)
            )
            точки[x, y] = (*чистый, a)
    return im


def нормализовать(путь_из: str, путь_в: str) -> str:
    im = без_каймы(Image.open(путь_из))
    поле = im.split()[-1].getbbox()
    if поле is None:
        raise SystemExit("картинка пустая: %s" % путь_из)
    машина = im.crop(поле)

    цель_ш = int(ШИРИНА * ДОЛЯ_ШИРИНЫ)
    к = цель_ш / машина.width
    цель_в = int(машина.height * к)
    # Страховка на случай непривычно высокой машины: за кадр не выпускаем.
    предел = int(ВЫСОТА * 0.97)
    if цель_в > предел:
        к = предел / машина.height
        цель_ш, цель_в = int(машина.width * к), предел
    машина = машина.resize((цель_ш, цель_в), Image.LANCZOS)

    холст = Image.new("RGBA", (ШИРИНА, ВЫСОТА), (0, 0, 0, 0))
    x = (ШИРИНА - цель_ш) // 2
    y = int(ВЫСОТА * НИЗ) - цель_в
    холст.paste(машина, (x, max(0, y)), машина)
    # Без потерь: витрина тарифов — рисунок с чёткими краями и прозрачным фоном, и любое
    # «почти незаметное» сжатие первым делом мылит именно контур машины. Вес всё равно
    # остаётся в разы меньше PNG, так что экономить на качестве здесь незачем.
    холст.save(путь_в, "WEBP", lossless=True, method=6)
    # PNG с тем же именем оставлять нельзя: в drawable окажутся два ресурса-близнеца,
    # и какой из них попадёт в сборку — вопрос удачи.
    старый_png = путь_в[: -len(".webp")] + ".png"
    if os.path.exists(старый_png):
        os.remove(старый_png)
    вес = os.path.getsize(путь_в) // 1024
    return "%dx%d -> машина %dx%d, %d КБ" % (im.width, im.height, цель_ш, цель_в, вес)


# --- метки машин на карте (вид сверху) -----------------------------------------------
# Метка квадратная: MapKit ставит её центром в точку, а машина уже нарисована носом вверх.
# Запас по бокам оставлен намеренно — если когда-нибудь начнём поворачивать метку по курсу
# движения, углы не срежутся.
КАРТА_СТОРОНА = 144
КАРТА_ДОЛЯ_ВЫСОТЫ = 0.92


def метка_карты(путь_из: str, путь_в: str) -> str:
    im = без_каймы(Image.open(путь_из))
    поле = im.split()[-1].getbbox()
    if поле is None:
        raise SystemExit("картинка пустая: %s" % путь_из)
    машина = im.crop(поле)
    высота = int(КАРТА_СТОРОНА * КАРТА_ДОЛЯ_ВЫСОТЫ)
    ширина = max(1, int(машина.width * высота / машина.height))
    if ширина > КАРТА_СТОРОНА:
        ширина = КАРТА_СТОРОНА
        высота = max(1, int(машина.height * ширина / машина.width))
    машина = машина.resize((ширина, высота), Image.LANCZOS)
    холст = Image.new("RGBA", (КАРТА_СТОРОНА, КАРТА_СТОРОНА), (0, 0, 0, 0))
    холст.paste(машина, ((КАРТА_СТОРОНА - ширина) // 2, (КАРТА_СТОРОНА - высота) // 2), машина)
    холст.save(путь_в, "WEBP", lossless=True, method=6)
    старый_png = путь_в[: -len(".webp")] + ".png"
    if os.path.exists(старый_png):
        os.remove(старый_png)
    return "метка %dx%d, %d КБ" % (ширина, высота, os.path.getsize(путь_в) // 1024)


def main() -> None:
    источник = sys.argv[1] if len(sys.argv) > 1 else ИСТОЧНИК
    карта = sys.argv[2] if len(sys.argv) > 2 else (
        ИСТОЧНИК_КАРТА if os.path.isdir(ИСТОЧНИК_КАРТА) else None)
    for имя in ФАЙЛЫ:
        из_ = os.path.join(источник, имя + ".png")
        if not os.path.exists(из_):
            print("нет в источнике, пропускаю:", имя)
            continue
        print(имя, нормализовать(из_, os.path.join(ЦЕЛЬ, имя + ".webp")))
    if карта:
        # business_night — та же машина сверху, но серебристая: на тёмной карте чёрная
        # не читается вовсе. Файла нет — просто не будет ночной метки, день не пострадает.
        for класс in ("economy", "comfort", "business", "minivan", "business_night"):
            из_ = os.path.join(карта, класс + ".png")
            if not os.path.exists(из_):
                print("нет вида сверху, пропускаю:", класс)
                continue
            print("карта/" + класс,
                  метка_карты(из_, os.path.join(ЦЕЛЬ, "yuldash_map_car_%s.webp" % класс)))


if __name__ == "__main__":
    main()
