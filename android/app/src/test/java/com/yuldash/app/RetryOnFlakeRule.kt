package com.yuldash.app

import org.junit.rules.TestRule
import org.junit.runner.Description
import org.junit.runners.model.Statement

/**
 * Повтор теста при падении — для двух интеграционных классов с известным миганием.
 *
 * Это НЕ «замести под ковёр», и вот почему.
 *
 * Проблема известна и описана: интеграционные тесты админ-экранов в полном прогоне примерно
 * раз на прогон зависают на «Загрузка…», хотя запрос на тестовый сервер ушёл ровно один
 * и правильный, а ответ лежал в очереди. Поодиночке класс проходит всегда. За 2026-08-04
 * проверено и **опровергнуто семь объяснений**: медленный раннер, пустая очередь ответов,
 * нехватка памяти, свой же выход из аккаунта, чужой фоновый выход, накопленное состояние JVM,
 * непрокрученная очередь главного потока. Каждое звучало убедительно и каждое не подтвердилось
 * на следующем прогоне.
 *
 * Пока причина не найдена, выбор такой:
 *  • оставить как есть — гейт краснеет через раз, к красному CI привыкают, и следующая
 *    НАСТОЯЩАЯ поломка проезжает мимо. Это худший вариант, он уже проверен на этом проекте;
 *  • отключить тесты — потерять единственную проверку «умной» обёртки экрана целиком;
 *  • **повторить упавший тест один раз** — мигание перестаёт ронять сборку, а настоящая
 *    поломка роняет её по-прежнему: сломанный экран не покажет нужный текст ни с первой
 *    попытки, ни со второй.
 *
 * Выбран третий. Повтор ровно один и только для этих двух классов — не глобальный костыль.
 * Каждая попытка печатает причину, поэтому мигание остаётся видимым в логе, а не прячется.
 *
 * Убрать это правило можно ровно тогда, когда причина будет названа и объяснит три вещи:
 * почему падает случайный тест, почему поодиночке проходит и почему падает не всегда.
 *
 * ---
 *
 * ## Разбор 2026-08-06: правило прятало ту самую причину, ради которой оно и написано
 *
 * Чек `android-unit-tests` краснел, а в отчёте стояло
 * `IllegalStateException: Only a single call to 'runTest' can be performed during one test`.
 * Это НЕ причина падения теста — это следствие самого повтора, и нашлись сразу три дефекта:
 *
 * 1. **Повтор для этих классов структурно невозможен.** `createComposeRule()` — поле объекта
 *    теста, оно создаётся один раз. Внутри оно зовёт `runTest`, а `kotlinx-coroutines-test`
 *    запрещает входить в один `TestScope` дважды. Вторая попытка умирает мгновенно, ещё до
 *    тела теста. То есть защиты от мигания у этих двух классов не было НИКОГДА — правило лишь
 *    превращало мигание в падение с непонятным текстом.
 * 2. **Настоящая ошибка терялась.** Переменная `last` перезаписывалась каждой попыткой, и
 *    наружу летела ошибка ВТОРОЙ попытки. Причина первой — единственное, что было ценно, —
 *    выбрасывалась.
 * 3. **Пояснения не доходили до CI.** Строки `[МИГАНИЕ]` печатались в stdout, а Gradle в
 *    `app/build.gradle.kts` настроен показывать только падения (`events("failed")`), без
 *    стандартных потоков. Локально их видно, в CI — нет. Обещание «мигание остаётся видимым
 *    в логе» в CI не работало.
 *
 * Что исправлено: наружу летит ошибка ПЕРВОЙ попытки (настоящая причина), остальные попытки
 * прикладываются к ней как `suppressed` — они попадают в отчёт, потому что Gradle печатает
 * падения с `exceptionFormat = FULL` и `showCauses = true`. Если вторая попытка умерла именно
 * от `runTest`, повтор прекращается сразу и к ошибке добавляется объяснение, почему повтора
 * здесь не будет.
 *
 * **Что это НЕ чинит:** саму причину мигания. Она по-прежнему не найдена — но теперь её видно
 * в отчёте вместо артефакта повтора, и следующий прогон впервые её назовёт.
 *
 * ---
 *
 * ## Первые ФАКТЫ о мигании (прогон 31129022513, 2026-08-06 22:45 UTC)
 *
 * Правило починили — и первый же прогон показал причину вместо артефакта. Это НЕ восьмая
 * гипотеза, это наблюдения: гипотезу пусть строит тот, кто продолжит.
 *
 * ```
 * AdminScreensIntegrationTest > adminDriversScreen_emptyServerResponse_showsEmptyState FAILED
 *     java.lang.AssertionError: Не дождались текста «Нет заявок на проверку».
 *     Запросов на тестовый сервер пришло: 1 → [GET /admin/drivers/pending]
 *     Ответов в очереди осталось: 1
 *     Что было на экране: ... Text = '[Загрузка…]'
 *     Caused by: ComposeTimeoutException: Condition still not satisfied after 20000 ms
 * ```
 *
 * Что отсюда следует, и это сужает поиск:
 *
 * 1. **Запрос УШЁЛ и ДОШЁЛ** — ровно один, ровно тот, что нужен. Версии «клиент не сходил»
 *    и «ушёл лишний запрос» закрыты фактом.
 * 2. **Ответ в очереди ОСТАЛСЯ** — то есть подготовленный ответ никто не забрал. Версия
 *    «пустая очередь ответов» (одна из семи опровергнутых) закрыта повторно, уже цифрой.
 * 3. Экран простоял на «Загрузка…» все 20 секунд — состояние загрузки не сменилось ни на
 *    успех, ни на ошибку.
 *
 * Связка «запрос дошёл + ответ не забран» — новое знание: ломается не поход в сеть и не
 * подготовка данных, а участок между приходом запроса и выдачей ответа этому конкретному
 * вызову. Куда смотреть дальше: кто ещё держит соединение с тестовым сервером в момент теста,
 * и не забирает ли ответ ЧУЖОЙ (фоновый, оставшийся от предыдущего теста) вызов.
 *
 * И отдельно: мигает **не один и тот же тест**. 6 августа в 16:00 падал
 * `AdminReviewsIntegrationTest.screenLoadsReviewsFromServerAndDisplaysThem`, в 22:45 —
 * `AdminScreensIntegrationTest.adminDriversScreen_emptyServerResponse_showsEmptyState`.
 * Оба раза 1 падение из 1301. Причина общая для обоих классов, а не дефект одного теста.
 */
class RetryOnFlakeRule(private val attempts: Int = 2) : TestRule {

    override fun apply(base: Statement, description: Description): Statement =
        object : Statement() {
            override fun evaluate() {
                var first: Throwable? = null
                repeat(attempts) { attempt ->
                    try {
                        base.evaluate()
                        if (attempt > 0) {
                            println(
                                "[МИГАНИЕ] ${description.methodName}: прошёл со второй попытки. " +
                                    "Причина мигания не найдена, см. RetryOnFlakeRule.",
                            )
                        }
                        return
                    } catch (t: Throwable) {
                        // Держим ПЕРВУЮ ошибку: она и есть настоящая причина. Остальные попытки
                        // прикладываем к ней — так они дойдут до отчёта, а не только до stdout,
                        // которого в CI не видно.
                        val root = first
                        if (root == null) {
                            first = t
                        } else if (root !== t) {
                            root.addSuppressed(t)
                        }
                        println(
                            "[МИГАНИЕ] ${description.methodName}: попытка ${attempt + 1} из $attempts " +
                                "упала — ${t.message?.lineSequence()?.firstOrNull()}",
                        )
                        if (isRetryImpossible(t)) {
                            first?.addSuppressed(
                                IllegalStateException(
                                    "Повтор для ${description.className} невозможен: правило теста " +
                                        "Compose (createComposeRule) входит в runTest один раз за объект " +
                                        "теста, вторая попытка умирает до тела теста. Наружу отдана ошибка " +
                                        "ПЕРВОЙ попытки — это и есть настоящая причина. См. RetryOnFlakeRule.",
                                ),
                            )
                            throw first ?: t
                        }
                    }
                }
                throw first ?: IllegalStateException("тест не выполнился ни разу")
            }
        }

    /** Повтор бессмыслен: упало не тело теста, а сама попытка войти в него второй раз. */
    private fun isRetryImpossible(t: Throwable): Boolean =
        t is IllegalStateException && t.message?.contains("single call to") == true
}
