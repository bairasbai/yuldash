package com.yuldash.app

import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Картинки в приложении не весят как фотоальбом.
 *
 * Юлдаш ставят в районах, где интернет — это две палки EDGE у сельмага. Каждый лишний мегабайт
 * установки — это минуты ожидания и повод бросить на половине. Три фотографии на входе и логотип
 * лежали в PNG и весили 6 МБ на четверых: PNG хранит фото без потерь, а для фотографии это худший
 * из возможных выборов. Те же картинки в WebP весят 0,9 МБ — на 85% меньше, и разницы не видно
 * даже на небе с плавным переходом, где сжатие обычно оставляет полосы (проверено попиксельно:
 * логотип совпал точно, фотографии — 40 дБ PSNR, это «отличий не видит глаз»).
 *
 * Сторож держит два правила: формат и вес. Формат — потому что следующую картинку добавят так же,
 * как добавили эти, и никто не вспомнит про WebP. Вес — потому что WebP тоже можно сохранить
 * гигантским, если выкрутить качество на максимум.
 */
class ImageWeightTest {

    /** Иконки запуска (`mipmap`) не считаем: они крошечные и формат им задаёт система. */
    private val предел_на_картинку_кб = 400
    private val предел_на_все_кб = 1600

    private fun ресурсы(): File? {
        var dir = File("").absoluteFile
        repeat(4) {
            for (rel in listOf("app/src/main/res", "src/main/res")) {
                val d = File(dir, rel)
                if (d.isDirectory) return d
            }
            dir = dir.parentFile ?: return null
        }
        return null
    }

    @Test
    fun `фотографии лежат в WebP, а не в PNG`() {
        val res = ресурсы()
        assertTrue("не нашёл папку ресурсов — сторож ничего не проверяет", res != null)
        val тяжёлые = res!!.walkTopDown()
            .filter { it.isFile && it.extension.lowercase() in setOf("png", "jpg", "jpeg") }
            .filter { !it.path.replace('\\', '/').contains("/mipmap") }   // иконки запуска — не наш случай
            .filter { it.length() > 60_000 }                              // мелкая графика роли не играет
            .map { "${it.name} (${it.length() / 1024} КБ)" }
            .toList()

        assertTrue(
            "эти картинки лежат в старом формате и весят лишнее. Юлдаш ставят там, где интернет " +
                "медленный: каждый лишний мегабайт установки — повод бросить на половине. " +
                "Пересохрани в WebP (фото — качество 90, логотипы — без потерь):\n  " +
                тяжёлые.joinToString("\n  "),
            тяжёлые.isEmpty(),
        )
    }

    @Test
    fun `ни одна картинка не раздулась`() {
        val res = ресурсы() ?: return
        val картинки = res.walkTopDown()
            .filter { it.isFile && it.extension.lowercase() in setOf("webp", "png", "jpg", "jpeg") }
            .filter { !it.path.replace('\\', '/').contains("/mipmap") }
            .toList()
        assertTrue("не нашёл ни одной картинки — сторож ничего не проверяет", картинки.isNotEmpty())

        val толстые = картинки
            .filter { it.length() > предел_на_картинку_кб * 1024L }
            .map { "${it.name} — ${it.length() / 1024} КБ" }
        assertTrue(
            "картинка тяжелее ${предел_на_картинку_кб} КБ. WebP тоже можно сохранить гигантским, " +
                "если выкрутить качество на максимум — для фотографии хватает 90:\n  " +
                толстые.joinToString("\n  "),
            толстые.isEmpty(),
        )

        val всего = картинки.sumOf { it.length() } / 1024
        assertTrue(
            "все картинки вместе весят $всего КБ при пределе $предел_на_все_кб КБ. Это прямо " +
                "столько же добавляется к размеру установки.",
            всего <= предел_на_все_кб,
        )
    }
}
