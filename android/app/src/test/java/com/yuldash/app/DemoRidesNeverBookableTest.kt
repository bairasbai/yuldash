package com.yuldash.app

import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Пример поездки нельзя забронировать как настоящую.
 *
 * Приложение стартует с демо-поездок, чтобы экран не пустел, и оставляет их, если сервер не
 * ответил вовсе (село, плохая связь — обычное дело для Юлдаша). Раньше у них были id «1», «2»,
 * «3». Приложение читает id как число (`toIntOrNull`) и шлёт серверу.
 *
 * Что из этого следовало. Человек в дороге видит ПРИМЕР — «Баймаҡ → Сибай, Ильдар, 300 ₽» —
 * жмёт «Забронировать». Если связь к этому моменту вернулась, он бронирует НАСТОЯЩУЮ поездку
 * номер один: чужой водитель, чужой маршрут, чужая цена, занятое чужое место. Ни он, ни
 * водитель этого не выбирали.
 *
 * Про эту опасность в коде уже написано — в `YuldashApp`, там, где серверный список заменяет
 * демо: «оставить демо с числовыми id 1..3, которые book() принял бы за реальные». Но закрыт
 * был только путь «сервер ответил». Путь «сервер молчит» остался открытым, а он и есть тот,
 * ради которого демо существуют.
 *
 * Теперь id заведомо не число, и превратиться в бронь пример не может физически.
 */
class DemoRidesNeverBookableTest {

    @Test
    fun `у примеров поездок id не число`() {
        val numeric = demoRides.filter { it.id.toIntOrNull() != null }
        assertTrue(
            "демо-поездки с числовым id: ${numeric.map { it.id }}. " +
                "Такой id уйдёт на сервер как номер НАСТОЯЩЕЙ поездки — человек забронирует чужую.",
            numeric.isEmpty(),
        )
    }

    @Test
    fun `id примера не превращается в номер поездки`() {
        // Ровно то преобразование, которое делает экран брони перед отправкой на сервер.
        for (ride in demoRides) {
            assertNull("пример «${ride.id}» превращается в номер поездки", ride.id.toIntOrNull())
        }
    }

    @Test
    fun `примеры вообще есть — иначе тест ничего не проверяет`() {
        assertTrue("список демо-поездок пуст", demoRides.isNotEmpty())
    }
}
