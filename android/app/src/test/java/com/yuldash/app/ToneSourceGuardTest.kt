package com.yuldash.app

import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Юлдаш говорит с человеком на «ты» — это правило тона из `CLAUDE.md` §9.
 *
 * Нарушения не бросаются в глаза: одна карточка на «вы» среди двадцати на «ты» читается
 * нормально, пока не заметишь. Так и находили — глазами, на живом экране: «Найдите поездку
 * и забронируйте место» рядом с «Здесь будут ТВОИ чаты», причём башкирский в той же строке
 * был уже на «ты» («бронла»). Тон разъезжался и между экранами, и между языками одной строки.
 *
 * Тест читает исходники и падает на вежливом обращении внутри строкового литерала:
 * повелительное «-ите» («Найдите», «Укажите») и местоимения «ваш/вам/вас/Вы».
 *
 * Что НЕ нарушение (в списке исключений ниже): «вам обоим» — там правда двое собеседников,
 * и это множественное число, а не вежливость.
 */
class ToneSourceGuardTest {

    private val verbs = listOf(
        "Найдите", "Укажите", "Введите", "Проверьте", "Выберите", "Нажмите", "Попробуйте",
        "Свяжитесь", "Отправьте", "Подтвердите", "Заполните", "Позвоните", "Напишите",
        "Дождитесь", "Откройте", "Включите", "Выключите", "Загрузите", "Сохраните",
        "Добавьте", "Оплатите", "Закройте", "Обновите", "Расскажите", "Опишите",
        "Помните", "Сделайте", "Поставьте", "Выйдите", "Войдите",
        // Вежливое ПРОШЕДШЕЕ — отдельный класс, повелительное правило его не ловит.
        // «Забыли вещь?» жило на четырёх экранах при зелёном стороже (2026-09-06):
        // человек только что вышел из машины и ищет телефон, а приложение выкает.
        "Забыли", "Доехали", "Приехали", "Потеряли", "Оставили", "Хотели",
        "Уверены", "Готовы", "Смогли", "Успели", "Решили", "Выбрали", "Указали",
    )
    private val pronouns = listOf(
        "ваш", "ваша", "ваше", "ваши", "вашу", "вашей", "вашего", "вашим", "вашими",
        "ваших", "вам", "вас", "Вы", "Ваш",
        // Строчное «вы» внутри фразы: «Кажется, вы уже приехали» проходило мимо сторожа,
        // потому что в списке стояло только «Вы» с большой буквы (2026-09-05).
        "вы",
    )

    /** Строки, где вежливая форма — не тон, а смысл. Каждая — с объяснением. */
    private val allowed = setOf(
        // «вам обоим» = двоим сразу (заявитель и вторая сторона), это множественное число.
        "FairnessScreens.kt:вам обоим",
        "InstantOrderScreen.kt:вам обоим",
        // Ниже — тот же случай: «вы» про ДВОИХ, а не вежливое обращение к одному.
        // Отличать их машинально нельзя, поэтому каждое место названо поимённо.
        "FairnessScreens.kt:вы двое",              // «Фото видят только вы двое»
        "MainActivity.kt:вы вместе",               // «Спасибо, что вы вместе» — паре
        "CourierScreen.kt:и вы попробуете ещё раз",   // отправитель и получатель — двое
        "TripReceiptScreen.kt:как вы договорились",  // две стороны поездки
        "TripReceiptScreen.kt:чтобы вы связались",   // те же две стороны
    )

    // Каталог исходников ищем вверх по дереву — как в MoneySourceGuardTest: рабочая папка
    // теста зависит от того, кто его запускает (Gradle из корня или из :app).
    private fun sources(): List<File> {
        var dir = File("").absoluteFile
        repeat(4) {
            for (rel in listOf("app/src/main/java/com/yuldash/app", "src/main/java/com/yuldash/app")) {
                val src = File(dir, rel)
                if (src.isDirectory) return src.walkTopDown().filter { it.isFile && it.extension == "kt" }.toList()
            }
            dir = dir.parentFile ?: return emptyList()
        }
        return emptyList()
    }

    @Test
    fun `сторож видит исходники`() {
        assertTrue("не нашёл исходники экранов, сторож ничего не проверяет", sources().size > 30)
    }

    @Test
    fun `тон на «ты» — вежливых форм в текстах нет`() {
        // Границу слова пишем явно через кириллицу, а НЕ через `\b`: в Java `\b` считает
        // «словом» только латиницу, поэтому `\bваш\b` по русскому тексту не находит ничего.
        // Первая версия сторожа была написана с `\b` и молча пропускала всё — поймал только
        // тем, что специально сломал строку и проверил, покраснеет ли (урок 2026-08-12).
        val letters = "А-Яа-яЁё"
        // ПРАВИЛО, а не список. Перечисление глаголов пропустило «Используйте Telegram» —
        // на ПЕРВОМ экране приложения, при зелёном стороже (2026-08-13). Список описывает то,
        // о чём вспомнил автор, а вежливое повелительное узнаётся по окончанию «-ите»/«-йте»
        // с большой буквы. Явный список оставлен: он ловит формы вроде «Свяжитесь», «Помните».
        val politeImperative = """[А-ЯЁ][а-яё]+(?:ите|йте)"""
        val re = Regex("""(?<![$letters])($politeImperative|${(verbs + pronouns).joinToString("|")})(?![$letters])""")
        val hits = mutableListOf<String>()
        for (file in sources()) {
            file.readLines().forEachIndexed { idx, line ->
                if (!line.contains('"')) return@forEachIndexed
                for (m in re.findAll(line)) {
                    // Только внутри строкового литерала: в комментариях и именах полей «вас»
                    // не встречается, но кавычка — дешёвая и надёжная граница.
                    if (line.take(m.range.first).count { it == '"' } % 2 == 0) continue
                    // Исключение — это ФАЙЛ + кусок строки (как в MoneySourceGuardTest),
                    // а не файл + найденное слово: иначе «вам» было бы разрешено везде.
                    if (allowed.any { it.substringBefore(':') == file.name && line.contains(it.substringAfter(':')) }) continue
                    hits += "${file.name}:${idx + 1}  «${m.value}»  ${line.trim().take(90)}"
                }
            }
        }
        assertTrue(
            "обращение на «вы» — ${hits.size} шт. (тон Юлдаша — «ты», CLAUDE.md §9):\n" +
                hits.joinToString("\n"),
            hits.isEmpty(),
        )
    }
}
