package com.yuldash.app

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * У каждой фоновой плашки свой номер — иначе одна затирает другую.
 *
 * История. Марат и таксует, и возит посылки по пути — одна машина, один телефон. Включает
 * «Я на линии» — внизу висит плашка «Ты на линии 🚕». Берёт посылку, открывает режим курьера —
 * и плашка такси подменяется на «доставка идёт». Назад она уже не возвращается.
 *
 * Дальше он не видит ни «ты на линии», ни предупреждение «сервер тебя не видит — заказы
 * не придут», ради которого плашку и делали: стоит час и не понимает, почему тишина
 * (аудит 2026-08-08, волна 129).
 *
 * Причина в одной цифре: у сервиса линии и у сервиса доставки был один и тот же номер
 * уведомления — 4712. Android считает уведомления с одинаковым номером одним и тем же
 * и просто перерисовывает его.
 *
 * Тест читает исходники, а не поведение: подменённую плашку видно только на живом телефоне
 * с двумя запущенными сервисами, а вот совпадение чисел — прямо в коде. Заодно это сторож
 * на будущее: четвёртый фоновый сервис возьмёт свободный номер, а не чужой.
 */
class BackgroundBadgesDoNotCollideTest {

    private val root = File("src/main/java/com/yuldash/app")

    /** Файлы, которые держат постоянную плашку: это Service с собственным уведомлением. */
    private fun сервисыСПлашкой(): List<File> =
        root.walkTopDown()
            .filter { it.isFile && it.extension == "kt" }
            .filter { f ->
                val t = f.readText()
                t.contains(": Service()") && t.contains("NOTIF_ID")
            }
            .toList()

    private fun номер(f: File): Int? =
        Regex("""NOTIF_ID\s*=\s*(\d+)""").find(f.readText())?.groupValues?.get(1)?.toInt()

    @Test
    fun `у каждого фонового сервиса свой номер плашки`() {
        val сервисы = сервисыСПлашкой()
        assertTrue("не нашёл ни одного сервиса с плашкой — сторож ослеп", сервисы.size >= 2)

        val занято = mutableMapOf<Int, String>()
        val столкновения = mutableListOf<String>()
        for (f in сервисы) {
            val n = номер(f) ?: continue
            val прежний = занято[n]
            if (прежний != null) столкновения += "$n: $прежний и ${f.name}"
            занято[n] = f.name
        }
        assertTrue(
            "эти фоновые сервисы делят один номер плашки: $столкновения. Android считает такие " +
                "уведомления одним и тем же и перерисовывает его: у человека, который и таксует, " +
                "и возит посылки, плашка «Ты на линии» подменяется на «доставка идёт» — вместе " +
                "с предупреждением «заказы не придут», ради которого она и нужна.",
            столкновения.isEmpty(),
        )
    }

    @Test
    fun `сторож видит все три известных сервиса`() {
        // Проверка зрения: ослабить поиск — значит сделать тест зелёным (приём волны 109).
        val имена = сервисыСПлашкой().map { it.nameWithoutExtension }.toSet()
        for (сервис in listOf("TripLocationService", "TaxiLineService", "CourierLocationService")) {
            assertTrue("сторож перестал видеть $сервис — столкновение номеров он там не заметит",
                сервис in имена)
        }
    }

    @Test
    fun `номера остались в своём диапазоне`() {
        // Мелочь, но полезная: чужие библиотеки тоже показывают уведомления, и «1» или «0»
        // легко пересечётся с ними. Держим свой диапазон.
        for (f in сервисыСПлашкой()) {
            val n = номер(f) ?: continue
            assertTrue("${f.name} взял номер $n вне диапазона 4700..4799", n in 4700..4799)
        }
    }

    @Test
    fun `у линии и доставки номера разные`() {
        // Именно эта пара и столкнулась — держим её отдельной проверкой с человеческим текстом.
        val линия = номер(File(root, "TaxiLineService.kt"))
        val доставка = номер(File(root, "CourierLocationService.kt"))
        assertTrue("не нашёл номера плашек", линия != null && доставка != null)
        assertEquals(
            "у линии такси и у доставки снова один номер — плашка «Ты на линии» опять пропадёт " +
                "у того, кто возит посылки по пути",
            false, линия == доставка,
        )
    }
}
