package com.yuldash.app.data

/**
 * Что переживает выход из аккаунта — и почему. Один список на всё приложение.
 *
 * Зачем (аудит 2026-08-12, волна 31). Телефон в селе переходит из рук в руки: муж отдал жене,
 * родитель — сыну, водитель продал старый аппарат. Выход из аккаунта должен уносить с собой
 * ЧУЖОЕ, а оставлять только настройки самого устройства (язык, тема, звук).
 *
 * Очистка была написана руками, списком «что вспомнили»: токены, имя, роль, пуш-токен, паспорта
 * поездок, очередь исходящих. Работала верно — но никто не проверял, что новый ключ кто-нибудь
 * не забудет. А забыть здесь означает оставить следующему владельцу телефона кусок чужой жизни.
 *
 * Теперь решение обязано быть записано у КАЖДОГО ключа, и это держит сторож
 * `SessionKeysGuardTest`: нашёл в исходниках новый ключ — красный тест, пока его не отнесут
 * либо сюда, либо в список «умирает при выходе».
 */
internal object SessionKeys {

    /** Ключи, которые выход из аккаунта СТИРАЕТ. Это чужое — оно не должно пережить владельца. */
    val CLEARED_ON_LOGOUT = listOf(
        "token",           // токен входа
        "refresh_token",   // токен продления сессии
        "user_name",       // имя человека
        "user_role",       // кем он был в приложении
        "push_token",      // иначе устройство прошлого владельца снова зарегистрируется
        "preferred_role",  // «я вожу» / «я езжу»: настройка АККАУНТА, а не телефона
    )

    /**
     * Ключи, которые ОСТАЮТСЯ, и причина у каждого. Общее правило: остаётся то, что человек
     * настроил под СЕБЯ И ТЕЛЕФОН, а не то, что он сделал внутри аккаунта.
     */
    val SURVIVES_LOGOUT = mapOf(
        "app_language" to "язык интерфейса — настройка телефона; сбросить значит встретить нового человека чужим языком",
        "dark_override" to "тёмная тема — настройка внешнего вида устройства",
        "sounds" to "звуки уведомлений — настройка устройства",
        "notifications" to "разрешение на уведомления — настройка устройства",
        "onboarding_completed" to "интро уже показывали на этом телефоне; повторять его новому человеку не вредно, но и не нужно",
        "simple_mode_opted_in" to "простой режим — это про зрение и привычки ЧЕЛОВЕКА с телефоном, а не про аккаунт",
        "chat_safety_seen" to "памятку о безопасности чата на этом телефоне уже читали",
        "verified_only" to "фильтр поиска «только проверенные» — привычка пользоваться, не личные данные",
    )
}
