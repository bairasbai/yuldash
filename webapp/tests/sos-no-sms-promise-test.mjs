// ================================================================
//  Экраны SOS, «Доверенные контакты», «Поделиться поездкой», «Позвать помощь» и справка
//  не обещают SMS близким (16.10.2026). Зеркало Android SosNoSmsPromiseGuardTest.kt.
//
//  Было: «Доверенные получат SMS с твоим местом», «Этим людям Юлдаш пришлёт SMS при SOS»,
//  «Ссылка отправлена близкому», «Близкие получили сообщение». На проде SMS выключены
//  (SMS_PROVIDER=mock), а человек в опасности рассчитывает, что родные уже знают, — и не
//  звонит им сам. Теперь экран обещает только то, что точно случится: сигнал поддержке
//  Юлдаш. Кому из близких сообщение правда ушло, говорит ОТВЕТ сервера — после отправки.
//
//  Читает только строки кода, не комментарии: в комментарии причину написать можно и нужно.
//  Читает исходники напрямую — сборка не нужна.
// ================================================================
import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "src");

const FILES = [
  "screens/SosScreen.tsx",
  "screens/TrustedContactsScreen.tsx",
  "components/ShareTripCard.tsx",
  "screens/HelpScreen.tsx",
  "components/RoadsideHelp.tsx",
  // Те же правила и «Безопасность»: Android проверяет и «Правила поездок» (приёмка PR146).
  "screens/RulesScreen.tsx",
  "screens/SafetyScreen.tsx",
  // Отмена в пути (23.10.2026): водителю и пассажиру — «увидят по ссылке», а не SMS.
  "utils/rideCancelWarning.ts",
  "components/CancelledInTransitCard.tsx",
];

/** Фразы-обещания. Русские и башкирские: надпись на двух языках, и обещание тоже. */
const FORBIDDEN = [
  [/сообщить близким/i, "«Сообщить близким и поддержке»"],
  [/(доверенные|близкие|родные|близкий|контакты)\s+получ(ат|ит|или|ил)/i, "«получат / получили»"],
  [/(уйд[её]т|придёт|придет|пришл[её]т|ушло|ушл[аи])\s+SMS/i, "«уйдёт / пришлёт SMS»"],
  [/SMS\s+(близким|доверенным|твоим|родным)/i, "«SMS близким»"],
  [/для\s+SMS\s+близким/i, "«Для SMS близким»"],
  [/SMS\s+со\s+ссылкой/i, "«SMS со ссылкой»"],
  [/получат\s+SMS/i, "«получат SMS»"],
  [/—\s*SMS/i, "«…— SMS» (первый вариант окна «Снять поездку?»)"],
  [/SMS\s+кит[әе]/i, "«SMS китә»"],
  [/SMS\s+при\s+SOS/i, "«SMS при SOS»"],
  [/ссылка\s+отправлена/i, "«Ссылка отправлена»"],
  [/отправлена\s+близкому/i, "«отправлена близкому»"],
  [/получили\s+сообщение/i, "«получили сообщение»"],
  [/близкие\s+получили/i, "«Близкие получили»"],
  // Башкирский
  [/Яҡындарға\s+һәм\s+ярҙамға\s+хәбәр/i, "«Яҡындарға һәм ярҙамға хәбәр итеү»"],
  [/Яҡындарға\s+хәбәр\s+китте/i, "«Яҡындарға хәбәр китте»"],
  [/Һылтанма\s+яҡын\s+кешегә\s+ебәрелде/i, "«Һылтанма яҡын кешегә ебәрелде»"],
  [/SMS\s+(ебәрер|алыр)/i, "«SMS ебәрер / алыр»"],
  [/Яҡындарға\s+SMS/i, "«Яҡындарға SMS»"],
];

let bad = 0;
const check = (ok, label, extra = "") => {
  if (!ok) bad++;
  console.log(`${ok ? "✓" : "✗"} ${label}${!ok && extra ? "\n    " + extra : ""}`);
};

// Строки файла без комментариев: блоки слэш-звёздочка (в т.ч. в JSX-фигурных скобках) и целые строки с двумя слэшами.
function codeLines(rel) {
  const file = join(SRC, rel);
  if (!existsSync(file)) return [];
  const text = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
  return text.split("\n").filter((line) => !line.trim().startsWith("//"));
}

// 1. Сторож видит все файлы: переименовали экран — сторож не должен молча ничего не проверять.
for (const rel of FILES) {
  check(codeLines(rel).length > 0, `сторож видит ${rel}`, "не нашёл файл — сторож ничего не проверяет");
}

// 2. Нет обещаний.
const hits = FILES.flatMap((rel) =>
  codeLines(rel).flatMap((line, i) =>
    FORBIDDEN.filter(([re]) => re.test(line)).map(([, name]) => `${rel}:${i + 1}  ${name}  ${line.trim().slice(0, 100)}`)
  )
);
check(
  hits.length === 0,
  "в SOS, контактах, «Поделиться», помощи на трассе и справке нет обещаний SMS близким",
  hits.length ? `SMS на проде выключены — не обещай их близким (${hits.length} шт.):\n    ` + hits.join("\n    ") : ""
);

// 3. Кнопка SOS обещает сигнал поддержке, а не близким (дословно как в Android).
const sos = codeLines("screens/SosScreen.tsx").join("\n");
check(
  sos.includes('appText("Сообщить поддержке", "Ярҙамға хәбәр итеү")'),
  "подпись кнопки SOS — «Сообщить поддержке» / «Ярҙамға хәбәр итеү»"
);
check(
  sos.includes("Близким позвони сам, если можешь.") && sos.includes("яҡындарыңа үҙең шылтырат."),
  "под кнопкой SOS: «Близким позвони сам, если можешь.»"
);

// 4. «Поделиться поездкой»: ссылка готова, отправляет человек сам.
const share = codeLines("components/ShareTripCard.tsx").join("\n");
check(
  /Ссылка готова — отправь её близкому сам/.test(share) && /navigator\.clipboard\.writeText/.test(share),
  "«Поделиться»: «Ссылка готова — отправь её близкому сам» и кнопка «Скопировать»"
);
check(/navigator\.share\b/.test(share), "«Поделиться»: кнопка «Отправить» через системное окно");

// 5. «Доверенные контакты»: заголовок и текст как в Android.
const trusted = codeLines("screens/TrustedContactsScreen.tsx").join("\n");
check(
  trusted.includes("Близкие видят статус поездки") && trusted.includes("Яҡындар сәфәр статусын күрә"),
  "«Доверенные контакты»: «Близкие видят статус поездки» (как в Android)"
);

// 6. Справка: вопрос про SOS есть — слово в слово из Android (SecondaryScreens.kt, FAQ) — и он
//    про звонок в службы и сигнал поддержке, а не про SMS близким (паритет, шаг 4, 17.10.2026).
const help = codeLines("screens/HelpScreen.tsx").join("\n");
const SOS_FAQ = [
  "Что делать в экстренной ситуации?",
  "Ашығыс хәлдә нимә эшләргә?",
  "Нажми SOS — откроется экран помощи. Там можно позвонить 112/102/101/103 или отправить сигнал в Юлдаш. Координаты добавятся, если геолокация разрешена и место определено. Не жди ответа — позвони в службы и близким сам, если можешь.",
  "SOS-ҡа баҫ — ярҙам экраны асыла. Унда 112/102/101/103-кә шылтыратырға йәки Юлдашҡа сигнал ебәрергә була. Урынды билдәләүгә рөхсәт бирелһә һәм координаталар билдәле булһа, улар сигналға өҫтәлә. Яуап көтмә — мөмкин булһа, хеҙмәттәргә һәм яҡындарыңа үҙең шылтырат.",
];
check(
  SOS_FAQ.every((s) => help.includes(`"${s}"`)),
  "справка: вопрос «Что делать в экстренной ситуации?» и ответ — как в Android, на двух языках",
  SOS_FAQ.filter((s) => !help.includes(`"${s}"`)).map((s) => s.slice(0, 40)).join("; ")
);
{
  const faq = help.slice(help.indexOf("Что делать в экстренной ситуации?"));
  const entry = faq.slice(0, faq.indexOf("},") + 2);
  check(entry.length > 40 && !/SMS/i.test(entry), "ответ про SOS не упоминает SMS вовсе");
}
{
  const android = join(HERE, "..", "..", "android", "app", "src", "main", "java", "com", "yuldash", "app", "SecondaryScreens.kt");
  if (existsSync(android)) {
    const kt = readFileSync(android, "utf8");
    check(SOS_FAQ.every((s) => kt.includes(`"${s}"`)), "тот же ответ и в Android (SecondaryScreens.kt) — тексты не разъехались");
  }
}

// 7. Сам сторож умеет ловить: проверка на заведомо плохой строке.
const bait = ["Доверенные получат SMS с твоим местом", "Ссылка отправлена близкому", "Близкие получили сообщение", "Яҡындарға һәм ярҙамға хәбәр итеү", "Этим людям Юлдаш пришлёт SMS при SOS"];
check(
  bait.every((line) => FORBIDDEN.some(([re]) => re.test(line))),
  "сторож узнаёт старые обещания (было в экранах до 16.10.2026)"
);

console.log(bad === 0 ? "\nВСЁ СОШЛОСЬ" : `\nПРОВАЛЕНО: ${bad}`);
process.exit(bad === 0 ? 0 : 1);
