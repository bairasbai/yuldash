// ================================================================
//  ⚠️ Безопасность в чате — плашки поверх сообщений.
//  Зеркало Android ChatFlagPlate / ChatSafetyDisclaimer / YuldashOfficialBadge.
//
//  Сервер помечает сообщение флагом, но НЕ блокирует его: решает человек,
//  а не фильтр. Плашка только объясняет, и каждому — своё:
//
//    warn    — похоже на развод (просят код из SMS, номер карты).
//              Читает ПОЛУЧАТЕЛЬ: он уже прочитал текст, помогаем не попасться.
//    contact — телефон или увод в мессенджер. Читает ОТПРАВИТЕЛЬ: рискует он,
//              собеседник ничего плохого не сделал — ему нотация ни к чему.
//    abuse   — грубость. Читает ПОЛУЧАТЕЛЬ. Отправителю не показываем:
//              нотация в ответ на эмоцию только злит.
//
//  Бейдж «Юлдаш ✓» ставится ТОЛЬКО по серверному флагу from_admin —
//  поэтому мошенник не может прикинуться поддержкой.
// ================================================================
import { useState } from "react";
import { useLang } from "../i18n/lang";

const SEEN_KEY = "yuldash.chatSafetySeen";

/**
 * Плашка под сообщением. Ничего не рисует, если этот флаг адресован не тебе
 * или сообщение удалено.
 */
export function ChatFlagPlate({ flag, mine }: { flag?: string; mine: boolean }) {
  const { appText } = useLang();
  if (!flag) return null;

  const forMe = flag === "contact" ? mine : !mine; // contact — отправителю, остальное — получателю
  if (!forMe) return null;

  const text =
    flag === "warn"
      ? appText(
          "Никому не сообщай коды из SMS. Юлдаш никогда их не просит",
          "СМС-тағы кодтарҙы бер кемгә лә әйтмә. Юлдаш уларҙы бер ҡасан да һорамай"
        )
      : flag === "contact"
        ? appText(
            "Договариваться мимо приложения небезопасно: поездка не будет застрахована, и решить спор будет нельзя",
            "Ҡулланманан тыш килешеү хәүефһеҙ түгел: сәфәр иминләштерелмәй, бәхәсте хәл итеп булмай"
          )
        : appText("Сообщение содержит грубые слова", "Хәбәрҙә ҡытыр һүҙҙәр бар");

  return <div className="chat-flag">⚠️ {text}</div>;
}

/**
 * Тонкий баннер при первом открытии чата. «Понятно» — больше не показываем
 * (метка в браузере). Один раз объяснить полезно, каждый раз — шум.
 */
export function ChatSafetyDisclaimer() {
  const { appText } = useLang();
  const [visible, setVisible] = useState(() => {
    try {
      return localStorage.getItem(SEEN_KEY) !== "1";
    } catch {
      return true; // приватный режим — покажем, это безопаснее, чем промолчать
    }
  });

  if (!visible) return null;

  function dismiss() {
    try {
      localStorage.setItem(SEEN_KEY, "1");
    } catch {
      /* не сохранилось — покажем в следующий раз, не беда */
    }
    setVisible(false);
  }

  return (
    <div className="chat-disclaimer">
      <span className="chat-disclaimer__text">
        ⚠️{" "}
        {appText(
          "Никому не сообщай коды из SMS и не переводи деньги «на другой номер». Юлдаш никогда их не просит",
          "СМС-тағы кодтарҙы бер кемгә лә әйтмә һәм «башҡа номерға» аҡса күсермә. Юлдаш уларҙы бер ҡасан да һорамай"
        )}
      </span>
      <button type="button" className="chat-disclaimer__ok" onClick={dismiss}>
        {appText("Понятно", "Аңлашылды")}
      </button>
    </div>
  );
}
