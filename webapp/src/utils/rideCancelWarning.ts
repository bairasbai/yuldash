// ================================================================
//  «Снять поездку?», когда пассажиры уже в машине (решение 23.10.2026). Зеркало Android
//  RideCancelWarning.kt: тот же счёт и те же слова.
//
//  Отмена «в пути» водителю оставлена (сломалась машина, высадил за поведение), но он должен
//  понимать, что делает: довёз — «Завершить рейс»; снимает — пассажирам придёт срочное
//  уведомление, а близкие, с кем они поделились поездкой, увидят по ссылке «отменили в пути».
//  SMS не обещаем: на проде SMS выключены (сторож sos-no-sms-promise-test).
// ================================================================
import type { DriverBookingRow } from "../api/bookings";

/** Сколько броней этой поездки сейчас «в пути». 0 — никого, или старый сервер без `ride_id`. */
export function onboardPassengers(rideId: number, rows: readonly DriverBookingRow[]): number {
  if (!rideId || rideId <= 0) return 0;
  return rows.filter((b) => b.ride_id === rideId && b.status === "onboard").length;
}

/** Строка предупреждения для окна «Снять поездку?». */
export function rideCancelOnboardWarning(onboard: number, appText: (ru: string, ba: string) => string): string {
  return appText(
    `В машине пассажиры: ${onboard}. Если довёз — нажми «Завершить рейс». Если снимаешь — им придёт уведомление, ` +
      "а близкие, с кем они поделились поездкой, увидят по ссылке, что поездку отменили в пути.",
    `Машинала юлаусылар: ${onboard}. Илтеп еткерһәң — «Рейсты тамамлау» төймәһенә баҫ. Алаһың икән — уларға хәбәр килә, ` +
      "ә улар сәфәр менән бүлешкән яҡындар һылтанма буйынса сәфәрҙең юлда кире алынғанын күрә."
  );
}
