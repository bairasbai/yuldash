//  Android: ProfileRole.kt, roleLabel).
//
//  Один аккаунт и возит, и ездит, а роль на сервере от публикации поездок не меняется: человек,
//  который каждую неделю возит соседей, был «Пассажир». /me отдаёт `drives` (публиковал поездки)
//  и `books` (бронировал чужие); `verified` — документы водителя одобрены.
// ================================================================

export interface RoleFacts {
  role: string;
  verified?: boolean;
  drives?: boolean;
  books?: boolean;
}

/** [русский, башкирский] — подпись роли. */
export function profileRole(me: RoleFacts): [string, string] {
  if (me.role === "admin") return ["Администратор", "Администратор"];
  const driver = me.role === "driver" || !!me.verified || !!me.drives;
  if (driver && me.books) return ["Водитель и пассажир", "Йөрөтөүсе һәм пассажир"];
  if (driver) return ["Водитель", "Йөрөтөүсе"];
  return ["Пассажир", "Пассажир"];
}
