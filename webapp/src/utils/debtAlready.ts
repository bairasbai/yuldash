// ================================================================
//  «Долг уже оплачен» — отдельный ответ сервера (`already: true`) на
//  подтвердить / отклонить / списать долг за такси.
//
//  Сервер так отвечает, когда долг закрыли другим путём, пока админ смотрел
//  на строку: банк подтвердил оплату картой, долг закрыт кошельком или
//  разбором жалобы (лист 1.2c). Раньше экран рисовал на это обычное
//  «Оплата подтверждена», и лишний перевод по СБП админ видел только
//  в журнале сервера. Тексты — те же, что в приложении (AdminDebtMsgs.kt).
// ================================================================

export type DebtAction = "confirm" | "reject" | "forgive";

/** Ответ сервера — «уже оплачено, ничего не изменилось»? */
export function isDebtAlreadySettled(res: unknown): boolean {
  return typeof res === "object" && res !== null && (res as { already?: unknown }).already === true;
}

