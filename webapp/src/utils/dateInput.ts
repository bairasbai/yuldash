// ================================================================
//  Границы для полей выбора даты и времени.
//
//  Сервер отказывается принимать поездку в прошлом («не раньше чем полчаса
//  назад») и предзаказ дальше чем на N суток. Поля на сайте таких границ
//  не имели: человек спокойно выбирал вчерашний день, жал «Опубликовать»
//  и получал отказ — уже после того, как заполнил всю форму.
//
//  Календарь телефона сам не даст выбрать запрещённое, если ему сказать
//  границы. Это дешевле любого объяснения после отправки.
// ================================================================

/** `Date` → строка для `<input type="datetime-local">` в МЕСТНОМ времени. */
export function toDateTimeInput(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(
    d.getHours()
  )}:${pad(d.getMinutes())}`;
}

/** «Не раньше, чем сейчас» — нижняя граница для выезда и подачи. */
export function minDateTimeNow(): string {
  return toDateTimeInput(new Date());
}

/** «Не дальше, чем через N суток» — верхняя граница для предзаказа. */
export function maxDateTimeInDays(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return toDateTimeInput(d);
}
